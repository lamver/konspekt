# -*- coding: utf-8 -*-
"""Окно не должно теряться за пределами экрана.

Беда, ради которой это написано: свернули окно, вышли из программы,
запустили снова — значок в трее есть, а окна нет нигде. Причина в том,
что Windows у свёрнутого окна отвечает координатами -32000, -32000, мы
их честно записывали в настройки и при следующем запуске создавали окно
ровно там. Достать его оттуда было нечем: ни мышью, ни горячей клавишей.

Второй случай той же болезни — отключённый монитор. Окно осталось на
координатах второго экрана, экрана больше нет, окна не видно.

Здесь два уровня. Сначала чистая арифметика: какие координаты считаем
годными. Потом живое окно: создаём его с заведомо потерянным
положением и смотрим, куда оно встало на самом деле.
"""
import testenv  # noqa: F401  песочница вместо боевого профиля

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from app.core import settings as settings_mod  # noqa: E402

провал = 0
сделано = 0


def проверить(что: str, хорошо: bool, доказательство: str = "") -> None:
    global провал, сделано
    сделано += 1
    if не_хорошо := not хорошо:
        провал += 1
    print(f"[{'ПЛОХО' if не_хорошо else 'OK   '}] {что}")
    if доказательство:
        print(f"         {доказательство}")


ЭКРАН = [(0, 0, 3440, 1392)]
ДВА_ЭКРАНА = [(0, 0, 1920, 1040), (1920, 0, 1920, 1040)]

print("--- какие координаты считаем годными ---")

# Ровно тот случай, что случился у человека.
проверить(
    "свёрнутое окно (-32000) не годится",
    settings_mod.геометрия_годится(-32000, -32000, 360, 420) is False,
    "иначе окно создастся за пределами экрана и его не достать",
)

проверить(
    "свёрнутое окно не годится и со списком экранов",
    settings_mod.геометрия_годится(-32000, -32000, 360, 420, ЭКРАН) is False,
)

проверить(
    "обычное положение годится",
    settings_mod.геометрия_годится(120, 120, 460, 640, ЭКРАН) is True,
)

проверить(
    "положение без экранов под рукой годится",
    settings_mod.геометрия_годится(120, 120, 460, 640) is True,
    "список мониторов знает только система: без него не выбрасываем годное",
)

проверить(
    "окно на втором мониторе годится, пока монитор есть",
    settings_mod.геометрия_годится(2400, 200, 460, 640, ДВА_ЭКРАНА) is True,
)

проверить(
    "то же окно не годится, когда второй монитор отключили",
    settings_mod.геометрия_годится(2400, 200, 460, 640, [ДВА_ЭКРАНА[0]]) is False,
    "экран отключили, окно осталось на его координатах",
)

# Окно, уехавшее почти целиком: поймать его мышью невозможно.
проверить(
    "окно, от которого видна полоска в 10 пикселей, не годится",
    settings_mod.геометрия_годится(3430, 700, 460, 640, ЭКРАН) is False,
)

проверить(
    "окно, наполовину выехавшее за край, годится",
    settings_mod.геометрия_годится(3200, 700, 460, 640, ЭКРАН) is True,
    "за такое окно ещё можно ухватиться мышью и вернуть",
)

проверить(
    "окно выше верхнего края не годится",
    settings_mod.геометрия_годится(500, -700, 460, 640, ЭКРАН) is False,
    "заголовок ушёл вверх, тащить не за что",
)

проверить(
    "пустое положение (окно ставит система) годится",
    settings_mod.геометрия_годится(None, None, 460, 640, ЭКРАН) is True,
)

проверить(
    "нулевой размер не годится",
    settings_mod.геометрия_годится(100, 100, 0, 0, ЭКРАН) is False,
)

проверить(
    "нулевой размер не годится и без списка экранов",
    settings_mod.геометрия_годится(100, 100, 0, 0) is False,
    "окно без ширины и высоты не покажешь, откуда бы мы о нём ни узнали",
)

проверить(
    "отрицательный размер не годится",
    settings_mod.геометрия_годится(100, 100, -460, -640, ЭКРАН) is False,
)

print("--- куда возвращаем потерянное окно ---")

x, y = settings_mod.поставить_по_центру(460, 640, ЭКРАН)
проверить(
    "потерянное окно возвращается на середину экрана",
    settings_mod.геометрия_годится(x, y, 460, 640, ЭКРАН) is True,
    f"новое место: x={x} y={y}",
)

x2, y2 = settings_mod.поставить_по_центру(460, 640, ДВА_ЭКРАНА)
проверить(
    "возвращаем на первый экран, а не на отключённый",
    settings_mod.геометрия_годится(x2, y2, 460, 640, [ДВА_ЭКРАНА[0]]) is True,
    f"новое место: x={x2} y={y2}",
)

проверить(
    "без списка экранов место выбирает система",
    settings_mod.поставить_по_центру(460, 640, []) == (None, None),
    "наугад ставить окно хуже, чем доверить системе",
)

print("--- чиним и размер, и место разом ---")

# Именно это лежало в settings.json у человека, к которому окно не
# вернулось: свёрнутому окну Windows приписывает и координаты -32000,
# и размер в полоску заголовка.
испорченное = settings_mod.WindowGeometry(x=-32000, y=-32000, width=160, height=28)
чинили = settings_mod.починить_геометрию(испорченное, ЭКРАН)
проверить(
    "испорченную геометрию признали испорченной",
    чинили is True,
)
проверить(
    "размер вернулся к рабочему",
    испорченное.width >= settings_mod.МИН_ШИРИНА
    and испорченное.height >= settings_mod.МИН_ВЫСОТА,
    f"было 160x28, стало {испорченное.width}x{испорченное.height}",
)
проверить(
    "место после починки годное",
    settings_mod.геометрия_годится(
        испорченное.x, испорченное.y, испорченное.width, испорченное.height, ЭКРАН
    ) is True,
    f"новое место: x={испорченное.x} y={испорченное.y}",
)

# Окно человека, которое ни разу не терялось, трогать нельзя.
целое = settings_mod.WindowGeometry(x=700, y=300, width=520, height=700)
проверить(
    "здоровое окно не трогаем",
    settings_mod.починить_геометрию(целое, ЭКРАН) is False
    and (целое.x, целое.y, целое.width, целое.height) == (700, 300, 520, 700),
    f"осталось x={целое.x} y={целое.y} {целое.width}x{целое.height}",
)

# Размер-полоска сам по себе, без потерянных координат.
полоска = settings_mod.WindowGeometry(x=200, y=200, width=160, height=28)
settings_mod.починить_геометрию(полоска, ЭКРАН)
проверить(
    "окно-полоска на экране тоже чинится",
    полоска.width >= settings_mod.МИН_ШИРИНА
    and полоска.height >= settings_mod.МИН_ВЫСОТА,
    f"стало {полоска.width}x{полоска.height}",
)

проверить(
    "размер меньше минимального не годится",
    settings_mod.геометрия_годится(200, 200, 160, 28, ЭКРАН) is False,
    "в окно 160x28 не помещается ни список записей, ни кнопки",
)

print("--- основной монитор идёт первым ---")

if sys.platform == "win32":
    from app.ui import win32 as win32_модуль

    # Система перечисляет мониторы как ей удобно. Если не разложить их
    # самим, потерянное окно уедет на боковой экран или на тот, что
    # стоит за спиной: формально видно, на деле нет.
    вперемешку = [
        (1920, 0, 1920, 1040, False),
        (0, 0, 2560, 1400, True),
        (-1920, 0, 1920, 1040, False),
    ]
    разложено = win32_модуль.основной_первым(вперемешку)
    проверить(
        "основной монитор оказывается первым",
        разложено[0] == (0, 0, 2560, 1400),
        f"порядок стал: {разложено}",
    )
    проверить(
        "остальные мониторы никуда не делись",
        len(разложено) == len(вперемешку),
        f"было {len(вперемешку)}, стало {len(разложено)}",
    )

    # Масштаб 125%: физические пиксели крупнее логических.
    в_масштабе = win32_модуль.основной_первым([(0, 0, 3000, 2000, True)], 1.25)
    проверить(
        "экран пересчитан в логические пиксели",
        в_масштабе == [(0, 0, 2400, 1600)],
        f"при масштабе 125% получили {в_масштабе}",
    )
else:
    print("[skip] порядок мониторов проверяется только на Windows")

print("--- настройки не запоминают потерянное положение ---")

сервис_настройки = settings_mod.Settings()
сервис_настройки.window.x, сервис_настройки.window.y = 300, 300


class ПоддельныйСервис:
    """Достаточно малая часть AppService, чтобы позвать сохранение."""

    def __init__(self) -> None:
        self.settings = сервис_настройки


from app.core.service import AppService  # noqa: E402

сохранить = AppService.save_window_geometry
поддельный = ПоддельныйСервис()

сохранить(поддельный, -32000, -32000, 360, 420)
проверить(
    "сворачивание не затирает запомненное место",
    (сервис_настройки.window.x, сервис_настройки.window.y) == (300, 300),
    f"в настройках осталось x={сервис_настройки.window.x} y={сервис_настройки.window.y}",
)

сохранить(поддельный, 640, 480, 460, 640)
проверить(
    "обычный переезд окна запоминается",
    (сервис_настройки.window.x, сервис_настройки.window.y) == (640, 480),
    f"в настройках теперь x={сервис_настройки.window.x} y={сервис_настройки.window.y}",
)

print("--- живое окно встаёт на экран, а не в пустоту ---")

try:
    import webview  # noqa: F401
    ЕСТЬ_WEBVIEW = True
except Exception as e:  # noqa: BLE001
    ЕСТЬ_WEBVIEW = False
    print(f"[skip] webview недоступен: {e}")

if ЕСТЬ_WEBVIEW and sys.platform == "win32":
    import threading
    import time

    import webview

    from app.ui import win32

    экраны = win32.экраны()
    проверить(
        "программа видит мониторы",
        len(экраны) > 0 and all(ш > 0 and в > 0 for _, _, ш, в in экраны),
        f"экраны: {экраны}",
    )

    # Берём ровно то, что лежало в settings.json у человека, к которому
    # окно не вернулось, и спрашиваем у самой программы, куда его ставить.
    # Считать место здесь самим нельзя: тогда проверка подтверждала бы
    # собственную арифметику, а не работу окна.
    from app.ui.window import MainWindow

    геом = settings_mod.WindowGeometry(x=-32000, y=-32000, width=160, height=28)

    class ПоддельныйСервис2:
        def __init__(self) -> None:
            self.settings = settings_mod.Settings()
            self.settings.window = геом

    подделка = type("Подделка", (), {"service": ПоддельныйСервис2()})()
    место = MainWindow._исправить_положение(подделка, геом)

    итог: dict[str, object] = {}

    окно = webview.create_window(
        "Проверка положения",
        html="<body style='background:#eee'>проверка</body>",
        x=место[0], y=место[1], width=геом.width, height=геом.height,
        hidden=True,
    )

    def осмотреть(w):
        try:
            w.show()
            time.sleep(0.6)
            итог["rect"] = win32.get_rect(w)
        except Exception as e:  # noqa: BLE001
            итог["ошибка"] = repr(e)
        finally:
            try:
                w.destroy()
            except Exception:  # noqa: BLE001
                pass

    threading.Thread(target=осмотреть, args=(окно,), daemon=True).start()
    try:
        webview.start()
    except Exception as e:  # noqa: BLE001
        итог["ошибка"] = repr(e)

    rect = итог.get("rect")
    if итог.get("ошибка"):
        проверить("живое окно удалось поднять", False, str(итог["ошибка"]))
    elif not rect:
        проверить("живое окно удалось поднять", False, "не получили координат окна")
    else:
        x, y, ш, в = rect
        проверить(
            "окно с потерянным положением встало на видное место",
            settings_mod.геометрия_годится(x, y, ш, в, экраны) is True,
            f"настройки говорили x=-32000 y=-32000 160x28, "
            f"окно встало x={x} y={y} {ш}x{в}",
        )
else:
    print("[skip] живое окно проверяется только на Windows")

print(f"\nпроверок: {сделано}, провалов: {провал}")
sys.exit(1 if провал else 0)
