# -*- coding: utf-8 -*-
"""Личные данные: находим настоящие и не трогаем случайные числа.

Две беды, и обе тихие.

Пропуск: номер карты ушёл в чат команды или на чужой сервер, хотя
человек нажал «без личных данных».

Ложная тревога: «выручка 12 345 678» или «2026 год» подсвечены как
паспорт, и через неделю кнопку никто не нажимает, потому что она
подсвечивает всё подряд.
"""
from __future__ import annotations

import testenv  # noqa: F401  песочница вместо боевого профиля

from app.core import personal
from app.core import settings as settings_mod
from app.core.service import AppService

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def виды(текст: str) -> list[tuple[str, str]]:
    return [(н.kind, н.text) for н in personal.find(текст)]


# --- находим -----------------------------------------------------------------

НАДО = [
    ("Звоните +7 (916) 123-45-67", "phone", "+7 (916) 123-45-67"),
    ("мой 8 916 123 45 67 вечером", "phone", "8 916 123 45 67"),
    ("номер +79161234567.", "phone", "+79161234567"),
    ("пишите ivan.petrov@mail.ru", "email", "ivan.petrov@mail.ru"),
    ("карта 4111 1111 1111 1111", "card", "4111 1111 1111 1111"),
    ("карта 5536913812345678", "card", None),  # не проходит Луна — не карта
    ("номер карты 2202-2005-1234-5677", "card", "2202-2005-1234-5677"),
    ("ИНН 7707083893", "inn", "7707083893"),
    ("ИНН физлица 500100732259", "inn", "500100732259"),
    ("СНИЛС 112-233-445 95", "snils", "112-233-445 95"),
    ("паспорт серии 45 08 № 123456", "passport", "45 08 № 123456"),
    ("паспорт 4508123456", "passport", "4508123456"),
    ("счёт DE89 3704 0044 0532 0130 00", "iban", "DE89 3704 0044 0532 0130 00"),
]
for текст, вид, кусок in НАДО:
    найдено = виды(текст)
    if кусок is None:
        проверить(not any(в == вид for в, _ in найдено),
                  f"«{текст}»: без контрольной суммы не {вид}: {найдено}")
    else:
        проверить((вид, кусок) in найдено, f"«{текст}» → {вид}: {найдено}")

# --- не трогаем ---------------------------------------------------------------

НЕЛЬЗЯ = [
    "Выручка 12345678 рублей за 2026 год",
    "встреча в 10:30, созвон 15.10.2026",
    "план на 1500000 и ещё 300 000",
    "версия 0.11.0, сборка 20260930",
    "ИНН 7707083894",  # контрольная цифра неверна
    "ИНН 500100732250",  # у человека верна первая контрольная цифра, вторая нет
    "СНИЛС 112-233-445 96",
    "код 4508123456 из системы",  # как паспорт, но без слова «паспорт»
    "тариф 8 900 рублей в месяц",
    "IBAN DE89 3704 0044 0532 0130 01",
    "заказ № 1234567890123",
]
for текст in НЕЛЬЗЯ:
    проверить(виды(текст) == [], f"«{текст}» не тревожит: {виды(текст)}")

# --- пересечения и замена ------------------------------------------------------

т = "Иван, карта 4111 1111 1111 1111, телефон +7 916 123-45-67, почта a@b.ru"
проверить(personal.mask(т) == "Иван, карта [карта], телефон [телефон], почта [почта]",
          f"замена пометками: {personal.mask(т)!r}")
проверить([в for в, _ in виды("4111111111111111")] == ["card"],
          "16 цифр карты — одна карта, а не карта и телефон")
# Номер карты, который начинается как телефон: «8 916 123 45 67…». Если
# телефон перебьёт карту, скроется только начало, а хвост номера уйдёт.
похожая = "карта 8 916 123 45 67 123 44"
проверить(виды(похожая) == [("card", "8 916 123 45 67 123 44")],
          f"карта, похожая на телефон, скрывается целиком: {виды(похожая)}")
проверить(personal.mask(похожая) == "карта [карта]", f"без обрывков номера: {personal.mask(похожая)!r}")
проверить(personal.mask("") == "" and personal.find("") == [], "пустой текст не ломает")
длинный = ("обычный разговор без цифр. " * 4000) + "карта 4111 1111 1111 1111"
проверить(personal.mask(длинный).endswith("[карта]"), "длинная встреча разбирается до конца")

# --- что уходит на свой сервер --------------------------------------------------

сервис = AppService.__new__(AppService)
сервис.settings = settings_mod.Settings()


class Бэкенд:
    backend = "local"


сервис.llm = Бэкенд()
сообщения = [
    {"role": "system", "content": "правила"},
    {"role": "user", "content": "Моя карта 4111 1111 1111 1111, позвоните +7 916 123-45-67"},
]
проверить(сервис._for_model(сообщения) == сообщения,
          "своей модели на этом компьютере текст уходит как есть")
Бэкенд.backend = "remote"
ушло = сервис._for_model(сообщения)
проверить("4111" not in ушло[1]["content"] and "[карта]" in ушло[1]["content"]
          and "[телефон]" in ушло[1]["content"],
          f"на свой сервер карта и телефон уходят пометками: {ушло[1]['content']!r}")
проверить(сообщения[1]["content"].startswith("Моя карта 4111"),
          "исходные сообщения не испорчены: скрываем копию")
сервис.settings.llm.mask_personal_remote = False
проверить(сервис._for_model(сообщения) == сообщения,
          "если человек выключил скрытие, на сервер уходит как есть")
проверить(settings_mod.Settings().llm.mask_personal_remote is True,
          "по умолчанию скрытие для своего сервера включено")

проверить(сервис.set_copy_mode("masked") == "masked", "вид копирования «без личных данных» запоминается")
проверить(сервис.find_personal(["карта 4111 1111 1111 1111", "ничего", None])[0][0]["kind"] == "card",
          "окно получает находки по каждой реплике, мусор не роняет")

print()
if БЕДЫ:
    print(f"Бед: {len(БЕДЫ)}")
    raise SystemExit(1)
print("Личные данные находятся, случайные числа не тревожат.")
