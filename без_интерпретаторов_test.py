# -*- coding: utf-8 -*-
"""Программа не запускает интерпретаторы и не похожа на троян.

Беда, из-за которой это написано. В 0.9.0 уведомление с кнопками
показывалось запуском `powershell -ExecutionPolicy Bypass -Command ...`
в скрытом окне. Работало, но Microsoft Defender пометил установщик как
`Trojan:Win32/Wacatac.C!ml`: для эвристики это вылитое поведение
закрепившегося зловреда — чужой процесс поднимает интерпретатор,
обходит политику выполнения и прячет окно.

Цена такой приметы не «одна тревога из 75 в отчёте». Defender стоит у
каждого пользователя Windows и включён по умолчанию: человек просто не
сможет установить программу, а мы узнаем об этом из жалобы, если он
вообще напишет. До 0.9.0 отчёт был 0 из 75, стало 1 из 75 — это
регрессия, а не данность.

Поэтому здесь сторожим сам приём: в коде программы не должно быть
запуска powershell, cmd и прочих интерпретаторов. Всё, что нужно от
системы, берётся через её собственные API.
"""
from __future__ import annotations

import io
from pathlib import Path

import testenv  # noqa: F401  русский вывод в консоли Windows

КОРЕНЬ = Path(__file__).resolve().parent
ПРОГРАММА = КОРЕНЬ / "app"

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


# Приметы, на которые реагируют антивирусные эвристики. Каждая сама по
# себе законна, вместе — портрет зловреда.
ПРИМЕТЫ = {
    '"powershell"': "запуск PowerShell",
    "'powershell'": "запуск PowerShell",
    "powershell.exe": "запуск PowerShell",
    "-ExecutionPolicy": "обход политики выполнения",
    "ExecutionPolicy": "обход политики выполнения",
    "Bypass": "обход политики выполнения",
    "-EncodedCommand": "команда в base64: так прячут полезную нагрузку",
    "FromBase64String": "раскодирование команды на лету",
}

# Где приметы допустимы и почему.
РАЗРЕШЕНО = {
    # Тихая установка обновления: это запуск нашего же установщика,
    # подписанного и скачанного по контрольной сумме, а не сторонний
    # интерпретатор.
    "updater.py": ("ShellExecute", "запуск своего установщика"),
}


def проверить_код() -> None:
    """Ни один файл программы не поднимает интерпретатор."""
    найдено: list[str] = []
    for путь in sorted(ПРОГРАММА.rglob("*.py")):
        текст = io.open(путь, encoding="utf-8", errors="replace").read()
        # Пояснения в комментариях и строках документации не в счёт:
        # мы сторожим код, а рассказ о прошлой беде полезен.
        без_док = _выкинуть_пояснения(текст)
        for примета, чем_плоха in ПРИМЕТЫ.items():
            if примета in без_док:
                найдено.append("%s: %s (%s)" % (путь.name, примета, чем_плоха))
    проверить(not найдено,
              "в коде программы нет запуска интерпретаторов"
              + (":\n      " + "\n      ".join(найдено) if найдено else ""))


def _выкинуть_пояснения(текст: str) -> str:
    """Убрать комментарии и строки документации.

    Грубо, но достаточно: нам важно, что примета не в исполняемом коде.
    Тройные кавычки и всё после # выбрасываются.
    """
    куски: list[str] = []
    в_доке = False
    закрывашка = ""
    for строка in текст.split("\n"):
        without = строка
        if в_доке:
            if закрывашка in строка:
                в_доке = False
                without = строка.split(закрывашка, 1)[1]
            else:
                continue
        for кавычки in ('"""', "'''"):
            if кавычки in without:
                до, _, после = without.partition(кавычки)
                if кавычки in после:
                    without = до + после.split(кавычки, 1)[1]
                else:
                    в_доке = True
                    закрывашка = кавычки
                    without = до
                break
        without = without.split("#", 1)[0]
        куски.append(without)
    return "\n".join(куски)


def проверить_уведомления() -> None:
    """Уведомления показываются через API системы, а не запуском чего-то."""
    from app.ui import уведомления

    исходник = io.open(
        КОРЕНЬ / "app/ui/уведомления.py", encoding="utf-8"
    ).read()
    без_док = _выкинуть_пояснения(исходник)

    проверить("subprocess" not in без_док,
              "модуль уведомлений не запускает дочерних процессов")
    проверить("winrt" in без_док.lower(),
              "тост показывается через WinRT, то есть средствами самой Windows")
    проверить(hasattr(уведомления, "доступны"),
              "есть честная проверка доступности: без WinRT молчим, а не падаем")


def проверить_сборку() -> None:
    """Библиотеки WinRT попадают в дистрибутив.

    Без них тост не покажется у людей, хотя у меня на машине работает:
    ровно тот случай, когда беда видна только после выпуска.
    """
    конфиг = io.open(КОРЕНЬ / "pyproject.toml", encoding="utf-8").read()
    проверить("winrt-Windows.UI.Notifications" in конфиг,
              "библиотека уведомлений объявлена зависимостью")
    проверить("winrt-Windows.Data.Xml.Dom" in конфиг,
              "библиотека разбора XML объявлена зависимостью")


def main() -> int:
    проверить_код()
    проверить_уведомления()
    проверить_сборку()

    if БЕДЫ:
        print(f"\nНе прошло проверок: {len(БЕДЫ)}")
        return 1
    print("\nПрограмма не поднимает интерпретаторы: антивирусам не за что зацепиться.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
