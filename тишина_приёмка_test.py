# -*- coding: utf-8 -*-
"""Приёмка задачи №27 на настоящих устройствах.

Случай пользователя: включены обе дорожки, он говорит в микрофон, а в
системном звуке в это время ничего не играет. Речь распознаётся, встреча
пишется — и поверх всего этого висит «за 10 секунд не было ни звука».

Берём настоящий захват с настоящими устройствами, но одну дорожку
заведомо делаем немой: подменяем ей устройство на пустое. Так случай
пользователя воспроизводится на любой машине, а не только там, где в
колонках тишина. Вторая дорожка при этом настоящая, и если она даёт
звук, предупреждения быть не должно.

Проверка честно снимается с себя, когда железа нет (сборочная машина без
микрофона): лучше пропустить, чем позвать ложную тревогу.
"""
import testenv  # noqa: F401  песочница вместо боевого профиля

import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))

from app.audio import devices, wasapi
from app.core.events import RECORDING_SILENT, bus

ТИШИНЫ_ХВАТИТ = wasapi.ПОРОГ_ТИШИНЫ + 4.0


class НемоеУстройство:
    """Открывается без ошибок и отдаёт ровный ноль.

    Так ведёт себя настоящий системный выход, когда в нём ничего не
    играет: именно это и видел пользователь.

    Отдаёт блоки в темпе настоящего звука, а не так быстро, как может.
    Это не придирка: счётчик тишины считает секунды записанного, а не
    по часам на стене. Устройство, отвечающее мгновенно, набирает
    десять «секунд» тишины за сотую долю настоящей секунды — раньше,
    чем живой микрофон успеет отдать первый блок. Проверка тогда падает
    на гонке, которой в жизни нет, и заставляет чинить исправное.
    """

    name = "Немой выход"

    def recorder(self, **_):
        return self

    def __enter__(self):
        return self

    def __exit__(self, *_):
        return False

    def record(self, numframes):
        time.sleep(numframes / wasapi.SAMPLE_RATE)
        return np.zeros(numframes, dtype="float32")


пойманное = []
отписаться = bus.on(RECORDING_SILENT, пойманное.append)

захват = wasapi.WasapiCapture()
захват.capture_mic = True
захват.capture_system = True
захват.chunk_seconds = 1.0
захват.on_chunk = None

try:
    захват.start("приёмка-27")
except Exception as ошибка:  # нет звуковых устройств
    отписаться()
    print(f"[пропуск] звук на этой машине не поднялся: {ошибка}")
    sys.exit(0)

# Подменяем системную дорожку на заведомо немую: случай пользователя не
# должен зависеть от того, играет ли сейчас музыка в колонках того, кто
# гоняет проверку.
система = захват._tracks.get(devices.TRACK_THEM)
if система is not None:
    система.stop()
    система._opener = lambda: НемоеУстройство()
    система._проверка_окончена = False
    система._звук_был = False
    система._тишина_секунд = 0.0
    пойманное.clear()
    система.start()

try:
    начало = time.monotonic()
    микрофон = захват._tracks.get(devices.TRACK_ME)
    ожил_на = None
    время_вышло = начало + ТИШИНЫ_ХВАТИТ
    while time.monotonic() < время_вышло:
        if ожил_на is None and микрофон is not None and микрофон.звук_был:
            ожил_на = time.monotonic() - начало
        time.sleep(0.05)

    ошибки = захват.errors()
    микрофон_живой = микрофон is not None and микрофон.звук_был
    система_молчала = система is not None and not система.звук_был
finally:
    захват.stop()
    отписаться()

if ошибки:
    print(f"[пропуск] устройства не открылись: {ошибки}")
    sys.exit(0)

print(f"[..] микрофон слышал звук: {микрофон_живой}; "
      f"системный звук молчал: {система_молчала}; "
      f"микрофон ожил на {ожил_на if ожил_на is None else round(ожил_на, 1)} с")

if not система_молчала:
    print("[пропуск] немую дорожку подменить не удалось")
    sys.exit(0)
if not микрофон_живой:
    print("[пропуск] микрофон не дал ни одного ненулевого блока: "
          "случай пользователя на этой машине не воспроизвести")
    sys.exit(0)

assert not пойманное, (
    f"микрофон пишет живой звук, встреча идёт, а программа всё равно "
    f"кричит о тишине на второй дорожке: {пойманное}. Человек видит "
    f"идущую расшифровку и тревогу поверх неё — ровно то, на что жалоба "
    f"в задаче №27"
)

print(f"[ok] {ТИШИНЫ_ХВАТИТ:.0f} секунд: системная дорожка пишет ровный "
      f"ноль, микрофон живой, ложной тревоги нет")
print("\nЗадача №27: на настоящих устройствах плашка больше не появляется")
