# -*- coding: utf-8 -*-
"""Записи из Zoom и диктофона получают человеческое имя.

В живой базе пользователя нашлось тридцать записей из девяноста восьми,
названных `7246a5e7-0c69-4c6d-a5de-560b15b42cd8`, `audio (1)` или
`20260714165030`. Найти среди них нужную нельзя даже глазами: имена
ничего не говорят и ничем не отличаются друг от друга.

Имя файла всё равно остаётся главным источником: «Планерка 7 мая» лучше
любой выдумки. Подменяем только то, в чём человеку не за что зацепиться.
"""
import testenv  # noqa: F401  песочница вместо боевого профиля

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from app.asr.audiofile import AudioInfo, похоже_на_идентификатор


def заголовок(имя: str, папка: Path) -> str:
    файл = папка / f"{имя}.wav"
    файл.write_bytes(b"")
    info = AudioInfo(path=файл, duration=1.0, codec="pcm", sample_rate=16000,
                     channels=1)
    return info.title


# --- Имена, в которых человеку не за что зацепиться ----------------------
#
# Все до одного взяты из настоящей базы, а не выдуманы.
НЕПОНЯТНЫЕ = [
    "7246a5e7-0c69-4c6d-a5de-560b15b42cd8",
    "fe8314d4-481c-4e63-8a65-ce5c0a3cc697",
    "22ed6573-d978-4fb6-9605-e09848694464",
    "b1b22919-b0c0-45f8-8d67-f2a557efa7e0",
    "audio",
    "audio (1)",
    "audio (2)",
    "Recording",
    "recording (3)",
    "20260714165030",
]
for имя in НЕПОНЯТНЫЕ:
    assert похоже_на_идентификатор(имя), (
        f"имя «{имя}» не распознано как бессмысленное: человек снова "
        f"увидит его в списке встреч и не поймёт, что это за запись"
    )
print(f"[ok] {len(НЕПОНЯТНЫЕ)} бессмысленных имён распознаны")

# --- Осмысленные имена не трогаем ----------------------------------------
#
# Ошибиться сюда дороже: подменить название, которое человек написал
# сам, значит отнять его работу.
ХОРОШИЕ = [
    "Планерка 7 мая",
    "Созвон с Ромашкой",
    "Речка ретро",
    "интервью Петров",
    "2026-07-14 планерка",
    "zoom с клиентом",
    "аудиозапись встречи",
    "voice memo про найм",
    "Встреча 01.09 15:08",
    "af_heart_ phi-man-how-are_20260714_164440",
    "aidar_ speakстарый-_20260714_165030",
]
for имя in ХОРОШИЕ:
    assert not похоже_на_идентификатор(имя), (
        f"имя «{имя}» посчитали бессмысленным: программа переименует "
        f"то, что человек назвал сам, и он не найдёт свою встречу"
    )
print(f"[ok] {len(ХОРОШИЕ)} осмысленных имён оставлены как есть")

# --- Заголовок встречи на настоящих файлах -------------------------------
песочница = Path(__file__).parent / "_имена"
песочница.mkdir(exist_ok=True)
try:
    имя = заголовок("7246a5e7-0c69-4c6d-a5de-560b15b42cd8", песочница)
    assert имя.startswith("Запись "), имя
    # Не просто «есть цифры», а именно дата и время файла: ради них всё
    # и затевалось. «Запись недавно» не отвечает на вопрос «когда» и
    # снова делает записи неразличимыми.
    ожидали = time.strftime("%d.%m %H:%M")
    assert ожидали in имя, (
        f"в имени нет даты и времени записи: {имя!r}, ждали {ожидали!r}. "
        f"Человеку не за что зацепиться, стало не лучше прежнего"
    )
    print(f"[ok] запись из Zoom называется по времени: {имя}")

    своё = заголовок("Планерка 7 мая", песочница)
    assert своё == "Планерка 7 мая", своё
    print(f"[ok] своё название сохраняется: {своё}")

    # Два разных файла не должны слиться в одно имя: иначе в списке
    # снова будет каша, только другая.
    первый = песочница / "audio.wav"
    первый.write_bytes(b"")
    второй = песочница / "audio (1).wav"
    второй.write_bytes(b"")
    # Разводим время: в жизни записи делаются в разные минуты.
    прошлое = time.time() - 3600
    import os
    os.utime(первый, (прошлое, прошлое))
    и1 = AudioInfo(path=первый, duration=1, codec="pcm", sample_rate=16000,
                   channels=1).title
    и2 = AudioInfo(path=второй, duration=1, codec="pcm", sample_rate=16000,
                   channels=1).title
    assert и1 != и2, (
        f"две разные записи получили одно имя «{и1}»: в списке снова "
        f"будут неразличимые строки"
    )
    print(f"[ok] разные записи различаются по времени: {и1} / {и2}")
finally:
    for ф in песочница.glob("*"):
        ф.unlink()
    песочница.rmdir()

print("\nЗаписи из Zoom и диктофона больше не безымянные.")
