from pathlib import Path

from app.core import источники as ист
from app.storage import Store

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ok] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


# --- Имена файлов -----------------------------------------------------------
def когда(*args) -> float:
    return dt.datetime(*args).timestamp()


примеры = [
    ("2026-10-03_14-22-05_+79161234567", "+7 916 123-45-67", когда(2026, 10, 3, 14, 22, 5)),
    ("out-79161234567-101-20261003-142205-1696333325.123", "+7 916 123-45-67", когда(2026, 10, 3, 14, 22, 5)),
    ("Звонок 03.10.2026 14.22 89161234567", "+7 916 123-45-67", когда(2026, 10, 3, 14, 22)),
    ("call_2026-10-03 09.05_8 (916) 123-45-67", "+7 916 123-45-67", когда(2026, 10, 3, 9, 5)),
    ("Планёрка 2026-10-03 10-00", None, когда(2026, 10, 3, 10, 0)),
    ("audio (1)", None, None),
    ("2026-99-99_14-22-05", None, None),
]
for имя, номер, время in примеры:
    н, в = ист.разобрать_имя(имя)
    проверить(н == номер and в == время, f"«{имя}» → {н}, {dt.datetime.fromtimestamp(в) if в else None}")
проверить(ист.название(Path("x/out-7916.wav"), "+7 916 123-45-67", "Звонок") == "Звонок +7 916 123-45-67",
          "с номером встреча называется «Звонок +7 …»")
проверить(ист.название(Path("x/Планёрка_по_запуску.m4a"), None, "Звонок") == "Планёрка по запуску",
          "без номера — имя файла без подчёркиваний")


# --- Сторож -----------------------------------------------------------------
class Мир:
    def __init__(self, каталог: Path) -> None:
        self.каталог = каталог
        self.взято: dict[tuple[str, str], str] = {}
        self.импорт: list[tuple[str, str, float | None]] = []
        self.проба_кончилась = False

    def папки(self):
        return [{"id": "f1", "source": str(self.каталог)}, {"id": "f2", "source": ""}]

    def уже_взят(self, папка, след):
        return (папка, след) in self.взято

    def отметить(self, папка, след, путь):
        self.взято[(папка, след)] = путь

    def импорт_(self, путь, папка, название, когда):
        if self.проба_кончилась:
            return "trial"
        self.импорт.append((Path(путь).name, название, когда))
        return "ok"


def записать(путь: Path, данные: bytes, давно: bool = True) -> None:
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_bytes(данные)
    if давно:
        t = time.time() - 60
        os.utime(путь, (t, t))


with tempfile.TemporaryDirectory() as tmp:
    каталог = Path(tmp) / "Звонки"
    мир = Мир(каталог)
    сторож = ист.СторожПапок(мир.папки, мир.уже_взят, мир.отметить, мир.импорт_,
                             слово_звонок=lambda: "Звонок")

    записать(каталог / "2026" / "10" / "out-79161234567-20261003-142205.wav", b"RIFF" + os.urandom(200_000))
    записать(каталог / "заметки.txt", b"not audio")
    записать(каталог / "пусто.mp3", b"")
    сторож.обойти()
    проверить(not мир.импорт, "первый обход только запоминает размер: файл мог ещё писаться")
    сторож.обойти()
    проверить(len(мир.импорт) == 1 and мир.импорт[0][1] == "Звонок +7 916 123-45-67",
              f"на втором обходе запись взята, из подпапки, с номером: {мир.импорт}")
    проверить(мир.импорт[0][2] == когда(2026, 10, 3, 14, 22, 5), "время встречи — время звонка из имени файла")
    сторож.обойти()
    проверить(len(мир.импорт) == 1, "третий обход файл не берёт повторно")
    проверить(all(имя.endswith(".wav") for имя, _, _ in мир.импорт), "текст и пустой файл не берутся")

    (каталог / "2026" / "10" / "out-79161234567-20261003-142205.wav").rename(каталог / "переименован.wav")
    сторож.обойти()
    сторож.обойти()
    проверить(len(мир.импорт) == 1, "переименованный файл не берётся второй раз: отпечаток по содержимому")

    # Файл пишется: размер растёт между обходами.
    пишется = каталог / "идёт_звонок.mp3"
    записать(пишется, b"ID3" + os.urandom(1000), давно=False)
    сторож.обойти()
    with пишется.open("ab") as f:
        f.write(os.urandom(5000))
    сторож.обойти()
    проверить(len(мир.импорт) == 1, "растущий файл не берётся, пока его дописывают")
    t = time.time() - 60
    os.utime(пишется, (t, t))
    сторож.обойти()
    сторож.обойти()
    проверить(len(мир.импорт) == 2, "дописанный и затихший файл взят")

    # Пробный период кончился.
    мир.проба_кончилась = True
    записать(каталог / "после_пробы.ogg", b"OggS" + os.urandom(3000))
    сторож.обойти()
    сторож.обойти()
    проверить(сторож.состояние("f1").get("trial") is True, "папка показывает, что пробные встречи кончились")
    проверить(len(мир.взято) == 2, "файл после пробы не помечен взятым")
    мир.проба_кончилась = False
    сторож.обойти()
    проверить(len(мир.импорт) == 3 and not сторож.состояние("f1").get("trial"),
              "с лицензией отложенный файл приходит сам")

    # Каталог пропал.
    мир2 = Мир(Path(tmp) / "нет_такой")
    с2 = ист.СторожПапок(мир2.папки, мир2.уже_взят, мир2.отметить, мир2.импорт_, lambda: "Звонок")
    с2.обойти()
    проверить(с2.состояние("f1").get("error") == "missing", "пропавший каталог виден как ошибка, а не тишина")

    # «Только новые»: лежащий архив помечается взятым без разбора.
    архив = Path(tmp) / "Архив"
    for i in range(5):
        записать(архив / f"звонок_{i}.mp3", b"ID3" + os.urandom(2000 + i))
    мир3 = Мир(архив)
    с3 = ист.СторожПапок(мир3.папки, мир3.уже_взят, мир3.отметить, мир3.импорт_, lambda: "Звонок")
    проверить(с3.взять_как_есть("f1", архив) == 5, "«только новые»: пять лежащих записей помечены взятыми")
    с3.обойти()
    с3.обойти()
    проверить(not мир3.импорт, "архив не разбирается")
    записать(архив / "новый.mp3", b"ID3" + os.urandom(9000))
    с3.обойти()
    с3.обойти()
    проверить([и[0] for и in мир3.импорт] == ["новый.mp3"], "новая запись после подключения взята")

    # --- База: отпечатки переживают перезапуск ------------------------------
    база = Store(str(Path(tmp) / "k.db"))
    папка = база.create_folder("Звонки")
    проверить(база.set_folder_source(папка["id"], str(каталог)), "каталог сохраняется у папки")
    проверить(база.list_folders()[0]["source"] == str(каталог), "папка помнит каталог")
