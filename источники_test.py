"""Папка-источник: записи из каталога на диске сами становятся встречами.

Проверяем то, что бьёт по человеку:
- недописанный файл не берётся: АТС пишет звонок минутами, облачный диск
  тянет файл частями, и полвстречи хуже, чем встреча через минуту;
- взятый файл не берётся снова, в том числе после переименования и
  перезапуска программы (отпечатки в базе);
- после пробного периода файлы не помечаются взятыми и придут с лицензией;
- «только новые» при подключении не трогает лежащий архив;
- номер и время звонка достаются из имён файлов разных АТС.
"""
from __future__ import annotations

import testenv  # noqa: F401

import datetime as dt
import os
import tempfile
