"""Докачка обязана переживать обрывы, а не начинать файл заново.

Из-за чего написано. Модель для заметок весит 1.8 ГБ, и на живом канале
она не скачивалась никогда: журнал показывал «скачано 0 байт» раз за
разом. Причина была не в канале. При обрыве посреди файла код стирал
весь недокачанный кусок, поэтому каждая следующая попытка начинала с
нуля и снова не успевала. Модель распознавания на 214 МБ при этом
доходила за семь заходов, и беда выглядела как «большие файлы почему-то
не качаются».

Проверка идёт против настоящего HTTP-сервера, который честно рвёт
соединение на середине: подделкой такую ошибку не поймать, она живёт
именно в разборе оборванного ответа.
"""

import testenv  # noqa: F401  русский вывод в консоли Windows

import http.server
import tempfile
import threading
from pathlib import Path

from app.asr import download as загрузка

# Файл, который «отдаёт» сервер. Небольшой: важна не длина, а то,
# что соединение рвётся, не дойдя до конца.
РАЗМЕР = 300_000
СОДЕРЖИМОЕ = bytes(range(256)) * (РАЗМЕР // 256)

# Сколько раз сервер оборвёт связь, прежде чем отдать файл целиком.
ОБРЫВОВ = 3

ПРОВАЛЫ: list[str] = []


def проверить(условие: bool, что: str) -> None:
    print(("[ok] " if условие else "[FAIL] ") + что)
    if not условие:
        ПРОВАЛЫ.append(что)


class Рвущийся(http.server.BaseHTTPRequestHandler):
    """Отдаёт кусок и обрывает соединение, как настоящий слабый канал."""

    осталось_обрывов = ОБРЫВОВ
    отдано: list[int] = []

    def log_message(self, *_а) -> None:  # тишина в выводе теста
        pass

    def do_GET(self) -> None:
        начало = 0
        диапазон = self.headers.get("Range")
        if диапазон:
            начало = int(диапазон.split("=")[1].split("-")[0])

        хвост = СОДЕРЖИМОЕ[начало:]
        код = 206 if диапазон else 200
        self.send_response(код)
        self.send_header("Content-Length", str(len(хвост)))
        if диапазон:
            self.send_header(
                "Content-Range", f"bytes {начало}-{len(СОДЕРЖИМОЕ) - 1}/{len(СОДЕРЖИМОЕ)}"
            )
        self.end_headers()

        Рвущийся.отдано.append(начало)
        if Рвущийся.осталось_обрывов > 0:
            Рвущийся.осталось_обрывов -= 1
            # Отдаём треть и обрываемся: ровно то, что делает слабый канал.
            self.wfile.write(хвост[: len(хвост) // 3])
            self.close_connection = True
            return
        self.wfile.write(хвост)


def main() -> int:
    проверить_обрывы_и_докачку()
    return 1 if ПРОВАЛЫ else 0


def проверить_готовый_файл() -> None:
    """Готовый файл на диске обязан прекращать загрузку.

    Из-за чего написано. Модель заметок положили в каталог рядом, пока
    программа её качала. Загрузка этого не заметила и продолжала тянуть
    те же 1.8 ГБ ещё час, потому что готовность проверялась только перед
    первой попыткой. То же самое бывает, когда файл дотянул другой
    экземпляр программы.
    """
    with tempfile.TemporaryDirectory() as врем:
        куда = Path(врем)
        (куда / "ves.bin").write_bytes(СОДЕРЖИМОЕ)
        (куда / "ves.bin.part").write_bytes(СОДЕРЖИМОЕ[:100])
        до = len(Рвущийся.отдано)

        качалка = загрузка.ModelDownloader("test/repo", ("ves.bin",), куда)
        качалка.run_blocking()

        проверить(
            len(Рвущийся.отдано) == до,
            "при готовом файле в сеть не ходим вовсе",
        )
        проверить(
            not (куда / "ves.bin.part").exists(),
            "остаток недокачанного куска убран",
        )


def проверить_обрывы_и_докачку() -> int:
    сервер = http.server.HTTPServer(("127.0.0.1", 0), Рвущийся)
    поток = threading.Thread(target=сервер.serve_forever, daemon=True)
    поток.start()
    порт = сервер.server_address[1]

    # Подменяем только адрес: весь остальной путь настоящий.
    было = загрузка.HF_BASE
    загрузка.HF_BASE = f"http://127.0.0.1:{порт}/{{repo}}/{{name}}"
    пауза = загрузка.RETRY_PAUSE
    загрузка.RETRY_PAUSE = 0.01

    try:
        with tempfile.TemporaryDirectory() as врем:
            куда = Path(врем)
            качалка = загрузка.ModelDownloader("test/repo", ("ves.bin",), куда)
            качалка.run_blocking()

            готовый = куда / "ves.bin"
            проверить(готовый.exists(), "файл докачался, несмотря на обрывы")
            if готовый.exists():
                проверить(
                    готовый.read_bytes() == СОДЕРЖИМОЕ,
                    "содержимое совпадает с исходным, склейки нет",
                )

            # Главное: каждая попытка продолжала с места обрыва, а не с нуля.
            начала = Рвущийся.отдано
            print(f"     запросы начинались с байтов: {начала}")
            проверить(
                len(начала) > 1 and all(н > 0 for н in начала[1:]),
                "докачка продолжала с места обрыва, а не начинала заново",
            )
            проверить(
                начала == sorted(начала),
                "загрузка шла вперёд, а не откатывалась назад",
            )

        проверить_готовый_файл()
    finally:
        загрузка.HF_BASE = было
        загрузка.RETRY_PAUSE = пауза
        сервер.shutdown()

    if ПРОВАЛЫ:
        print(f"\nПровалено проверок: {len(ПРОВАЛЫ)}")
        return 1
    print("\nДокачка переживает обрывы: большие модели дойдут до конца.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
