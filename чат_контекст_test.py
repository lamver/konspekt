# -*- coding: utf-8 -*-
"""Чат по встрече: модель видит нужные отрывки и помнит переписку.

Жалоба со снимка экрана (30 сентября): на «кто ты?», «1+6», «+9», «+3»
модель отвечала «Я помощник по встрече», «Сегодня, 06.09», «06.09» —
будто каждый вопрос первый, а о встрече ей ничего не известно.

Две беды, от которых это сторожит:

1. В модель уходила вся расшифровка, а длинная — обрезанной с начала.
   Вопрос про начало часовой встречи оставался без ответа, а каждый
   вопрос заново гнал через модель десятки тысяч знаков.
2. Короткие продолжения вроде «+9» и «а он?» ничего не находят сами по
   себе: без прошлых вопросов в поиске модель получала случайные куски.
"""
from __future__ import annotations

import testenv  # noqa: F401  песочница вместо боевого профиля

import numpy as np

from app.llm import context as ctx_mod
from app.llm.chunking import estimate_tokens
from app.llm.prompts import chat_messages

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


# --- Длинная встреча: нужное место в начале --------------------------------

ВОДА = [
    "обсуждали погоду и планы на выходные, ничего конкретного",
    "говорили про общие вещи, кто куда ездил летом и что видел",
    "вспоминали прошлый квартал в целом, без цифр и без решений",
    "перебирали мелочи по офису, кофе, парковку и расписание",
]


def встреча() -> list[dict]:
    реплики = [
        {"text": "Договорились: Лёвин готовит лекцию про оплату картой к пятнице.",
         "start": 30.0, "who": "Маша"},
        {"text": "Я возьму на себя проверку платежей по картам на стенде.",
         "start": 45.0, "who": "Петя"},
    ]
    t = 60.0
    for i in range(400):
        реплики.append({"text": f"{ВОДА[i % 4]}, пункт {i}.", "start": t, "who": "Собеседник"})
        t += 10.0
    реплики.append({"text": "Итог: созвон в среду, все свободны.", "start": t, "who": "Маша"})
    return реплики


РЕПЛИКИ = встреча()
всё_целиком = "\n".join(f"{r['who']}: {r['text']}" for r in РЕПЛИКИ)
проверить(estimate_tokens(всё_целиком) > 3 * ctx_mod.CONTEXT_TOKENS,
          f"встреча для проверки длинная: {estimate_tokens(всё_целиком)} токенов")

к = ctx_mod.build(РЕПЛИКИ, "Кто готовит лекцию про оплату?", [])
проверить(not к.whole, "длинная встреча не уходит в модель целиком")
проверить("Лёвин" in к.transcript,
          "вопрос про начало встречи находит ответ в начале, а не отрезает его")
проверить(estimate_tokens(к.transcript) <= ctx_mod.CONTEXT_TOKENS + 100,
          f"отрывки укладываются в бюджет: {estimate_tokens(к.transcript)} токенов")
проверить("[0:30]" in к.transcript or "[0:" in к.transcript,
          "у отрывка есть отметка времени, чтобы найти место")
проверить("Маша" in к.transcript, "у отрывка есть говорящий")
проверить("Петя: Я возьму на себя" in к.transcript,
          "у каждой реплики в отрывке свой говорящий, а не только у первой")

# --- Соседи: фраза видна вместе с тем, к чему сказана ---------------------

куски = ctx_mod.chunk_segments(РЕПЛИКИ)
номер = next(i for i, c in enumerate(куски) if "Лёвин" in c["text"])
проверить(len(к.starts) >= 2 and куски[номер + 1]["start"] in к.starts,
          "вместе с найденным куском идёт соседний")

# --- «+9» ищет по прошлому вопросу ----------------------------------------

история = [
    {"role": "user", "content": "Кто готовит лекцию про оплату?"},
    {"role": "assistant", "content": "Лёвин, к пятнице."},
]
# Нужная фраза в середине, чтобы её не подобрал запасной вариант «начало
# и конец»: найти её можно только по прошлому вопросу.
в_середине = РЕПЛИКИ[2:200] + РЕПЛИКИ[:2] + РЕПЛИКИ[200:]
к2 = ctx_mod.build(в_середине, "а он?", история)
проверить("Лёвин" in к2.transcript,
          "короткое продолжение ищет вместе с прошлым вопросом")
проверить(len(к2.history) == 2 and к2.history[0]["role"] == "user",
          "прошлая переписка идёт в модель")

# --- Слова находят место в середине встречи --------------------------------
#
# В начале и конце встречи искомого нет, поэтому запасной вариант «начало
# и конец» тут не выручит: найти можно только по словам.

с_серединой = [dict(r) for r in РЕПЛИКИ[2:]]
с_серединой.insert(150, {"text": "Бюджет на рекламу утвердили: триста тысяч в месяц.",
                         "start": с_серединой[150]["start"] - 5, "who": "Оля"})
кс = ctx_mod.build(с_серединой, "какой бюджет на рекламу?", [])
проверить("триста тысяч" in кс.transcript, "по словам находится место в середине встречи")

# Соседи: ответ на вопрос часто в следующей реплике после найденной.
с_ответом = [dict(r) for r in РЕПЛИКИ[2:]]
с_ответом.insert(150, {"text": "Кто подпишет договор с подрядчиком?",
                       "start": с_ответом[150]["start"] - 5, "who": "Оля"})
куски_о = ctx_mod.chunk_segments(с_ответом)
н = next(i for i, c in enumerate(куски_о) if "подпишет" in c["text"])
с_ответом.insert(с_ответом.index(next(r for r in с_ответом if r["start"] == куски_о[н + 1]["start"])),
                 {"text": "Лично Григорьев, в среду.", "start": куски_о[н + 1]["start"] - 0.5, "who": "Иван"})
ко = ctx_mod.build(с_ответом, "кто подпишет договор?", [])
проверить("Григорьев" in ко.transcript,
          "ответ из соседнего куска тоже попадает к модели")

# Бюджет: вопрос, слова которого есть в каждом куске, не должен
# притащить всю встречу.
# Бюджет урезан, чтобы шести лучших кусков с соседями в него не влезло.
было = ctx_mod.CONTEXT_TOKENS
ctx_mod.CONTEXT_TOKENS = 300
try:
    кб = ctx_mod.build(РЕПЛИКИ, "пункт обсуждали говорили вспоминали перебирали", [])
finally:
    ctx_mod.CONTEXT_TOKENS = было
проверить(estimate_tokens(кб.transcript) <= 300 + 60,
          f"отрывки не выходят за бюджет: {estimate_tokens(кб.transcript)} из 300")

# --- Смысл помогает, когда слов из вопроса в тексте нет --------------------


def вектор(текст: str) -> np.ndarray:
    """Игрушечный «смысл»: платёжная тема против всего остального."""
    платёж = any(с in текст.lower() for с in ("оплат", "карт", "платеж", "деньг", "заплатить"))
    v = np.array([1.0, 0.05] if платёж else [0.05, 1.0], dtype=np.float32)
    return v / np.linalg.norm(v)


# Платёжная фраза в середине: там её не спасает запасной вариант «начало
# и конец», и найти её можно только по смыслу.
середина = [dict(r) for r in РЕПЛИКИ[2:]]
середина.insert(200, {"text": "Клиенты смогут вносить деньги картой прямо в приложении.",
                      "start": середина[200]["start"] - 5, "who": "Петя"})
куски_с = ctx_mod.chunk_segments(середина)
начала = [c["start"] for c in куски_с]
векторы = np.vstack([вектор(c["text"]) for c in куски_с])
к3 = ctx_mod.build(середина, "как оплатить покупку?", [], (начала, векторы), вектор)
проверить("вносить деньги" in к3.transcript,
          "по смыслу находится кусок без общих слов с вопросом")
к3б = ctx_mod.build(середина, "как оплатить покупку?", [], None, None)
проверить("вносить деньги" not in к3б.transcript,
          "без смысла тот же вопрос кусок не находит (проверка смысла не пустая)")

начала = [c["start"] for c in куски]
векторы = np.vstack([вектор(c["text"]) for c in куски])


def сломанный(_):
    raise RuntimeError("модель смысла упала")


к4 = ctx_mod.build(РЕПЛИКИ, "Кто готовит лекцию?", [], (начала, векторы), сломанный)
проверить("Лёвин" in к4.transcript, "упавшая модель смысла не ломает чат, ищем по словам")

# --- Общий вопрос: начало и конец ------------------------------------------

к5 = ctx_mod.build(РЕПЛИКИ, "о чём?", [])
проверить("Итог" in к5.transcript and "Лёвин" in к5.transcript,
          "на общий вопрос модель видит начало и конец встречи")

# --- Короткая встреча целиком ----------------------------------------------

короткая = РЕПЛИКИ[:3]
к6 = ctx_mod.build(короткая, "что угодно", [])
проверить(к6.whole and "Лёвин" in к6.transcript and "проверку платежей" in к6.transcript,
          "короткая встреча уходит целиком")

# --- Переписка: свежее остаётся, начинается с вопроса ----------------------

длинная_история = []
for i in range(30):
    длинная_история.append({"role": "user", "content": f"вопрос {i} " + "слово " * 40})
    длинная_история.append({"role": "assistant", "content": f"ответ {i} " + "слово " * 40})
обрезано = ctx_mod.trim_history(длинная_история)
проверить(обрезано and обрезано[-1]["content"].startswith("ответ 29"),
          "из длинной переписки остаются свежие сообщения")
проверить(len(обрезано) <= ctx_mod.HISTORY_MESSAGES, f"переписка обрезана: {len(обрезано)} сообщений")
проверить(обрезано[0]["role"] == "user", "обрезанная переписка начинается с вопроса человека")
нечётная = длинная_история[:-1]  # последним стоит вопрос без ответа
обрезано2 = ctx_mod.trim_history(нечётная)
проверить(обрезано2 and обрезано2[0]["role"] == "user",
          "и при нечётном срезе переписка не начинается с ответа модели")

# --- Счёт без встречи ------------------------------------------------------
#
# На «1+6» модель с приложенными отрывками пересказывала их вместо ответа.

for q in ("1+6", "+9", "?", "  +3 "):
    кс = ctx_mod.build(РЕПЛИКИ, q, история)
    проверить(not кс.attach and кс.transcript == "",
              f"к «{q.strip()}» встреча не прикладывается")
    мс = chat_messages("Планёрка", кс.transcript, кс.history, q, attach=кс.attach)
    проверить(мс[-1]["content"] == q.strip() and len(мс) == 4,
              f"«{q.strip()}» уходит голым вопросом после переписки")
проверить(ctx_mod.build(РЕПЛИКИ, "а он?", история).attach,
          "к вопросу со словами встреча прикладывается")

# --- Промпт: отрывки названы отрывками -------------------------------------

m = chat_messages("Планёрка", к.transcript, к.history, "Кто?", whole=False)
проверить("Это не вся встреча" in m[-1]["content"],
          "модели сказано, что это отрывки, а не вся встреча")
m2 = chat_messages("Планёрка", к6.transcript, [], "Кто?", whole=True)
проверить("Это не вся встреча" not in m2[-1]["content"], "целую встречу отрывками не называем")
проверить("Лёвин" in m[-1]["content"] and m[-1]["content"].rstrip().endswith("Вопрос: Кто?"),
          "текст встречи лежит рядом с вопросом, вопрос последним")
проверить("Лёвин" not in m[0]["content"],
          "в системном сообщении нет встречи: на ней модель повторяла вопрос эхом")
проверить("продолжает предыдущий вопрос" in m[0]["content"],
          "модели объяснено, что короткие реплики продолжают разговор")
проверить("+9" not in m[0]["content"],
          "в правилах нет примера «+9»: маленькая модель копирует его в ответ")
m3 = chat_messages("Планёрка", "Я: привет", история, "+9")
проверить([x["role"] for x in m3] == ["system", "user", "assistant", "user"],
          "переписка идёт в модель по ролям, вопрос последним")
проверить(m3[1]["content"] == история[0]["content"],
          "в переписке голые вопросы, без старых отрывков встречи")

print()
if БЕДЫ:
    print(f"Бед: {len(БЕДЫ)}")
    raise SystemExit(1)
print("Чат видит нужные отрывки встречи и помнит переписку.")
