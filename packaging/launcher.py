"""Точка входа для собранного приложения.

PyInstaller запускает указанный файл как самостоятельный скрипт, а не как
модуль пакета. Из-за этого относительные импорты внутри `app/__main__.py`
(`from .core import paths`) падают с ImportError: пакета вокруг них нет.
Поэтому в сборке стартуем отсюда и зовём ту же функцию обычным импортом.

В режиме разработки этот файл не нужен, там работает `python -m app`.
"""

from __future__ import annotations

import multiprocessing
import sys

if __name__ == "__main__":
    # Без этого дочерние процессы в собранном приложении заново запускают
    # само приложение: в exe нет отдельного интерпретатора, и каждый
    # spawn открывает второе окно.
    multiprocessing.freeze_support()

    # Проверить сборку снаружи нельзя: код библиотек лежит внутри exe, а
    # не файлами на диске, и проверка «импортируем и посмотрим» молча
    # берёт библиотеку из окружения разработчика и говорит «всё хорошо».
    # Поэтому сборка проверяет себя сама: с этим ключом окна нет, она
    # печатает итог и выходит.
    if "--самопроверка" in sys.argv:
        from app.самопроверка import проверить

        sys.exit(проверить())

    from app.__main__ import main

    sys.exit(main())
