# -*- coding: utf-8 -*-
"""Закрытая задача должна быть сделана на самом деле.

Задачу легко закрыть по памяти: «я же это делал». Но человек получает не
исходники и не чьи-то воспоминания, а дистрибутив. Поэтому каждое
обещание сверяется с кодом и, где возможно, с собранной программой.

Печатаем, ЧТО именно нашли, а не просто «ок»: строчка «ок» без
доказательства ничем не лучше честного слова.

Проверка однажды уже сработала на себе: искала play_chunk, которого
никогда не было, и чуть не объявила сделанную работу несделанной.
Поэтому ищем цепочку целиком, а не одно угаданное имя.
"""
import testenv  # noqa: F401  русский вывод и песочница вместо боевого профиля

import json
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).parent
СБОРКА = КОРЕНЬ / "dist" / "Konspekt"
ВНУТРИ = СБОРКА / "_internal"
ЕСТЬ_СБОРКА = (ВНУТРИ / "web").exists()

провал = 0
# Какие задачи проверены. Считаем сами, а не числом в конце: число
# разъехалось бы с реальностью при первой же новой задаче.
проверены: list[int] = []


def сказать(номер, обещание, хорошо, доказательство):
    global провал
    проверены.append(номер)
    метка = "OK   " if хорошо else "ПЛОХО"
    if not хорошо:
        провал += 1
    print(f"[{метка}] #{номер}: {обещание}")
    print(f"         {доказательство}")


def есть_в(файл: Path, *куски: str) -> tuple[bool, str]:
    if not файл.exists():
        return False, f"нет файла {файл}"
    текст = файл.read_text(encoding="utf-8", errors="replace")
    пропало = [к for к in куски if к not in текст]
    if пропало:
        return False, f"в {файл.name} нет: {пропало}"
    return True, f"{файл.name}: всё на месте ({len(куски)} признаков)"


def закрытые_задачи() -> dict[int, str] | None:
    """Закрытые задачи из трекера, или None, если он недоступен.

    Молчим, когда нет сети или `gh`: на чужой машине и в сборке трекера
    быть не должно, и падать из-за этого значит приучать себя
    пропускать красное.
    """
    try:
        ответ = subprocess.run(
            ["gh", "issue", "list", "--state", "closed",
             "--json", "number,title", "--limit", "60"],
            capture_output=True, text=True, encoding="utf-8",
            shell=True, timeout=30,
        )
        if ответ.returncode != 0:
            return None
        return {з["number"]: з["title"] for з in json.loads(ответ.stdout)}
    except Exception:
        return None


# --- #1 Сборка билда ------------------------------------------------------
#
# Здесь и дальше: если сборки нет, смотрим исходники. На чужой
# машине дистрибутива и не должно быть, а падать из-за этого —
# значит приучать себя пропускать красное.
exe = СБОРКА / "Konspekt.exe"
спек = КОРЕНЬ / "packaging" / "konspekt.spec"
сказать(
    1, "Сборка билда для передачи пользователям",
    спек.exists(),
    (f"собранный exe есть, {exe.stat().st_size // 1024 // 1024} МБ"
     if exe.exists() else f"сборки нет, но есть рецепт {спек.name}"),
)

# --- #2 Локализация на четыре языка ---------------------------------------
языки = ["ru", "en", "es", "sr"]
где_словари = (ВНУТРИ if ЕСТЬ_СБОРКА else КОРЕНЬ) / "web" / "i18n"
размеры = {}
for я in языки:
    ф = где_словари / f"{я}.json"
    if ф.exists():
        размеры[я] = len(json.loads(ф.read_text(encoding="utf-8")))
сказать(
    2, "Локализация интерфейса: ru, en, es, sr",
    len(размеры) == 4,
    f"словари ({'сборка' if ЕСТЬ_СБОРКА else 'исходники'}): {размеры}",
)

# --- #3 Режим диктовки ----------------------------------------------------
#
# Одно слово «dictation» в настройках ничего не доказывает: галочка
# без работы за ней — тоже «dictation». Смотрим всю цепочку: горячая
# клавиша, сама диктовка и вставка текста в чужое окно.
диктовка_файлы = [
    п
    for п in (КОРЕНЬ / "app").rglob("*.py")
    if "dictation" in п.read_text(encoding="utf-8", errors="replace").lower()
    or "\u0434иктовк" in п.read_text(encoding="utf-8", errors="replace").lower()
]
хорошо_настр, док_настр = есть_в(
    КОРЕНЬ / "app" / "core" / "settings.py", "dictation", "hotkey", "paste_method"
)
сказать(
    3, "Режим диктовки: текст в активное поле другого приложения",
    хорошо_настр and len(диктовка_файлы) >= 2,
    док_настр + "; модулей с диктовкой: "
    + str([п.name for п in диктовка_файлы][:6]),
)

# --- #4 Удаление данных ---------------------------------------------------
#
# Удаление должно убирать и записи с диска, иначе «удалил» значит
# только «спрятал из списка», а звук остался лежать.
хорошо_api, док_api = есть_в(КОРЕНЬ / "app" / "ui" / "api.py", "delete_meeting")
хорошо_серв, док_серв = есть_в(
    КОРЕНЬ / "app" / "core" / "service.py", "def delete_meeting"
)
сказать(
    4, "Удаление данных",
    хорошо_api and хорошо_серв,
    f"{док_api}; {док_серв}",
)

# --- #8 Прослушать кусок аудио рядом с репликой ---------------------------
#
# Проверяем всю цепочку, а не одно имя: мост наружу, работа в сервисе и
# вызов из окна. Кнопка, за которой ничего нет, обещание не выполняет.
хорошо_api, док_api = есть_в(КОРЕНЬ / "app" / "ui" / "api.py", "audio_clip")
хорошо_серв, док_серв = есть_в(КОРЕНЬ / "app" / "core" / "service.py", "def audio_clip")
хорошо_окно, док_окно = есть_в(
    (ВНУТРИ if ЕСТЬ_СБОРКА else КОРЕНЬ) / "web" / "app.js", "audio_clip"
)
сказать(
    8, "Прослушать кусок аудио рядом с репликой",
    хорошо_api and хорошо_серв and хорошо_окно,
    f"{док_api}; {док_серв}; в сборке {док_окно}",
)

# --- #22 Публичный репозиторий релизов ------------------------------------
latest = КОРЕНЬ / "tools" / "обновить_latest.py"
сказать(
    22, "Публичный репозиторий для релизов и документации",
    latest.exists(),
    f"{latest} есть" if latest.exists() else "нет инструмента обновления latest.json",
)

# --- #25 Лицензии моделей и NOTICE ----------------------------------------
notice = next(
    (п for п in [КОРЕНЬ / "NOTICE", КОРЕНЬ / "NOTICE.md", ВНУТРИ / "NOTICE"] if п.exists()),
    None,
)
сказать(
    25, "Лицензии моделей и файл NOTICE",
    notice is not None,
    f"{notice} есть, {notice.stat().st_size} байт" if notice else "NOTICE не найден",
)

# --- #28 Системный звук: спрашивать, а не решать --------------------------
хорошо, док = есть_в(
    КОРЕНЬ / "app" / "audio" / "wasapi.py", "_следить_за_чужой_речью", "только_слушать"
)
сторож = (КОРЕНЬ / "app" / "audio" / "сторож.py").exists()
сказать(
    28, "Системный звук: спрашивать, а не решать за человека",
    хорошо and сторож,
    док + f"; сторож вне записи: {сторож}",
)

# --- #27 Ложное предупреждение о тишине -----------------------------------
хорошо, док = есть_в(
    КОРЕНЬ / "app" / "audio" / "wasapi.py", "_сосед_живой", "_дорожка_слышит"
)
сказать(27, "Ложное предупреждение о тишине", хорошо, док)

# --- #26 Копирование текста и диктовка в поле ввода ------------------------
#
# Обе половины задачи: забрать текст из программы и продиктовать вопрос.
# Смотрим и разметку, и код окна, и мост: кнопка без обработчика или
# обработчик без кнопки обещание не выполняют.
разметка = (ВНУТРИ if ЕСТЬ_СБОРКА else КОРЕНЬ) / "web" / "index.html"
окно = (ВНУТРИ if ЕСТЬ_СБОРКА else КОРЕНЬ) / "web" / "app.js"
хорошо_кнопки, док_кнопки = есть_в(разметка, "summary-copy", "chat-mic")
хорошо_код, док_код = есть_в(
    окно, "цитатаРеплики", "toggleFieldDictation", "bubble__copy",
)
хорошо_мост, док_мост = есть_в(
    КОРЕНЬ / "app" / "ui" / "api.py",
    "start_field_dictation", "finish_field_dictation",
)
сказать(
    26, "Копирование текста и диктовка в поле ввода",
    хорошо_кнопки and хорошо_код and хорошо_мост,
    f"{док_кнопки}; {док_код}; {док_мост}",
)

print()
print(f"закрытых задач подтверждено: {len(проверены) - провал}/{len(проверены)}")

# Самое важное: проверка должна знать про ВСЕ закрытые задачи, а не
# только про те, что я вспомнил. Иначе она будет бодро отчитываться
# «всё хорошо», пока новая закрытая задача тихо остаётся без проверки.
# Ровно так и вышло с №26 через час после написания этой проверки.
закрытые = закрытые_задачи()
if закрытые is None:
    print("[..] трекер недоступен, полноту покрытия не сверяли")
else:
    забытые = sorted(set(закрытые) - set(проверены))
    assert not забытые, (
        f"закрытые задачи без проверки: "
        + ", ".join(f"#{н} {закрытые[н]}" for н in забытые)
        + ". Закрытая задача, которую никто не стережёт, тихо расклеивается"
    )
    print(f"[ok] все {len(закрытые)} закрытых задач покрыты проверкой")

sys.exit(1 if провал else 0)
