# -*- coding: utf-8 -*-
"""Диктовка в поле вопроса: сторона питона.

Окно спрашивает у сервиса три вещи: начать, закончить (и отдать текст),
отменить. Здесь проверяем, что сервис отвечает честно, а главное — что
текст возвращается окну, а не печатается в чужое приложение.

Почему это важно: обычная диктовка (задача №3) шлёт нажатия клавиш в
активное окно. Для поля внутри самого Konspekt так нельзя — webview
примет ввод только в фокусе, а человек в этот момент смотрит на Zoom.
"""
import testenv  # noqa: F401  песочница вместо боевого профиля

import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from app.core.service import AppService


class ПоддельнаяСлужба:
    """Служба диктовки без микрофона и без модели."""

    def __init__(self, беда="", текст="проверим оплату"):
        self.беда = беда
        self.текст = текст
        self.начата = False
        self.отменена = False
        self.вставляла = False

    def _почему_нельзя(self):
        return self.беда

    def начать(self):
        self.начата = True
        return True

    def распознать_для_окна(self):
        return self.текст

    def закончить(self):
        # Если позовут это, значит текст ушёл в чужое окно клавишами.
        self.вставляла = True
        return self.текст

    def отменить(self):
        self.отменена = True


def сервис(служба):
    """Голый AppService с подставленной диктовкой."""
    с = AppService.__new__(AppService)
    с.диктовка = служба
    с.settings = types.SimpleNamespace(
        dictation=types.SimpleNamespace(enabled=True)
    )
    return с


# --- Обычный путь: начали, сказали, получили текст -----------------------
служба = ПоддельнаяСлужба()
с = сервис(служба)

ответ = с.начать_диктовку_в_окно()
assert ответ["ok"], ответ
assert служба.начата, "сервис не начал слушать"

ответ = с.закончить_диктовку_в_окно()
assert ответ["ok"], ответ
assert ответ["текст"] == "проверим оплату", ответ
assert not служба.вставляла, (
    "текст напечатали в активное окно вместо того, чтобы вернуть его "
    "нашему полю: если человек в этот момент смотрит на Zoom, вопрос к "
    "встрече уедет в чужой чат"
)
print("[ok] текст возвращается окну и никуда не печатается")

# --- Идёт запись встречи: отказ с причиной -------------------------------
служба = ПоддельнаяСлужба(беда="идёт запись встречи, модель занята")
с = сервис(служба)
ответ = с.начать_диктовку_в_окно()
assert not ответ["ok"], "диктовка началась во время записи встречи"
assert "запись" in ответ["причина"], ответ
assert not служба.начата, "микрофон открыли, хотя диктовать нельзя"
print(f"[ok] при записи встречи отказ с причиной: {ответ['причина']}")

# --- Диктовка выключена в настройках -------------------------------------
с = AppService.__new__(AppService)
с.диктовка = None
с.settings = types.SimpleNamespace(
    dictation=types.SimpleNamespace(enabled=False)
)
ответ = с.начать_диктовку_в_окно()
assert not ответ["ok"], "диктовка началась, хотя выключена в настройках"
assert ответ["причина"], "отказали молча: человек не поймёт, что чинить"
print(f"[ok] при выключенной диктовке отказ с причиной: {ответ['причина']}")

# --- Отмена --------------------------------------------------------------
служба = ПоддельнаяСлужба()
с = сервис(служба)
с.начать_диктовку_в_окно()
с.отменить_диктовку_в_окно()
assert служба.отменена, "отмена не дошла до службы: микрофон остался открыт"
print("[ok] отмена закрывает микрофон")

# --- Мост наружу знает про все три ---------------------------------------
from app.ui.api import Api  # noqa: E402

for имя in ("start_field_dictation", "finish_field_dictation",
            "cancel_field_dictation"):
    assert hasattr(Api, имя), (
        f"мост не отдаёт наружу {имя}: кнопка в окне не сможет её позвать"
    )
print("[ok] мост отдаёт наружу все три вызова")

print("\nДиктовка в поле работает и не печатает в чужие окна.")
