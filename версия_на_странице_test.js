// Номер выложенной версии на странице загрузки.
//
// Номер вписанный руками устаревает в первом же выпуске, и страница
// начинает врать о том, что человек скачает. Поэтому он берётся из
// ответа GitHub про последний релиз. Здесь проверяется, что берётся он
// верно, показывается только когда известен, и ведёт на список
// изменений того самого выпуска.
//
// Разбор берётся из настоящей docs/index.html, а не переписан здесь:
// копия разошлась бы с оригиналом и проверяла бы саму себя.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const беды = [];
function проверить(ок, что) {
  console.log((ок ? '[ok] ' : '[FAIL] ') + что);
  if (!ок) беды.push(что);
}

const html = fs.readFileSync(path.join(__dirname, 'docs', 'index.html'), 'utf8');
const i18n = fs.readFileSync(path.join(__dirname, 'docs', 'i18n.js'), 'utf8');

const от = html.indexOf('function показатьВыпуск');
const до = html.indexOf('async function показатьПроверку');
if (от < 0 || до < 0) {
  console.error('не нашёл показатьВыпуск в docs/index.html');
  process.exit(1);
}

// Крошечный DOM: нужны только те узлы, что трогает показатьВыпуск.
function сделатьУзел(тег) {
  return {
    tagName: тег,
    children: [],
    hidden: false,
    innerHTML: '',
    textContent: '',
    className: '',
    href: '',
    rel: '',
    target: '',
    append(...что) { this.children.push(...что); },
  };
}

const релизУзел = сделатьУзел('p');
релизУзел.hidden = true;

const песочница = {
  console,
  document: {
    getElementById: (id) => (id === 't-release' ? релизУзел : null),
    createElement: сделатьУзел,
    createTextNode: (t) => ({ text: t }),
  },
};
vm.createContext(песочница);
// Словари нужны настоящие: подпись версии идёт из них.
vm.runInContext(i18n, песочница, { filename: 'i18n.js' });
vm.runInContext(html.slice(от, до) +
  '\nglobalThis.показать = показатьВыпуск;', песочница, { filename: 'index.html' });
const показать = песочница.показать;

/** Весь видимый текст узла в одну строку. */
function текстом(узел) {
  return узел.children.map((ч) => {
    if (typeof ч.text === 'string') return ч.text;
    return ч.textContent || '';
  }).join('');
}

function заново() {
  релизУзел.children = [];
  релизУзел.hidden = true;
  релизУзел.innerHTML = '';
}

// --- Настоящий ответ GitHub ----------------------------------------------
const ответ = {
  tag_name: 'v0.10.0',
  html_url: 'https://github.com/lamver/konspekt-releases/releases/tag/v0.10.0',
  body: '## What\'s new\n\n- Something changed.\n',
};

заново();
показать(ответ, 'ru');
проверить(релизУзел.hidden === false, 'строка версии показана, когда версия известна');
проверить(текстом(релизУзел).includes('0.10.0'),
  'виден номер версии (было: «' + текстом(релизУзел) + '»)');
проверить(!текстом(релизУзел).includes('v0.10.0'),
  'буква v из тега убрана: человеку показываем 0.10.0, а не v0.10.0');

const ссылка = релизУзел.children.find((ч) => ч.tagName === 'a');
проверить(!!ссылка, 'ссылка на список изменений есть');
проверить(ссылка && ссылка.href === ответ.html_url,
  'ссылка ведёт на страницу этого же выпуска');
проверить(ссылка && ссылка.textContent === 'Что изменилось',
  'подпись ссылки по-русски (было: «' + (ссылка && ссылка.textContent) + '»)');

// --- Четыре языка ---------------------------------------------------------
// Страницу читают на четырёх языках; забытый перевод показал бы
// служебный ключ или английский текст посреди русской страницы.
for (const [язык, ожидание] of [
  ['en', 'What changed'],
  ['es', 'Qué cambió'],
  ['sr', 'Šta je novo'],
  ['ru', 'Что изменилось'],
]) {
  заново();
  показать(ответ, язык);
  const а = релизУзел.children.find((ч) => ч.tagName === 'a');
  проверить(а && а.textContent === ожидание,
    'язык ' + язык + ': «' + (а && а.textContent) + '»');
  проверить(текстом(релизУзел).includes('0.10.0'),
    'язык ' + язык + ': номер версии на месте');
}

// Незнакомый язык не роняет страницу и не показывает пустоту.
заново();
показать(ответ, 'кхм');
проверить(релизУзел.hidden === false && текстом(релизУзел).includes('0.10.0'),
  'незнакомый язык откатывается на английский, а не ломает строку');

// --- Ответа нет или он испорчен ------------------------------------------
// Молчать честнее, чем показать «Версия undefined».
for (const [имя, плохой] of [
  ['без тега', { html_url: 'https://example.com' }],
  ['тег пустой', { tag_name: '' }],
  ['тег не строка', { tag_name: 42 }],
  ['пустой объект', {}],
]) {
  заново();
  показать(плохой, 'ru');
  проверить(релизУзел.hidden === true, имя + ': строка версии скрыта, а не врёт');
}

// Без html_url адрес собирается из тега: страница выпуска всё равно есть.
заново();
показать({ tag_name: 'v0.9.1' }, 'ru');
const своя = релизУзел.children.find((ч) => ч.tagName === 'a');
проверить(своя && своя.href ===
  'https://github.com/lamver/konspekt-releases/releases/tag/v0.9.1',
  'без html_url адрес выпуска собирается из тега');

// --- Разметка на странице -------------------------------------------------
проверить(/id="t-release"[^>]*hidden/.test(html),
  'в разметке строка версии скрыта до ответа GitHub');

// Ищем именно место вызова, а не любое упоминание имени: объявление
// «function показатьВыпуск(релиз, lang)» содержит ту же подстроку, и
// проверка на упоминание проспала бы удаление вызова целиком.
const тело = html.slice(html.indexOf('async function показатьПроверку'));
проверить(/\n\s+показатьВыпуск\(релиз, lang\);/.test(тело),
  'показатьВыпуск действительно зовётся из ответа GitHub');

// Один запрос на обе плашки: у GitHub без ключа шестьдесят запросов в
// час на адрес, и второй fetch ронял бы обе плашки вдвое быстрее.
const запросов = (html.match(/fetch\(РЕЛИЗЫ/g) || []).length;
проверить(запросов === 1, 'к GitHub ровно один запрос (было: ' + запросов + ')');

if (беды.length) {
  console.log('\nНе прошло проверок: ' + беды.length);
  process.exit(1);
}
console.log('\nСтраница честно показывает выложенную версию.');
