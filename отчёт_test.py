"""Проверить разбор SHA256SUMS и склейку описания без похода в сеть.

Скрипт отчёта запускается на сервере, где отладка стоит минут пять на
попытку. Поэтому разбор данных вынесен в чистые функции и проверяется
здесь: остаётся только то, без чего правда не обойтись без сети.
"""

import importlib.util
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import testenv  # noqa: E402,F401  русский вывод в консоли Windows

# Скрипт лежит в tools/ и не является пакетом: имя с кириллицей обычным
# импортом не берётся, поэтому грузим по пути.
спец = importlib.util.spec_from_file_location(
    "отчёт_вирустотал", Path(__file__).parent / "tools" / "отчёт_вирустотал.py"
)
отчёт = importlib.util.module_from_spec(спец)
спец.loader.exec_module(отчёт)


def проверить_сумму_из_файла() -> None:
    """Сумма берётся из первого поля, а не из имени файла.

    В SHA256SUMS формат «сумма  имя», и если перепутать поля местами,
    в VirusTotal уйдёт запрос по имени файла. Тот честно ответит «не
    видел», скрипт зальёт файл заново и получит новый отчёт — вместо
    того, чтобы найти уже готовый.
    """
    строка = (
        "ef8b32b0e372d6c7669ec62220fc1ad4d85bf5ecf28e10baf7d71c9877ed2052  "
        "konspekt-0.8.0-setup.exe\n"
    )
    сумма = отчёт.сумма_из_файла(строка)
    assert сумма == "ef8b32b0e372d6c7669ec62220fc1ad4d85bf5ecf28e10baf7d71c9877ed2052", сумма
    assert len(сумма) == 64, f"сумма не похожа на sha256: {сумма}"
    print("[ок] сумма читается из первого поля SHA256SUMS")


def проверить_отказ_от_мусора() -> None:
    """Пустой или битый SHA256SUMS должен ронять скрипт, а не идти дальше.

    Иначе в VirusTotal уйдёт запрос по мусору, тот ответит «не видел»,
    и скрипт зальёт установщик заново — молча сделав не то, что просили.
    """
    for мусор in ("", "   \n", "konspekt-0.8.0-setup.exe", "не_сумма  файл"):
        try:
            отчёт.сумма_из_файла(мусор)
        except SystemExit:
            continue
        raise AssertionError(f"на мусоре {мусор!r} скрипт не остановился")
    print("[ок] битый SHA256SUMS останавливает скрипт")


def проверить_описание() -> None:
    """Ссылка добавляется в конец, старое описание не теряется."""
    старое = "## What's new\n\n- Что-то поменялось\n"
    новое = отчёт.собрать_описание(старое, "абв123", {"malicious": 0, "undetected": 70})
    assert старое.rstrip() in новое, "потеряли исходное описание"
    assert "https://www.virustotal.com/gui/file/абв123" in новое, "нет ссылки"
    assert "0 of 70" in новое, f"не тот счёт: {новое}"
    print("[ок] ссылка на отчёт дописывается, описание цело")


def проверить_счёт_подозрений() -> None:
    """Подозрительные считаются вместе с вредоносными.

    Движки часто ставят не «вирус», а «подозрительно». Показать «0 из 70»,
    когда пятеро насторожились, значит соврать человеку ровно в том
    месте, ради которого он вообще открыл отчёт.
    """
    новое = отчёт.собрать_описание(
        "описание", "абв", {"malicious": 1, "suspicious": 2, "undetected": 67}
    )
    assert "3 of 70" in новое, f"подозрения не учтены: {новое}"
    print("[ок] подозрительные считаются наравне с вредоносными")


def проверить_повтор() -> None:
    """Второй запуск не должен дописывать ссылку повторно."""
    первое = отчёт.собрать_описание("описание", "абв", {"malicious": 0, "undetected": 70})
    assert отчёт.уже_дописано(первое, "абв"), "повторный запуск задвоит ссылку"
    assert not отчёт.уже_дописано("описание", "абв"), "ложное срабатывание"
    print("[ок] повторный запуск ссылку не задваивает")


def main() -> int:
    проверок = 0
    for имя, функция in sorted(globals().items()):
        if имя.startswith("проверить_"):
            функция()
            проверок += 1
    print(f"\nОтчёт VirusTotal: {проверок} проверок прошли")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
