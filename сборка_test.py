"""Проверка условия шага VirusTotal: логика, а не текст YAML.

Зачем вообще: сломанная версия (`env.VT_API_KEY != ''` в собственном
шаге) выглядела осмысленно и всегда была ложной, из-за чего скан молча
не запускался ни разу. Такую поломку глазами не видно — пропущенный по
ложному условию шаг выглядит ровно как осознанно пропущенный.

Разбираем файл сами, без pyyaml: он приезжает транзитивно, через
huggingface_hub, и однажды уедет вместе с ним. Проверке сборки не место
в зависимости от чужого дерева зависимостей.

Логику ветвления считаем по тексту, а не гоняем bash: на Windows `bash`
это WSL со своей файловой системой, туда не проходят ни переменные, ни
пути к временным файлам, и проверка ловила бы собственную среду.
Настоящее поведение шага подтверждено живым прогоном сборки: шаг
«Проверить, есть ли ключ VirusTotal» отработал и написал причину
пропуска в сводку (run 34344485994).
"""

import io
import re
import sys

import testenv  # noqa: F401  русский вывод в консоли Windows

ФАЙЛ = ".github/workflows/build.yml"
ошибки = []


def проверить(ок, что):
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        ошибки.append(что)


текст = io.open(ФАЙЛ, encoding="utf-8").read()


def шаг(признак: str) -> str:
    """Кусок файла от строки с признаком до начала следующего шага.

    Шаги идут списком с одинаковым отступом, поэтому границей служит
    следующая строка вида `      - name:`.
    """
    начало = текст.index(признак)
    # Отступаем назад до начала своего шага.
    начало = текст.rindex("      - name:", 0, начало)
    следующий = текст.find("\n      - name:", начало + 10)
    return текст[начало:следующий if следующий != -1 else len(текст)]


есть_ключ = "id: vt_key" in текст
проверить(есть_ключ, "шаг vt_key есть в сборке")
проверить("VirusTotal скан" in текст, "шаг скана есть в сборке")
if not (есть_ключ and "VirusTotal скан" in текст):
    sys.exit(1)

блок_ключа = шаг("id: vt_key")
блок_скана = шаг("VirusTotal скан")

условие = re.search(r"if: (.+)", блок_скана)
условие = условие.group(1) if условие else ""
проверить("steps.vt_key.outputs.has_key" in условие,
          "условие скана смотрит на вывод шага vt_key")
# Та самая ловушка: env, объявленный в шаге, в его же `if` не виден.
проверить("env." not in условие,
          "в условии скана нет обращения к env своего шага (та самая ловушка)")
проверить(текст.index("id: vt_key") < текст.index("VirusTotal скан"),
          "шаг с ключом идёт раньше скана, иначе выводу неоткуда взяться")

проверить('if [ -n "$VT_API_KEY" ]' in блок_ключа, "шаг проверяет непустоту ключа")
проверить(bool(re.search(r'has_key=yes"\s*>>\s*"\$GITHUB_OUTPUT"', блок_ключа)),
          "с ключом шаг пишет has_key=yes в вывод")
проверить(bool(re.search(r'has_key=no"\s*>>\s*"\$GITHUB_OUTPUT"', блок_ключа)),
          "без ключа шаг пишет has_key=no в вывод")
проверить("has_key=yes" in блок_ключа and "has_key=no" in блок_ключа
          and блок_ключа.index("has_key=yes") < блок_ключа.index("has_key=no"),
          "ветки не перепутаны местами")
проверить("::notice::" in блок_ключа,
          "без ключа шаг объясняет причину пропуска, а не молчит")
проверить("${{ secrets.VT_API_KEY }}" in блок_ключа,
          "ключ приходит в шаг из секретов")

print()
if ошибки:
    print(f"Не прошло: {len(ошибки)}")
    sys.exit(1)
print("Условие шага VirusTotal собрано правильно.")
