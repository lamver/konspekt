# -*- coding: utf-8 -*-
"""Программа предупреждает, когда дорожка пишет пустоту.

Живой случай: подкаст играл на одном выходе, а Konspekt слушал другой.
Дорожка «системный звук» открылась без ошибок и 68 секунд писала
ровный ноль, микрофон при этом ловил подкаст из воздуха — в
расшифровке вышла каша из огрызков. Программа об этом молчала, и
человек узнал о беде только по бессмысленному тексту.
"""
import testenv  # noqa: F401  русский вывод в консоли Windows

import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))

from app.audio import devices, wasapi
from app.core.events import RECORDING_SILENT, bus


class ПустоеУстройство:
    """Устройство, которое открывается и отдаёт ровный ноль."""

    name = "Немой выход"

    def recorder(self, **_):
        return self

    def __enter__(self):
        return self

    def __exit__(self, *_):
        return False

    def record(self, numframes):
        time.sleep(0.001)
        return np.zeros(numframes, dtype="float32")


class ТихийНоЖивой(ПустоеУстройство):
    """Очень тихий, но настоящий звук: тревожить человека не за что."""

    name = "Тихий выход"

    def record(self, numframes):
        time.sleep(0.001)
        return np.full(numframes, 1e-5, dtype="float32")


def записать(устройство, секунд, только_слушать=False, сосед_живой=None):
    """Прогнать дорожку и вернуть пойманные предупреждения."""
    пойманное = []
    отписаться = bus.on(RECORDING_SILENT, пойманное.append)
    дорожка = wasapi._Track(
        name=devices.TRACK_THEM,
        opener=lambda: устройство,
        wav_path=Path(__file__).parent / "_тишина.wav",
        chunk_seconds=1.0,
        on_chunk=None,
        только_слушать=только_слушать,
        сосед_живой=сосед_живой,
    )
    дорожка.start()
    # Время в проверке не ждём по-настоящему: на медленной машине
    # десять секунд звука не наберутся, и проверка падала бы не от
    # поломки. Крутим цикл, пока дорожка не пройдёт нужный объём.
    ждём = time.monotonic() + 20
    while дорожка._тишина_секунд < секунд and not пойманное:
        if time.monotonic() > ждём:
            break
        time.sleep(0.02)
    дорожка.stop()
    отписаться()
    (Path(__file__).parent / "_тишина.wav").unlink(missing_ok=True)
    return пойманное


# --- Немая дорожка: человека предупреждают ------------------------------
беды = записать(ПустоеУстройство(), wasapi.ПОРОГ_ТИШИНЫ)
assert беды, (
    f"дорожка писала {wasapi.ПОРОГ_ТИШИНЫ} секунд ровного нуля, а программа "
    f"промолчала: человек узнает о беде только по бессмысленной расшифровке"
)
текст = беды[0].get("message", "")
assert "системный звук" in текст, f"в предупреждении не сказано, какая дорожка: {текст}"
assert беды[0].get("silent"), "предупреждение не помечено как тишина"
print(f"[ok] о немой дорожке предупреждают: {текст}")

# --- Тихий, но живой звук: молчим ---------------------------------------
беды = записать(ТихийНоЖивой(), wasapi.ПОРОГ_ТИШИНЫ)
assert not беды, (
    f"на тихой, но живой дорожке подняли тревогу: {беды}. Так программа "
    f"будет кричать на каждой негромкой встрече"
)
print("[ok] тихий, но живой звук тревоги не поднимает")

# --- Задача №27: слушающая дорожка не пугает человека --------------------
#
# Снимок от пользователя: реплики распознаются одна за другой, встреча
# пишется, а внизу висит «за 10 секунд не было ни звука». Так вышло
# потому, что вторая дорожка была открыта не ради записи, а ради
# вопроса «не записать ли собеседника» (задача №28). Она ничего не
# пишет, её тишина ничего не стоит, но предупреждение выглядело как
# «вы теряете встречу» — и человек пошёл менять исправные настройки.
беды = записать(ПустоеУстройство(), wasapi.ПОРОГ_ТИШИНЫ, только_слушать=True)
assert not беды, (
    f"дорожка только слушает и ничего не пишет, а человека напугали "
    f"потерей записи: {беды}. Ровно на это жалоба в задаче №27"
)
print("[ok] слушающая дорожка молчит о своей тишине")

# --- Вторая дорожка пишет звук: встречу не теряем ------------------------
#
# Человек слушает встречу и сам молчит — микрофон отдаёт ноль, а
# системный звук пишет всё. Встреча при этом цела, пугать не за что.
беды = записать(
    ПустоеУстройство(), wasapi.ПОРОГ_ТИШИНЫ, сосед_живой=lambda: True
)
assert not беды, (
    f"одна дорожка молчит, но вторая пишет звук, а тревогу всё равно "
    f"подняли: {беды}. Человек молчит на встрече — это не поломка"
)
print("[ok] при живой второй дорожке тишина первой не тревожит")

# --- Обе дорожки молчат: это настоящая беда, говорим ---------------------
беды = записать(
    ПустоеУстройство(), wasapi.ПОРОГ_ТИШИНЫ, сосед_живой=lambda: False
)
assert беды, (
    "обе дорожки пишут ровный ноль, и программа промолчала: это и есть "
    "потерянная встреча, о которой человек должен узнать сразу"
)
print("[ok] когда молчат обе дорожки, предупреждение остаётся")

# --- Дорожка, пожаловавшаяся на тишину, не прикрывает соседку ------------
#
# Защёлка «больше не повторяться» и правда «звук был» — разные вещи.
# Если держать их в одном флажке, то после собственной жалобы дорожка
# начнёт отвечать соседке «да, у меня звук есть», и молчание обеих
# дорожек — единственный случай настоящей потери встречи — пройдёт
# незамеченным.
захват = wasapi.WasapiCapture.__new__(wasapi.WasapiCapture)
немая = wasapi._Track(
    name=devices.TRACK_ME,
    opener=lambda: ПустоеУстройство(),
    wav_path=Path(__file__).parent / "_нет.wav",
    chunk_seconds=1.0,
    on_chunk=None,
)
немая._проверка_окончена = True  # уже пожаловалась
захват._tracks = {devices.TRACK_ME: немая}
assert not захват._дорожка_слышит(devices.TRACK_ME), (
    "дорожка, сама пожаловавшаяся на тишину, выдала себя за живую: "
    "теперь молчание обеих дорожек никого не потревожит"
)
print("[ok] пожаловавшаяся дорожка не выдаёт себя за живую")

# --- Слушающая дорожка со звуком не прикрывает немой микрофон ------------
#
# Худший случай: микрофон пишет ровный ноль, а вторая дорожка открыта
# только ради слушания (запись системного звука выключена). Звук в ней
# есть, но в файл не идёт ни байта — встреча теряется целиком. Если
# считать такую дорожку «живой соседкой», программа промолчит ровно
# тогда, когда обязана кричать.
слушающая = wasapi._Track(
    name=devices.TRACK_THEM,
    opener=lambda: ТихийНоЖивой(),
    wav_path=Path(__file__).parent / "_нет.wav",
    chunk_seconds=1.0,
    on_chunk=None,
    только_слушать=True,
)
слушающая._звук_был = True  # слышит настоящий звук
захват._tracks = {devices.TRACK_THEM: слушающая}
assert not захват._дорожка_слышит(devices.TRACK_THEM), (
    "дорожка в режиме «только слушать» сошла за пишущую: теперь немой "
    "микрофон промолчит, и встреча пропадёт целиком без единого слова"
)
print("[ok] слушающая дорожка не считается за пишущую")

# --- Окно разошлось с сервисом: повторный старт чинит его ----------------
#
# Если окно всё-таки решит, что записи нет (а именно так и вышло в
# 0.7.3 из-за предупреждения о тишине), человек нажмёт кнопку — и до
# этой правки сервис молча писал в журнал «Запись уже идёт», ничего не
# отвечая. Кнопка оставалась мёртвой до перезапуска программы.
class ЗанятыйЗахват:
    is_recording = True


class ПустаяБаза:
    def get_meeting(self, _id):
        return None


class ФальшивыйСервис:
    """Только то, что трогает start_recording на занятой записи."""

    capture = ЗанятыйЗахват()
    store = ПустаяБаза()
    active_meeting_id = "встреча-1"

    def get_meeting(self, _id):
        return {"id": "встреча-1"}


from app.core.events import RECORDING_STARTED  # noqa: E402
from app.core.service import AppService  # noqa: E402

пойманное = []
отписаться = bus.on(RECORDING_STARTED, пойманное.append)
AppService.start_recording(ФальшивыйСервис())
отписаться()

assert пойманное, (
    "на повторный «начать» во время записи сервис ничего не ответил: "
    "разошедшееся окно останется с мёртвой кнопкой до перезапуска"
)
assert пойманное[0]["meeting_id"] == "встреча-1", пойманное[0]
print("[ok] повторный старт возвращает окну состояние записи")

print("\nПустая дорожка больше не проходит незамеченной")
