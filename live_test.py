"""Отзывчивость во время записи: речь без пауз и перетаскивание окна.

Две жалобы с живого прогона подкаста, обе про одно — программа
перестаёт поспевать за человеком, пока идёт запись.

1. «Отставать начнёт». На речи без пауз фраза копилась до потолка
   MAX_SEGMENT, и готовый текст ждал этого потолка. С 18 секундами
   человек видел, как программа отстаёт всё сильнее.
2. «Само окно при перетаскивании фризится». Перетаскивание слало вызов
   в питон на каждое движение мыши, сотнями в секунду. Пока питон
   свободен, это сходит с рук; во время записи он занят распознаванием,
   очередь вызовов не разгребается, и окно виснет в руках.
3. «Сказал „ок“, продолжил говорить, а он лепит это к предыдущей
   реплике». Окно склеивало реплики при паузе до 1.5с, хотя само
   распознавание объявляет фразу законченной уже после 0.6с тишины.
   Порог склейки был вдвое больше порога разделения, и окно склеивало
   обратно ровно то, что распознавание успело разделить.

Все три места проверяем на том, что можно измерить, а не на глаз.
"""
import testenv  # noqa: F401  русский вывод в консоли Windows

import re
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
RATE = 16000


def речь_без_пауз(секунд: float) -> np.ndarray:
    """Сплошная речь: как подкаст, диктор не замолкает."""
    n = int(RATE * секунд)
    t = np.arange(n) / RATE
    # Голосоподобный сигнал с формантами, без единой паузы.
    сигнал = (
        0.30 * np.sin(2 * np.pi * 130 * t)
        + 0.20 * np.sin(2 * np.pi * 420 * t)
        + 0.10 * np.sin(2 * np.pi * 900 * t)
    )
    # Лёгкая огибающая слогов, но никогда не до тишины.
    слоги = 0.75 + 0.25 * np.sin(2 * np.pi * 3.5 * t)
    return (сигнал * слоги).astype(np.float32)


def main() -> int:
    from app.asr import vad as vadmod

    # --- 1. Речь без пауз не заставляет ждать потолок ---

    assert vadmod.MAX_SEGMENT <= 10.0, (
        f"MAX_SEGMENT={vadmod.MAX_SEGMENT}: на речи без пауз готовый текст "
        f"будет ждать столько же секунд, и человек увидит, как программа "
        f"отстаёт от говорящего"
    )
    print(f"[ok] потолок фразы {vadmod.MAX_SEGMENT}с, а не 18с")

    звук = речь_без_пауз(30.0)
    seg = vadmod.SpeechSegmenter(sample_rate=RATE)
    шаг = int(RATE * 0.5)
    ожидания = []
    for i in range(0, len(звук) - шаг, шаг):
        отдано = i / RATE + 0.5
        for p in seg.feed(звук[i:i + шаг], i / RATE):
            ожидания.append(отдано - p.offset)

    assert ожидания, "на 30 секундах сплошной речи не отдано ни одного куска"
    худшее = max(ожидания)
    assert худшее <= 10.0, (
        f"на речи без пауз кусок ждал {худшее:.1f}с, прежде чем уйти в "
        f"распознавание: человек столько же не видит готового текста"
    )
    print(f"[ok] на сплошной речи текст уходит в модель не позже {худшее:.1f}с")

    # Куски при этом не должны стать крошевом: слишком короткие лишают
    # модель контекста, и распознавание портится.
    seg2 = vadmod.SpeechSegmenter(sample_rate=RATE)
    длины = []
    for i in range(0, len(звук) - шаг, шаг):
        for p in seg2.feed(звук[i:i + шаг], i / RATE):
            длины.append(len(p.pcm) / RATE)
    assert np.median(длины) >= 2.0, (
        f"куски стали слишком мелкими (медиана {np.median(длины):.1f}с): "
        f"модели не хватит контекста"
    )
    print(f"[ok] куски не измельчали: медиана {np.median(длины):.1f}с")

    # --- 2. Перетаскивание не заваливает мост вызовами ---

    js = (ROOT / "web" / "app.js").read_text(encoding="utf-8")
    начало = js.index("function setupDrag()")
    конец = js.index("function setupResize()")
    тело = js[начало:конец]

    assert "requestAnimationFrame" in тело, (
        "перетаскивание окна шлёт move_window на каждое движение мыши. "
        "Во время записи питон занят распознаванием, вызовы копятся, и "
        "окно виснет прямо в руках у человека"
    )
    print("[ok] перетаскивание копит смещения и шлёт их раз в кадр")

    # Вызов моста должен быть ровно один, внутри flush: если он остался
    # ещё и в самом mousemove, ограничение ничего не даёт.
    вызовов = len(re.findall(r"api\.move_window\(", тело))
    assert вызовов == 1, (
        f"move_window зовётся из {вызовов} мест: ограничение частоты "
        f"обходится стороной"
    )
    print("[ok] окно двигается ровно одним вызовом моста")

    # Отпустили кнопку — окно обязано доехать до места. Без дошлёпывания
    # остатка оно замирает чуть раньше, чем человек отпустил мышь.
    mouseup = тело[тело.index("mouseup"):]
    assert "flush()" in mouseup, (
        "остаток пути не досылается: окно не доедет до места, где "
        "человек отпустил кнопку"
    )
    print("[ok] при отпускании окно доезжает до места")

    # То же ограничение давно стоит на изменении размера. Если оно
    # оттуда пропадёт, вернётся ровно та же беда.
    resize = js[js.index("function setupResize()"):]
    resize = resize[:resize.index("\n}")]
    assert "requestAnimationFrame" in resize, (
        "изменение размера потеряло ограничение частоты вызовов"
    )
    print("[ok] изменение размера тоже ограничено кадром")

    # --- 3. Склейка реплик не спорит с разделением фраз ---

    # Ключ всей проверки: порог склейки в окне не должен быть больше
    # порога, по которому распознавание считает фразу законченной.
    # Иначе окно склеивает назад то, что распознавание разделило, и
    # короткое «ок» прилипает к следующей мысли.
    м = re.search(r"const TURN_GAP = ([\d.]+);", js)
    assert м, "в окне не найден порог склейки реплик TURN_GAP"
    turn_gap = float(м.group(1))

    assert turn_gap <= vadmod.SILENCE_TAIL, (
        f"порог склейки в окне {turn_gap}с больше порога конца фразы "
        f"{vadmod.SILENCE_TAIL}с: окно склеит обратно то, что "
        f"распознавание разделило, и короткая реплика прилипнет к "
        f"следующей мысли"
    )
    print(f"[ok] склейка {turn_gap}с не спорит с концом фразы "
          f"{vadmod.SILENCE_TAIL}с")

    # Но и слишком мелкий порог вреден: принудительная резка длинной
    # речи даёт куски встык, и они обязаны склеиться обратно, иначе
    # фраза рвётся посреди слова.
    assert turn_gap > 0.3, (
        f"порог склейки {turn_gap}с слишком мал: куски разрезанной "
        f"длинной речи перестанут склеиваться и фраза порвётся"
    )
    print("[ok] разрезанная длинная речь всё ещё склеивается обратно")

    # Проверяем это не на числах, а на деле: гоняем через VAD сплошную
    # речь и смотрим, что соседние куски идут с зазором меньше порога.
    seg3 = vadmod.SpeechSegmenter(sample_rate=RATE)
    куски = []
    for i in range(0, len(звук) - шаг, шаг):
        for p in seg3.feed(звук[i:i + шаг], i / RATE):
            куски.append((p.offset, p.offset + len(p.pcm) / RATE))
    зазоры = [b[0] - a[1] for a, b in zip(куски, куски[1:])]
    assert зазоры, "сплошная речь дала меньше двух кусков, сравнивать нечего"
    склеятся = [g for g in зазоры if g < turn_gap]
    assert len(склеятся) == len(зазоры), (
        f"куски разрезанной сплошной речи не склеятся обратно: "
        f"{len(зазоры) - len(склеятся)} из {len(зазоры)} зазоров больше "
        f"порога {turn_gap}с"
    )
    print(f"[ok] все {len(зазоры)} кусков сплошной речи склеятся в одну реплику")

    print("\nВо время записи окно слушается рук, а текст не отстаёт от речи.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
