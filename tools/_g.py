from pathlib import Path

p = Path("CHANGELOG.md")
s = p.read_text(encoding="utf-8")
nl = "\r\n" if "\r\n" in s else "\n"
o = "## Не выпущено" + nl + nl + "### Добавлено" + nl + nl
assert s.count(o) == 1
t = """- Пробный период: первые 10 встреч программа работает целиком. В счёт
  идут только встречи, где набралась минута речи, так что случа��ное
  «Запись» — «Стоп» пробу не съедает. Плашка под заголовком говорит,
  сколько встреч осталось. После десяти все записи остаются на месте:
  их можно смотреть, искать, копировать, считать в чате. Записывать и
  загружать новые, делать по ним заметки, разборы и вопросы — с
  лицензией. Встречу, начатую десятой, можно дописать. У встреч,
  записанных до обновления, всё работает как раньше, и в счёт они не
  идут.

"""
s = s.replace(o, o + t.replace("\n", nl))
p.write_text(s, encoding="utf-8")

p = Path("ROADMAP.md")
s = p.read_text(encoding="utf-8")
nl = "\r\n" if "\r\n" in s else "\n"
o = "- [ ] Покупка без учётной записи: оплата, ключ на странице и PDF на"
assert s.count(o) == 1
t = """- [x] Пробный период вместо «всё работает без лицензии» (решение 30.09).
  Первые 10 встреч с минутой речи работают целиком, дальше только
  просмотр, поиск и копирование. Считаются встречи, а не дни: кто
  поставил и неделю не пользовался, ничего не потерял. Удаление
  встречи пробу не возвращает, встречи до обновления в счёт не идут,
  десятую встречу можно дописать, калькулятор в чате работает всегда.
  Выпускать только вместе со страницей покупки: иначе человек
  останется с программой только для просмотра и без выхода.
"""
s = s.replace(o, t.replace("\n", nl) + o)
p.write_text(s, encoding="utf-8")
for f in ("CHANGELOG.md", "ROADMAP.md"):
    assert "\ufffd" not in Path(f).read_text(encoding="utf-8")

