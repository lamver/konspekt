"""Обновить latest.json в публичном репозитории релизов.

Отдельным скриптом, потому что руками это делается через base64 и sha
существующего файла, и один промах оставляет пользователей без
обновления, ничего не сказав.

Поле notes показывается в окне программы, поэтому это сообщение
интерфейса, а не публичная страница релиза: его переводим на все языки,
на которых говорит программа.

Осторожно с форматом. До 0.8.0 включительно notes был строкой, и
установленные копии разбирают именно строку. Словарь они покажут
человеку целиком, вместе с фигурными скобками. Поэтому переводы
попадают в файл только по явному требованию, а по умолчанию пишется
строка — см. ЗНАЕТ_ПРО_ПЕРЕВОДЫ.
"""

import argparse
import base64
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import testenv  # noqa: E402,F401  русский вывод в консоли Windows

from app import __version__  # noqa: E402
from app.core.version_check import is_newer  # noqa: E402

РЕПОЗИТОРИЙ = "lamver/konspekt-releases"
ФАЙЛ = "latest.json"

# Первая версия, которая понимает словарь переводов в notes. Проверено по
# коду выпущенных тегов: `выбрать_новость` появилась в 0.8.1, а в 0.8.0 и
# старше notes подставлялся в окно как есть. Таких выпусков семнадцать, и
# у людей они ещё стоят.
ЗНАЕТ_ПРО_ПЕРЕВОДЫ = "0.8.1"

ЯЗЫКИ = ("ru", "en", "es", "sr")


def гх(*аргументы: str) -> str:
    """Позвать gh.

    Без shell=True: на Linux он запускает первый элемент списка через
    оболочку, а остальные теряет, и gh молча выполняется без аргументов.
    """
    готово = subprocess.run(
        ["gh", *аргументы], capture_output=True, text=True,
        encoding="utf-8", errors="replace",
    )
    if готово.returncode != 0:
        raise SystemExit(f"gh не смог: {готово.stderr.strip()}")
    return готово.stdout.strip()


def собрать_новость(аргументы, версия: str) -> str | dict[str, str]:
    """Строка или словарь переводов — что класть в latest.json.

    Отдельной функцией, чтобы решение о формате можно было проверить, не
    трогая сеть: ошибка здесь тихо ломает окно обновления у всех, кто ещё
    не обновился.
    """
    переводы = {
        язык: getattr(аргументы, язык)
        for язык in ЯЗЫКИ
        if getattr(аргументы, язык, None)
    }
    if not переводы:
        raise SystemExit("не задано ни одной новости: нужен хотя бы --ru")

    if list(переводы) == ["ru"]:
        return переводы["ru"]

    # Словарь понимают только копии от 0.8.1 и новее. Те, что старше,
    # покажут человеку «{'ru': ...}» целиком, со скобками и кавычками.
    #
    # Сравнивать тут выпускаемую версию бессмысленно: она всегда новее
    # порога, условие не срабатывает никогда. Так и вышло с 0.10.0 —
    # предупреждение было написано, но молчало. Спрашивать надо не
    # «какую версию выпускаем», а «какие версии стоят у людей», а этого
    # мы не знаем. Поэтому требуем явного согласия всегда.
    if not аргументы.всё_равно:
        raise SystemExit(
            f"Переводы понимают копии от {ЗНАЕТ_ПРО_ПЕРЕВОДЫ} и новее.\n"
            f"Те, что старше, покажут словарь целиком, со скобками.\n"
            f"Либо оставьте только --ru, либо добавьте --всё-равно, если\n"
            f"уверены, что старых копий не осталось."
        )
    return переводы


def main() -> int:
    разбор = argparse.ArgumentParser(
        description="Рассказать программе о новой версии",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog='Пример: обновить_latest.py --ru "Появилась диктовка"',
    )
    разбор.add_argument("новость", nargs="?", help="то же, что --ru")
    for язык in ЯЗЫКИ:
        разбор.add_argument(f"--{язык}", help=f"новость на языке «{язык}»")
    разбор.add_argument(
        "--всё-равно", dest="всё_равно", action="store_true",
        help="положить переводы, даже если старые копии их не поймут",
    )
    аргументы = разбор.parse_args()
    if аргументы.новость and not аргументы.ru:
        аргументы.ru = аргументы.новость

    новость = собрать_новость(аргументы, __version__)

    старый_sha = гх("api", f"repos/{РЕПОЗИТОРИЙ}/contents/{ФАЙЛ}", "--jq", ".sha")

    содержимое = {
        "version": __version__,
        "url": f"https://github.com/{РЕПОЗИТОРИЙ}/releases/latest",
        "notes": новость,
    }
    текст = json.dumps(содержимое, ensure_ascii=False, indent=2) + "\n"
    закодировано = base64.b64encode(текст.encode("utf-8")).decode("ascii")

    гх(
        "api", f"repos/{РЕПОЗИТОРИЙ}/contents/{ФАЙЛ}",
        "--method", "PUT",
        "-f", f"message=Версия {__version__}",
        "-f", f"content={закодировано}",
        "-f", f"sha={старый_sha}",
    )
    вид = "переводы" if isinstance(новость, dict) else "строка"
    print(f"latest.json обновлён до {__version__} ({вид})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
