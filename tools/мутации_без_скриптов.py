#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Умеет ли проверка «без скриптов» падать.

Зелёная проверка ничего не стоит, пока не показано, что она ловит
порчу. Портим страницу несколькими способами и смотрим, ругается ли
проверка на каждый. Отдельно проверяем обратное: на исправной странице
она обязана молчать, иначе будет кричать всегда и её перестанут читать.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import testenv  # noqa: F401,E402  русский вывод в консоли Windows

КОРЕНЬ = Path(__file__).resolve().parent.parent
СТРАНИЦА = КОРЕНЬ / "docs" / "index.html"
ПРОВЕРКА = КОРЕНЬ / "без_скриптов_test.py"

исходник = СТРАНИЦА.read_text(encoding="utf-8")


def прогнать() -> bool:
    """Возвращает True, если проверка прошла."""
    готово = subprocess.run(
        [sys.executable, str(ПРОВЕРКА)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=str(КОРЕНЬ),
    )
    return готово.returncode == 0


def опустошить_узлы(html: str) -> str:
    """Возврат к прежнему устройству: все узлы t-* пустые."""
    return re.sub(
        r'(<([a-z0-9]+)\b[^>]*\bid="t-[a-z-]+"[^>]*>)([\s\S]*?)(</\2>)',
        r"\1\4",
        html,
        flags=re.I,
    )


порчи = [
    ("текст снова рисуется скриптом (узлы пусты)", опустошить_узлы),
    (
        "пропала карточка про локальную расшифровку",
        lambda h: h.replace("Transcribes locally", ""),
    ),
    (
        "у снимков убрали подписи alt",
        lambda h: re.sub(r'\salt="[^"]*"', ' alt=""', h),
    ),
    (
        "у снимков убрали размеры",
        lambda h: re.sub(r'\swidth="\d+"\sheight="\d+"', "", h),
    ),
    (
        "заголовок первого уровня опустел",
        lambda h: re.sub(r'(<h1[^>]*>)[\s\S]*?(</h1>)', r"\1\2", h, flags=re.I),
    ),
    (
        "текст в разметке разошёлся со словарём",
        lambda h: h.replace("Why local matters", "Why it matters"),
    ),
]

print("ЛОВИТ ЛИ ПРОВЕРКА «БЕЗ СКРИПТОВ» ПОРЧУ")
print("=" * 66)

поймано = 0
try:
    for название, испортить in порчи:
        испорченный = испортить(исходник)
        if испорченный == исходник:
            print(f"НЕ ПРИМЕНЕНО  {название} (страница не изменилась)")
            continue
        СТРАНИЦА.write_text(испорченный, encoding="utf-8")
        прошла = прогнать()
        print(f"{'ПРОПУЩЕНО' if прошла else 'OK       '}  {название}")
        if not прошла:
            поймано += 1

    # Контрольный случай: на исправной странице проверка обязана молчать.
    СТРАНИЦА.write_text(исходник, encoding="utf-8")
    чисто = прогнать()
    print(f"{'OK       ' if чисто else 'ПРОПУЩЕНО'}  исправная страница не вызывает ложных тревог")
finally:
    # Возвращаем страницу в любом случае, даже если проверка сорвалась.
    СТРАНИЦА.write_text(исходник, encoding="utf-8")

всего = len(порчи)
print()
if поймано == всего and чисто:
    print(f"Проверка не декоративная: ловит все {всего} вида порчи и молчит на исправной странице.")
    sys.exit(0)

print(f"ВНИМАНИЕ: поймано {поймано} из {всего}, исправная страница {'в порядке' if чисто else 'ложно признана сломанной'}.")
sys.exit(1)
