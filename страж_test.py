"""Страж выпуска: разбор ответа VirusTotal и условие в сборке по тегу.

0.10.1 ушла к людям с тревогой Microsoft Defender: скан шёл уже после
публикации. Теперь сборка по тегу проверяет установщик до выпуска и
падает на тревоге. Здесь без сети проверяем, что страж считает тревоги
честно, и что в сборке он стоит до публикации, а не после.
"""

import importlib.util
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent
sys.path.insert(0, str(КОРЕНЬ))

import testenv  # noqa: E402,F401  русский вывод в консоли Windows

спец = importlib.util.spec_from_file_location(
    "страж_выпуска", КОРЕНЬ / "tools" / "страж_выпуска.py"
)
страж = importlib.util.module_from_spec(спец)
спец.loader.exec_module(страж)

ошибки: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ok] " if ок else "[FAIL] ") + что)
    if not ок:
        ошибки.append(что)


def ответ(malicious=0, suspicious=0, undetected=67, unsupported=6, timeout=1, кто=None):
    return {
        "last_analysis_stats": {
            "malicious": malicious, "suspicious": suspicious,
            "undetected": undetected, "harmless": 0,
            "type-unsupported": unsupported, "timeout": timeout,
        },
        "last_analysis_results": кто or {},
    }


# --- разбор ответа ----------------------------------------------------------

тревог, проверили, кто = страж.вердикт(ответ(
    malicious=1, undetected=67,
    кто={"Microsoft": {"category": "malicious", "result": "Trojan:Win32/Wacatac.B!ml"},
         "Avast": {"category": "undetected", "result": None}},
))
проверить(тревог == 1 and not страж.годится(тревог, проверили),
          "одна тревога Microsoft — ровно случай 0.10.1 — выпуск не пускает")
проверить(кто == ["Microsoft: Trojan:Win32/Wacatac.B!ml"],
          "в отчёте назван движок и его вердикт, остальные не упомянуты")

тревог, проверили, _ = страж.вердикт(ответ(suspicious=1, undetected=67))
проверить(not страж.годится(тревог, проверили),
          "«подозрительно» тоже тревога: Defender удаляет файл и так")

тревог, проверили, _ = страж.вердикт(ответ(undetected=68))
проверить(страж.годится(тревог, проверили), "чистый установщик выпуск пропускает")
проверить(проверили == 68,
          f"не открывшие файл движки не считаются проверившими: {проверили} из 68")

тревог, проверили, _ = страж.вердикт(ответ(undetected=0, unsupported=6, timeout=69))
проверить(not страж.годится(тревог, проверили),
          "ни один движок файл не проверил — это не «чисто», а «неизвестно»")

тревог, проверили, _ = страж.вердикт({})
проверить(not страж.годится(тревог, проверили), "пустой ответ не считается чистым")

проверить(страж.main([]) == 2, "без файла страж не делает вид, что проверил")

# --- место в сборке ---------------------------------------------------------

сборка = (КОРЕНЬ / ".github" / "workflows" / "build.yml").read_text(encoding="utf-8")
проверить("tools/страж_выпуска.py" in сборка, "сборка по тегу зовёт стража")
if "tools/страж_выпуска.py" in сборка:
    место_стража = сборка.index("tools/страж_выпуска.py")
    место_выпуска = сборка.index("softprops/action-gh-release")
    проверить(место_стража < место_выпуска,
              "страж стоит до публикации: после неё тревога уже у людей")
    шаг = сборка[сборка.rindex("      - name:", 0, место_стража):сборка.index("\n      - name:", место_стража)]
    проверить("continue-on-error" not in шаг,
              "провал стража останавливает сборку, а не проглатывается")
    условие = re.search(r"\n        if: (.+)", шаг)
    проверить(bool(условие) and "refs/tags/v" in условие.group(1),
              "страж обязателен для выпуска по тегу")
    проверить("${{ secrets.VT_API_KEY }}" in шаг, "ключ VirusTotal приходит в шаг стража")
    # pwsh не останавливается на провале внешней программы: без явного
    # выхода по её коду шаг «успешен», даже если страж нашёл тревогу.
    проверить(bool(re.search(r"if \(\$LASTEXITCODE -ne 0\) \{ exit \$LASTEXITCODE \}", шаг)),
              "код стража доходит до сборки: pwsh сам не падает на провале программы")

print()
if ошибки:
    print(f"Не прошло: {len(ошибки)}")
    sys.exit(1)
print("Установщик с тревогой антивируса к людям не уйдёт.")
