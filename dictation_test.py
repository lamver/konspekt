def продиктовать_в_блокнот(служба, клавиша) -> tuple[str, str]:
    """Прожать клавишу над настоящим Блокнотом. Вернёт (что в файле, беда)."""
    # Имя своё на каждую попытку. С общим именем повторный заход
    # находил окно предыдущего Блокнота (закрыться он успевает не
    # мгновенно) и печатал в мертвеца: проверка падала через раз не
    # из-за диктовки, а из-за самой себя.
    global _попытка
    _попытка += 1
    имя = f"konspekt_диктовка_{os.getpid()}_{_попытка}"
    файл = os.path.join(tempfile.gettempdir(), f"{имя}.txt")
    open(файл, "w", encoding="utf-8").close()
    блокнот = subprocess.Popen(["notepad.exe", файл])
    try:
        окно = 0
        предел = time.time() + 15
        while time.time() < предел and not окно:
            окно = _u.FindWindowW("Notepad", f"{имя}.txt - Notepad")
            time.sleep(0.2)
        if not окно:
            return "", "Блокнот не открылся"

        предел = time.time() + 8
        while time.time() < предел and _u.GetForegroundWindow() != окно:
            _поднять(окно)
            time.sleep(0.3)
        if _u.GetForegroundWindow() != окно:
            return "", "не удалось отдать фокус Блокноту"

        time.sleep(0.6)
        # Фокус мог уехать за эти доли секунды: на рабочей машине окна
        # всплывают сами. Возвращаем окно, иначе текст уйдёт в чужое, а
        # проверка обвинит диктовку.
        if _u.GetForegroundWindow() != окно:
            _поднять(окно)
            time.sleep(0.4)
            if _u.GetForegroundWindow() != окно:
                return "", "фокус увели прямо перед диктовкой"
        # Именно так это выглядит у человека: зажал Ctrl+Shift+D,
        # наговорил, отпустил.
        клавиша.нажатие(Клавиша(name="ctrl_l"))
        клавиша.нажатие(Клавиша(name="shift"))
        клавиша.нажатие(Клавиша(char="\x04"))  # Ctrl+D приходит так
        assert служба.идёт, "диктовка не началась по нажатию"
        клавиша.отпускание(Клавиша(char="\x04"))
        клавиша.отпускание(Клавиша(name="shift"))
        клавиша.отпускание(Клавиша(name="ctrl_l"))

        time.sleep(1.0)
        _u.keybd_event(0x11, 0, 0, 0)
        _u.keybd_event(0x53, 0, 0, 0)
        _u.keybd_event(0x53, 0, 2, 0)
        _u.keybd_event(0x11, 0, 2, 0)
        time.sleep(1.2)
        return open(файл, encoding="utf-8-sig").read().strip(), ""
    finally:
        блокнот.kill()
        time.sleep(0.4)
        try:
            os.unlink(файл)
        except OSError:
            pass


def проверить_сквозной_путь(речь: np.ndarray, модель) -> None:
    """Зажал клавишу, наговорил, отпустил — текст в чужом окне."""
    сервис = ЛожныйСервис(модель)
    служба = СлужбаДиктовки(сервис)
    # Подменяем только микрофон: всё остальное настоящее.
    служба._захват_для_проверки = ЗаписаннаяРечь(речь)
    настоящий = служба.начать

    def начать() -> bool:
        если_нельзя = служба._почему_нельзя()
        assert not если_нельзя, f"диктовка отказалась: {если_нельзя}"
        служба._захват = служба._захват_для_проверки
        служба._идёт = True
        return True

    служба.начать = начать
    клавиша = КлавишаДиктовки(
        "<ctrl>+<shift>+d", ЗАЖАТИЕ, служба.начать, служба.закончить
    )

    # Три попытки: чужое окно может перехватить фокус в самый неудачный
    # миг, и одиночная неудача говорит о шуме на машине, а не о нашем
    # коде. Три подряд — уже наша беда.
    последнее = ""
    for _ in range(3):
        было, беда = продиктовать_в_блокнот(служба, клавиша)
        # Настоящая речь и настоящая модель: точных слов не знаем, но
        # текст обязан быть осмысленным, а не знаком препинания.
        if not беда and sum(1 for c in было if c.isalpha()) >= 8:
            print(f"[ок] речь дошла до чужого окна: {было[:70]!r}")
            return
        последнее = беда or f"в окне оказалось {было!r}"
        time.sleep(1.0)
    raise AssertionError(
        f"за три попытки речь так и не доехала до чужого окна. {последнее}"
    )


def проверить_переключатель(речь: np.ndarray, модель) -> None:
    """Второй режим: нажал — пошло, нажал ещё раз — закончилось."""
    служба = СлужбаДиктовки(ЛожныйСервис(модель))
    захват = ЗаписаннаяРечь(речь)

    def начать() -> bool:
        служба._захват = захват
        служба._идёт = True
        return True

    служба.начать = начать
    вставлено: list[str] = []
    настоящая = вставка.вставить
    вставка.вставить = lambda т, способ=None: (вставлено.append(т), True)[1]
    try:
        клавиша = КлавишаДиктовки(
            "<ctrl>+<shift>+d", ПЕРЕКЛЮЧАТЕЛЬ, служба.начать, служба.закончить
        )
        # Первое нажатие: пошла запись, и отпускание её не прерывает.
        клавиша.нажатие(Клавиша(name="ctrl_l"))
        клавиша.нажатие(Клавиша(name="shift"))
        клавиша.нажатие(Клавиша(char="\x04"))
        assert служба.идёт, "переключатель не начал запись"
        клавиша.отпускание(Клавиша(char="\x04"))
        assert служба.идёт, (
            "переключатель остановился на отпускании клавиши: это режим "
            "зажатия, а не переключателя"
        )
        клавиша.отпускание(Клавиша(name="shift"))
        клавиша.отпускание(Клавиша(name="ctrl_l"))
        assert служба.идёт, "переключатель остановился на отпускании Ctrl"

        # Второе нажатие: закончили.
        клавиша.нажатие(Клавиша(name="ctrl_l"))
        клавиша.нажатие(Клавиша(name="shift"))
        клавиша.нажатие(Клавиша(char="\x04"))
        assert not служба.идёт, "переключатель не остановил запись"
    finally:
        вставка.вставить = настоящая

    assert вставлено and вставлено[0].strip(), "текст не был вставлен"
    print(f"[ок] режим переключателя: {вставлено[0][:50]!r}")


def проверить_конец_по_букве(модель) -> None:
    """Отпустил букву, не отпуская Ctrl — диктовка закончилась.

    Так и бывает у человека: Ctrl и Shift он держит всей ладонью и
    отпускает последними, а букву снимает пальцем первой. Если ждать
    отпускания модификаторов, запись висит лишние доли секунды и
    прихватывает то, чего человек говорить не собирался.
    """
    служба = СлужбаДиктовки(ЛожныйСервис(модель))
    концов: list[int] = []
    клавиша = КлавишаДиктовки(
        "<ctrl>+<shift>+d", ЗАЖАТИЕ,
        на_старт=lambda: True,
        на_стоп=lambda: концов.append(1),
    )
    клавиша.нажатие(Клавиша(name="ctrl_l"))
    клавиша.нажатие(Клавиша(name="shift"))
    клавиша.нажатие(Клавиша(char="\x04"))
    # Отпускаем только букву. Ctrl и Shift всё ещё зажаты.
    клавиша.отпускание(Клавиша(char="\x04"))
    assert концов, (
        "диктовка не закончилась по отпусканию буквы: она будет писать, "
        "пока человек не снимет с клавиатуры всю ладонь"
    )
    print("[ок] отпустил букву — диктовка закончилась")


def проверить_автоповтор(модель) -> None:
    """Зажатая клавиша не начинает диктовку заново десятки раз."""
    служба = СлужбаДиктовки(ЛожныйСервис(модель))
    стартов = []

    def начать() -> bool:
        стартов.append(1)
        служба._идёт = True
        return True

    клавиша = КлавишаДиктовки("<ctrl>+<shift>+d", ЗАЖАТИЕ, начать, lambda: None)
    клавиша.нажатие(Клавиша(name="ctrl_l"))
    клавиша.нажатие(Клавиша(name="shift"))
    # Windows шлёт нажатие снова и снова, пока клавишу держат.
    for _ in range(30):
        клавиша.нажатие(Клавиша(char="\x04"))

    assert len(стартов) == 1, (
        f"диктовка начиналась {len(стартов)} раз вместо одного: автоповтор "
        "клавиши рвёт запись на куски"
    )
    print("[ок] автоповтор клавиши не рвёт диктовку")


def проверить_полоску(попыток: int = 3) -> None:
    """Обёртка с повтором: одиночная неудача говорит о шуме на машине."""
    последняя = None
    for _ in range(попыток):
        try:
            _полоска_однажды()
            return
        except AssertionError as беда:
            последняя = беда
            time.sleep(1.0)
    raise AssertionError(f"за {попыток} попыток: {последняя}")


def _полоска_однажды() -> None:
    """Полоска не мешает тексту доехать до чужого окна.

    Судим не по тому, у кого фокус (это лишь признак), а по итогу:
    после показа и скрытия полоски текст обязан попасть туда же, куда
    попал бы без неё.

    Отдельно проверяется щелчок мышью. Он здесь главный: пока по
    полоске не щёлкнули, беда не видна, и снятый `WS_EX_NOACTIVATE`
    ничего не ломает. А человек по ней однажды щёлкнет — и без этого
    флага окно станет активным, забрав следующую фразу себе.

    Ради этого полоска написана на голом WinAPI с `WS_EX_NOACTIVATE`:
    обычное всплывающее окно забирает фокус себе. У Handy этому посвящён
    отдельный раздел README, они на этом обожглись.
    """
    from app.dictation.полоска import Полоска

    global _попытка
    _попытка += 1
    имя = f"konspekt_полоска_{os.getpid()}_{_попытка}"
    ОБРАЗЕЦ = "полоска не помешала"
    файл = os.path.join(tempfile.gettempdir(), f"{имя}.txt")
    open(файл, "w", encoding="utf-8").close()
    блокнот = subprocess.Popen(["notepad.exe", файл])
    полоска = Полоска()
    try:
        окно = 0
        предел = time.time() + 15
        while time.time() < предел and not окно:
            окно = _u.FindWindowW("Notepad", f"{имя}.txt - Notepad")
            time.sleep(0.2)
        assert окно, "Блокнот не открылся, проверка недействительна"
        # Окно уже есть, но поле ввода готово принимать позже. Без этой
        # паузы первый ввод улетает в пустоту, и проверка винит наш код
        # вместо неторопливого Блокнота.
        time.sleep(1.2)

        предел = time.time() + 8
        while time.time() < предел and _u.GetForegroundWindow() != окно:
            _поднять(окно)
            time.sleep(0.3)
        assert _u.GetForegroundWindow() == окно, (
            "не удалось отдать фокус Блокноту, проверка недействительна"
        )

        # Ровно то, что происходит при диктовке: показали, сменили
        # надпись, спрятали и вставили текст.
        полоска.показать("Слушаю…")
        time.sleep(0.8)
        assert полоска.видна, "полоска не появилась: диктовка идёт вслепую"

        полоска.сменить_текст("Распознаю…")
        time.sleep(0.3)
        полоска.скрыть()
        time.sleep(0.4)
        assert not полоска.видна, (
            "полоска не убралась и осталась висеть поверх всех окон"
        )

        # Фокус мог уехать к постороннему окну, пока мы возились с
        # полоской: на рабочей машине сами всплывают уведомления. Это
        # шум среды, а не наша беда, поэтому возвращаем окно и только
        # потом судим.
        if _u.GetForegroundWindow() != окно:
            _поднять(окно)
            time.sleep(0.4)
        assert _u.GetForegroundWindow() == окно, (
            "фокус увели посторонние окна, проверка недействительна"
        )

        вставка.вставить(ОБРАЗЕЦ, через_буфер=True)
        time.sleep(0.6)
        _u.keybd_event(0x11, 0, 0, 0)
        _u.keybd_event(0x53, 0, 0, 0)
        _u.keybd_event(0x53, 0, 2, 0)
        _u.keybd_event(0x11, 0, 2, 0)
        time.sleep(1.2)
        было = open(файл, encoding="utf-8-sig").read().strip()
        assert было == ОБРАЗЕЦ, (
            f"после полоски текст не доехал до нужного окна (в файле {было!r}): "
            "полоска помешала вводу"
        )
        print("[ок] полоска видна, убирается и не уводит текст мимо окна")

        # Щелчок по полоске. Человек попадёт по ней случайно, и вот
        # тут-то и нужен WS_EX_NOACTIVATE: без него окно от щелчка
        # становится активным, а следующая фраза уезжает в никуда.
        полоска.показать("Слушаю…")
        time.sleep(0.6)
        область = wintypes.RECT()
        _u.GetWindowRect(полоска.hwnd, ctypes.byref(область))
        x = (область.left + область.right) // 2
        y = (область.top + область.bottom) // 2
        _u.SetCursorPos(x, y)
        time.sleep(0.2)
        _u.mouse_event(0x0002, 0, 0, 0, 0)  # левая вниз
        time.sleep(0.05)
        _u.mouse_event(0x0004, 0, 0, 0, 0)  # левая вверх
        time.sleep(0.6)
        активное = _u.GetForegroundWindow()
        полоска.скрыть()
        assert активное != полоска.hwnd, (
            "щелчок по полоске сделал её активным окном: следующая "
            "продиктованная фраза уедет в неё, а не в работу человека"
        )
        print("[ок] щелчок по полоске не забирает фокус")
    finally:
        полоска.закрыть()
        блокнот.kill()
        time.sleep(0.3)
        try:
            os.unlink(файл)
        except OSError:
            pass


