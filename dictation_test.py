def найти_речь(модель, секунд: float = 6.0) -> np.ndarray | None:
    """Кусок настоящей речи из боевой записи, который модель понимает.

    Мало найти громкое место: громким бывает и стук по столу. Поэтому
    кандидат сразу проверяется моделью, и берётся тот, где получились
    настоящие слова. Иначе проверка диктовки падала бы не потому, что
    диктовка сломана, а потому, что мы скормили ей шум.

    Шесть секунд, а не четыре: GigaAM рассчитан на длинный вход и на
    коротком куске молча отдаёт пустоту.
    """
    корень = paths.audio_dir()
    if not корень.exists():
        return None
    файлы = sorted(
        (p for p in корень.rglob("*-me.wav") if p.stat().st_size > 5_000_000),
        key=lambda p: p.stat().st_size,
        reverse=True,
    )
    for файл in файлы[:6]:
        try:
            with wave.open(str(файл), "rb") as w:
                частота = w.getframerate()
                кадров = min(w.getnframes(), частота * 300)
                pcm = np.frombuffer(w.readframes(кадров), dtype=np.int16)
        except Exception:
            continue
        нужно = int(секунд * частота)
        if pcm.size < нужно * 2:
            continue

        окна = sorted(
            (
                (float(np.abs(pcm[н:н + нужно]).mean()), н)
                for н in range(0, pcm.size - нужно, частота)
            ),
            reverse=True,
        )
        занято: list[int] = []
        проверено = 0
        for громкость, начало in окна:
            if any(abs(начало - з) < нужно for з in занято):
                continue
            занято.append(начало)
            кусок = pcm[начало:начало + нужно]
            сегменты = list(модель.transcribe(кусок, частота, "", 0.0, "me"))
            текст = сегменты[0].text if сегменты else ""
            if sum(1 for c in текст if c.isalpha()) >= 8:
                return кусок
            проверено += 1
            if проверено >= 4:
                break
    return None

