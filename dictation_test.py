class ЗаписаннаяРечь:
    """Микрофон, подменённый боевой записью.

    Настоящий микрофон в проверке не годится: он молчит на машине сборки
    и слышит что попало на рабочей. Зато звук должен быть настоящей
    речью, иначе распознавание вернёт пустоту и проверка выродится.
    """

    def __init__(self, pcm: np.ndarray) -> None:
        self.pcm = pcm
        self.ошибка = None
        self._идёт = False

    @property
    def идёт_запись(self) -> bool:
        return self._идёт

    @property
    def уровень(self) -> float:
        return 0.5 if self._идёт else 0.0

    def старт(self, ждать: float = 2.0) -> bool:
        self._идёт = True
        return True

    def стоп(self) -> np.ndarray:
        self._идёт = False
        return self.pcm


