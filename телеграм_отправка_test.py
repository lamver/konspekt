# -*- coding: utf-8 -*-
"""«Отправить в Telegram»: какую ссылку программа открывает.

Ни бота, ни сервера: открываем tg://msg_url, Telegram показывает выбор
чата. Telegram Desktop без url отказывает, поэтому первая строка идёт в
url, остальное в text. Сообщение не длиннее 4096 знаков: длинные заметки
режем по строке, а целиком они уходят в буфер (это делает окно).
"""
from __future__ import annotations

import testenv  # noqa: F401

from urllib.parse import parse_qs, urlparse

from app.core import telegram as tg

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ok] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)



def части(адрес: str) -> dict:
    р = urlparse(адрес)
    return {"схема": р.scheme, "что": р.netloc, **{k: v[0] for k, v in parse_qs(р.query).items()}}


с = tg.ссылка("Итоги встречи\n- Петя чинит вход\n- Маша пишет письмо")
ч = части(с.адрес)
проверить(ч["схема"] == "tg" and ч["что"] == "msg_url", f"ссылка tg://msg_url ({с.адрес[:30]}…)")
проверить(ч.get("url") == "Итоги встречи", "первая строка в url: без него Telegram Desktop отказывает")
проверить(ч.get("text") == "- Петя чинит вход\n- Маша пишет письмо", "остальное в text, переводы строк целы")
проверить(с.целиком, "короткие заметки целиком")

проверить(tg.ссылка("   ") is None, "пустые заметки — никакой ссылки")
одна = части(tg.ссылка("Только заголовок").адрес)
проверить("text" not in одна and одна["url"] == "Только заголовок", "одна строка — только url")
собака = части(tg.ссылка("@bot запрос\nтекст").адрес)
проверить(not собака["url"].startswith("@"), "«@» в начале не превращается в запрос к боту")
амп = части(tg.ссылка("A & B\nx=1&y=2 #тег").адрес)
проверить(амп["url"] == "A & B" and амп["text"] == "x=1&y=2 #тег", "& и # в тексте не ломают ссылку")

длинный = "Итоги\n" + "\n".join(f"- пункт номер {i}, где что-то решили и кто-то взялся" for i in range(200))
д = tg.ссылка(длинный)
текст = части(д.адрес)
проверить(not д.целиком, "длинные заметки помечены: целиком не влезли")
проверить(len(текст["url"]) + 1 + len(текст["text"]) <= 4096, "сообщение не длиннее 4096 знаков")
проверить(текст["text"].endswith("\n…") and "\n- пункт номер" in текст["text"][-80:],
          "длинный текст обрезан по границе строки и помечен «…»")

# Открытие: только через ассоциацию Windows, без запуска чего-либо руками.
открыто: list[str] = []
настоящий = tg.os.startfile if hasattr(tg.os, "startfile") else None
tg.os.startfile = открыто.append
tg.sys.platform = "win32"
ответ = tg.открыть("Итоги\nтекст")
проверить(ответ == {"ok": True, "целиком": True} and открыто and открыто[0].startswith("tg://msg_url"),
          "открывает tg:// через ассоциацию Windows")


def нет_телеграма(адрес: str) -> None:
    raise OSError("Нет приложения, сопоставленного с этим протоколом")


tg.os.startfile = нет_телеграма
проверить(tg.открыть("Итоги\nтекст") == {"ok": False, "error": "no_telegram"},
          "Telegram не установлен — понятная ошибка, а не падение")
проверить(tg.открыть("") == {"ok": False, "error": "empty"}, "пустые заметки не открывают Telegram")
if настоящий:
    tg.os.startfile = настоящий

print()
if БЕДЫ:
    print(f"Бед: {len(БЕДЫ)}")
    raise SystemExit(1)
print("Отправка в Telegram собирает ссылку правильно.")
