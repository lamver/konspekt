"""Проверка признака речи в системном звуке (задача №28).

Главная опасность здесь не «не заметили речь», а «дёрнули человека
на музыке». Поэтому проверяем обе стороны: и что речь узнаётся, и что
ровная музыка, гул и тишина вопроса не вызывают.

Звук синтетический, звуковая карта не нужна: детектор — чистая
функция над кадрами, в этом и был смысл его так писать.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

import testenv  # noqa: F401  русский вывод в консоли Windows

from app.audio.чужая_речь import Слушатель, похоже_на_речь

ЧАСТОТА = 16000
БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def _тон(секунд: float, гц: float = 220.0, громкость: float = 0.2) -> np.ndarray:
    t = np.arange(int(секунд * ЧАСТОТА), dtype=np.float32) / ЧАСТОТА
    return (громкость * np.sin(2 * np.pi * гц * t)).astype(np.float32)


def речь(секунд: float = 6.0, слогов_в_секунду: float = 4.0) -> np.ndarray:
    """Похожее на речь: слоги вперемежку с паузами, плюс паузы между фразами.

    Настоящая речь это не ровный тон, а всплески энергии со слоговым
    ритмом. Но одного ритма мало: слоги должны быть разными. В речи
    чередуются гласные (низкий гудящий звук) и согласные (шипящие),
    и детектор смотрит в том числе на это чередование. Поэтому здесь
    слоги двух видов: тон и шум.
    """
    rng = np.random.default_rng(7)
    куски: list[np.ndarray] = []
    время = 0.0
    while время < секунд:
        # Слог: короткий всплеск шума с огибающей.
        длина = rng.uniform(0.12, 0.22)
        n = int(длина * ЧАСТОТА)
        огибающая = np.hanning(n).astype(np.float32)
        if rng.random() > 0.35:
            # Гласная: низкий тон с обертоном.
            t = np.arange(n, dtype=np.float32) / ЧАСТОТА
            основа = rng.uniform(90, 220)
            ядро = (np.sin(2 * np.pi * основа * t)
                    + 0.3 * np.sin(2 * np.pi * 2 * основа * t)).astype(np.float32)
        else:
            # Согласная: шипение.
            ядро = rng.normal(0, 1.0, n).astype(np.float32)
        куски.append((0.25 * ядро * огибающая).astype(np.float32))
        время += длина
        # Пауза между слогами, изредка длинная пауза между фразами.
        пауза = rng.uniform(0.04, 0.10) if rng.random() > 0.15 else rng.uniform(0.35, 0.6)
        куски.append(np.zeros(int(пауза * ЧАСТОТА), dtype=np.float32))
        время += пауза
        # Слоговой ритм задаёт частоту всплесков; параметр держим для
        # читаемости вызова.
        _ = слогов_в_секунду
    return np.concatenate(куски)[: int(секунд * ЧАСТОТА)]


def музыка(секунд: float = 6.0) -> np.ndarray:
    """Ровное полотно звука: несколько тонов без пауз."""
    основа = _тон(секунд, 220.0, 0.18)
    вторая = _тон(секунд, 277.0, 0.14)
    третья = _тон(секунд, 330.0, 0.12)
    # Лёгкое дыхание громкости, как в настоящей музыке, но без пауз.
    t = np.arange(len(основа), dtype=np.float32) / ЧАСТОТА
    оболочка = (0.85 + 0.15 * np.sin(2 * np.pi * 0.5 * t)).astype(np.float32)
    return ((основа + вторая + третья) * оболочка).astype(np.float32)


def гул(секунд: float = 6.0) -> np.ndarray:
    """Кулер или кондиционер: ровный шум без структуры."""
    rng = np.random.default_rng(3)
    return rng.normal(0, 0.03, int(секунд * ЧАСТОТА)).astype(np.float32)


def ноты_с_паузами(секунд: float = 6.0) -> np.ndarray:
    """Музыка с тишиной между нотами.

    Самый опасный случай: по громкости это неотличимо от речи, там тоже
    звук-пауза-звук. Разница в том, что нота однородна, а слоги речи
    разные.
    """
    куски: list[np.ndarray] = []
    время = 0.0
    i = 0
    while время < секунд:
        t = np.arange(int(0.7 * ЧАСТОТА), dtype=np.float32) / ЧАСТОТА
        нота = (0.2 * np.sin(2 * np.pi * (220 + 40 * i) * t)
                * np.hanning(len(t))).astype(np.float32)
        куски.append(нота)
        куски.append(np.zeros(int(0.3 * ЧАСТОТА), dtype=np.float32))
        время += 1.0
        i += 1
    return np.concatenate(куски)[: int(секунд * ЧАСТОТА)]


def щелчки(секунд: float = 6.0) -> np.ndarray:
    """Уведомления и клики: частые короткие всплески.

    По ритму похоже на очень быструю речь, но каждый щелчок одинаков.
    """
    rng = np.random.default_rng(11)
    звук = np.zeros(int(секунд * ЧАСТОТА), dtype=np.float32)
    for _ in range(int(секунд * 10)):
        поз = int(rng.uniform(0, len(звук) - 500))
        звук[поз:поз + 300] = rng.normal(0, 0.3, 300).astype(np.float32)
    return звук


def тишина(секунд: float = 6.0) -> np.ndarray:
    return np.zeros(int(секунд * ЧАСТОТА), dtype=np.float32)


def говор_без_пауз(секунд: float = 6.0) -> np.ndarray:
    """Слитный звук с речевым тембром: диктор без единой паузы.

    Тембр здесь речевой, а пауз нет вовсе. Отсечь это должна верхняя
    граница доли звука: сплошная стена — не разговор, а вещание.
    """
    rng = np.random.default_rng(5)
    куски: list[np.ndarray] = []
    время = 0.0
    while время < секунд:
        длина = rng.uniform(0.12, 0.22)
        n = int(длина * ЧАСТОТА)
        if rng.random() > 0.35:
            t = np.arange(n, dtype=np.float32) / ЧАСТОТА
            основа = rng.uniform(90, 220)
            ядро = np.sin(2 * np.pi * основа * t).astype(np.float32)
        else:
            ядро = rng.normal(0, 1.0, n).astype(np.float32)
        # Без огибающей и без пауз: звук идёт стеной.
        куски.append((0.25 * ядро).astype(np.float32))
        время += длина
    return np.concatenate(куски)[: int(секунд * ЧАСТОТА)]


def ровный_говор(секунд: float = 12.0) -> np.ndarray:
    """Речевой тембр без слогового ритма: длинные слитные куски.

    Переключений мало, хотя тембр скачет. Отсечь должен порог
    переключений: разговор — это слоговой ритм, а не два звука за
    десять секунд.
    """
    rng = np.random.default_rng(13)
    куски: list[np.ndarray] = []
    время = 0.0
    while время < секунд:
        длина = 2.5
        n = int(длина * ЧАСТОТА)
        часть = np.zeros(n, dtype=np.float32)
        шаг = n // 12
        for i in range(12):
            a, b = i * шаг, (i + 1) * шаг
            if i % 2 == 0:
                t = np.arange(b - a, dtype=np.float32) / ЧАСТОТА
                часть[a:b] = np.sin(2 * np.pi * 150 * t)
            else:
                часть[a:b] = rng.normal(0, 1.0, b - a)
        куски.append((0.25 * часть).astype(np.float32))
        время += длина
        куски.append(np.zeros(int(0.5 * ЧАСТОТА), dtype=np.float32))
        время += 0.5
    return np.concatenate(куски)[: int(секунд * ЧАСТОТА)]


def стена_с_щелями(секунд: float = 6.0) -> np.ndarray:
    """Почти непрерывный звук: звучит 97% времени.

    Всё остальное здесь речевое: громкость гуляет, тембр скачет,
    переключения есть. Единственное, что выдаёт вещание, — доля времени,
    в которое вообще есть звук. В разговоре так не бывает: люди дышат и
    делают паузы.
    """
    rng = np.random.default_rng(2)
    кадр = int(0.02 * ЧАСТОТА)
    кадров = int(секунд * ЧАСТОТА) // кадр
    # Два уровня громкости, оба заметно выше тишины: разброс получается
    # речевой, но звук не смолкает ни на миг.
    громкости = np.where(rng.random(кадров) > 0.5, 0.95, 0.25)
    # Редкие провалы: раз в 40 кадров, то есть раз в 0.8 секунды.
    for i in range(0, кадров, 40):
        громкости[i] = 0.005
    звук = np.zeros(кадров * кадр, dtype=np.float32)
    for i, g in enumerate(громкости):
        a = i * кадр
        if i % 3 == 0:
            t = np.arange(кадр, dtype=np.float32) / ЧАСТОТА
            звук[a:a + кадр] = g * np.sin(2 * np.pi * 150 * t)
        else:
            звук[a:a + кадр] = rng.normal(0, g, кадр)
    return звук


def проверить_речь() -> None:
    о = похоже_на_речь(речь())
    проверить(о.есть_речь, f"речь узнаётся ({о.to_dict()})")

    # Тихая речь тоже речь: собеседник в наушниках звучит негромко.
    о = похоже_на_речь(речь() * 0.25)
    проверить(о.есть_речь, f"тихая речь узнаётся ({о.to_dict()})")


def проверить_не_речь() -> None:
    """Ложная тревога хуже пропуска: она дёргает человека посреди встречи."""
    о = похоже_на_речь(музыка())
    проверить(not о.есть_речь, f"музыка не принимается за речь ({о.to_dict()})")

    о = похоже_на_речь(гул())
    проверить(not о.есть_речь, f"ровный гул не принимается за речь ({о.to_dict()})")

    о = похоже_на_речь(тишина())
    проверить(not о.есть_речь, f"тишина не принимается за речь ({о.to_dict()})")

    # Громкая тишина: ровный тон на всю длину, ни одной паузы.
    о = похоже_на_речь(_тон(6.0, 440.0, 0.3))
    проверить(not о.есть_речь, f"ровный тон не принимается за речь ({о.to_dict()})")

    # Музыка с паузами между нотами: по громкости неотличима от речи,
    # спасает только разница в тембре.
    о = похоже_на_речь(ноты_с_паузами())
    проверить(not о.есть_речь,
              f"музыка с паузами между нотами не принимается за речь ({о.to_dict()})")

    # Щелчки уведомлений: ритм есть, а речи нет.
    о = похоже_на_речь(щелчки())
    проверить(not о.есть_речь, f"щелчки не принимаются за речь ({о.to_dict()})")

    # Речевой тембр без пауз: вещание, а не разговор. Здесь решает
    # верхняя граница доли звука.
    о = похоже_на_речь(говор_без_пауз())
    проверить(not о.есть_речь,
              f"сплошной звук без пауз не принимается за речь ({о.to_dict()})")

    # Речевой тембр без слогового ритма. Здесь решает порог переключений.
    о = похоже_на_речь(ровный_говор())
    проверить(not о.есть_речь,
              f"звук без слогового ритма не принимается за речь ({о.to_dict()})")

    # Самый хитрый случай: звук идёт почти сплошь, но с крошечными
    # провалами. Громкость гуляет, провалы дают переключения, тембр
    # речевой — то есть все прочие признаки обмануты. Отсечь такое может
    # только верхняя граница доли: разговор, в котором звучит 99%
    # времени, это не разговор, а вещание с придыханиями.
    о = похоже_на_речь(стена_с_щелями())
    проверить(not о.есть_речь,
              f"стена звука с крошечными щелями не речь ({о.to_dict()})")


def проверить_края() -> None:
    """Пустое и короткое не должно ни падать, ни выдумывать речь."""
    проверить(not похоже_на_речь(np.zeros(0, dtype=np.float32)).есть_речь,
              "пустой звук не роняет и не даёт речи")
    проверить(not похоже_на_речь(None).есть_речь,
              "None не роняет и не даёт речи")
    # Полсекунды: слоговой ритм измерить не на чем, судить нельзя.
    проверить(not похоже_на_речь(речь(0.5)).есть_речь,
              "слишком короткий кусок не даёт вердикта")


def проверить_чистоту() -> None:
    """Функция не должна портить то, что ей дали, и обязана быть повторяемой."""
    звук = речь()
    копия = звук.copy()
    первый = похоже_на_речь(звук)
    второй = похоже_на_речь(звук)
    проверить(np.array_equal(звук, копия), "исходный звук не испорчен")
    проверить(первый.to_dict() == второй.to_dict(),
              "повторный вызов даёт тот же ответ")


def _кормить(слушатель: Слушатель, звук: np.ndarray, куском: float = 0.5) -> int:
    """Скормить звук маленькими кусками, как это делает захват.

    Возвращает число тревог: их должно быть не больше одной.
    """
    шаг = int(куском * ЧАСТОТА)
    тревог = 0
    for i in range(0, len(звук), шаг):
        if слушатель.добавить(звук[i:i + шаг]):
            тревог += 1
    return тревог


def проверить_слушателя() -> None:
    """Тревога поднимается на речи, молчит на музыке и звучит один раз."""
    с = Слушатель()
    тревог = _кормить(с, речь(30.0))
    проверить(тревог == 1, f"на речи спросили ровно один раз (было {тревог})")

    с = Слушатель()
    тревог = _кормить(с, музыка(30.0))
    проверить(тревог == 0, f"на музыке не спросили ни разу (было {тревог})")

    с = Слушатель()
    тревог = _кормить(с, тишина(30.0))
    проверить(тревог == 0, f"на тишине не спросили ни разу (было {тревог})")

    # Одного окна мало: короткая заставка ролика не должна дёргать.
    с = Слушатель()
    тревог = _кормить(с, np.concatenate([речь(6.5), тишина(20.0)]))
    проверить(тревог == 0,
              f"одиночный всплеск речи не поднимает тревогу (было {тревог})")

    # Ответ человека затыкает наблюдателя до конца записи.
    с = Слушатель()
    с.замолчать()
    тревог = _кормить(с, речь(30.0))
    проверить(тревог == 0, f"после ответа человека больше не спрашиваем (было {тревог})")

    # Сброс возвращает всё в исходное: новая встреча спросит заново.
    с = Слушатель()
    _кормить(с, речь(30.0))
    с.сброс()
    тревог = _кормить(с, речь(30.0))
    проверить(тревог == 1, f"после сброса спрашиваем снова (было {тревог})")

    # Два далёких всплеска речи не должны сложиться в тревогу: между
    # ними была тишина, значит счёт начинается заново.
    с = Слушатель()
    тревог = _кормить(с, np.concatenate([
        речь(6.5), тишина(12.0), речь(6.5), тишина(12.0),
    ]))
    проверить(тревог == 0,
              f"два всплеска через паузу не складываются в тревогу (было {тревог})")


def main() -> int:
    проверить_речь()
    проверить_не_речь()
    проверить_края()
    проверить_чистоту()
    проверить_слушателя()

    if БЕДЫ:
        print(f"\nНе прошло проверок: {len(БЕДЫ)}")
        return 1
    print("\nПризнак речи в системном звуке в порядке.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
