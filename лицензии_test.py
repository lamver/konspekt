"""Сторож лицензий: не приехала ли в зависимости заразная GPL.

Зачем это нужно. Konspekt продаётся под FSL-1.1-MIT. Полная GPL требует,
чтобы всю программу целиком выпустили под GPL, и одна такая библиотека
делает продажу лицензий невозможной. Заметить это через полгода на этапе
продаж — катастрофа, заметить в день установки — мелкая правка.

Ловушка не выдумана, а близка. При переносе на Linux pywebview предлагает
выбор: `pywebview[gtk]` тянет PyGObject под LGPL (можно), а
`pywebview[qt]` тянет PyQt6 под GPL v3 (нельзя). Разница в одном слове
в команде установки, и без этой проверки её никто не заметит.

LGPL при этом разрешена: она не затрагивает наш код, требуя лишь
возможности подменить саму библиотеку. Мы это обеспечиваем открытым
кодом и пересборкой, о чём написано в ЛИЦЕНЗИИ.md.
"""

from __future__ import annotations

import testenv  # noqa: F401  русский вывод в консоли Windows

import re
import sys
from importlib.metadata import distributions
from pathlib import Path
from urllib.parse import unquote

sys.path.insert(0, ".")

КОРЕНЬ = Path(__file__).resolve().parent

# Известные заразные лицензии. LGPL сюда намеренно не входит: она
# ограничивает только саму библиотеку, а не программу вокруг неё.
#
# Про «(?<!L)» и «(?<!Lesser )». Без них образцы ловят и LGPL: в строке
# «LGPLv3» сидит «GPLv3», а в «Lesser General Public License v3» —
# «General Public License v3». Проверено: без этих оговорок сторож
# требовал выбросить pynput и pystray, то есть диктовку и значок в трее.
ЗАРАЗНЫЕ = [
    (r"(?<!L)GPL-?[23]", "GPL"),
    (r"(?<!L)GPLv[23]", "GPL"),
    (r"(?<!Lesser )General Public License v[23]", "GPL"),
    (r"\bAGPL", "AGPL"),
    (r"Affero", "AGPL"),
    (r"\bSSPL", "SSPL"),
]

# Кому заразность прощена и почему. Каждое исключение — обещание,
# которое мы даём покупателю, поэтому оно записано словами.
ИСКЛЮЧЕНИЯ = {
    # У PyInstaller особая оговорка: собранные им программы не обязаны
    # быть под GPL. Он упаковщик, его код в сборку не попадает.
    "pyinstaller": "GPL v2 с оговоркой для собранных программ",
    "pyinstaller-hooks-contrib": "часть упаковщика, в сборку не попадает",
}


def лицензия_пакета(dist) -> str:
    """Всё, что пакет говорит о своей лицензии, одной строкой."""
    m = dist.metadata
    куски = [m.get("License") or "", m.get("License-Expression") or ""]
    куски += [c for c in (m.get_all("Classifier") or []) if "License" in c]
    return " ".join(куски)


def проверить_зависимости() -> None:
    беда = []
    осмотрено = 0
    for dist in distributions():
        имя = (dist.metadata.get("Name") or "").lower()
        if not имя:
            continue
        осмотрено += 1
        текст = лицензия_пакета(dist)
        for образец, ярлык in ЗАРАЗНЫЕ:
            if re.search(образец, текст, re.IGNORECASE):
                if имя in ИСКЛЮЧЕНИЯ:
                    break
                беда.append((имя, ярлык, текст.strip()[:70]))
                break

    assert осмотрено > 20, f"пакетов подозрительно мало ({осмотрено}), окружение не то"

    if беда:
        строки = "\n".join(f"    {и} — {я}: {т}" for и, я, т in беда)
        raise AssertionError(
            "заразная лицензия в зависимостях, продажа Konspekt под FSL "
            f"станет невозможной:\n{строки}\n"
            "    Уберите библиотеку или найдите замену под MIT/BSD/Apache/LGPL.\n"
            "    На Linux ставьте pywebview[gtk], а не pywebview[qt]."
        )
    print(f"[ок] среди {осмотрено} зависимостей нет заразных лицензий")


def проверить_документы() -> None:
    """Лицензия и её пересказ на месте и не разошлись между собой."""
    лиц = КОРЕНЬ / "LICENSE.md"
    свод = КОРЕНЬ / "ЛИЦЕНЗИИ.md"

    assert лиц.exists(), "нет LICENSE.md: открытый репозиторий без лицензии никому не даёт прав"
    текст = лиц.read_text(encoding="utf-8")
    assert "FSL-1.1-MIT" in текст, "LICENSE.md не похож на FSL"
    assert "Competing Use" in текст, "в лицензии нет запрета на конкурирующий продукт"
    assert "second anniversary" in текст, "потерян переход в MIT через два года"
    assert "Valerij Frolov" in текст, "в лицензии не указан правообладатель"
    assert "${" not in текст, "в лицензии остались неподставленные места из шаблона"

    assert свод.exists(), "нет ЛИЦЕНЗИИ.md: покупателю негде прочитать про чужие библиотеки"
    свод_текст = свод.read_text(encoding="utf-8")
    for слово in ("pynput", "pystray", "LGPL", "GigaAM"):
        assert слово in свод_текст, f"в ЛИЦЕНЗИИ.md не упомянут {слово}"

    print("[ок] лицензия на месте, запрет на копирование и переход в MIT целы")


def проверить_упоминание_в_readme() -> None:
    """Человек должен видеть условия сразу, а не искать их по файлам.

    Условия именно «и», а не «или»: ссылка на LICENSE.md без слова FSL
    ничего не говорит о правилах, а название лицензии без ссылки не даёт
    её прочитать. Мутационная проверка показала, что с «или» пропадание
    FSL из README оставалось незамеченным.
    """
    readme = (КОРЕНЬ / "README.md").read_text(encoding="utf-8")
    assert "FSL" in readme, "README не называет лицензию: читатель не поймёт условий"
    assert "LICENSE.md" in readme, "README не ведёт к тексту лицензии"
    assert "ЛИЦЕНЗИИ.md" in readme, "README не ведёт к разбору чужих лицензий"
    print("[ок] README рассказывает про лицензию и ведёт к подробностям")


def проверить_ссылки_в_документах() -> None:
    """Ссылки на лицензию ведут на файлы, а не в пустоту.

    В открытом репозитории README — первое, что видит человек, и битая
    ссылка на лицензию выглядит небрежностью именно там, где нужно
    доверие. Отдельный риск: ЛИЦЕНЗИИ.md назван кириллицей, а такие
    ссылки ломаются чаще прочих.
    """
    ссылка = re.compile(r"\[[^\]]+\]\(([^)]+)\)")
    плохие = []
    проверено = 0
    for имя in ("README.md", "ЛИЦЕНЗИИ.md", "ROADMAP.md", "CHANGELOG.md"):
        п = КОРЕНЬ / имя
        if not п.exists():
            continue
        for цель in ссылка.findall(п.read_text(encoding="utf-8")):
            if цель.startswith(("http://", "https://", "#", "mailto:")):
                continue
            путь = unquote(цель.split("#")[0])
            if not путь:
                continue
            проверено += 1
            if not (КОРЕНЬ / путь).exists():
                плохие.append(f"{имя} -> {цель}")

    assert not плохие, "ссылки ведут в пустоту: " + ", ".join(плохие)
    assert проверено >= 2, f"ссылок подозрительно мало ({проверено}), проверять нечего"
    print(f"[ок] {проверено} ссылок в документах ведут на существующие файлы")


def main() -> int:
    проверить_зависимости()
    проверить_документы()
    проверить_упоминание_в_readme()
    проверить_ссылки_в_документах()
    print("Проверка лицензий пройдена")
    return 0


if __name__ == "__main__":
    sys.exit(main())
