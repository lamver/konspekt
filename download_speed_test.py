# -*- coding: utf-8 -*-
"""Большие файлы модели качаются несколькими соединениями сразу.

Hugging Face режет скорость одного соединения. Замер на живом канале:
в один поток 0.30 МБ/с, в четыре-восемь 0.6-1.1 МБ/с. Человек ждал
модель на 214 МБ около двенадцати минут вместо двух-трёх.

Скорость здесь нарочно не сравниваем: канал скачет втрое от минуты к
минуте, и такая проверка падала бы от погоды в сети, а не от поломки.
Проверяем то, что от нас зависит: файл просят кусками, куски идут
разными соединениями одновременно, а собранный файл совпадает с
исходным побайтово.
"""
import hashlib
import shutil
import sys
import tempfile
import threading
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from app.asr.download import ПОРОГ_ДРОБЛЕНИЯ, ПОТОКОВ, ModelDownloader


def сеть_жива() -> bool:
    try:
        urllib.request.urlopen("https://huggingface.co", timeout=10).close()
        return True
    except Exception:
        return False


if not сеть_жива():
    print("[пропуск] нет сети, качать неоткуда")
    raise SystemExit(0)

РЕПО = "istupakov/gigaam-v3-onnx"
# Небольшой файл: проверка про устройство загрузки, а не про терпение.
ФАЙЛ = "v3_e2e_rnnt_decoder.onnx"

tmp = Path(tempfile.mkdtemp(prefix="konspekt-качалка-"))
try:
    d = ModelDownloader(РЕПО, (ФАЙЛ,), tmp)

    всего = d._размер_на_сервере(ФАЙЛ)
    assert всего > 0, (
        "сервер не сказал размер файла: тогда дробить нельзя и загрузка "
        "молча скатится в один медленный поток"
    )
    print(f"[ok] сервер отдаёт размер и берёт запросы по кускам: {всего} байт")

    # Сколько соединений открылось на самом деле. Без этого проверка
    # прошла бы и на однопоточной загрузке.
    соединений = set()
    настоящий = urllib.request.urlopen

    def считая(запрос, *a, **kw):
        if getattr(запрос, "headers", None) and "Range" in str(запрос.headers):
            соединений.add(threading.current_thread().name)
        return настоящий(запрос, *a, **kw)

    urllib.request.urlopen = считая
    try:
        d._качать_кусками(ФАЙЛ, tmp / ФАЙЛ, всего, None)
    finally:
        urllib.request.urlopen = настоящий

    assert len(соединений) > 1, (
        f"файл качало одно соединение ({соединений}): человек по-прежнему "
        f"ждёт модель в несколько раз дольше нужного"
    )
    print(f"[ok] файл качали {len(соединений)} соединений одновременно")

    факт = (tmp / ФАЙЛ).stat().st_size
    assert факт == всего, (
        f"собранный файл весит {факт} вместо {всего}: на диск лёг обрубок, "
        f"который выглядит как готовая модель и падает уже при распознавании"
    )

    # Побайтовая сверка с исходником: склейка кусков не должна их
    # перепутать местами. По размеру такую беду не заметить.
    url = f"https://huggingface.co/{РЕПО}/resolve/main/{ФАЙЛ}"
    with urllib.request.urlopen(url, timeout=120) as о:
        эталон = hashlib.sha256(о.read()).hexdigest()
    наш = hashlib.sha256((tmp / ФАЙЛ).read_bytes()).hexdigest()
    assert наш == эталон, (
        "собранный файл не совпадает с исходным: куски склеены неверно, "
        "модель из такого файла не загрузится"
    )
    print(f"[ok] файл совпадает с исходным побайтово ({факт} байт)")

    остатки = list(tmp.glob("*.куски"))
    assert not остатки, (
        f"временные куски не убраны: {остатки}. Они весят столько же, "
        f"сколько модель, и человек молча теряет место вдвое"
    )
    print("[ok] временные куски убраны")

    print("\nМодель качается в несколько соединений и собирается верно")
finally:
    shutil.rmtree(tmp, ignore_errors=True)
