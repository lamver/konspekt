// Проверка: предупреждение о немой дорожке не должно глушить кнопку записи.
//
// Живой случай (0.7.3): на дорожке «системный звук» не было звука,
// внизу мелькнуло сообщение — и после него пропала визуализация
// микрофона, а кнопка осталась в положении «Остановить» и перестала
// реагировать на клики. Причина: предупреждение приходило тем же
// событием, что и «не удалось начать запись», а от него окно решает,
// что записи больше нет. Запись при этом продолжалась.
//
// Гоняем настоящий web/app.js, а не его копию: копия разошлась бы с
// кодом молча, и проверка охраняла бы уже не то.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const код = fs.readFileSync(path.join(__dirname, 'web', 'app.js'), 'utf8');

// --- поддельное окно ----------------------------------------------------
function узел() {
  const себя = {
    hidden: false,
    textContent: '',
    value: '',
    style: {},
    dataset: {},
    children: [],
    classList: { toggle() {}, add() {}, remove() {}, contains: () => false },
    addEventListener() {},
    removeEventListener() {},
    appendChild() {},
    setAttribute() {},
    removeAttribute() {},
    querySelector: () => узел(),
    querySelectorAll: () => [],
    getBoundingClientRect: () => ({ width: 0, height: 0, top: 0, left: 0 }),
    focus() {},
    scrollIntoView() {},
    remove() {},
  };
  return себя;
}

const песочница = {
  console,
  setTimeout,
  clearTimeout,
  setInterval,
  clearInterval,
  document: {
    getElementById: () => узел(),
    createElement: () => узел(),
    querySelector: () => узел(),
    querySelectorAll: () => [],
    body: узел(),
    documentElement: узел(),
    addEventListener() {},
  },
  localStorage: { getItem: () => null, setItem() {}, removeItem() {} },
  navigator: { userAgent: 'test' },
  fetch: async () => ({ ok: true, json: async () => ({}) }),
};
песочница.addEventListener = () => {};
песочница.removeEventListener = () => {};
песочница.matchMedia = () => ({ matches: false, addEventListener() {} });
песочница.window = песочница;
песочница.globalThis = песочница;

vm.createContext(песочница);
// state объявлен через const и наружу сам не выходит. Достаём его
// хвостовой строкой, а не копией: проверять надо то самое состояние,
// которым живёт настоящее окно.
vm.runInContext(код + '\nglobalThis.__state = state;', песочница,
                { filename: 'app.js' });
песочница.state = песочница.__state;

// Обычно ui наполняет bindUi(), но звать его нельзя: он заводит таймеры
// и подписки, и проверка после этого не завершается. Кладём поддельные
// узлы сами. Рисование пойдёт настоящим кодом, просто в пустоту: нас
// интересует state, а не пиксели.
песочница.__узел = узел;
vm.runInContext(
  "for (const и of ['record','recLabel','levels','timer','levelMe'," +
  "'levelThem','toast','toastText']) ui[и] = globalThis.__узел();",
  песочница
);

const событие = песочница.window.__konspekt_event;
if (typeof событие !== 'function') {
  throw new Error('app.js не выставил приёмник событий');
}

// Ставим окно в состояние живой записи.
песочница.state.isRecording = true;
песочница.state.recordingId = 'встреча-1';
песочница.state.startedAt = Date.now();

// Показанные человеку сообщения. Без этого проверка была слепа к
// худшему случаю: событие никуда не подключено, окно его молча
// проглатывает, состояние цело — и о немой дорожке снова никто не
// узнает. Ровно так и вышло при первой попытке.
const сообщения = [];
песочница.showToast = (текст) => сообщения.push(текст);

// --- Немая дорожка ------------------------------------------------------
событие({
  topic: 'recording.silent',
  track: 'them',
  silent: true,
  message: 'Тишина на дорожке «системный звук»',
});

if (!песочница.state.isRecording) {
  throw new Error(
    'после предупреждения о тишине окно считает, что записи нет: кнопка ' +
    'перестанет слушаться, а визуализация звука пропадёт посреди встречи'
  );
}
if (песочница.state.recordingId !== 'встреча-1') {
  throw new Error('предупреждение о тишине потеряло текущую запись');
}
if (сообщения.length !== 1) {
  throw new Error(
    'о немой дорожке человеку ничего не показали: событие никуда не ' +
    'подключено, и человек снова узнает о беде только по бессмысленной ' +
    'расшифровке'
  );
}
console.log('[ok] предупреждение о тишине показано и не сбивает состояние записи');

// --- Задача №27: плашка говорит на языке человека и подсказывает выход ---
//
// Текст раньше целиком собирался в Python по-русски. Человек с
// интерфейсом на английском получал русскую фразу — та же беда, что
// ключ перевода вместо текста. И главное: предупреждение не говорило,
// что делать, а только пугало посреди нормально идущей встречи.
const словарь = JSON.parse(
  fs.readFileSync(path.join(__dirname, 'web', 'i18n', 'en.json'), 'utf8')
);
vm.runInContext('i18n.dict = globalThis.__словарь;', Object.assign(
  песочница, { __словарь: словарь }
));

сообщения.length = 0;
событие({
  topic: 'recording.silent',
  track: 'them',
  silent: true,
  'секунд': 10,
  message: 'Тишина на дорожке «системный звук»: за 10 секунд не было ни звука.',
});

const текст = сообщения[0] || '';
if (/[а-яё]/i.test(текст)) {
  throw new Error(
    'при английском интерфейсе показали русский текст: "' + текст + '". ' +
    'Человек, не знающий русского, не поймёт, что случилось с записью'
  );
}
if (!текст.includes('system audio')) {
  throw new Error(
    'в предупреждении не сказано, какая именно дорожка молчит: "' + текст +
    '". Человеку негде узнать, что чинить'
  );
}
if (!текст.includes('10')) {
  throw new Error('в предупреждении потерялось, сколько секунд молчала дорожка: ' + текст);
}
if (!текст.toLowerCase().includes('settings')) {
  throw new Error(
    'предупреждение не говорит, что делать: "' + текст + '". Тревога без ' +
    'выхода посреди идущей встречи — это и есть жалоба из задачи №27'
  );
}
console.log('[ok] плашка о тишине говорит на языке человека и подсказывает выход:');
console.log('     ' + текст);

// --- Словарь ещё не доехал: показываем русский запасной текст -----------
//
// Он честнее ключа «recording.silent», который человеку ничего не
// говорит ни на одном языке.
vm.runInContext('i18n.dict = {};', песочница);
сообщения.length = 0;
событие({
  topic: 'recording.silent',
  track: 'them',
  silent: true,
  'секунд': 10,
  message: 'Тишина на дорожке «системный звук»: за 10 секунд не было ни звука.',
});
if (сообщения[0] !== 'Тишина на дорожке «системный звук»: за 10 секунд не было ни звука.') {
  throw new Error(
    'без словаря показали не запасной текст, а "' + сообщения[0] + '": ' +
    'человек увидит ключ перевода вместо объяснения'
  );
}
console.log('[ok] без словаря показывается человеческий запасной текст');

vm.runInContext('i18n.dict = globalThis.__словарь;', песочница);

// --- Настоящая ошибка старта --------------------------------------------
событие({ topic: 'recording.error', message: 'Устройство занято' });
if (песочница.state.isRecording) {
  throw new Error(
    'запись не началась, а окно продолжает показывать «идёт запись»: ' +
    'человек будет думать, что встреча пишется, и потеряет её'
  );
}
console.log('[ok] настоящая ошибка старта по-прежнему снимает запись');

// --- Возврат в строй ----------------------------------------------------
// Сервис на повторный «начать» во время записи заново сообщает окну,
// что запись идёт. Без этого разошедшееся окно чинится только
// перезапуском программы.
событие({
  topic: 'recording.started',
  meeting_id: 'встреча-1',
  started_at: Date.now() / 1000,
});
if (!песочница.state.isRecording) {
  throw new Error('окно не восстановилось по повторному recording.started');
}
console.log('[ok] окно чинится, когда сервис заново сообщает о записи');

console.log('\nТишина на дорожке больше не глушит кнопку записи.');

// Окно завело секундомер записи. Он на setInterval и держал бы node
// вечно: без этого проверка не завершается и висит в прогоне.
песочница.stopTimer();
