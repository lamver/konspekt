провалов = 0


def проверить(условие: bool, что: str) -> None:
    global провалов
    if условие:
        print(f"[ok] {что}")
    else:
        провалов += 1
        print(f"[FAIL] {что}")


# --- поддельная модель ---------------------------------------------------

ТЕМЫ = {
    "деньги": ("оплат", "платеж", "карт", "деньг", "счёт", "тариф"),
    "сервер": ("сервер", "нагрузк", "база", "упал", "сеть"),
    "еда": ("пицц", "обед", "кофе", "ужин"),
}


class FakeModel:
    """Раскладывает текст по темам: вектор — сколько слов какой темы.

    Добавлена небольшая общая часть, чтобы все тексты были «немного
    похожи», как у настоящей модели: иначе отбор по выделению из толпы
    нечем было бы проверить.
    """

    name = "fake-meaning"

    def __init__(self, downloaded: bool = True) -> None:
        self.downloaded = downloaded
        self.passages_calls = 0

    def is_downloaded(self) -> bool:
        return self.downloaded

    def _vec(self, text: str) -> np.ndarray:
        low = text.lower()
        v = np.array([sum(low.count(k) for k in ключи) for ключи in ТЕМЫ.values()]
                     + [1.0], dtype=np.float32)
        return v / np.linalg.norm(v)

    def query(self, text: str) -> np.ndarray:
        return self._vec(text)

    def passages(self, texts: list[str]) -> np.ndarray:
        self.passages_calls += 1
        if not texts:
            return np.zeros((0, 4), dtype=np.float32)
        return np.vstack([self._vec(t) for t in texts])


def реплики(store: Store, meeting_id: str, тексты: list[str], начало: float = 0.0) -> None:
    for i, текст in enumerate(тексты):
        store.add_segment(TranscriptSegment(
            meeting_id=meeting_id, text=текст, speaker=Speaker.THEM,
            start=начало + i * 5.0, end=начало + i * 5.0 + 4.0,
        ))


ДЛИННО = " и ещё немного обычных слов для длины куска"
# Фоновых встреч столько, чтобы находка могла выделиться из толпы, как
# в настоящем архиве: на десятке встреч выделяться просто не из чего.
ШУМА = 40


# --- 1. нарезка ---------------------------------------------------------

def check_chunks() -> None:
    сегменты = [{"text": f"реплика номер {i} " + "слово " * 10, "start": i * 3.0, "who": f"Голос {i}"}
                for i in range(20)]
    куски = m.chunk_segments(сегменты)
    проверить(1 < len(куски) < 20, f"реплики склеиваются в куски, а не идут по одной ({len(куски)} из 20)")
    проверить(all(len(к["text"]) <= m.CHUNK_CHARS + 120 for к in куски),
              "кусок не разрастается сильно дальше заданного размера")
    проверить(куски[0]["start"] == 0.0 and куски[1]["start"] > 0,
              "у куска время его первой реплики: клик откроет нужное место")
    проверить(куски[1]["who"] == сегменты[куски[1]["start"] and int(куски[1]["start"] / 3)]["who"],
              "говорящий куска — тот, кто начал этот кусок")
    склеено = " ".join(к["text"] for к in куски)
    проверить(all(f"номер {i} " in склеено for i in range(20)), "ни одна реплика не потерялась при нарезке")

    мусор = m.chunk_segments([{"text": "а.", "start": 0.0}, {"text": "Д", "start": 1.0}])
    проверить(мусор == [], "обрывки вроде «а.» и «Д» не становятся кусками: модель нашла бы их везде")
    проверить(m.chunk_segments([{"text": "   ", "start": 0}, {"text": "", "start": 1}]) == [],
              "пустые реплики не ломают нарезку")


# --- 2. отбор -----------------------------------------------------------

def check_pick() -> None:
    items = [{"i": i} for i in range(100)]
    шум = np.full(100, 0.83, dtype=np.float32) + np.linspace(0, 0.01, 100).astype(np.float32)
    проверить(m.pick(items, шум) == [], "все похожи одинаково — это шум, не находка")

    # Шум с высокой близостью: у настоящей модели так бывает на общих
    # запросах, и отсечь его может только выделение из толпы. Первая
    # версия этой проверки держала шум ниже порога близости, и выбрось
    # кто-нибудь второй порог, она бы этого не заметила.
    громкий_шум = np.full(100, 0.86, dtype=np.float32) + np.linspace(0, 0.01, 100).astype(np.float32)
    проверить(m.pick(items, громкий_шум) == [],
              "шум с высокой близостью тоже шум: общий запрос не тянет весь архив")

    с_находкой = шум.copy()
    с_находкой[42] = 0.88
    найдено = m.pick(items, с_находкой)
    проверить([н["i"] for н in найдено] == [42], "кусок, стоящий особняком, находится, а толпа нет")

    слабый = шум.copy()
    слабый[7] = 0.849
    проверить(m.pick(items, слабый) == [],
              "выделяется, но близость ниже порога: не показываем, иначе полезет чужая тема")

    проверить(m.pick([], np.zeros(0, dtype=np.float32)) == [], "пустой указатель не падает")
    одна = m.pick([{"i": 0}], np.array([0.9], dtype=np.float32))
    проверить(len(одна) == 1, "в архиве из одного куска выделяться не из чего, хватает близости")


# --- 3. слияние ---------------------------------------------------------

def check_merge() -> None:
    по_словам = [{"meeting_id": "a", "title": "А", "created_at": 1, "hits": 2, "quotes": [{"text": "x"}]}]
    по_смыслу = [
        {"meeting_id": "a", "title": "А", "created_at": 1, "start_s": 0, "who": "", "text": "повтор", "score": 0.9},
        {"meeting_id": "b", "title": "Б", "created_at": 2, "start_s": 5, "who": "Я", "text": "б1", "score": 0.87},
        {"meeting_id": "c", "title": "В", "created_at": 3, "start_s": 9, "who": "", "text": "в1", "score": 0.89},
        {"meeting_id": "b", "title": "Б", "created_at": 2, "start_s": 50, "who": "", "text": "б2", "score": 0.86},
    ]
    итог = m.merge(по_словам, по_смыслу)
    проверить([и["meeting_id"] for и in итог] == ["a", "c", "b"],
              "найденное словами первым, дальше по смыслу от близкого к дальнему")
    проверить(not итог[0].get("by_meaning"), "встреча, найденная словами, не помечена «по смыслу»")
    проверить(итог[0]["quotes"] == [{"text": "x"}], "смысл не подмешивает цитаты во встречу, найденную словами")
    проверить(all(и.get("by_meaning") for и in итог[1:]), "найденное только по смыслу помечено")
    б = итог[2]
    проверить(б["hits"] == 2 and [q["text"] for q in б["quotes"]] == ["б1", "б2"],
              "куски одной встречи собираются под ней, а не дублируют встречу")
    проверить(б["quotes"][0]["start"] == 5, "цитата помнит своё время: клик откроет нужное место")

    много = [{"meeting_id": f"m{i}", "title": "", "created_at": 0, "start_s": 0, "who": "",
              "text": "", "score": 0.9 - i * 0.001} for i in range(30)]
    проверить(len(m.merge([], много)) == m.MAX_MEETINGS,
              f"по смыслу добавляется не больше {m.MAX_MEETINGS} встреч: иначе список не читается")
    проверить(m.merge(по_словам, []) == по_словам, "без смысла выдача ровно та же, что была до него")


# --- 4. указатель и база -----------------------------------------------

def check_index() -> None:
    tmp = Path(tempfile.mkdtemp(prefix="konspekt-смысл-"))
    store = Store(str(tmp / "k.db"))
    модель = FakeModel()
    вызовы: list[int] = []
    указатель = m.MeaningIndex(store, модель, who=lambda s: s.voice_label or "Собеседник",
                               on_done=lambda: вызовы.append(1))

    деньги = store.create_meeting(Meeting(title="Про деньги"))
    реплики(store, деньги.id, ["Нужен тестовый приём платежей по картам" + ДЛИННО,
                               "И тариф пересчитать, и счёт выставить" + ДЛИННО])
    сервер = store.create_meeting(Meeting(title="Про сервер"))
    реплики(store, сервер.id, ["Сервер упал под нагрузкой, база не отвечала" + ДЛИННО])
    обед = store.create_meeting(Meeting(title="Про обед"))
    реплики(store, обед.id, ["Пойдём на обед, возьмём пиццу и кофе" + ДЛИННО])
    пустая = store.create_meeting(Meeting(title="Пустая"))
    for i in range(ШУМА):
        шум = store.create_meeting(Meeting(title=f"Шум {i}"))
        реплики(store, шум.id, [f"обычный разговор ни о чём номер {i}" + ДЛИННО])

    проверить(указатель.update_all() == ШУМА + 4, "первый проход считает все встречи, и пустые тоже")
    проверить(указатель.update_all() == 0, "второй проход ничего не пересчитывает: считать зря нельзя")
    done, total = store.meaning_progress(модель.name)
    проверить((done, total) == (ШУМА + 3, ШУМА + 3), f"прогресс считает встречи с текстом: {done} из {total}")

    найдено = указатель.search("оплата картой")
    проверить(найдено and найдено[0]["meeting_id"] == деньги.id,
              "запрос без общих слов находит встречу по теме")
    проверить(all(н["meeting_id"] != обед.id for н in найдено), "чужая тема не находится")
    проверить(найдено[0]["who"] == "Собеседник", "у куска подпись говорящего, как у поиска по словам")
    проверить(указатель.search("а") == [], "запрос в одну букву не ищется")

    # Новая реплика: отпечаток меняется, встреча пересчитывается. Реплик
    # несколько: одна короткая склеится в кусок с обедом, и тема
    # размоется — так и должно быть, но проверить так нечего.
    реплики(store, обед.id, ["А после обеда обсудили оплату картой и тариф" + ДЛИННО] * 5,
            начало=100)
    проверить(store.meetings_needing_meaning(модель.name) == [обед.id],
              "дописанная реплика требует пересчёта ровно своей встречи")
    указатель.update_all()
    проверить(any(н["meeting_id"] == обед.id for н in указатель.search("оплата картой")),
              "дописанное находится после пересчёта")

    # Правка языка меняет текст: встреча тоже устаревает.
    сег = store.list_segments(сервер.id)[0]
    store.update_segment(сег.id, "Server went down под нагрузкой" + ДЛИННО, "en")
    проверить(сервер.id in store.meetings_needing_meaning(модель.name),
              "исправленная реплика требует пересчёта")
    указатель.update_all()

    # Удаление: из базы и из памяти.
    проверить(any(н["meeting_id"] == деньги.id for н in указатель.search("оплата картой")),
              "перед удалением встреча находится")
    store.delete_meeting(деньги.id)
    указатель.forget(деньги.id)
    проверить(all(н["meeting_id"] != деньги.id for н in указатель.search("оплата картой")),
              "удалённая встреча больше не находится по смыслу")
    осталось = store._conn.execute(
        "SELECT COUNT(*) FROM meaning_chunks WHERE meeting_id=?", (деньги.id,)).fetchone()[0]
    проверить(осталось == 0, "текст удалённой встречи не остаётся лежать в указателе")

    # Встреча, застрявшая в «идёт запись» после падения, тоже считается.
    застряла = store.create_meeting(Meeting(title="Застряла"))
    store.update_meeting(застряла.id, status=MeetingStatus.RECORDING)
    реплики(store, застряла.id, ["Сервер снова упал, нагрузка на базу" + ДЛИННО])
    проверить(застряла.id in store.meetings_needing_meaning(модель.name),
              "встреча в статусе записи не выпадает из указателя навсегда")

    # Смена модели: старые векторы несравнимы с новыми.
    другая = FakeModel()
    другая.name = "fake-meaning-2"
    проверить(len(store.meetings_needing_meaning(другая.name)) == ШУМА + 4,
              "с новой моделью весь архив пересчитывается заново")
    проверить(m.MeaningIndex(store, другая).search("оплата") == [],
              "векторы старой модели не смешиваются с новой")

    # Без модели указатель молчит, а не падает.
    без = m.MeaningIndex(store, FakeModel(downloaded=False))
    проверить(без.search("оплата картой") == [], "без скачанной модели поиск по смыслу просто пуст")

    # Фоновый поток: пересчитывает сам и сообщает окну.
    указатель.start()
    реплики(store, застряла.id, ["и про оплату картой тоже" + ДЛИННО], начало=200)
    вызовы.clear()
    указатель.refresh()
    конец = time.time() + 5
    while not вызовы and time.time() < конец:
        time.sleep(0.05)
    проверить(bool(вызовы), "фоновый пересчёт сообщает окну, что указатель пополнился")
    указатель.stop()
    store.close()


# --- 5. сервис: смысл не ломает слова ----------------------------------

def check_service() -> None:
    from app.core.service import AppService

    tmp = Path(tempfile.mkdtemp(prefix="konspekt-смысл-сервис-"))
    store = Store(str(tmp / "k.db"))
    встреча = store.create_meeting(Meeting(title="Планёрка"))
    реплики(store, встреча.id, ["Обсудили тестовый приём платежей" + ДЛИННО])
    другая = store.create_meeting(Meeting(title="Про деньги"))
    реплики(store, другая.id, ["Нужно выставить счёт и принять оплату картой" + ДЛИННО])
    for i in range(ШУМА):
        шум = store.create_meeting(Meeting(title=f"Шум {i}"))
        реплики(store, шум.id, [f"обычный разговор ни о чём номер {i}" + ДЛИННО])

    сервис = AppService.__new__(AppService)
    сервис.store = store
    сервис.meaning = m.MeaningIndex(store, FakeModel())
    сервис.meaning.update_all()

    итог = сервис.search("платежей")
    проверить(итог and итог[0]["meeting_id"] == встреча.id and not итог[0].get("by_meaning"),
              "совпадение по слову первым и без пометки")
    проверить(any(и["meeting_id"] == другая.id and и.get("by_meaning") for и in итог),
              "встреча без этого слова, но про то же, добавлена по смыслу")

    class Сломанный:
        def search(self, query):
            raise RuntimeError("модель упала")

    сервис.meaning = Сломанный()
    итог = сервис.search("платежей")
    проверить([и["meeting_id"] for и in итог] == [встреча.id],
              "поломка модели не ломает поиск по словам")
    store.close()


# --- 6. окно ------------------------------------------------------------

def check_ui() -> None:
    from app.core.events import MEANING_STATE
    from app.ui.window import FORWARDED_EVENTS

    проверить(MEANING_STATE in FORWARDED_EVENTS, "событие о поиске по смыслу доходит до окна")
    js = (КОРЕНЬ / "web" / "app.js").read_text(encoding="utf-8")
    проверить("hit.by_meaning" in js and "search.by_meaning" in js,
              "цитата встречи, найденной по смыслу, помечена")
    проверить("case 'meaning.state'" in js, "окно переспрашивает поиск, когда указатель досчитался")
    css = (КОРЕНЬ / "web" / "styles.css").read_text(encoding="utf-8")
    проверить(".meeting-item__by-meaning" in css, "у пометки есть оформление")
    for язык in ("ru", "en", "es", "sr"):
        данные = json.loads((КОРЕНЬ / "web" / "i18n" / f"{язык}.json").read_text(encoding="utf-8-sig"))
        поиск = данные.get("search", {})
        проверить(bool(поиск.get("by_meaning")) and bool(поиск.get("by_meaning_tooltip")),
                  f"пометка переведена: {язык}")


def main() -> int:
    check_chunks()
    check_pick()
    check_merge()
    check_index()
    check_service()
    check_ui()
    if провалов:
        print(f"\nПровалов: {провалов}")
        return 1
    print("\nПоиск по смыслу дополняет поиск по словам и ничего в нём не ломает.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
