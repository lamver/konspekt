def реплика(mid: str, текст: str, start: float = 0.0, rank: float = -1.0) -> dict:
    return {"meeting_id": mid, "title": mid.upper(), "created_at": 0, "text": текст,
            "start_s": start, "who": "Я", "rank": rank}


def кусок(mid: str, текст: str, standout: float, strong: bool, score: float = 0.86) -> dict:
    return {"meeting_id": mid, "title": mid.upper(), "created_at": 0, "text": текст,
            "start_s": 7.0, "who": "", "score": score, "standout": standout, "strong": strong}


def check_rank() -> None:
    осн = r.основы("выручка за август что там по продажам")
    проверить(осн == ["выруч", "авгу", "продаж"],
              f"служебные слова выброшены, длинные обрезаны до основы: {осн}")
    проверить(r.основы("сеть") == ["сеть"], "короткое слово не обрезается: «се» нашлось бы везде")
    проверить(r.основы("что там") != [], "запрос из одних служебных слов всё равно ищет")
    # Указатель базы сравнивает ё как е и й как и. Если здесь считать
    # иначе, реплика найдётся базой, но не засчитается ни одним словом
    # и пропадёт из выдачи.
    проверить(r.покрытие("Приём платежей и ещё тариф", r.основы("прием тарифа")) == 1.0,
              "«прием» засчитывается в «Приём»: ё и й сравниваются как в указателе базы")

    # Ровно случай человека: всех слов в одной реплике нет, а разговор был.
    по_словам = [
        реплика("речка", "А чё, какие перспективы по продажам там, по выручке, влечение?", 1500),
        реплика("другая", "Спасибо тебе большое, выручаешь.", 30),
        реплика("третья", "...продаж проводился.", 90),
    ]
    итог = r.rank(осн, по_словам, [])
    проверить(итог and итог[0]["meeting_id"] == "речка",
              "«выручка за август что там по продажам» находит разговор про продажи и выручку")
    проверить(итог[0]["quotes"][0]["start"] == 1500, "клик по цитате откроет то самое место")
    проверить(итог[0]["cover"] > итог[1]["cover"],
              "реплика, где сошлось больше слов запроса, выше той, где одно")
    проверить(итог[0]["terms"] == осн, "окну отданы основы: подсветит «продажам» и «выручке»")

    # Смысл поднимает найденное словами, но не тянет шум сам.
    слабый = [кусок("третья", "про продажи", standout=4.0, strong=False)]
    с_смыслом = r.rank(осн, по_словам[1:], слабый)
    проверить(с_смыслом[0]["meeting_id"] == "третья",
              "близость по смыслу поднимает встречу выше другой с тем же числом слов")
    шум = [кусок("чужая", "про погоду", standout=2.5, strong=False)]
    проверить(all(в["meeting_id"] != "чужая" for в in r.rank(осн, по_словам, шум)),
              "слабое сходство без единого общего слова в выдачу не попадает")

    сильный = [кусок("тема", "перспективы по доходам", standout=4.5, strong=True)]
    итог = r.rank(осн, [], сильный)
    проверить([в["meeting_id"] for в in итог] == ["тема"] and итог[0]["by_meaning"],
              "сильная находка по смыслу приходит и без общих слов, с пометкой")
    проверить(итог[0]["quotes"][0]["start"] == 7.0, "у находки по смыслу цитата с её временем")

    итог = r.rank(осн, по_словам, сильный)
    проверить(not any(в["by_meaning"] for в in итог if в["meeting_id"] == "речка"),
              "встреча, найденная словами, не помечена «по смыслу»")

    много = [кусок(f"м{i}", "т", standout=5.0, strong=True) for i in range(30)]
    проверить(sum(в["by_meaning"] for в in r.rank(осн, [], много)) == r.НАИБОЛЬШЕ_ПО_СМЫСЛУ,
              f"без общих слов приходит не больше {r.НАИБОЛЬШЕ_ПО_СМЫСЛУ} встреч")
    куча = [реплика(f"в{i}", "продажи") for i in range(60)]
    проверить(len(r.rank(осн, куча, [])) == r.НАИБОЛЬШЕ_ВСТРЕЧ,
              f"список не длиннее {r.НАИБОЛЬШЕ_ВСТРЕЧ} встреч: хвост никто не читает")
    проверить(r.rank(осн, [реплика("х", "ничего общего")], []) == [],
              "реплика без единой основы запроса не считается находкой")

    две = [реплика("речка", "Отдел продаж.", 100, rank=-9.0),
           реплика("речка", "Продажи и выручка за август", 900, rank=-1.0)]
    проверить(r.rank(осн, две, [])[0]["quotes"][0]["start"] == 900,
              "цитатой идёт реплика, где сошлось больше слов, а не первая попавшаяся")

    # Какие куски по смыслу идут на прибавку, а какие приводят встречу
    # сами. Толпа из ста одинаковых и три выделяющихся над ней.
    куски = [{"i": i} for i in range(100)]
    близость = np.full(100, 0.80, dtype=np.float32) + np.linspace(0, 0.004, 100).astype(np.float32)
    близость[0] = 0.90   # сильный: близко и выделяется
    близость[1] = 0.84   # выделяется, но ниже порога близости: только прибавка
    близость[2] = 0.83
    отобрано = m.candidates(куски, близость)
    по_номеру = {к["i"]: к for к in отобрано}
    проверить(по_номеру.get(0, {}).get("strong") is True, "сильный кусок помечен сильным")
    проверить(1 in по_номеру and по_номеру[1]["strong"] is False,
              "слабый, но выделяющийся кусок отдаётся на прибавку и не приводит встречу сам")
    проверить(all(к["i"] in (0, 1, 2) for к in отобрано),
              f"толпа на прибавку не идёт: {sorted(по_номеру)[:6]}")


