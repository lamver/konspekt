def check_chunks() -> None:
    сегменты = [{"text": f"реплика номер {i} " + "слово " * 10, "start": i * 3.0, "who": f"Голос {i}"}
                for i in range(20)]
    куски = m.chunk_segments(сегменты)
    проверить(1 < len(куски) < 20, f"реплики склеиваются в куски, а не идут по одной ({len(куски)} из 20)")
    проверить(all(len(к["text"]) <= m.CHUNK_CHARS + 120 for к in куски),
              "кусок не разрастается сильно дальше заданного размера")
    проверить(куски[0]["start"] == 0.0 and куски[1]["start"] > 0,
              "у куска время его первой реплики: клик откроет нужное место")
    проверить(куски[1]["who"] == сегменты[куски[1]["start"] and int(куски[1]["start"] / 3)]["who"],
              "говорящий куска — тот, кто начал этот кусок")
    склеено = " ".join(к["text"] for к in куски)
    проверить(all(f"номер {i} " in склеено for i in range(20)), "ни одна реплика не потерялась при нарезке")

    мусор = m.chunk_segments([{"text": "а.", "start": 0.0}, {"text": "Д", "start": 1.0}])
    проверить(мусор == [], "обрывки вроде «а.» и «Д» не становятся кусками: модель нашла бы их везде")
    проверить(m.chunk_segments([{"text": "   ", "start": 0}, {"text": "", "start": 1}]) == [],
              "пустые реплики не ломают нарезку")


# --- 2. отбор -----------------------------------------------------------

def check_pick() -> None:
    items = [{"i": i} for i in range(100)]
    шум = np.full(100, 0.83, dtype=np.float32) + np.linspace(0, 0.01, 100).astype(np.float32)
    проверить(m.pick(items, шум) == [], "все похожи одинаково — это шум, не находка")

    # Шум с высокой близостью: у настоящей модели так бывает на общих
    # запросах, и отсечь его может только выделение из толпы. Первая
    # версия этой проверки держала шум ниже порога близости, и выбрось
    # кто-нибудь второй порог, она бы этого не заметила.
    громкий_шум = np.full(100, 0.86, dtype=np.float32) + np.linspace(0, 0.01, 100).astype(np.float32)
    проверить(m.pick(items, громкий_шум) == [],
              "шум с высокой близостью тоже шум: общий запрос не тянет весь архив")

    с_находкой = шум.copy()
    с_находкой[42] = 0.88
    найдено = m.pick(items, с_находкой)
    проверить([н["i"] for н in найдено] == [42], "кусок, стоящий особняком, находится, а толпа нет")

    слабый = шум.copy()
    слабый[7] = 0.849
    проверить(m.pick(items, слабый) == [],
              "выделяется, но близость ниже порога: не показываем, иначе полезет чужая тема")

    проверить(m.pick([], np.zeros(0, dtype=np.float32)) == [], "пустой указатель не падает")
    одна = m.pick([{"i": 0}], np.array([0.9], dtype=np.float32))
    проверить(len(одна) == 1, "в архиве из одного куска выделяться не из чего, хватает близости")


