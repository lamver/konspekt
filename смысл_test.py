ТЕМЫ = {
    "деньги": ("оплат", "платеж", "карт", "деньг", "счёт", "тариф"),
    "сервер": ("сервер", "нагрузк", "база", "упал", "сеть"),
    "еда": ("пицц", "обед", "кофе", "ужин"),
}


class FakeModel:
    """Раскладывает текст по темам: вектор — сколько слов какой темы.

    Добавлена небольшая общая часть, чтобы все тексты были «немного
    похожи», как у настоящей модели: иначе отбор по выделению из толпы
    нечем было бы проверить.
    """

    name = "fake-meaning"

    def __init__(self, downloaded: bool = True) -> None:
        self.downloaded = downloaded
        self.passages_calls = 0

    def is_downloaded(self) -> bool:
        return self.downloaded

    def _vec(self, text: str) -> np.ndarray:
        low = text.lower()
        v = np.array([sum(low.count(k) for k in ключи) for ключи in ТЕМЫ.values()]
                     + [1.0], dtype=np.float32)
        return v / np.linalg.norm(v)

    def query(self, text: str) -> np.ndarray:
        return self._vec(text)

    def passages(self, texts: list[str]) -> np.ndarray:
        self.passages_calls += 1
        if not texts:
            return np.zeros((0, 4), dtype=np.float32)
        return np.vstack([self._vec(t) for t in texts])


def реплики(store: Store, meeting_id: str, тексты: list[str], начало: float = 0.0) -> None:
    for i, текст in enumerate(тексты):
        store.add_segment(TranscriptSegment(
            meeting_id=meeting_id, text=текст, speaker=Speaker.THEM,
            start=начало + i * 5.0, end=начало + i * 5.0 + 4.0,
        ))


