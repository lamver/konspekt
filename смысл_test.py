"""Поиск по смыслу: нарезка, отбор, слияние, указатель, окно.

Человек помнит тему, а не слово: «где мы говорили про оплату картой».
Поиск по словам находит такое, только если слово совпало. Поиск по
смыслу добавляет встречи, где слова другие, а тема та же.

Модель здесь поддельная: она раскладывает текст по темам из словаря.
Настоящую модель проверяет смысл_модель_test.py, а здесь проверяется
всё вокруг неё, и ломается оно молча:

1. Нарезка: куски из соседних реплик, пустые обрывки отброшены, клик
   ведёт на начало куска.
2. Отбор: шум не проходит, даже если близость у него высокая.
3. Слияние: найденное словами первым, без повторов, с пометкой.
4. Указатель: пересчитывает только изменившееся, видит новые реплики,
   забывает удалённое, не падает без модели.
5. Сервис: поломка смысла не ломает поиск по словам.
6. Окно: событие доходит, пометка и её перевод на месте.
"""

