# -*- coding: utf-8 -*-
"""Страница должна читаться без JavaScript.

Робот, не выполняющий скрипты, видит только исходный HTML. Пока текст
рисовался скриптом, в исходном HTML было 96 знаков и семь пустых
заголовков: ни слова «transcribe», «local», «offline» — то есть ровно
тех слов, по которым нас должны находить. Google скрипты выполняет
отложенно и не всегда, а Bing, Яндекс и сборщики ссылок в мессенджерах
чаще читают только текст.

Отдельно проверяется, что встроенный текст совпадает со словарём.
Разойтись они могут молча: в браузере страница выглядит верно, потому
что скрипт подставляет свежие строки поверх, а устаревшим остаётся
только то, что видит робот, — то есть именно то, ради чего всё делалось.

Правится не руками, а `tools/встроить-текст.mjs`.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import testenv  # noqa: F401  русский вывод в консоли Windows

КОРЕНЬ = Path(__file__).resolve().parent
СТРАНИЦА = КОРЕНЬ / "docs" / "index.html"
СЛОВАРЬ = КОРЕНЬ / "docs" / "i18n.js"

сбои: list[str] = []


def проверить(условие: bool, что: str, подробности: str = "") -> None:
    метка = "[ок]" if условие else "[СБОЙ]"
    хвост = f" ({подробности})" if подробности else ""
    print(f"{метка} {что}{хвост}")
    if not условие:
        сбои.append(что)


def текст_без_скриптов(html: str) -> str:
    """То же, что видит робот: без скриптов, стилей, примечаний и тегов."""
    без = re.sub(r"<script[\s\S]*?</script>", " ", html, flags=re.I)
    без = re.sub(r"<style[\s\S]*?</style>", " ", без, flags=re.I)
    без = re.sub(r"<!--[\s\S]*?-->", " ", без)
    без = re.sub(r"<[^>]+>", " ", без)
    return re.sub(r"\s+", " ", без).strip()


html = СТРАНИЦА.read_text(encoding="utf-8")
видно = текст_без_скриптов(html)

# --- Есть ли текст вообще ---
проверить(
    len(видно) > 1500,
    "в исходном HTML есть связный текст, а не одна строка",
    f"{len(видно)} знаков",
)

# --- Слова, по которым продукт ищут ---
# Проверяются корни, а не целые слова: «transcribes» и «transcription»
# должны засчитываться наравне с «transcribe».
for корень in ("transcri", "local", "record", "offline", "privacy", "Whisper", "Granola"):
    проверить(
        корень.lower() in видно.lower(),
        f"в исходном HTML есть «{корень}»",
    )

# --- Заголовки ---
заголовки = re.findall(r"<h([1-6])[^>]*>([\s\S]*?)</h\1>", html, flags=re.I)
пустые = [f"h{ур}" for ур, тело in заголовки if not re.sub(r"<[^>]+>", "", тело).strip()]
проверить(
    not пустые,
    "ни один заголовок не пустой в исходном HTML",
    f"пустых: {пустые}" if пустые else f"всего заголовков: {len(заголовки)}",
)

h1 = [тело for ур, тело in заголовки if ур == "1"]
проверить(len(h1) == 1, "ровно один заголовок первого уровня", f"найдено {len(h1)}")
if h1:
    проверить(
        "konspekt" in re.sub(r"<[^>]+>", "", h1[0]).strip().lower()
        or len(re.sub(r"<[^>]+>", "", h1[0]).strip()) > 10,
        "заголовок первого уровня содержателен",
        re.sub(r"<[^>]+>", "", h1[0]).strip(),
    )

# --- Снимки: подписи и размеры на месте ---
снимки = re.findall(r"<img[^>]+>", html, flags=re.I)
проверить(len(снимки) >= 4, "снимки есть в исходном HTML", f"{len(снимки)} шт.")
без_alt = [s for s in снимки if 'alt="' not in s or 'alt=""' in s]
проверить(not без_alt, "у каждого снимка есть подпись alt", f"без подписи: {len(без_alt)}")
без_размеров = [s for s in снимки if "width=" not in s or "height=" not in s]
проверить(
    not без_размеров,
    "у каждого снимка указаны размеры, чтобы вёрстка не прыгала",
    f"без размеров: {len(без_размеров)}",
)

# --- Совпадает ли встроенный текст со словарём ---
# Словарь читаем тем же способом, что и генератор: выполняем файл.
# Разбор регулярными выражениями завёл бы второе толкование словаря,
# которое однажды разойдётся с настоящим.
import json
import shutil
import subprocess

node = shutil.which("node")
if not node:
    print("[пропуск] node не найден: сверку со словарём пропускаем")
else:
    код = (
        f"const fs=require('fs');"
        f"const s=fs.readFileSync({json.dumps(str(СЛОВАРЬ))},'utf8');"
        f"const I=new Function(s+'\\n;return I18N;')();"
        f"process.stdout.write(JSON.stringify(I.en));"
    )
    готово = subprocess.run([node, "-e", код], capture_output=True, text=True, encoding="utf-8")
    if готово.returncode != 0:
        проверить(False, "словарь читается", готово.stderr.strip()[:200])
    else:
        en = json.loads(готово.stdout)

        def в_странице(значение: str) -> bool:
            # Сравниваем по тексту без разметки: в HTML кавычки и
            # амперсанды экранированы, и дословное сравнение строк
            # давало бы ложные тревоги.
            эталон = re.sub(r"\s+", " ", значение).strip()
            эталон = эталон.replace("&", "&").replace("’", "’")
            return эталон in видно

        for ключ in (
            "tagline",
            "lead",
            "downloadNote",
            "featuresTitle",
            "shotsTitle",
            "privacyTitle",
            "privacyText",
            "langsTitle",
            "langsText",
            "verifyTitle",
            "verifyText",
            "licenseTitle",
            "licenseText",
        ):
            значение = en.get(ключ, "")
            проверить(
                bool(значение) and в_странице(значение),
                f"строка «{ключ}» из словаря стоит в разметке",
                значение[:60] + ("…" if len(значение) > 60 else ""),
            )

        for голова, тело in en["features"]:
            проверить(голова in видно, f"возможность «{голова}» видна без скриптов")

        for _файл, голова, _тело in en["shots"]:
            проверить(голова in видно, f"подпись снимка «{голова}» видна без скриптов")

print()
if сбои:
    print(f"Сбоев: {len(сбои)}")
    for с in сбои:
        print(f"  - {с}")
    sys.exit(1)

print("Страница читается без JavaScript.")
