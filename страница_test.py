def проверить_страницу() -> None:
    html = СТРАНИЦА.read_text(encoding="utf-8")
    проверить("i18n.js" in html, "страница подключает словарь переводов")
    проверить("konspekt-releases/releases/latest" in html,
              "кнопка скачивания ведёт на последний релиз")
    проверить("LICENSE.md" in html, "страница ведёт к лицензии")

    # Каждому t-ключу в js должен соответствовать узел в html, иначе
    # перевод есть, а показать его негде.
    for ключ in ("t-title", "t-tagline", "t-download", "t-features-title",
                 "t-shots-title", "t-privacy-text", "t-langs-text",
                 "t-verify-text", "t-license-text"):
        проверить(f'id="{ключ}"' in html, f"на странице есть узел {ключ}")


СЧЁТЧИК_МЕТКИ = ("op.ingdg.com", "schet.js",
                 "5c5c0aa1-4a0f-4f84-a792-9e1cd12b3fd8")


# Файл счётчика лежит рядом со страницей и называется нейтрально.
# Имя не случайное: op1.js, tracker.js, analytics.js и подобные ловятся
# правилами блокировщиков сами по себе, без привязки к домену.
ФАЙЛ_СЧЁТЧИКА = "schet.js"

# Адреса, с которых счётчик грузить нельзя: они перечислены в списках
# блокировщиков поимённо, и посетитель с блокировщиком просто исчезает
# из статистики.
ЗАПРЕЩЁННЫЕ_ИСТОЧНИКИ = (
    "openpanel.dev",
    "api.openpanel.dev",
)


def проверить_счётчик() -> None:
    """Счётчик стоит на странице и только на ней.

    Два разных требования, и второе важнее. Посещения сайта считать
    можно, это чужая публичная страница в интернете. А вот такой же
    код внутри программы означал бы, что мы следим за человеком на его
    же машине, ровно вопреки тому, что обещаем на этой самой странице.
    Поэтому ищем метки счётчика во всём коде приложения и падаем, если
    они там завелись.
    """
    html = СТРАНИЦА.read_text(encoding="utf-8")
    for метка in СЧЁТЧИК_МЕТКИ:
        проверить(метка in html, f"на странице есть счётчик: {метка}")

    # Скрипт обязан быть отложенным: счётчик не имеет права задерживать
    # показ страницы, если его сервер вдруг не отвечает.
    хвост = [с for с in html.splitlines() if 'src="' + ФАЙЛ_СЧЁТЧИКА + '"' in с]
    проверить(bool(хвост) and "defer" in хвост[0],
              "счётчик подключён с defer и не тормозит страницу")

    # Сам файл обязан лежать рядом со страницей, иначе ссылка мёртвая.
    проверить((СТРАНИЦА.parent / ФАЙЛ_СЧЁТЧИКА).exists(),
              "файл счётчика лежит рядом со страницей")

    # Главное. Счётчик, загружаемый с чужого домена рекламной сети,
    # не грузится у людей с блокировщиком, и такие посетители не
    # считаются вовсе. Мы на этом уже обожглись: адрес
    # openpanel.dev/op1.js запрещён явным правилом в EasyPrivacy,
    # uBlock privacy и AdGuard Tracking, и месяц статистики оказался
    # неполным. Файл должен отдаваться со своего домена.
    for чужой in ЗАПРЕЩЁННЫЕ_ИСТОЧНИКИ:
        проверить('src="' + чужой not in html and 'src="https://' + чужой not in html,
                  f"счётчик не грузится с заблокированного адреса {чужой}")

    следы: list[str] = []
    for файл in (КОРЕНЬ / "app").rglob("*"):
        if файл.suffix.lower() not in (".py", ".js", ".html", ".css"):
            continue
        текст = файл.read_text(encoding="utf-8", errors="replace")
        if any(метка in текст for метка in СЧЁТЧИК_МЕТКИ):
            следы.append(файл.name)
    проверить(not следы,
              "счётчика нет внутри программы"
              + (f" (нашёлся в: {следы})" if следы else ""))


ЗЕРКАЛА = {
    "en": "https://konspekt.aisearch.tech/",
    # Русская версия объявляется подпапкой, а не корнем русского домена.
    #
    # Корень того домена отдаёт тот же файл, что и главный, то есть
    # английскую разметку: сервер раздаёт статику из общей папки и
    # ничего не подменяет. Человек английского не увидит, скрипт
    # переключит язык по домену, а робот верит разметке. Объявлять такой
    # адрес русской версией значит обещать то, чего по нему нет.
    "ru": "https://konspekt.aisearch.ru/ru/",
}


def проверить_зеркала() -> None:
    """Три адреса одной страницы не должны выглядеть тремя дублями.

    Поиск сам решает, какую из копий показывать, и без подсказки
    выбирает не ту. Сторожим два разных требования. Первое: canonical
    и hreflang вообще есть. Второе, менее очевидное: русская копия
    остаётся канонической сама для себя. Если её схлопнуть в
    английскую, по-русски нас перестанут находить, а заметить это
    можно только через месяцы по упавшему трафику.
    """
    html = СТРАНИЦА.read_text(encoding="utf-8")

    проверить('rel="canonical"' in html, "у страницы есть канонический адрес")
    for язык, адрес in ЗЕРКАЛА.items():
        проверить(f'hreflang="{язык}" href="{адрес}"' in html,
                  f"объявлено зеркало для {язык}: {адрес}")
    проверить('hreflang="x-default"' in html,
              "объявлен адрес по умолчанию для остальных языков")

    # Русский адрес обязан упоминаться в подстановке canonical, иначе
    # он канонизируется в английский.
    хвост = html.split('rel="canonical"', 1)[1]
    проверить("konspekt.aisearch.ru" in хвост,
              "русская копия остаётся канонической сама для себя")

    # Языки зеркал должны быть теми же, что знает сама страница.
    for язык in ЗЕРКАЛА:
        проверить(язык in ЯЗЫКИ, f"язык зеркала {язык} есть в словаре страницы")


СОБЫТИЕ_СКАЧИВАНИЯ = "download_click"


def проверить_событие_скачивания() -> None:
    """Клик по кнопке скачивания должен доезжать до счётчика.

    Загрузок у GitHub видно и так, но обезличенно и без причины: там
    не отличить человека от робота и не понять, с какого языка он
    пришёл. Событие на кнопке даёт то, чего в цифрах GitHub нет —
    сколько посетителей вообще дошло до кнопки и на каком языке.

    Ловим три отдельные поломки: атрибут потеряли, счётчик перестали
    просить смотреть на атрибуты, язык перестали подставлять.
    """
    html = СТРАНИЦА.read_text(encoding="utf-8")

    кнопка = [с for с in html.splitlines() if 'id="t-download"' in с]
    проверить(bool(кнопка) and f'data-track="{СОБЫТИЕ_СКАЧИВАНИЯ}"' in кнопка[0],
              f"на кнопке скачивания висит событие {СОБЫТИЕ_СКАЧИВАНИЯ}")

    # Без trackAttributes атрибут на кнопке — просто мёртвая разметка.
    проверить("trackAttributes: true" in html,
              "счётчику велено следить за такими кнопками")

    проверить("setAttribute('data-lang'" in html,
              "вместе с событием уезжает язык страницы")


def проверить_виджет_проверки() -> None:
    """Плашка «0/75 антивирусов» под кнопкой должна обновляться сама.

    Готового виджета у VirusTotal нет: их API требует ключ, а ключ на
    публичной странице отдаст квоту первому любопытному. Поэтому число
    берётся из описания последнего релиза — туда его кладёт сборка, а
    GitHub отдаёт описание браузеру без ключа.

    Ловим три поломки. Число вшили в страницу руками: тогда после
    следующего выпуска оно молча устареет, а плашка про вирусы врать не
    имеет права. Плашку показывают до ответа: человек увидит пустоту
    там, где решает, доверять нам или нет. Разбор счёта не совпал с
    тем, что кладёт сборка.
    """
    html = СТРАНИЦА.read_text(encoding="utf-8")

    проверить("api.github.com/repos/lamver/konspekt-releases/releases/latest" in html,
              "счёт берётся из последнего релиза, а не вшит в страницу")

    # Разбор должен совпадать с тем, что кладёт сборка: значок shields
    # вида «VirusTotal-0%2F75-brightgreen» и ссылка на отчёт.
    проверить("VirusTotal-" in html and "%2F" in html,
              "страница знает формат значка, который кладёт сборка")
    проверить("virustotal" in html and "gui" in html and "file" in html,
              "страница умеет достать ссылку на отчёт")

    # Плашка спрятана в разметке и показывается только после ответа.
    плашка = [с for с in html.splitlines() if 'id="t-vt"' in с]
    проверить(bool(плашка) and "hidden" in плашка[0],
              "плашка проверки скрыта, пока ответ не пришёл")
    проверить("узел.hidden = false" in html,
              "плашка показывается только после разбора ответа")

    # Ноль движков — это сломанный разбор, а не «всё чисто».
    проверить("всего <= 0" in html,
              "нулевое число движков считается поломкой, а не чистотой")


def main() -> int:
    словарь = разобрать_переводы()
    проверить_переводы(словарь)
    проверить_снимки()
    проверить_страницу()
    проверить_счётчик()
    проверить_зеркала()
    проверить_событие_скачивания()
    проверить_виджет_проверки()

    if БЕДЫ:
        print(f"\nНе прошло проверок: {len(БЕДЫ)}")
        return 1
    print("\nСтраница проекта в порядке.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
