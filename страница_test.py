"""Проверка страницы проекта: все ли снимки на месте и все ли тексты переведены.

Дешевле, чем открывать четыре языка глазами, и ловит ровно ту ошибку,
которую глазами пропускают: добавили ключ в один язык и забыли в трёх
других, а на странице вместо текста осталась пустота.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import testenv  # noqa: F401  русский вывод в консоли Windows

КОРЕНЬ = Path(__file__).resolve().parent
СТРАНИЦА = КОРЕНЬ / "docs" / "index.html"
ПЕРЕВОДЫ = КОРЕНЬ / "docs" / "i18n.js"
СНИМКИ = КОРЕНЬ / "docs" / "screenshots"

ЯЗЫКИ = ("en", "es", "sr", "ru")
ЭКРАНЫ = ("summary", "transcript", "notes", "dictation")

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def разобрать_переводы() -> dict[str, dict]:
    """Вытащить словарь I18N из js без запуска браузера.

    Файл написан объектным литералом, поэтому json его не съест: там
    одинарные кавычки и ключи без кавычек. Приводим к json руками —
    надёжнее, чем тащить в проверки движок js.
    """
    текст = ПЕРЕВОДЫ.read_text(encoding="utf-8")
    начало = текст.index("{", текст.index("const I18N"))
    тело = текст[начало:текст.rindex("};") + 1]

    # Комментарии и висячие запятые json не понимает.
    тело = re.sub(r"/\*.*?\*/", "", тело, flags=re.S)
    тело = re.sub(r"//[^\n]*", "", тело)
    # Строки в одинарных кавычках с экранированным апострофом внутри.
    def в_двойные(m: re.Match) -> str:
        внутри = m.group(1).replace("\\'", "'").replace('"', '\\"')
        return '"' + внутри + '"'
    тело = re.sub(r"'((?:[^'\\]|\\.)*)'", в_двойные, тело)
    # Ключи без кавычек.
    тело = re.sub(r"(?m)^(\s*)([A-Za-z][A-Za-z0-9]*)\s*:", r'\1"\2":', тело)
    тело = re.sub(r",(\s*[}\]])", r"\1", тело)
    return json.loads(тело)


def проверить_переводы(словарь: dict[str, dict]) -> None:
    проверить(set(словарь) == set(ЯЗЫКИ),
              f"в словаре ровно четыре языка (есть: {sorted(словарь)})")

    ключи = {я: set(словарь[я]) for я in словарь}
    основные = ключи.get("en", set())
    for язык in словарь:
        не_хватает = основные - ключи[язык]
        лишние = ключи[язык] - основные
        проверить(not не_хватает,
                  f"{язык}: переведено всё, что есть в английском"
                  + (f" (не хватает: {sorted(не_хватает)})" if не_хватает else ""))
        проверить(not лишние,
                  f"{язык}: нет ключей, которых нет в английском"
                  + (f" (лишние: {sorted(лишние)})" if лишние else ""))

    for язык, данные in словарь.items():
        пустые = [к for к, з in данные.items() if isinstance(з, str) and not з.strip()]
        проверить(not пустые, f"{язык}: нет пустых строк (пустые: {пустые})")

        # Английский текст, забытый в переводе, — самая частая ошибка:
        # ключ на месте, проверка молчит, а человек видит чужой язык.
        # Служебные значения (код языка, самоназвание) сравнивать нельзя:
        # htmlLang по смыслу разный, а label и должен быть «English».
        if язык != "en":
            служебные = {"htmlLang", "label"}
            совпало = [
                к for к, з in данные.items()
                if isinstance(з, str)
                and к not in служебные
                and з == словарь["en"].get(к)
            ]
            проверить(not совпало,
                      f"{язык}: ничего не осталось дословно английским"
                      + (f" (совпало: {совпало})" if совпало else ""))

        снимки = данные.get("shots", [])
        проверить(len(снимки) == len(ЭКРАНЫ),
                  f"{язык}: описаны все {len(ЭКРАНЫ)} снимка (есть {len(снимки)})")
        имена = [с[0] for с in снимки]
        проверить(имена == list(ЭКРАНЫ),
                  f"{язык}: снимки в ожидаемом порядке (есть {имена})")


def проверить_снимки() -> None:
    for язык in ЯЗЫКИ:
        for экран in ЭКРАНЫ:
            файл = СНИМКИ / язык / f"{экран}.png"
