"""Вставка распознанного текста в чужое окно — сердце режима диктовки.

Проверяем на настоящем Блокноте, а не на заглушке. Причина простая:
здесь почти всё поведение живёт в Windows, а не в нашем коде. Ошибка в
размере структуры `INPUT` или лишняя торопливость при переключении окна
не видны никакой имитацией — программа честно зовёт `SendInput`, тот
честно отвечает успехом, и текст просто не появляется. Именно так и
вышло на первом заходе.

Что тут ловится по-настоящему:
- неверный размер `INPUT` (система молча отвергает весь ввод);
- слишком быстрый поток символов (текст приезжает изувеченным);
- порча буфера обмена человека;
- время жизни временных объектов ctypes.

Без Windows проверка честно пропускается: подделывать её нечем.
"""

from __future__ import annotations

import testenv  # noqa: F401  русский вывод в консоли Windows

import ctypes
import os
import subprocess
import sys
import tempfile
import time
from ctypes import wintypes

sys.path.insert(0, ".")

from app.dictation import вставка

ОБРАЗЕЦ = "Привет, это диктовка. Ёжик, 42%!"
# Длиннее порога, чтобы «реши сам» выбрал буфер обмена.
ДЛИННЫЙ = "Проверка длинной диктовки. " * 8

if вставка.ДОСТУПНО:
    _u = ctypes.windll.user32
    _k = ctypes.windll.kernel32
    _u.FindWindowW.argtypes = [wintypes.LPCWSTR, wintypes.LPCWSTR]
    _u.FindWindowW.restype = wintypes.HWND
    _u.SetForegroundWindow.restype = wintypes.BOOL
    _u.GetForegroundWindow.restype = wintypes.HWND
    _u.GetWindowTextW.argtypes = [wintypes.HWND, wintypes.LPWSTR, ctypes.c_int]


def _поднять(hwnd: int) -> None:
    """Вытащить чужое окно на передний план.

    `SetForegroundWindow` из фонового процесса Windows игнорирует: это
    защита от программ, ворующих фокус. Штатный обход — на время
    привязаться к потоку ввода активного окна.
    """
    _u.ShowWindow(hwnd, 9)  # SW_RESTORE
    свой = _k.GetCurrentThreadId()
    чужой = _u.GetWindowThreadProcessId(_u.GetForegroundWindow(), None)
    _u.AttachThreadInput(свой, чужой, True)
    try:
        _u.BringWindowToTop(hwnd)
        _u.SetForegroundWindow(hwnd)
    finally:
        _u.AttachThreadInput(свой, чужой, False)


def _в_блокноте(название: str, действие, образец: str) -> tuple[bool, str]:
    """Выполнить действие в своём окне Блокнота и вернуть, что вышло.

    Окно ищется строго по своему уникальному имени файла. Искать «любой
    Блокнот» нельзя: у человека открыт свой, и печатать в него мы права
    не имеем. Такое уже случалось при разработке.
    """
    имя = f"konspekt_проверка_{os.getpid()}_{название}"
    файл = os.path.join(tempfile.gettempdir(), f"{имя}.txt")
    open(файл, "w", encoding="utf-8").close()
    блокнот = subprocess.Popen(["notepad.exe", файл])
    try:
        окно = 0
        предел = time.time() + 15
        while time.time() < предел and not окно:
            окно = _u.FindWindowW("Notepad", f"{имя}.txt - Notepad")
            time.sleep(0.2)
        if not окно:
            return False, "окно Блокнота не открылось"

        # Фокус приходит не мгновенно. Без ожидания текст улетает в
        # чужое окно, и проверка становится бессмысленной, оставаясь
        # зелёной: именно на этом она сначала и обманывала.
        предел = time.time() + 8
        while time.time() < предел and _u.GetForegroundWindow() != окно:
            _поднять(окно)
            time.sleep(0.3)
        if _u.GetForegroundWindow() != окно:
            return False, "не удалось получить фокус, проверка недействительна"

        time.sleep(0.6)  # окно активно, поле ввода готово чуть позже
        действие(образец)
        time.sleep(0.6)

        # Ctrl+S и чтение файла с диска: свидетель, не зависящий ни от
        # буфера обмена, ни от нашего же кода.
        _u.keybd_event(0x11, 0, 0, 0)
        _u.keybd_event(0x53, 0, 0, 0)
        _u.keybd_event(0x53, 0, 2, 0)
        _u.keybd_event(0x11, 0, 2, 0)
        time.sleep(1.2)
        return True, open(файл, encoding="utf-8-sig").read().strip()
    finally:
        блокнот.kill()
        time.sleep(0.4)
        try:
            os.unlink(файл)
        except OSError:
            pass


def _добиться(название: str, действие, образец: str, попыток: int = 4) -> str:
    """Повторить попытку, пока мешает окружение, а не наш код.

    Блокнот открывается за разное время, окно принимает фокус не сразу,
    и в свежеоткрытое окно ввод иногда уходит в пустоту. Это шум чужой
    системы, а не поведение вставки: одиночная неудача не значит ничего,
    а вот четыре подряд — уже наша беда.
    """
    последнее = ""
    for попытка in range(попыток):
        удалось, было = _в_блокноте(f"{название}{попытка}", действие, образец)
        if удалось and было == образец.strip():
            return было
        последнее = было if удалось else f"сценарий не воспроизведён: {было}"
        time.sleep(1.0)
    raise AssertionError(
        f"за {попыток} попыток текст так и не дошёл. Последнее: {последнее!r}"
    )


def проверить_печать() -> None:
    """Текст, набранный по буквам, доходит до чужого окна дословно."""
    _добиться("печать", вставка.печатать, ОБРАЗЕЦ)
    print("[ок] набранный текст дошёл до чужого окна дословно")


def проверить_буфер() -> None:
    """Вставка через буфер работает и возвращает буфер человека назад."""
    вставка._записать_буфер("это было в буфере до диктовки")
    _добиться("буфер", вставка.вставить_через_буфер, ДЛИННЫЙ)

    осталось = вставка._прочитать_буфер()
    assert осталось == "это было в буфере до диктовки", (
        f"буфер человека испорчен диктовкой: {осталось!r}. "
        "Там мог лежать пароль или ссылка"
    )
    print("[ок] длинный текст вставлен, буфер человека возвращён на место")


def проверить_выбор_способа() -> None:
    """Короткое печатается, длинное идёт буфером. Решение принимается само."""
    выбор: list[bool] = []
    настоящая_печать = вставка.печатать
    настоящий_буфер = вставка.вставить_через_буфер
    вставка.печатать = lambda т: (выбор.append(False), True)[1]
    вставка.вставить_через_буфер = lambda т: (выбор.append(True), True)[1]
    try:
        вставка.вставить("коротко")
        вставка.вставить("д" * (вставка.ПОРОГ_БУФЕРА + 1))
    finally:
        вставка.печатать = настоящая_печать
        вставка.вставить_через_буфер = настоящий_буфер

    assert выбор == [False, True], (
        f"выбор способа неверен: {выбор}. Короткое должно печататься "
        "(буфер человека не наш), длинное идти буфером (иначе минуты)"
    )
    print("[ок] короткое печатается, длинное идёт через буфер")


def проверить_пустое() -> None:
    """Пустая диктовка ничего не жмёт и никуда не лезет."""
    assert not вставка.вставить("")
    assert not вставка.вставить("   \n ")
    print("[ок] пустой текст никуда не вставляется")


def main() -> int:
    if not вставка.ДОСТУПНО:
        print("[пропуск] вставка текста есть только под Windows")
        return 0
    проверить_пустое()
    проверить_выбор_способа()
    проверить_печать()
    проверить_буфер()
    print("\nВсе проверки пройдены.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
