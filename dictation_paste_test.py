"""Вставка распознанного текста в чужое окно — сердце режима диктовки.

Проверяем на настоящем окне, а не на заглушке. Причина простая: здесь
почти всё поведение живёт в Windows, а не в нашем коде. Ошибка в размере
структуры `INPUT` или лишняя торопливость при переключении окна не видны
никакой имитацией — программа честно зовёт `SendInput`, тот честно
отвечает успехом, и текст просто не появляется. Именно так и вышло на
первом заходе.

Окно поднимаем своё (`dictation_окна.py`), а не Блокнот. Блокнот в
Windows 11 переиспользует одно окно на все файлы: проверка думала, что
печатает в свой временный файл, а печатала в общее окно с открытыми
файлами человека, и однажды так и вышло.

Что тут ловится по-настоящему:
- неверный размер `INPUT` (система молча отвергает весь ввод);
- слишком быстрый поток символов (текст приезжает изувеченным);
- порча буфера обмена человека;
- время жизни временных объектов ctypes.

Без Windows проверка честно пропускается: подделывать её нечем.
"""

from __future__ import annotations

import testenv  # noqa: F401  русский вывод в консоли Windows

import sys
import time

sys.path.insert(0, ".")

from app.dictation import вставка
from dictation_окна import НетОкна, ОкноПриёмник

ОБРАЗЕЦ = "Привет, это диктовка. Ёжик, 42%!"
# Длиннее порога, чтобы «реши сам» выбрал буфер обмена.
ДЛИННЫЙ = "Проверка длинной диктовки. " * 8


def _добиться(название: str, действие, образец: str, попыток: int = 3) -> str:
    """Выполнить действие в своём окне, повторив при помехах среды.

    Одиночная неудача обычно значит, что фокус увело всплывшее
    уведомление: это шум чужой системы, а не поведение вставки. Три
    неудачи подряд — уже наша беда.
    """
    последнее = ""
    for попытка in range(попыток):
        try:
            with ОкноПриёмник(f"{название} {попытка}") as окно:
                окно.удержать_фокус()
                действие(образец)
                time.sleep(0.5)
                было = окно.содержимое()
            if было == образец.strip():
                return было
            последнее = f"в окне оказалось {было!r}"
        except НетОкна as беда:
            последнее = f"сценарий не воспроизведён: {беда}"
        time.sleep(0.6)
    raise AssertionError(
        f"за {попыток} попыток текст так и не дошёл. Последнее: {последнее}"
    )


def проверить_печать() -> None:
    """Текст, набранный по буквам, доходит до чужого окна дословно."""
    _добиться("печать", вставка.печатать, ОБРАЗЕЦ)
    print("[ок] набранный текст дошёл до чужого окна дословно")


def проверить_паузу_между_символами() -> None:
    """Пауза между символами не роскошь: без неё медленные окна теряют текст.

    Наше окно для проверок читает очередь ввода мгновенно и с нулевой
    паузой работает прекрасно — то есть само по себе ничего не
    доказывает. Замер на настоящем Блокноте: с паузой 12 мс текст дошёл
    3 раза из 3, без паузы — 0 из 3.

    Поэтому здесь проверяется не скорость, а сам факт: пауза объявлена и
    отлична от нуля. Убери её, считая лишней, и диктовка сломается ровно
    у того человека, у которого окно неторопливое, а у нас всё зелено.
    """
    assert вставка.ЗАДЕРЖКА_СИМВОЛА > 0, (
        "пауза между символами обнулена: на Блокноте это давало 0 успехов "
        "из 3, текст приезжал изувеченным"
    )
    print(f"[ок] пауза между символами на месте ({вставка.ЗАДЕРЖКА_СИМВОЛА} с)")


def проверить_ожидание_буфера() -> None:
    """Прежний буфер возвращается не мгновенно, а дав приложению забрать текст.

    Между Ctrl+V и возвратом буфера нужна пауза: приложение забирает
    содержимое не в тот же миг, и вернув прежнее слишком рано, мы
    вставим именно прежнее. Наше быстрое окно этого не ловит, поэтому
    стережём саму величину паузы.
    """
    assert вставка.ПАУЗА_БУФЕРА > 0, (
        "исчезла пауза между Ctrl+V и возвратом буфера: приложение не "
        "успеет забрать текст, и вставится прежнее содержимое"
    )
    print(f"[ок] возврат буфера ждёт приложение ({вставка.ПАУЗА_БУФЕРА} с)")


def проверить_буфер() -> None:
    """Вставка через буфер работает и возвращает буфер человека назад."""
    вставка._записать_буфер("это было в буфере до диктовки")
    _добиться("буфер", вставка.вставить_через_буфер, ДЛИННЫЙ)

    осталось = вставка._прочитать_буфер()
    assert осталось == "это было в буфере до диктовки", (
        f"буфер человека испорчен диктовкой: {осталось!r}. "
        "Там мог лежать пароль или ссылка"
    )
    print("[ок] длинный текст вставлен, буфер человека возвращён на место")


def проверить_выбор_способа() -> None:
    """Короткое печатается, длинное идёт буфером. Решение принимается само."""
    выбор: list[bool] = []
    настоящая_печать = вставка.печатать
    настоящий_буфер = вставка.вставить_через_буфер
    вставка.печатать = lambda т: (выбор.append(False), True)[1]
    вставка.вставить_через_буфер = lambda т: (выбор.append(True), True)[1]
    try:
        вставка.вставить("коротко")
        вставка.вставить("д" * (вставка.ПОРОГ_БУФЕРА + 1))
    finally:
        вставка.печатать = настоящая_печать
        вставка.вставить_через_буфер = настоящий_буфер

    assert выбор == [False, True], (
        f"выбор способа неверен: {выбор}. Короткое должно печататься "
        "(буфер человека не наш), длинное идти буфером (иначе минуты)"
    )
    print("[ок] короткое печатается, длинное идёт через буфер")


def проверить_пустое() -> None:
    """Пустая диктовка ничего не жмёт и никуда не лезет."""
    assert not вставка.вставить("")
    assert not вставка.вставить("   \n ")
    print("[ок] пустой текст никуда не вставляется")


def main() -> int:
    if not вставка.ДОСТУПНО:
        print("[пропуск] вставка текста есть только под Windows")
        return 0
    проверить_пустое()
    проверить_выбор_способа()
    проверить_паузу_между_символами()
    проверить_ожидание_буфера()
    проверить_печать()
    проверить_буфер()
    print("\nВсе проверки пройдены.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
