// Разбор счёта VirusTotal из описания релиза.
//
// Виджета, который сам показывал бы свежий счёт, у VirusTotal нет: их
// API требует ключ, а ключ на публичной странице заберёт первый же
// любопытный. Поэтому число берётся из описания последнего релиза —
// туда его кладёт сборка, а GitHub отдаёт описание браузеру без ключа.
//
// Здесь проверяется разбор: он живёт на публичной странице, где ошибка
// видна не нам, а незнакомому человеку, и именно в том месте, где он
// решает, доверять нам или нет. Соврать тут нельзя.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const беды = [];
function проверить(ок, что) {
  console.log((ок ? '[ok] ' : '[FAIL] ') + что);
  if (!ок) беды.push(что);
}

// Достаём функцию разбора из настоящей страницы, а не переписываем её
// здесь: копия разошлась бы с оригиналом и проверяла бы саму себя.
const html = fs.readFileSync(path.join(__dirname, 'docs', 'index.html'), 'utf8');
const от = html.indexOf('function разобратьПроверку');
const до = html.indexOf('async function показатьПроверку');
if (от < 0 || до < 0) {
  console.error('не нашёл разобратьПроверку в docs/index.html');
  process.exit(1);
}
const песочница = {};
vm.createContext(песочница);
vm.runInContext(html.slice(от, до) + '\nglobalThis.разбор = разобратьПроверку;',
                песочница, { filename: 'index.html' });
const разобрать = песочница.разбор;

// --- Настоящее описание релиза, как его кладёт сборка --------------------
const настоящее = `## What's new

- Something changed.

---

[![VirusTotal](https://img.shields.io/badge/VirusTotal-0%2F75-brightgreen?logo=virustotal&logoColor=white)](https://www.virustotal.com/gui/file/71be674ff73d771ebf0ac1fb284cdc44ad6f0bf835f3bd5966acf249f210578f)

Scanned by VirusTotal: 0 of 75 engines flagged this file.
`;

const разбор = разобрать(настоящее);
проверить(разбор !== null, 'настоящее описание релиза разбирается');
проверить(разбор && разбор.тревог === 0, 'тревог 0 (было: ' + (разбор && разбор.тревог) + ')');
проверить(разбор && разбор.всего === 75, 'движков 75 (было: ' + (разбор && разбор.всего) + ')');
проверить(разбор && разбор.ссылка ===
  'https://www.virustotal.com/gui/file/71be674ff73d771ebf0ac1fb284cdc44ad6f0bf835f3bd5966acf249f210578f',
  'ссылка на отчёт ведёт на тот файл, что в релизе');

// --- Тревога есть: показываем честно -------------------------------------
const тревожное = настоящее.replace('VirusTotal-0%2F75', 'VirusTotal-3%2F72');
const сТревогой = разобрать(тревожное);
проверить(сТревогой && сТревогой.тревог === 3 && сТревогой.всего === 72,
  'ненулевая тревога читается как есть, а не прячется');

// --- Описание без значка: молчим -----------------------------------------
// Так выглядят старые релизы и ручные правки описания. Придумывать
// «наверное, ноль» нельзя: это враньё в самом чувствительном месте.
проверить(разобрать('## Что нового\n\nПросто текст без значка.') === null,
  'описание без значка не превращается в выдуманный ноль');
проверить(разобрать('') === null, 'пустое описание ничего не даёт');
проверить(разобрать(null) === null, 'отсутствующее описание не роняет страницу');
проверить(разобрать(undefined) === null, 'undefined не роняет страницу');
проверить(разобрать(42) === null, 'не строка не роняет страницу');

// --- Значок есть, ссылки нет: тоже молчим --------------------------------
// Плашка без ссылки бесполезна: человек не сможет проверить сам, а
// поверить на слово и есть то, чего мы от него не просим.
проверить(разобрать(
  '[![VirusTotal](https://img.shields.io/badge/VirusTotal-0%2F75-brightgreen)](https://example.com)'
) === null, 'значок без ссылки на отчёт не показывается');

// --- Ноль движков: это поломка, а не чистота -----------------------------
проверить(разобрать(настоящее.replace('VirusTotal-0%2F75', 'VirusTotal-0%2F0')) === null,
  'ноль движков считается поломкой разбора, а не «всё чисто»');

// --- Описание с несколькими ссылками -------------------------------------
// В описании есть и другие ссылки; разбор не должен хватать первую попавшуюся.
const шумное = `Смотрите https://github.com/lamver/konspekt и https://example.com/gui/file/abc

[![VirusTotal](https://img.shields.io/badge/VirusTotal-1%2F70-yellow)](https://www.virustotal.com/gui/file/aaaabbbbccccddddeeeeffff0000111122223333444455556666777788889999)
`;
const изШума = разобрать(шумное);
проверить(изШума && изШума.тревог === 1 && изШума.всего === 70,
  'счёт достаётся из шумного описания');
проверить(изШума && изШума.ссылка.endsWith('9999'),
  'ссылка берётся именно от VirusTotal, а не первая попавшаяся');

// --- Ссылка только на virustotal.com -------------------------------------
// Описание релиза правится руками, и туда может попасть чужая ссылка с
// похожим путём. Увести человека с плашки «проверено антивирусами» на
// сторонний сайт — это ровно то, от чего мы его и защищаем.
const чужое = `[![VirusTotal](https://img.shields.io/badge/VirusTotal-0%2F75-brightgreen)](https://evil.example.com/gui/file/aaaabbbbccccddddeeeeffff0000111122223333444455556666777788889999)
`;
проверить(разобрать(чужое) === null,
  'ссылка на чужой сайт не принимается за отчёт VirusTotal');

// А вот поддомен самого VirusTotal — это по-прежнему он.
const подДомен = `[![VirusTotal](https://img.shields.io/badge/VirusTotal-0%2F75-brightgreen)](https://www.virustotal.com/gui/file/aaaabbbbccccddddeeeeffff0000111122223333444455556666777788889999)
`;
проверить(разобрать(подДомен) !== null,
  'настоящая ссылка VirusTotal принимается');

if (беды.length) {
  console.log('\nНе прошло проверок: ' + беды.length);
  process.exit(1);
}
console.log('\nСчёт проверки на вирусы читается из релиза честно.');
