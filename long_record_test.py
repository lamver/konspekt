"""Многочасовая встреча не должна разъедать программу.

Название задачи — «бесконечная запись». Всё, что проверено до сих пор,
касалось поведения на десятках кусков: досчёт, порядок реплик, борьба за
очередь. Но главный страх у длинной записи другой: за четыре часа через
программу проходит около трёх тысяч кусков речи, и любая структура,
которая растёт с каждым куском и не очищается, к концу встречи съест
память или замедлит работу.

Здесь проверяется, что за длинную встречу не растёт ничего лишнего:

- нарезка звука не копит буфер (`ChunkBuffer` отдаёт куски и забывает);
- поиск речи (`SpeechSegmenter`) не копит кадры между фразами;
- список пропусков ограничен и не растёт бесконечно даже тогда, когда
  модель безнадёжно отстаёт всю встречу.

Время сжато: гонять настоящие четыре часа звука бессмысленно, потому что
проверяется не скорость, а рост. Объём данных при этом настоящий —
столько же кусков, сколько в реальной четырёхчасовой записи.
"""
from __future__ import annotations

import gc
import logging
import sys
import time

import numpy as np

import testenv  # noqa: F401  русский вывод в консоли Windows

from app.asr.queue import MAX_PENDING, TranscriptionQueue
from app.asr.vad import SpeechSegmenter
from app.audio.buffers import ChunkBuffer
from app.core.models import Speaker, TranscriptSegment

RATE = 16000
ЧАСОВ = 4.0
БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def вес(obj) -> int:
    """Сколько памяти занимает numpy-буфер объекта."""
    total = 0
    for name in dir(obj):
        if name.startswith("__"):
            continue
        try:
            v = getattr(obj, name)
        except Exception:
            continue
        if isinstance(v, np.ndarray):
            total += v.nbytes
        elif isinstance(v, (list, tuple)):
            total += sum(x.nbytes for x in v if isinstance(x, np.ndarray))
    return total


def проверить_нарезку() -> None:
    """Нарезка звука не копит буфер за длинную встречу."""
    chunk_seconds = 0.5  # как в настройках по умолчанию
    buf = ChunkBuffer(chunk_seconds=chunk_seconds, sample_rate=RATE)
    # Звуковая карта отдаёт блоки произвольного размера, не кратные куску:
    # если бы остаток копился, это вылезло бы именно здесь.
    блок = np.zeros(int(RATE * 0.137), dtype=np.int16)
    блоков = int(ЧАСОВ * 3600 / 0.137)
    выдано = 0
    пик = 0
    for _ in range(блоков):
        выдано += len(buf.push(блок))
        пик = max(пик, вес(buf))
    ожидалось = int(ЧАСОВ * 3600 / chunk_seconds)
    print(f"       за {ЧАСОВ:.0f} ч выдано кусков: {выдано} (ожидалось ~{ожидалось}), "
          f"пик буфера: {пик} байт")
    проверить(abs(выдано - ожидалось) <= 2,
              f"нарезка выдала все куски четырёхчасовой записи ({выдано})")
    # Потолок буфера — один кусок плюс один блок. Всё, что больше, значит
    # накопление: к концу встречи оно съело бы память.
    потолок = int((chunk_seconds + 0.2) * RATE) * 2
    проверить(пик <= потолок,
              f"буфер нарезки не растёт со временем встречи "
              f"(пик {пик} байт при потолке {потолок})")


def проверить_поиск_речи() -> None:
    """Поиск речи не копит кадры между фразами."""
    vad = SpeechSegmenter(sample_rate=RATE)
    кусок = int(RATE * 0.5)
    t = np.arange(кусок, dtype=np.float32) / RATE
    речь = (np.sin(2 * np.pi * 180 * t) * 0.3).astype(np.float32)
    тишина = np.zeros(кусок, dtype=np.float32)

    кусков = int(ЧАСОВ * 3600 / 0.5)
    пик = 0
    фраз = 0
    offset = 0.0
    for i in range(кусков):
        # Полторы секунды речи, полторы тишины: обычный разговор, где
        # фразы всё время начинаются и заканчиваются.
        pcm = речь if (i // 3) % 2 == 0 else тишина
        фраз += len(vad.feed(pcm, offset))
        offset += 0.5
        if i % 200 == 0:
            пик = max(пик, вес(vad))
    print(f"       за {ЧАСОВ:.0f} ч найдено фраз: {фраз}, пик буфера поиска речи: {пик} байт")
    проверить(фраз > 100,
              f"поиск речи действительно работал всю встречу (фраз {фраз}), "
              f"иначе проверять рост не на чем")
    # MAX_SEGMENT = 8 с: дольше этого VAD режет принудительно, значит
    # больше 8 секунд звука во float32 он держать не должен ни при каких
    # условиях. Берём тройной запас на кадры и служебные копии.
    потолок = int(8.0 * RATE * 4) * 3
    проверить(пик <= потолок,
              f"поиск речи не копит кадры за длинную встречу "
              f"(пик {пик} байт при потолке {потолок})")


def проверить_список_пропусков() -> None:
    """Список пропусков ограничен даже когда модель отстаёт всю встречу.

    Худший случай: модель не справляется с самого начала и до конца. Тогда
    в список пропусков попадает почти каждый кусок. За четыре часа это
    тысячи записей, и если бы там лежал сам звук, память кончилась бы
    задолго до конца встречи.
    """
    class Медленная:
        name = "медленная"
        languages = ("ru",)

        def transcribe(self, pcm, sample_rate, meeting_id, offset, speaker, **_):
            time.sleep(0.01)
            return [TranscriptSegment(
                meeting_id=meeting_id, speaker=Speaker(speaker),
                text="…", start=offset, end=offset + 0.5,
            )]

    q = TranscriptionQueue(Медленная(), on_segment=lambda s: None, use_vad=False)
    # Каждая потеря пишет строку в лог. Это правильно в работе, но здесь
    # потерь тысячи, и они утопили бы результат проверки.
    logging.getLogger("app.asr.queue").setLevel(logging.ERROR)
    q.start()
    кусок = np.zeros(int(RATE * 0.5), dtype=np.int16)
    кусков = int(ЧАСОВ * 3600 / 0.5)
    for i in range(кусков):
        q.submit("длинная", "me", кусок, i * 0.5, block=False)
    q.stop(timeout=60)

    пропусков = len(q.take_missed("длинная"))
    # Список хранит только координаты (встреча, дорожка, секунда, длина),
    # а не звук: сам звук лежит в WAV. Записи по 4 числа против 16000
    # байт на кусок — разница между мегабайтами и сотнями килобайт.
    вес_списка = пропусков * sys.getsizeof((0.0, 0.0, "", ""))
    вес_звука = пропусков * кусок.nbytes
    print(f"       кусков за встречу: {кусков}, из них потеряно: {пропусков}")
    print(f"       список пропусков весит ~{вес_списка // 1024} КБ; "
          f"если бы он хранил звук, было бы ~{вес_звука // 1024 // 1024} МБ")
    проверить(пропусков > 100,
              f"модель действительно отставала всю встречу (пропусков {пропусков}), "
              f"иначе худший случай не воспроизведён")
    проверить(вес_списка < 5 * 1024 * 1024,
              f"список пропусков остаётся дешёвым даже в худшем случае "
              f"(~{вес_списка // 1024} КБ)")
    # Ни один кусок не должен пропасть бесследно: он либо распознан, либо
    # записан как пропущенный. Иначе «бесконечная запись» теряет речь.
    проверить(пропусков == q.dropped,
              f"каждый выброшенный кусок записан как пропущенный "
              f"({пропусков} против {q.dropped} выброшенных)")


def main() -> int:
    print(f"Проверяем встречу длиной {ЧАСОВ:.0f} часа")
    проверить_нарезку()
    gc.collect()
    проверить_поиск_речи()
    gc.collect()
    проверить_список_пропусков()

    if БЕДЫ:
        print(f"\nПровалено проверок: {len(БЕДЫ)}")
        return 1
    print("\nЗа многочасовую встречу в программе не растёт ничего лишнего")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
