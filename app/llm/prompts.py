"""Промпты для саммари и чата.

Тексты по-русски намеренно: основной язык продукта русский, и модели
на русском промпте отвечают по-русски без отдельного указания. Встречу
на другом языке модель пишет на её языке: строка «Отвечай на русском
языке» заменяется указанием языка (см. на_языке и core/язык_итогов.py).

Главная забота здесь — не дать модели пересказывать. Маленькие модели
склонны переписывать транскрипт своими словами вместо того, чтобы
выделять главное, поэтому запреты в промпте сформулированы жёстко.
"""

from __future__ import annotations

from typing import Any

from ..core.язык_итогов import код, название

Message = dict[str, str]

ПО_РУССКИ = "Отвечай на русском языке."


def на_языке(system: str, lang: str = "ru") -> str:
    """Системная инструкция, которая велит писать на языке встречи.

    Заголовки разделов в шаблонах русские, и маленькая модель охотно
    оставляет их как есть посреди испанского текста. Поэтому про
    заголовки сказано отдельно и прямо.
    """
    if код(lang) in ("", "ru"):
        return system
    return system.replace(
        ПО_РУССКИ,
        f"Пиши весь ответ на {название(lang)}, включая заголовки разделов: "
        "переведи их. Имена людей оставляй как есть.",
    )


# Последняя строка запроса на языке самой встречи. Русская инструкция
# «пиши по-сербски» маленькую модель не убеждает: проба на Qwen3-4B
# (03.10) дала сербской встрече итоги по-русски, а разбору — сербскую
# кириллицу под русскими заголовками. Просьба на нужном языке в самом
# конце запроса перетягивает: модель продолжает тем языком, которым с
# ней заговорили последним.
ПРОСЬБА_НА_ЯЗЫКЕ = {
    "en": "Write the whole answer in English, including the section headings: translate them.",
    "es": "Escribe toda la respuesta en español, incluidos los títulos de las secciones: tradúcelos.",
    "sr": "Napiši ceo odgovor na srpskom jeziku, latinicom, uključujući naslove odeljaka: prevedi ih.",
    "de": "Schreibe die ganze Antwort auf Deutsch, auch die Überschriften: übersetze sie.",
    "fr": "Rédige toute la réponse en français, titres des sections compris : traduis-les.",
    "it": "Scrivi tutta la risposta in italiano, compresi i titoli delle sezioni: traducili.",
    "pt": "Escreva toda a resposta em português, incluindo os títulos das seções: traduza-os.",
}


def _про_заголовки(lang: str) -> str:
    """Напоминание в конце запроса: последнее модель помнит лучше всего."""
    к = код(lang)
    if к in ("", "ru"):
        return ""
    return "\n\n" + ПРОСЬБА_НА_ЯЗЫКЕ.get(
        к, f"Заголовки разделов переведи, а весь текст пиши на {название(lang)}.")


# Заголовки итогов на языках интерфейса. Итоги — главное, что человек
# уносит со встречи, поэтому тут не надеемся на перевод моделью, а даём
# готовые слова. Разборы по методикам переводит модель: их форм много.
ЗАГОЛОВКИ_ИТОГОВ = {
    "en": ("Summary", "Decisions", "Tasks", "Questions"),
    "es": ("Resumen", "Decisiones", "Tareas", "Preguntas"),
    "sr": ("Ukratko", "Odluke", "Zadaci", "Pitanja"),
}


def _шаблон_итогов(lang: str) -> str:
    заголовки = ЗАГОЛОВКИ_ИТОГОВ.get(код(lang))
    if not заголовки:
        return SUMMARY_TEMPLATE
    шаблон = SUMMARY_TEMPLATE
    for ru, свой in zip(("Кратко", "Решения", "Задачи", "Вопросы"), заголовки):
        шаблон = шаблон.replace(f"**{ru}**", f"**{свой}**").replace(f"«{ru}»", f"«{свой}»")
    return шаблон


def после_ответа(text: str, lang: str) -> str:
    """Поправить готовый ответ модели под язык встречи.

    Сербский модель пишет то латиницей, то кириллицей, а сербский
    интерфейс у нас латиницей: переводим буква к букве.
    """
    if код(lang) == "sr":
        from ..asr.whisper import латиница
        return латиница(text)
    return text

SUMMARY_SYSTEM = """Ты помощник, который превращает запись встречи в короткие заметки.

Правила:
- Пиши по существу. Не пересказывай разговор, выделяй суть.
- Разделяй решения, задачи и открытые вопросы.
- Задача — это то, что человек вслух взялся сделать. «Неплохо бы»,
  «надо бы когда-нибудь» и «непонятно, что делать» задачами не являются:
  это открытые вопросы.
- Исполнителя указывай, только если человек сам согласился взяться.
  Не приписывай новые дела тому, кто уже взял одно.
- Если срок не назван, не пиши про срок вообще.
- Одно и то же не должно попадать сразу в задачи и в вопросы.
- Не добавляй ничего, чего не было в разговоре.
- Если чего-то в разговоре не было, просто пропусти этот раздел.
- Отвечай на русском языке. Без вступлений и заключений."""

SUMMARY_TEMPLATE = """Вот запись встречи.

{notes_block}{transcript}

Сделай заметки строго в таком виде:

**Кратко**
Три-четыре предложения о том, что произошло.

**Решения**
- по одному решению в строке

**Задачи**
- Исполнитель — что делает (срок, если назван)

**Вопросы**
- по одному нерешённому вопросу в строке

Каждый пункт с новой строки и начинается с дефиса. В «Задачи» попадает
только то, что человек согласился сделать вслух. Всё остальное идёт в
«Вопросы». Раздел, для которого ничего нет, пропусти целиком."""

NOTES_BLOCK = """Мои пометки во время встречи (они важнее остального,
это то, что я счёл главным):

{notes}

Полная расшифровка:

"""

# Без примеров вида «+9» в самих правилах: маленькая модель копирует
# пример из промпта в ответ. С примером «+9» она на «1+6» отвечала «+9»,
# без него считала верно: 7, 16, 19 (проба на живой модели 30.09).
#
# Запись встречи — не слова человека, а материал: так и сказано в первой
# строке. Раньше встреча и вопрос склеивались через «Вопрос:», и модель
# путала, кто с ней говорит. На «Слышишь меня? Алло?» она три раза из
# трёх отвечала «Нет.», на «ты кто?» — «Я — Валерий Николаевич» (имя из
# записи), на «О чём была встреча?» повторяла вопрос. С этой подачей на
# той же встрече и той же модели: «Алло! Я здесь», «Я помощник в
# Konspekt», пересказ встречи (проба 30.09, Qwen3-4B).
#
# Правило «не о встрече — отвечай сам» сказано прямо и с запретом
# отказываться. Без этого на «напиши код php фибоначчи» модель три раза
# из трёх отвечала «не могу, это не связано с записью встречи». Ответы
# про встречу от этого не пострадали: срок, которого нет, она так же
# называет неназванным (проба 30.09).
CHAT_SYSTEM = """Ты помощник в программе Konspekt. Ты разговариваешь с человеком,
который записал встречу. Запись встречи приложена к его сообщению в
теге <встреча>: это не его слова, а материал, по которому он может
спрашивать.

Как отвечать:
- Сообщение человека обращено к тебе. Приветствие, «ты тут?», «кто ты» —
  это к тебе, ответь как живой собеседник.
- Вопрос о встрече — отвечай по записи, своими словами. Нет ответа в
  записи — так и скажи, не додумывай. Кто говорит во встрече, перечислено
  перед записью; спросили о человеке, которого там нет и в тексте не
  упоминают, — скажи, что его в записи нет.
- Спросили «кто» — назови человека. Спросили «когда» — назови срок.
  Просят точную формулировку — процитируй дословно, можно с временем
  отрывка в квадратных скобках.
- Ты не ограничен встречей. Просьбу не о встрече — написать код,
  посчитать, перевести, посоветовать — выполняй сам, полностью и по
  существу. Не отказывайся из-за того, что во встрече этого не было, и
  не пересказывай встречу.
- Помни переписку: короткая реплика продолжает предыдущую. Спросил о
  человеке, потом «а он?» — речь о нём же.
- Отвечай коротко и ровно на то, что спросили. Не повторяй вопрос.
- Отвечай на языке сообщения."""

CHAT_CONTEXT = """<встреча «{title}»>
{transcript}
</встреча>"""

CHAT_EXCERPTS = """<отрывки встречи «{title}»>
Это не вся встреча, а отрывки, подобранные к вопросу. Если ответа в них
нет, скажи, что не нашёл его, а не что его не было.

{transcript}
</отрывки>"""

TITLE_SYSTEM = """Придумай короткий заголовок встречи: три-пять слов,
по сути разговора. Только заголовок, без кавычек и пояснений."""


def summary_messages(
    title: str,
    transcript: str,
    notes: str = "",
    template: str = "general",
    lang: str = "ru",
) -> list[Message]:
    """Собрать запрос на саммари встречи.

    Пометки пользователя идут перед расшифровкой и с прямым указанием
    на их важность: человек писал их руками, значит, счёл главным, и
    саммари должно вращаться вокруг них.
    """
    notes_block = ""
    if notes.strip():
        notes_block = NOTES_BLOCK.format(notes=notes.strip())

    system = на_языке(SUMMARY_SYSTEM, lang)
    extra = TEMPLATE_HINTS.get(template, "")
    if extra:
        system = f"{system}\n\n{extra}"

    user = _шаблон_итогов(lang).format(
        notes_block=notes_block,
        transcript=transcript.strip() or "(расшифровки нет)",
    ) + _про_заголовки(lang)
    if title.strip():
        user = f"Название встречи: {title.strip()}\n\n{user}"
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def speakers(transcript: str) -> list[str]:
    """Кто говорит в расшифровке: имена в начале строк «Кто: что».

    Отрывки начинаются с отметки времени «[1:05] Маша: ...», её пропускаем.
    Порядок — как впервые заговорили.
    """
    import re

    out: list[str] = []
    for line in transcript.splitlines():
        m = re.match(r"^\s*(?:\[[\d:]+\]\s*)?([^:\n\[\]]{1,40}?):\s", line)
        if m:
            who = m.group(1).strip()
            # Имя с большой буквы: «Маша», «Я», «Собеседник 2». Строка вроде
            # «и ещё: дальше» — продолжение речи, а не говорящий.
            if who and who[0].isupper() and who not in out:
                out.append(who)
    return out


def chat_messages(
    title: str,
    transcript: str,
    history: list[dict[str, Any]],
    question: str,
    summary: str = "",
    whole: bool = True,
    attach: bool = True,
) -> list[Message]:
    """Собрать запрос чата по одной встрече.

    Текст встречи идёт в последнее сообщение, рядом с вопросом, а в
    переписке остаются только голые вопросы и ответы. Проверено на копии
    живой базы: когда встреча лежала в системном сообщении, маленькая
    модель повторяла вопрос эхом или отвечала «я помощник по встрече»;
    рядом с вопросом она отвечает по существу. Заодно отрывки к каждому
    вопросу свои (см. llm/context.py), и старые не копятся в переписке.
    """
    шаблон = CHAT_CONTEXT if whole else CHAT_EXCERPTS
    context = шаблон.format(
        title=title.strip() or "без названия",
        transcript=transcript.strip() or "(расшифровки нет)",
    )
    # Кто говорит, явно и перед записью. Без этого на «что говорила
    # Маша?» модель пересказывала слова единственного собеседника от
    # имени Маши, которой во встрече не было (проба 30.09). С явным
    # списком отвечает «В записи нет Маши».
    говорящие = speakers(transcript)
    if говорящие:
        context = (f"Говорят во встрече: {', '.join(говорящие)}. "
                   f"Других говорящих в записи нет.\n\n{context}")
    if summary.strip():
        context = f"{context}\n\n<заметки по всей встрече>\n{summary.strip()}\n</заметки>"

    messages: list[Message] = [{"role": "system", "content": CHAT_SYSTEM}]
    for item in history:
        role = item.get("role")
        content = (item.get("content") or "").strip()
        if role in ("user", "assistant") and content:
            messages.append({"role": role, "content": content})
    if not attach:
        # Вопрос не о встрече (см. llm/context.py): отдаём как есть.
        messages.append({"role": "user", "content": question.strip()})
        return messages
    messages.append({"role": "user", "content": f"{context}\n\nСообщение человека: {question.strip()}"})
    return messages


CHUNK_SYSTEM = """Ты выписываешь главное из куска записи встречи.

Правила:
- Только то, что сказано в этом куске. Ничего не додумывай.
- Короткими пунктами: решения, взятые обязательства, открытые вопросы.
- Сохраняй имена и названные сроки дословно.
- Это черновик, а не готовые заметки: не подводи итогов.
- Отвечай на русском языке."""

MERGE_SYSTEM = """Ты собираешь заметки о встрече из черновиков её частей.

Правила:
- Черновики идут по порядку, от начала встречи к концу.
- Объединяй повторы: одно и то же обсуждали в нескольких частях.
- Если в конце решение отменили или изменили, верным считается позднее.
- Не добавляй ничего, чего нет в черновиках.
- Отвечай на русском языке. Без вступлений и заключений."""


def chunk_messages(text: str, lang: str = "ru") -> list[Message]:
    """Выжимка из куска длинной встречи."""
    return [
        {"role": "system", "content": на_языке(CHUNK_SYSTEM, lang)},
        {"role": "user", "content": text.strip()},
    ]


def merge_messages(
    title: str,
    drafts: list[str],
    notes: str = "",
    template: str = "general",
    lang: str = "ru",
) -> list[Message]:
    """Собрать итоговые заметки из черновиков частей.

    Работает по тому же шаблону вывода, что и обычное саммари: человеку
    не должно быть видно, что длинную встречу разбирали по частям.
    """
    system = на_языке(MERGE_SYSTEM, lang)
    extra = TEMPLATE_HINTS.get(template, "")
    if extra:
        system = f"{system}\n\n{extra}"

    body = "\n\n".join(
        f"Часть {i + 1}:\n{d.strip()}" for i, d in enumerate(drafts) if d.strip()
    )
    notes_block = ""
    if notes.strip():
        notes_block = NOTES_BLOCK.format(notes=notes.strip())

    user = _шаблон_итогов(lang).format(notes_block=notes_block, transcript=body)
    user = user.replace("Вот запись встречи.", "Вот черновики частей встречи.") + _про_заголовки(lang)
    if title.strip():
        user = f"Название встречи: {title.strip()}\n\n{user}"
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def title_messages(transcript: str) -> list[Message]:
    return [
        {"role": "system", "content": TITLE_SYSTEM},
        {"role": "user", "content": transcript.strip()[:4000]},
    ]


