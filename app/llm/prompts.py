"""Промпты для саммари и чата.

Тексты по-русски намеренно: основной язык продукта русский, и модели
на русском промпте отвечают по-русски без отдельного указания.

Главная забота здесь — не дать модели пересказывать. Маленькие модели
склонны переписывать транскрипт своими словами вместо того, чтобы
выделять главное, поэтому запреты в промпте сформулированы жёстко.
"""

from __future__ import annotations

from typing import Any

Message = dict[str, str]

SUMMARY_SYSTEM = """Ты помощник, который превращает запись встречи в короткие заметки.

Правила:
- Пиши по существу. Не пересказывай разговор, выделяй суть.
- Разделяй решения, задачи и открытые вопросы.
- Задача — это то, что человек вслух взялся сделать. «Неплохо бы»,
  «надо бы когда-нибудь» и «непонятно, что делать» задачами не являются:
  это открытые вопросы.
- Исполнителя указывай, только если человек сам согласился взяться.
  Не приписывай новые дела тому, кто уже взял одно.
- Если срок не назван, не пиши про срок вообще.
- Одно и то же не должно попадать сразу в задачи и в вопросы.
- Не добавляй ничего, чего не было в разговоре.
- Если чего-то в разговоре не было, просто пропусти этот раздел.
- Отвечай на русском языке. Без вступлений и заключений."""

SUMMARY_TEMPLATE = """Вот запись встречи.

{notes_block}{transcript}

Сделай заметки строго в таком виде:

**Кратко**
Три-четыре предложения о том, что произошло.

**Решения**
- по одному решению в строке

**Задачи**
- Исполнитель — что делает (срок, если назван)

**Вопросы**
- по одному нерешённому вопросу в строке

Каждый пункт с новой строки и начинается с дефиса. В «Задачи» попадает
только то, что человек согласился сделать вслух. Всё остальное идёт в
«Вопросы». Раздел, для которого ничего нет, пропусти целиком."""

NOTES_BLOCK = """Мои пометки во время встречи (они важнее остального,
это то, что я счёл главным):

{notes}

Полная расшифровка:

"""

# Без примеров вида «+9» в самих правилах: маленькая модель копирует
# пример из промпта в ответ. С примером «+9» она на «1+6» отвечала «+9»,
# без него считала верно: 7, 16, 19 (проба на живой модели 30.09).
CHAT_SYSTEM = """Ты помощник в программе Konspekt. Человек спрашивает о своей
встрече и ведёт с тобой обычный разговор.

Правила:
- Помни переписку. Короткая реплика продолжает предыдущий вопрос: если
  человек что-то считал, а потом пишет только число со знаком, продолжи
  тот же счёт; если спросил о человеке, а потом «а он?», речь о нём же.
- О встрече отвечай только по тексту встречи, приложенному к вопросу.
  Если ответа там нет, так и скажи. Не додумывай.
- На вопросы не о встрече (посчитать, перевести, написать письмо по
  итогам) отвечай сам и не пересказывай встречу.
- Отвечай коротко, своими словами и ровно на заданный вопрос. Не
  повторяй вопрос.
- Спросили «кто» — назови человека. Спросили «когда» — назови срок.
- Цитируй дословно, когда просят точную формулировку. Можно указать
  время отрывка в квадратных скобках, чтобы человек нашёл место.
- Отвечай на языке вопроса."""

CHAT_CONTEXT = """<встреча «{title}»>
{transcript}
</встреча>"""

CHAT_EXCERPTS = """<отрывки встречи «{title}»>
Это не вся встреча, а отрывки, подобранные к вопросу. Если ответа в них
нет, скажи, что не нашёл его, а не что его не было.

{transcript}
</отрывки>"""

TITLE_SYSTEM = """Придумай короткий заголовок встречи: три-пять слов,
по сути разговора. Только заголовок, без кавычек и пояснений."""


def summary_messages(
    title: str,
    transcript: str,
    notes: str = "",
    template: str = "general",
) -> list[Message]:
    """Собрать запрос на саммари встречи.

    Пометки пользователя идут перед расшифровкой и с прямым указанием
    на их важность: человек писал их руками, значит, счёл главным, и
    саммари должно вращаться вокруг них.
    """
    notes_block = ""
    if notes.strip():
        notes_block = NOTES_BLOCK.format(notes=notes.strip())

    system = SUMMARY_SYSTEM
    extra = TEMPLATE_HINTS.get(template, "")
    if extra:
        system = f"{system}\n\n{extra}"

    user = SUMMARY_TEMPLATE.format(
        notes_block=notes_block,
        transcript=transcript.strip() or "(расшифровки нет)",
    )
    if title.strip():
        user = f"Название встречи: {title.strip()}\n\n{user}"
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def chat_messages(
    title: str,
    transcript: str,
    history: list[dict[str, Any]],
    question: str,
    summary: str = "",
    whole: bool = True,
    attach: bool = True,
) -> list[Message]:
    """Собрать запрос чата по одной встрече.

    Текст встречи идёт в последнее сообщение, рядом с вопросом, а в
    переписке остаются только голые вопросы и ответы. Проверено на копии
    живой базы: когда встреча лежала в системном сообщении, маленькая
    модель повторяла вопрос эхом или отвечала «я помощник по встрече»;
    рядом с вопросом она отвечает по существу. Заодно отрывки к каждому
    вопросу свои (см. llm/context.py), и старые не копятся в переписке.
    """
    шаблон = CHAT_CONTEXT if whole else CHAT_EXCERPTS
    context = шаблон.format(
        title=title.strip() or "без названия",
        transcript=transcript.strip() or "(расшифровки нет)",
    )
    if summary.strip():
        context = f"{context}\n\n<заметки по всей встрече>\n{summary.strip()}\n</заметки>"

    messages: list[Message] = [{"role": "system", "content": CHAT_SYSTEM}]
    for item in history:
        role = item.get("role")
        content = (item.get("content") or "").strip()
        if role in ("user", "assistant") and content:
            messages.append({"role": role, "content": content})
    if not attach:
        # Вопрос не о встрече (см. llm/context.py): отдаём как есть.
        messages.append({"role": "user", "content": question.strip()})
        return messages
    messages.append({"role": "user", "content": f"{context}\n\nВопрос: {question.strip()}"})
    return messages


CHUNK_SYSTEM = """Ты выписываешь главное из куска записи встречи.

Правила:
- Только то, что сказано в этом куске. Ничего не додумывай.
- Короткими пунктами: решения, взятые обязательства, открытые вопросы.
- Сохраняй имена и названные сроки дословно.
- Это черновик, а не готовые заметки: не подводи итогов.
- Отвечай на русском языке."""

MERGE_SYSTEM = """Ты собираешь заметки о встрече из черновиков её частей.

Правила:
- Черновики идут по порядку, от начала встречи к концу.
- Объединяй повторы: одно и то же обсуждали в нескольких частях.
- Если в конце решение отменили или изменили, верным считается позднее.
- Не добавляй ничего, чего нет в черновиках.
- Отвечай на русском языке. Без вступлений и заключений."""


def chunk_messages(text: str) -> list[Message]:
    """Выжимка из куска длинной встречи."""
    return [
        {"role": "system", "content": CHUNK_SYSTEM},
        {"role": "user", "content": text.strip()},
    ]


def merge_messages(
    title: str,
    drafts: list[str],
    notes: str = "",
    template: str = "general",
) -> list[Message]:
    """Собрать итоговые заметки из черновиков частей.

    Работает по тому же шаблону вывода, что и обычное саммари: человеку
    не должно быть видно, что длинную встречу разбирали по частям.
    """
    system = MERGE_SYSTEM
    extra = TEMPLATE_HINTS.get(template, "")
    if extra:
        system = f"{system}\n\n{extra}"

    body = "\n\n".join(
        f"Часть {i + 1}:\n{d.strip()}" for i, d in enumerate(drafts) if d.strip()
    )
    notes_block = ""
    if notes.strip():
        notes_block = NOTES_BLOCK.format(notes=notes.strip())

    user = SUMMARY_TEMPLATE.format(notes_block=notes_block, transcript=body)
    user = user.replace("Вот запись встречи.", "Вот черновики частей встречи.")
    if title.strip():
        user = f"Название встречи: {title.strip()}\n\n{user}"
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def title_messages(transcript: str) -> list[Message]:
    return [
        {"role": "system", "content": TITLE_SYSTEM},
        {"role": "user", "content": transcript.strip()[:4000]},
    ]


# Подсказки под тип встречи. Намеренно короткие: длинные инструкции
# маленькая модель начинает пересказывать вместо выполнения.
TEMPLATE_HINTS: dict[str, str] = {
    "one_on_one": (
        "Это встреча один на один. Обрати внимание на договорённости о "
        "развитии, обратную связь и то, что человека беспокоит."
    ),
    "sales": (
        "Это разговор с клиентом. Отдельно отметь потребности клиента, "
        "возражения, договорённости о цене и следующий шаг."
    ),
    "standup": (
        "Это статус-встреча команды. Сгруппируй по людям: что сделано, "
        "что в работе, что мешает."
    ),
    "interview": (
        "Это собеседование. Отметь опыт кандидата, сильные и слабые "
        "стороны, ответы на ключевые вопросы."
    ),
}
