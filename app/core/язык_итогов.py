"""На каком языке писать итоги, разборы и заголовок встречи.

Раньше всё, что пишет модель, шло по-русски: в инструкции стояло
«Отвечай на русском языке». Испанец, записавший испанскую встречу в
испанском интерфейсе, получал итоги по-русски. Теперь язык берётся из
самой встречи: на каком языке в ней больше всего сказано, на том и
итоги. Это честнее, чем язык интерфейса: человек с английским
интерфейсом, записавший русскую планёрку, ждёт русские заметки, потому
что понесёт их русским коллегам.

Язык интерфейса остаётся запасным: у встречи без расшифровки (одни
пометки) языка реплик нет.
"""

from __future__ import annotations

from typing import Iterable

# Языки, на которых переведён сам интерфейс. Подписи разборов без модели
# («Кто сколько говорил») есть только на них.
ЯЗЫКИ_ИНТЕРФЕЙСА = ("ru", "en", "es", "sr")

# Как назвать язык в инструкции модели. Инструкции написаны по-русски,
# поэтому и названия в предложном падеже: «пиши на испанском языке».
# Сербский — латиницей: так пишут сербы в сети, и так переведён наш
# сербский интерфейс.
НАЗВАНИЯ = {
    "ru": "русском языке",
    "en": "английском языке",
    "es": "испанском языке",
    "sr": "сербском языке, латиницей",
    "hr": "хорватском языке",
    "bs": "боснийском языке",
    "de": "немецком языке",
    "fr": "французском языке",
    "it": "итальянском языке",
    "pt": "португальском языке",
    "nl": "нидерландском языке",
    "pl": "польском языке",
    "cs": "чешском языке",
    "tr": "турецком языке",
    "uk": "украинском языке",
    "zh": "китайском языке",
    "ja": "японском языке",
    "ko": "корейском языке",
    "ar": "арабском языке",
}


def код(lang: str) -> str:
    """«en-US», «EN» и «en» — один язык."""
    return (lang or "").split("-")[0].split("_")[0].strip().lower()


def язык_встречи(реплики: Iterable[tuple[str, str]], запасной: str = "ru") -> str:
    """Язык, на котором в встрече сказано больше всего текста.

    `реплики` — пары (язык, текст). Считаем по длине текста, а не по
    числу реплик: десяток «ок», «да», «yes» не должен перевесить
    пятиминутный доклад. Реплики без пометки языка не считаем: это старые
    встречи и загруженные файлы, у которых языка не знаем.
    """
    счёт: dict[str, int] = {}
    for lang, текст in реплики:
        к = код(lang)
        if к:
            счёт[к] = счёт.get(к, 0) + len((текст or "").strip())
    if not счёт:
        return код(запасной) or "ru"
    return max(счёт.items(), key=lambda п: п[1])[0]


def язык_подписей(язык: str, интерфейс: str) -> str:
    """Язык подписей у разборов без модели: встречи, если есть перевод."""
    к = код(язык)
    if к in ЯЗЫКИ_ИНТЕРФЕЙСА:
        return к
    к = код(интерфейс)
    return к if к in ЯЗЫКИ_ИНТЕРФЕЙСА else "en"


def название(язык: str) -> str:
    """«испанском языке»; незнакомый язык — его код, модель поймёт."""
    к = код(язык)
    return НАЗВАНИЯ.get(к, f"языке с кодом «{к}»")
