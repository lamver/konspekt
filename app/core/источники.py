"""Папка-источник: записи из папки на диске сами становятся встречами.

Источник — свойство папки встреч (решение 30.09): у папки «Звонки» есть
каталог на диске, куда АТС, диктофон или облачный диск складывают записи,
и новые файлы оттуда сами появляются в «Звонках» с расшифровкой.

Правила, каждое оплачено чьей-то бедой в похожих программах:
- Берём только дописанный файл. АТС пишет звонок минутами, синхронизация
  облачного диска тянет файл частями; схватить его на середине значит
  получить полвстречи. Файл берётся, когда размер и время изменения не
  менялись между двумя обходами и с последней записи прошло ТИШИНА секунд.
- Не берём повторно. Отпечаток — размер, начало и конец содержимого: он
  переживает перезапуск программы и переименование файла. Путь в
  отпечаток не входит, иначе перенос папки на другой диск дал бы дубли.
- Ничего не удаляем и не переносим: каталог чужой, им пользуются другие
  программы. Только запоминаем, что уже взяли.
- После пробного периода не молчим: папка показывает, что новые записи
  не берутся, а файлы не помечаются взятыми и придут, когда появится
  лицензия.

Обход опросом раз в ИНТЕРВАЛ секунд, без подписки на события файловой
системы: сетевые папки и облачные диски эти события теряют, а опрос
работает везде одинаково.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import logging
import os
import re
import threading
import time
from pathlib import Path
from typing import Any, Callable

log = logging.getLogger(__name__)

ЗВУК = {
    ".mp3", ".wav", ".m4a", ".ogg", ".oga", ".opus", ".flac", ".aac", ".wma",
    ".amr", ".gsm", ".mp4", ".m4v", ".webm", ".mkv", ".mov", ".3gp",
}
ИНТЕРВАЛ = 10.0
ТИШИНА = 5.0
ГЛУБИНА = 3          # АТС раскладывает записи по годам, месяцам и дням
ПРЕДЕЛ_ФАЙЛОВ = 20000
КУСОК = 64 * 1024


def отпечаток(путь: Path) -> str:
    """Размер, начало и конец файла: одинаковые записи узнаются под любым именем."""
    размер = путь.stat().st_size
    h = hashlib.sha1(str(размер).encode())
    with путь.open("rb") as f:
        h.update(f.read(КУСОК))
        if размер > КУСОК:
            f.seek(max(КУСОК, размер - КУСОК))
            h.update(f.read(КУСОК))
    return h.hexdigest()


_ДАТЫ = (
    # 2026-10-03_14-22-05, 2026-10-03 14.22, 2026-10-03T14:22:05
    re.compile(r"(?P<y>20\d\d)[-_.](?P<m>[01]\d)[-_.](?P<d>[0-3]\d)[ _T-]+(?P<H>[0-2]\d)[-_.:](?P<M>[0-5]\d)(?:[-_.:](?P<S>[0-5]\d))?"),
    # 20261003-142205, 20261003_1422 (Asterisk: out-…-20261003-142205)
    re.compile(r"(?<!\d)(?P<y>20\d\d)(?P<m>[01]\d)(?P<d>[0-3]\d)[-_T]?(?P<H>[0-2]\d)(?P<M>[0-5]\d)(?P<S>[0-5]\d)?(?!\d)"),
    # 03.10.2026 14.22
    re.compile(r"(?P<d>[0-3]\d)[.](?P<m>[01]\d)[.](?P<y>20\d\d)[ _-]+(?P<H>[0-2]\d)[-_.:](?P<M>[0-5]\d)"),
)
# Российский номер: +7, 7 или 8 и ещё десять цифр, с разделителями или без.
_НОМЕР = re.compile(r"(?<!\d)(?:\+?7|8)[\s()-]*(\d{3})[\s()-]*(\d{3})[\s-]*(\d{2})[\s-]*(\d{2})(?!\d)")


def разобрать_имя(имя: str) -> tuple[str | None, float | None]:
    """Номер и время звонка из имени файла записи. Чего нет — None."""
    номер = None
    м = _НОМЕР.search(имя)
    if м:
        номер = f"+7 {м.group(1)} {м.group(2)}-{м.group(3)}-{м.group(4)}"
    когда = None
    for образец in _ДАТЫ:
        д = образец.search(имя)
        if not д:
            continue
        try:
            когда = dt.datetime(
                int(д["y"]), int(д["m"]), int(д["d"]),
                int(д["H"]), int(д["M"]), int(д.groupdict().get("S") or 0),
            ).timestamp()
            break
        except ValueError:
            continue
    return номер, когда


def название(путь: Path, номер: str | None, слово_звонок: str) -> str:
    """Название встречи: номер, если он есть, иначе понятное имя файла."""
    if номер:
        return f"{слово_звонок} {номер}"
    return re.sub(r"[_]+", " ", путь.stem).strip() or путь.name


def файлы_записей(каталог: Path) -> list[Path]:
    """Звуковые файлы в каталоге и подкаталогах до ГЛУБИНА уровней."""
    найдено: list[Path] = []
    корень = len(каталог.parts)
    for где, папки, имена in os.walk(каталог):
        уровень = len(Path(где).parts) - корень
        if уровень >= ГЛУБИНА:
            папки[:] = []
        # Скрытые и служебные каталоги синхронизации не трогаем.
        папки[:] = [п for п in папки if not п.startswith((".", "$", "~"))]
        for имя in имена:
            if имя.startswith((".", "~$")):
                continue
            if Path(имя).suffix.lower() in ЗВУК:
                найдено.append(Path(где) / имя)
                if len(найдено) >= ПРЕДЕЛ_ФАЙЛОВ:
                    return найдено
    return найдено


class СторожПапок:
    """Обходит папки с источником и отдаёт новые записи в импорт."""

    def __init__(
        self,
        папки: Callable[[], list[dict[str, Any]]],
        уже_взят: Callable[[str, str], bool],
        отметить: Callable[[str, str, str], None],
        импорт: Callable[[Path, str, str, float | None], str],
        слово_звонок: Callable[[], str],
        интервал: float = ИНТЕРВАЛ,
        тишина: float = ТИШИНА,
    ) -> None:
        """
        импорт(путь, папка, название, время) отвечает: "ok", "trial" или "failed".
        """
        self._папки = папки
        self._уже_взят = уже_взят
        self._отметить = отметить
        self._импорт = импорт
        self._слово = слово_звонок
        self.интервал = интервал
        self.тишина = тишина
        self._размеры: dict[str, tuple[int, int]] = {}
        self._состояние: dict[str, dict[str, Any]] = {}
        self._стоп = threading.Event()
        self._поток: threading.Thread | None = None
        self._замок = threading.Lock()

    def запустить(self) -> None:
        if self._поток and self._поток.is_alive():
            return
        self._стоп.clear()
        self._поток = threading.Thread(target=self._цикл, name="source-folders", daemon=True)
        self._поток.start()

    def остановить(self) -> None:
        self._стоп.set()
        if self._поток:
            self._поток.join(timeout=3)

    def состояние(self, папка_id: str) -> dict[str, Any]:
        with self._замок:
            return dict(self._состояние.get(папка_id, {}))

    def _цикл(self) -> None:
        while not self._стоп.is_set():
            try:
                self.обойти()
            except Exception:
                log.exception("Источники: обход не удался")
            self._стоп.wait(self.интервал)

    def обойти(self) -> None:
        for папка in self._папки():
            if папка.get("source"):
                self._обойти_папку(папка["id"], Path(папка["source"]))

    def _обойти_папку(self, папка_id: str, каталог: Path) -> None:
        if not каталог.is_dir():
            with self._замок:
                self._состояние[папка_id] = {"error": "missing"}
            return
        состояние: dict[str, Any] = {"error": "", "trial": False}
        try:
            for путь in файлы_записей(каталог):
                if self._стоп.is_set():
                    return
                итог = self._рассмотреть(папка_id, путь)
                if итог == "trial":
                    # Пробные встречи кончились: файлы не помечаем взятыми,
                    # с лицензией они придут сами. Дальше по папке не идём.
                    состояние["trial"] = True
                    break
        except OSError:
            log.warning("Источники: папка %s не читается", каталог, exc_info=True)
            состояние["error"] = "unreadable"
        with self._замок:
            self._состояние[папка_id] = состояние

    def _рассмотреть(self, папка_id: str, путь: Path) -> str:
        try:
            st = путь.stat()
        except OSError:
            return "skip"
        ключ = str(путь)
        сейчас = (st.st_size, st.st_mtime_ns)
        прежде = self._размеры.get(ключ)
        self._размеры[ключ] = сейчас
        # Дописан ли файл: не менялся с прошлого обхода и давно не трогался.
        if прежде != сейчас or st.st_size == 0 or time.time() - st.st_mtime < self.тишина:
            return "wait"
        try:
            след = отпечаток(путь)
        except OSError:
            return "skip"  # файл занят или пропал: посмотрим в следующий раз
        if self._уже_взят(папка_id, след):
            return "seen"
        номер, когда = разобрать_имя(путь.stem)
        итог = self._импорт(путь, папка_id, название(путь, номер, self._слово()), когда or st.st_mtime)
        if итог == "trial":
            return "trial"
        # И принятый, и не звук: второй раз брать незачем.
        self._отметить(папка_id, след, ключ)
        log.info("Источники: %s взят (%s)", путь.name, итог)
        return итог

    def взять_как_есть(self, папка_id: str, каталог: Path) -> int:
        """Отметить уже лежащие записи взятыми: при подключении «только новые»."""
        отмечено = 0
        for путь in файлы_записей(каталог):
            try:
                self._отметить(папка_id, отпечаток(путь), str(путь))
                отмечено += 1
            except OSError:
                continue
        return отмечено
