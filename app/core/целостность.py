"""Файлы окна той же сборки, что и сама программа.

Зачем (задача №5 в konspekt-releases, 05.10): человек обновился до
0.15.3, «О программе» честно показывало 0.15.3, а меню настроек было из
версий 0.8–0.11, без «Telegram» и «Лицензии». Номер версии зашит в
питон, а окно рисуется из файлов `web/`, и одно обновилось без другого.
Со стороны это выглядит как «обновилась, а обещанного нет», и ни журнал,
ни сама программа об этом не говорили.

Поэтому сборка записывает сумму каждого файла окна в `app/build_info.py`,
а собранная программа при запуске сверяет с ней то, что лежит на диске.
Сверять должен питон, а не окно: старый app.js про новую проверку не
знает, и как раз в беде её бы и не случилось.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path


# Замок, который держит установщик, пока подменяет файлы (SetupMutex
# в packaging/konspekt.iss).
ЗАМОК_УСТАНОВКИ = "KonspektSetup"


def идёт_установка(имя: str = ЗАМОК_УСТАНОВКИ) -> bool:
    """Подменяет ли установщик файлы программы прямо сейчас.

    Зовётся первой строкой запуска, до библиотек. Значок пропал посреди
    тихого обновления, человек жмёт ярлык — и запущенный exe занимает сам
    себя: установщик не может его заменить и откатывает всё (проверено
    05.10, «DeleteFile: код 5»). Ждать внутри exe нельзя, он так и
    остаётся занятым. Поэтому сразу выходим: после тихого обновления
    установщик сам поднимет программу.
    """
    if sys.platform != "win32":
        return False
    import ctypes

    kernel32 = ctypes.windll.kernel32
    SYNCHRONIZE = 0x00100000
    замок = kernel32.OpenMutexW(SYNCHRONIZE, False, имя)
    if not замок:
        return False
    kernel32.CloseHandle(замок)
    return True


def пора_чинить(данные: Path, версия: str) -> bool:
    """Чинить ли окно этой версии. Один раз на версию, дальше нет.

    Если и после переустановки файлы не сходятся, второй круг ничего не
    даст, а качать 100 МБ на каждом запуске было бы хуже самой беды.
    """
    метка = данные / "починка_окна.txt"
    try:
        if метка.read_text(encoding="utf-8").strip() == версия:
            return False
    except OSError:
        pass
    try:
        метка.write_text(версия, encoding="utf-8")
    except OSError:
        return False
    return True


def опись(web: Path) -> dict[str, str]:
    """Сумма каждого файла окна, путь относительно `web/` через «/»."""
    итог: dict[str, str] = {}
    for файл in sorted(web.rglob("*")):
        if файл.is_file():
            итог[файл.relative_to(web).as_posix()] = hashlib.sha256(файл.read_bytes()).hexdigest()
    return итог


def расхождения(web: Path, ожидаемо: dict[str, str]) -> list[str]:
    """Файлы, которых нет или которые не совпадают со сборкой.

    Лишние файлы не считаются: после старых версий в папке может лежать
    то, что уже не нужно, и окну это не мешает.
    """
    беды: list[str] = []
    for путь, сумма in ожидаемо.items():
        файл = web / путь
        if not файл.is_file():
            беды.append(f"{путь}: нет")
        elif hashlib.sha256(файл.read_bytes()).hexdigest() != сумма:
            беды.append(f"{путь}: другой")
    return беды


def проверить_окно(web: Path) -> list[str]:
    """Сверить файлы окна с описью сборки. В разработке сверять не с чем.

    В разработке `build_info.py` остаётся от последней сборки, а `web/`
    правится каждый день, поэтому там проверка только мешала бы.
    """
    if not getattr(sys, "frozen", False):
        return []
    try:
        from app.build_info import WEB_FILES
    except ImportError:
        return []
    return расхождения(web, WEB_FILES)
