"""Личные данные в тексте встречи: найти и скрыть.

Зачем. Конспект встречи уходит дальше: в чат команды, в трекер, в
письмо, а при своём сервере — ещё и в чужую модель. В разговоре легко
проскакивают номер карты, телефон, паспорт, и человек не замечает их в
длинном тексте. Здесь они находятся и заменяются пометкой вроде
«[телефон]».

Как устроено. Идея взята из SentiGuard (lamver/SentiGuard), но без его
зависимостей: Presidio и spaCy добавили бы программе сотни мегабайт и
лишний повод антивирусам. Всё, у чего есть контрольная сумма, проверяем
ею (карта — Луном, ИНН и СНИЛС — своими правилами, IBAN — mod 97): так
случайные числа из разговора, вроде «двенадцать миллионов», не
принимаются за документ. Паспорт контрольной суммы не имеет, поэтому
ищем его только рядом со словом «паспорт».

Люди и адреса. Одиночное имя не ищем: без модели морфологии «Роза» в
«розу посадили» неотличима от человека, а ложная тревога на каждом
втором слове хуже, чем её отсутствие. Ищем то, что само себя выдаёт:
- имя с отчеством («Валерий Николаевич»), с фамилией или без: отчество
  с заглавной буквы и окончанием -ович, -евна и подобными в обычной
  речи не встречается;
- имя из списка частых имён рядом с фамилией на -ов, -ин, -ский и
  подобные («Иван Петров», «Петрову Ивану»);
- адрес: дом с корпусом или квартирой («Колпакова, дом 40, корпус 3,
  квартира 46») или улица, проспект, переулок с номером дома.
Проверено на архиве из 10 770 реплик: 13 находок (10 людей, 3 адреса
доставки), и все настоящие, ложных тревог нет.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

# Порядок важен: при пересечении побеждает то, что раньше. Карта раньше
# телефона (16 цифр карты содержат «телефон»), СНИЛС и ИНН раньше
# паспорта и телефона: у них есть контрольная сумма, и совпадение по ней
# надёжнее совпадения по виду.
ВИДЫ = ("email", "card", "iban", "snils", "inn", "passport", "phone", "address", "person")

ПОМЕТКИ = {
    "email": "[почта]",
    "card": "[карта]",
    "iban": "[счёт]",
    "snils": "[СНИЛС]",
    "inn": "[ИНН]",
    "passport": "[паспорт]",
    "phone": "[телефон]",
    "address": "[адрес]",
    "person": "[имя]",
}


@dataclass(frozen=True)
class Находка:
    kind: str
    start: int
    end: int
    text: str

    def to_dict(self) -> dict:
        return {"kind": self.kind, "start": self.start, "end": self.end, "text": self.text}


def _цифры(s: str) -> str:
    return re.sub(r"\D", "", s)


# --- контрольные суммы -----------------------------------------------------


def луна(цифры: str) -> bool:
    """Контрольная сумма банковской карты."""
    сумма = 0
    for i, c in enumerate(reversed(цифры)):
        d = int(c)
        if i % 2:
            d *= 2
            if d > 9:
                d -= 9
        сумма += d
    return сумма % 10 == 0


def инн(цифры: str) -> bool:
    """ИНН: 10 цифр у организации, 12 у человека."""
    def к(веса: tuple[int, ...], n: int) -> int:
        return sum(int(цифры[i]) * веса[i] for i in range(n)) % 11 % 10

    if len(цифры) == 10:
        return к((2, 4, 10, 3, 5, 9, 4, 6, 8), 9) == int(цифры[9])
    if len(цифры) == 12:
        return (
            к((7, 2, 4, 10, 3, 5, 9, 4, 6, 8), 10) == int(цифры[10])
            and к((3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8), 11) == int(цифры[11])
        )
    return False


def снилс(цифры: str) -> bool:
    if len(цифры) != 11:
        return False
    сумма = sum(int(цифры[i]) * (9 - i) for i in range(9))
    if сумма > 101:
        сумма %= 101
    контроль = 0 if сумма in (100, 101) else сумма
    return контроль == int(цифры[9:])


def iban(текст: str) -> bool:
    s = re.sub(r"\s", "", текст).upper()
    if not re.fullmatch(r"[A-Z]{2}\d{2}[A-Z0-9]{11,30}", s):
        return False
    переставлено = s[4:] + s[:4]
    число = "".join(str(int(c, 36)) for c in переставлено)
    return int(число) % 97 == 1


# --- шаблоны ---------------------------------------------------------------

# Граница числа: не цифра и не часть длинного числа рядом. \b тут не
# годится: для него «+» и «-» уже граница, и из «12345678901» вырезалось
# бы что угодно.
_Н = r"(?<![\d])"
_К = r"(?![\d])"

ШАБЛОНЫ = {
    "email": re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+", re.UNICODE),
    "card": re.compile(_Н + r"\d(?:[ -]?\d){12,18}" + _К),
    "iban": re.compile(r"\b[A-Za-z]{2}\d{2}(?:[ ]?[A-Za-z0-9]){11,30}\b"),
    "snils": re.compile(_Н + r"\d{3}[- ]?\d{3}[- ]?\d{3}[- ]?\d{2}" + _К),
    "inn": re.compile(_Н + r"(?:\d{12}|\d{10})" + _К),
    "passport": re.compile(
        r"(?i)паспорт\w*[^\d\n]{0,40}?(" + _Н + r"\d{2}[ ]?\d{2}[ №]{0,3}\d{6}" + _К + r")"
    ),
    "phone": re.compile(
        _Н + r"(?:\+7|8|\+\d{1,3})[\s(-]{0,2}\d{3}[\s)-]{0,2}\d{3}[\s-]?\d{2}[\s-]?\d{2}" + _К
    ),
}

# --- люди и адреса ------------------------------------------------------------

_З = r"[А-ЯЁ][а-яё]+"  # слово с заглавной
_ИМЯ_ИЛИ_ФАМИЛИЯ = r"[А-ЯЁ][а-яё]{1,20}(?:-[А-ЯЁ][а-яё]+)?"
# Отчество во всех падежах: Николаевич, Николаевичу, Петровна, Ильинична,
# Ильич, Кузьмича. Только с заглавной: «условна», «типична» — не люди.
_ОТЧЕСТВО = (r"[А-ЯЁ][а-яё]+(?:ович|евич|ич)(?:а|у|ем|е)?\b"
             r"|[А-ЯЁ][а-яё]+(?:овн|евн|ичн|иничн)(?:а|ы|е|у|ой)\b")
# Фамилия по окончанию, во всех падежах.
_ФАМИЛИЯ = (r"[А-ЯЁ][а-яё]+(?:ов|ев|ёв|ин|ын|ск|цк|ых|их)"
            r"(?:а|у|ым|ом|е|ой|ы|ий|ая|ого|ому|им|ую|ей)?\b")

# Частые имена, основой. Нарочно без тех, что совпадают с обычными
# словами: Вера, Надежда, Любовь, Роза, Лев, Слава, Мира, Лилия.
_ИМЕНА = (
    "александр алексе анатоли андре антон аркади арсени артём артем богдан борис вадим "
    "валентин валери василий васили виктор виталий витали влад владимир владислав "
    "всеволод вячеслав геннади георги герман глеб григори давид даниил данил денис "
    "дмитри евгени егор захар иван игор илья ильи иннокенти кирилл константин леонид "
    "максим марк матвей матве михаил никита никола олег павел павл пётр петр роман руслан "
    "семён семен сергей серге станислав степан тимофе тимур фёдор федор филипп эдуард юри "
    "ярослав "
    "александр алин алл анастаси ангелин анн антонин валентин валери варвар вероник "
    "виктори галин дарь диан евгени екатерин елен елизавет жанн зинаид зо инн ирин "
    "карин кир клавди ксени лариса ларис лидия лиди людмил маргарит марин мари "
    "милан наталь натали нин оксан ольг полин раис светлан снежан софи софь тамар "
    "татьян ульян эльвир юли юлиан яна ян"
).split()
_ИМЯ_СПИСОК = r"(?:" + "|".join(sorted(set(_ИМЕНА), key=len, reverse=True)) + r")[а-яё]{0,4}"

ЛЮДИ = [
    # [Фамилия] Имя Отчество [Фамилия]
    re.compile(r"(?:" + _ИМЯ_ИЛИ_ФАМИЛИЯ + r"\s+)?" + _ИМЯ_ИЛИ_ФАМИЛИЯ + r"\s+(?:" + _ОТЧЕСТВО + r")"
               r"(?:\s+" + _ФАМИЛИЯ + r")?"),
    # Имя Фамилия и Фамилия Имя
    re.compile(r"\b(?i:" + _ИМЯ_СПИСОК + r")(?<=[А-ЯЁа-яё])\s+" + _ФАМИЛИЯ),
    re.compile(_ФАМИЛИЯ + r"\s+(?i:" + _ИМЯ_СПИСОК + r")\b"),
]

_НОМЕР = r"\d{1,4}\s?[а-яА-Я]?(?:/\d{1,3})?"
_ДОМ = r"(?:дом|д\.)\s*" + _НОМЕР
_КОРПУС = r"(?:корпус|корп\.|к\.|строение|стр\.)\s*" + _НОМЕР
_КВАРТИРА = r"(?:квартира|кв\.|офис|оф\.)\s*\d{1,4}"
_УЛИЦА = (r"(?:улиц[аеуы]|ул\.|проспект[ае]?|пр-т|переул(?:ок|ке)|пер\.|бульвар[ае]?|б-р|"
          r"шоссе|набережн(?:ая|ой)|наб\.|площад(?:ь|и)|пл\.|проезд[ае]?|микрорайон[ае]?|мкр\.?)")
_НАЗВАНИЕ = r"(?:[А-ЯЁ0-9][А-ЯЁа-яё0-9-]*)(?:\s+[А-ЯЁ][А-ЯЁа-яё-]*){0,2}"
_Р = r"[,\s]+"

АДРЕСА = [
    # Улица с номером дома: «улица Ленина, 5», «ул. Ленина, д. 5, кв. 3»,
    # «Ленинский проспект 12».
    re.compile(r"(?i:" + _УЛИЦА + r")\s+" + _НАЗВАНИЕ + _Р + r"(?:" + _ДОМ + r"|\d{1,4}[а-я]?\b)"
               r"(?:" + _Р + _КОРПУС + r")*(?:" + _Р + _КВАРТИРА + r")?"),
    re.compile(_НАЗВАНИЕ + r"\s+(?i:" + _УЛИЦА + r")" + _Р + r"(?:" + _ДОМ + r"|\d{1,4}[а-я]?\b)"
               r"(?:" + _Р + _КОРПУС + r")*(?:" + _Р + _КВАРТИРА + r")?"),
    # Дом с корпусом или квартирой, с названием улицы перед ним или без:
    # «Колпакова, дом 40, корпус 3, квартира 46», «д. 5, кв. 12».
    # Одинокий «дом 2» не трогаем: это и телепередача, и номер в списке.
    re.compile(r"(?:" + _З + r"(?:\s+" + _З + r")?" + _Р + r")?(?i:" + _ДОМ +
               r"(?:(?:" + _Р + _КОРПУС + r")+(?:" + _Р + _КВАРТИРА + r")?|" + _Р + _КВАРТИРА + r"))"),
]

ПРОВЕРКИ = {
    "card": lambda т: 13 <= len(_цифры(т)) <= 19 and луна(_цифры(т)),
    "iban": iban,
    "snils": lambda т: снилс(_цифры(т)),
    "inn": lambda т: инн(_цифры(т)),
}


def find(текст: str) -> list[Находка]:
    """Все находки по порядку в тексте, без пересечений."""
    if not текст:
        return []
    кандидаты: list[tuple[int, Находка]] = []
    for место, вид in enumerate(ВИДЫ):
        шаблоны = ЛЮДИ if вид == "person" else АДРЕСА if вид == "address" else [ШАБЛОНЫ[вид]]
        for m in (m for ш in шаблоны for m in ш.finditer(текст)):
            группа = 1 if m.re.groups else 0
            начало, конец = m.span(группа)
            кусок = текст[начало:конец]
            проверка = ПРОВЕРКИ.get(вид)
            if проверка is not None and not проверка(кусок):
                continue
            кандидаты.append((место, Находка(вид, начало, конец, кусок)))
    # Сначала надёжные виды, потом остальные, и только если не
    # пересекаются с уже принятыми.
    принято: list[Находка] = []
    for _, н in sorted(кандидаты, key=lambda x: (x[0], x[1].start)):
        if any(н.start < п.end and п.start < н.end for п in принято):
            continue
        принято.append(н)
    return sorted(принято, key=lambda н: н.start)


def mask(текст: str) -> str:
    """Тот же текст, где личные данные заменены пометками."""
    части: list[str] = []
    прошлый = 0
    for н in find(текст):
        части.append(текст[прошлый:н.start])
        части.append(ПОМЕТКИ[н.kind])
        прошлый = н.end
    части.append(текст[прошлый:])
    return "".join(части)
