"""Отправить заметки в Telegram: открыть Telegram с готовым текстом.

Ни бота, ни нашего сервера: программа только открывает ссылку tg://,
Telegram на этом компьютере показывает выбор чата, и человек сам решает,
кому отправить. Обещание «ничего не уходит с компьютера» не страдает:
текст уходит туда, куда человек сам его отправил, его же руками.

Telegram Desktop понимает tg://msg_url?url=…&text=…, а без url отказывает
(так он не даёт подсунуть запрос встроенному боту). Поэтому первая строка
заметок — обычно заголовок — идёт в url, остальное в text: в окне
отправки они снова складываются в одно сообщение через перевод строки.
"""
from __future__ import annotations

import logging
import os
import sys
import webbrowser
from dataclasses import dataclass
from urllib.parse import quote

log = logging.getLogger(__name__)

# Сообщение в Telegram — до 4096 знаков. Берём с запасом: перевод строки
# между первой строкой и остальным тоже знак, а эмодзи считаются двумя.
ПРЕДЕЛ = 3800


@dataclass(frozen=True)
class Ссылка:
    адрес: str
    целиком: bool  # весь ли текст поместился в сообщение


def ссылка(текст: str) -> Ссылка | None:
    """Собрать tg://msg_url для текста. Пустой текст — None."""
    текст = (текст or "").strip()
    if not текст:
        return None
    целиком = len(текст) <= ПРЕДЕЛ
    if not целиком:
        # Режем по последнему переводу строки до предела: оборванная
        # посередине фраза выглядит как ошибка, а не как сокращение.
        срез = текст[:ПРЕДЕЛ]
        граница = срез.rfind("\n")
        текст = (срез[:граница] if граница > ПРЕДЕЛ // 2 else срез).rstrip() + "\n…"
    первая, _, остальное = текст.partition("\n")
    первая = первая.strip() or "Конспект"
    # «@» в начале url Telegram принял бы за запрос к встроенному боту.
    if первая.startswith("@"):
        первая = "⁠" + первая
    адрес = f"tg://msg_url?url={quote(первая, safe='')}"
    if остальное.strip():
        адрес += f"&text={quote(остальное.strip(), safe='')}"
    return Ссылка(адрес=адрес, целиком=целиком)


def открыть(текст: str) -> dict:
    """Открыть Telegram с текстом. Ответ для окна: ok, целиком, нет_телеграма."""
    с = ссылка(текст)
    if с is None:
        return {"ok": False, "error": "empty"}
    try:
        if sys.platform == "win32":
            # Через реестр Windows, той программе, что записала себя на tg://.
            # Не запускаем ничего сами: ни командной строки, ни интерпретатора.
            os.startfile(с.адрес)  # noqa: S606
        elif not webbrowser.open(с.адрес):
            return {"ok": False, "error": "no_telegram"}
    except OSError:
        # Ссылки tg:// никто не обрабатывает: Telegram на компьютере нет.
        log.info("Telegram на компьютере не найден")
        return {"ok": False, "error": "no_telegram"}
    return {"ok": True, "целиком": с.целиком}
