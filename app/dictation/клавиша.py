"""Горячая клавиша диктовки: зажал, наговорил, отпустил.

Почему отдельно от `HotkeyManager` окна. Тому нужен один щелчок по
факту нажатия, а здесь важны оба края: по нажатию начинаем писать, по
отпусканию заканчиваем. Это не настройка того же механизма, а другое
поведение, и склеивать их в один класс значило бы получить в нём
развилку на каждом шагу.

Два режима, потому что удобство у людей разное:

- **Зажатие.** Держишь клавишу, пока говоришь. Не нужно помнить, что
  запись идёт, и невозможно забыть её выключить. Плохо для длинного
  текста: держать клавишу минуту неудобно.
- **Переключатель.** Нажал — пошло, нажал ещё раз — закончилось. Руки
  свободны, но забыть про включённую запись легко, поэтому индикатор
  обязателен.

Отдельная ловушка Windows: при зажатом Ctrl буква приходит не буквой, а
управляющим символом (Ctrl+D это `\\x04`). Штатный матчер pynput этого
не знает и хоткей молча не срабатывает. Разворачиваем обратно.

Второй камень — автоповтор: пока клавиша зажата, система шлёт нажатие
десятки раз в секунду. Без защиты диктовка начиналась бы заново на
каждом повторе.
"""

from __future__ import annotations

import logging
from typing import Callable

log = logging.getLogger(__name__)

ЗАЖАТИЕ = "hold"
ПЕРЕКЛЮЧАТЕЛЬ = "toggle"


def разобрать(сочетание: str) -> tuple[set[str], str]:
    """`<ctrl>+<shift>+d` → ({ctrl, shift}, d)."""
    модификаторы: set[str] = set()
    клавиша = ""
    for часть in сочетание.lower().split("+"):
        часть = часть.strip()
        if часть.startswith("<") and часть.endswith(">"):
            модификаторы.add(часть[1:-1])
        elif часть:
            клавиша = часть
    return модификаторы, клавиша


class КлавишаДиктовки:
    """Слушает сочетание и зовёт начало и конец диктовки."""

    def __init__(
        self,
        сочетание: str = "<ctrl>+<shift>+d",
        режим: str = ЗАЖАТИЕ,
        на_старт: Callable[[], bool] | None = None,
        на_стоп: Callable[[], None] | None = None,
    ) -> None:
        self.сочетание = сочетание
        self.режим = режим
        self._модификаторы, self._клавиша = разобрать(сочетание)
        self._на_старт = на_старт
        self._на_стоп = на_стоп
        self._слушатель = None
        self._зажаты: set[str] = set()
        self._сработала = False
        self._диктует = False

    # --- разбор клавиш ----------------------------------------------------

    @staticmethod
    def _имя_модификатора(клавиша) -> str | None:
        имя = getattr(клавиша, "name", "") or ""
        for модификатор in ("ctrl", "shift", "alt", "cmd"):
            if имя.startswith(модификатор):
                return модификатор
        return None

    @staticmethod
    def _буква(клавиша) -> str | None:
        """Буква клавиши, развёрнутая из управляющего символа."""
        символ = getattr(клавиша, "char", None)
        if not символ:
            # Клавиши без буквы: пробел, F-ряд и прочие.
            имя = getattr(клавиша, "name", "") or ""
            return имя.lower() or None
        if len(символ) == 1 and ord(символ) < 32:
            # Ctrl+D приходит как \x04: 0x04 + 96 == ord('d').
            return chr(ord(символ) + 96)
        return символ.lower()

    # --- события ----------------------------------------------------------

    def нажатие(self, клавиша) -> None:
        модификатор = self._имя_модификатора(клавиша)
        if модификатор:
            self._зажаты.add(модификатор)
            return

        if self._буква(клавиша) != self._клавиша:
            return
        if not self._модификаторы.issubset(self._зажаты):
            return
        # Автоповтор шлёт нажатие десятки раз в секунду, пока клавишу
        # держат. Без этой защиты диктовка начиналась бы заново на
        # каждом повторе.
        if self._сработала:
            return
        self._сработала = True

        if self.режим == ПЕРЕКЛЮЧАТЕЛЬ:
            if self._диктует:
                self._диктует = False
                self._стоп()
            else:
                self._диктует = bool(self._старт())
            return

        self._диктует = bool(self._старт())

    def отпускание(self, клавиша) -> None:
        модификатор = self._имя_модификатора(клавиша)
        if модификатор:
            self._зажаты.discard(модификатор)
            # Модификатор отпустили раньше буквы. В режиме зажатия это
            # значит, что человек закончил: держать Ctrl он больше не
            # обязан, а вот запись висеть не должна.
            if self.режим == ЗАЖАТИЕ and self._диктует:
                self._диктует = False
                self._сработала = False
                self._стоп()
            return

        if self._буква(клавиша) != self._клавиша:
            return
        self._сработала = False
        if self.режим == ЗАЖАТИЕ and self._диктует:
            self._диктует = False
            self._стоп()

    def _старт(self) -> bool:
        if self._на_старт is None:
            return False
        try:
            return bool(self._на_старт())
        except Exception:
            log.exception("Диктовка не запустилась")
            return False

    def _стоп(self) -> None:
        if self._на_стоп is None:
            return
        try:
            self._на_стоп()
        except Exception:
            log.exception("Диктовка не завершилась чисто")

    # --- жизненный цикл ---------------------------------------------------

    def старт(self) -> bool:
        """Начать слушать. False — не удалось, но это не повод падать."""
        try:
            from pynput import keyboard
        except Exception:
            log.warning("pynput недоступен, клавиша диктовки отключена")
            return False
        try:
            self._слушатель = keyboard.Listener(
                on_press=self.нажатие, on_release=self.отпускание
            )
            self._слушатель.daemon = True
            self._слушатель.start()
            log.info("Клавиша диктовки %s активна (%s)", self.сочетание, self.режим)
            return True
        except Exception:
            log.warning(
                "Не удалось перехватить %s", self.сочетание, exc_info=True
            )
            return False

    def стоп(self) -> None:
        if self._слушатель is not None:
            try:
                self._слушатель.stop()
            except Exception:
                log.debug("Слушатель клавиши диктовки уже остановлен", exc_info=True)
            self._слушатель = None
