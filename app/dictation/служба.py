"""Служба диктовки: связывает клавишу, микрофон, модель и чужое окно.

Порядок такой. Человек зажал клавишу — пишем микрофон в память. Отпустил
— обрезаем тишину по краям, отдаём звук распознаванию и печатаем текст
туда, где стоит курсор.

Главное требование здесь не точность, а задержка: человек стоит и ждёт
свой текст, глядя в пустое поле. Поэтому модель держим прогретой, а не
поднимаем на первом же слове — первая загрузка занимает пару секунд, и
получить их в подарок к первой диктовке было бы обидно.

Осознанный отказ: пока идёт встреча, диктовка не работает. Модель одна,
и распознавать ей два потока разом значит испортить оба: встреча
получит дыры в расшифровке, диктовка — задержку в секунды. Честно
сказать «не сейчас» лучше, чем молча сделать плохо и то и другое.
"""

from __future__ import annotations

import logging
import threading
import time

import numpy as np

from ..audio.buffers import SAMPLE_RATE
from ..core.events import bus
from . import вставка
from .запись import ЗахватГолоса, обрезать_тишину

log = logging.getLogger(__name__)

# События для окна. Индикатор диктовки живёт в том же окне, что и всё
# остальное, поэтому ходят они по общей шине.
ДИКТОВКА_НАЧАЛАСЬ = "dictation:started"
ДИКТОВКА_СЛЫШНО = "dictation:level"
ДИКТОВКА_ДУМАЕТ = "dictation:thinking"
ДИКТОВКА_ГОТОВА = "dictation:done"
ДИКТОВКА_БЕДА = "dictation:failed"

# Короче этого распознавать нечего: человек задел клавишу, а не диктовал.
МИНИМУМ_СЕКУНД = 0.3


class СлужбаДиктовки:
    """Один голосовой ввод от начала до вставки текста."""

    def __init__(self, service) -> None:
        # `service` — это AppService. Берём у него готовое распознавание и
        # настройки, а не заводим своё: вторая копия модели в памяти
        # стоила бы ещё 200 МБ ради того же самого.
        self._service = service
        self._захват: ЗахватГолоса | None = None
        self._замок = threading.Lock()
        self._идёт = False

    @property
    def идёт(self) -> bool:
        return self._идёт

    # --- запуск и остановка ----------------------------------------------

    def начать(self) -> bool:
        """Начать слушать. False — если сейчас нельзя, причина в событии."""
        with self._замок:
            if self._идёт:
                return True
            беда = self._почему_нельзя()
            if беда:
                log.info("Диктовка невозможна: %s", беда)
                bus.emit(ДИКТОВКА_БЕДА, {"причина": беда})
                return False

            устройство = self._service.settings.audio.mic_device_id
            self._захват = ЗахватГолоса(устройство)
            if not self._захват.старт():
                причина = self._захват.ошибка or "микрофон не отвечает"
                self._захват = None
                bus.emit(ДИКТОВКА_БЕДА, {"причина": причина})
                return False
            self._идёт = True

        bus.emit(ДИКТОВКА_НАЧАЛАСЬ, {})
        return True

    def закончить(self) -> str:
        """Остановить запись, распознать и вставить. Возвращает текст."""
        with self._замок:
            if not self._идёт or self._захват is None:
                return ""
            захват, self._захват = self._захват, None
            self._идёт = False

        звук = захват.стоп()
        bus.emit(ДИКТОВКА_ДУМАЕТ, {})

        речь = обрезать_тишину(звук)
        if речь.size < МИНИМУМ_СЕКУНД * SAMPLE_RATE:
            # Клавишу задели случайно. Молчим: вставлять нечего, а
            # ругаться на человека за случайное нажатие незачем.
            bus.emit(ДИКТОВКА_ГОТОВА, {"текст": "", "пусто": True})
            return ""

        начало = time.monotonic()
        текст = self._распознать(речь)
        ушло = time.monotonic() - начало
        log.info(
            "Диктовка: %.1f с речи распознаны за %.1f с, %d знаков",
            речь.size / SAMPLE_RATE, ушло, len(текст),
        )

        if not текст:
            bus.emit(ДИКТОВКА_ГОТОВА, {"текст": "", "пусто": True})
            return ""

        try:
            получилось = вставка.вставить(
                текст, self._способ_вставки()
            )
        except вставка.НедоступноОкно as e:
            # Окно администратора. Текст не потерян: он уходит в буфер,
            # чтобы человек вставил его руками, а не диктовал заново.
            вставка._записать_буфер(текст)
            bus.emit(ДИКТОВКА_БЕДА, {
                "причина": f"{e}. Текст положили в буфер обмена",
                "текст": текст,
            })
            return текст

        if not получилось:
            вставка._записать_буфер(текст)
            bus.emit(ДИКТОВКА_БЕДА, {
                "причина": "не удалось вставить текст, он в буфере обмена",
                "текст": текст,
            })
            return текст

        bus.emit(ДИКТОВКА_ГОТОВА, {"текст": текст})
        return текст

    def отменить(self) -> None:
        """Бросить запись, ничего не распознавая и не вставляя."""
        with self._замок:
            захват, self._захват = self._захват, None
            self._идёт = False
        if захват is not None:
            захват.стоп()
            bus.emit(ДИКТОВКА_ГОТОВА, {"текст": "", "отменено": True})

    @property
    def уровень(self) -> float:
        захват = self._захват
        return захват.уровень if захват else 0.0

    # --- внутреннее -------------------------------------------------------

    def _почему_нельзя(self) -> str:
        """Пустая строка значит «можно»."""
        if not вставка.ДОСТУПНО:
            return "диктовка работает только под Windows"
        if getattr(self._service, "is_recording", False):
            return "идёт запись встречи, модель занята"
        распознавание = self._получить_распознавание()
        if распознавание is None:
            return "распознавание выключено в настройках"
        if hasattr(распознавание, "is_downloaded") and not распознавание.is_downloaded():
            return "модель распознавания ещё не скачана"
        return ""

    def _получить_распознавание(self):
        return getattr(self._service, "transcriber", None)

    def _способ_вставки(self) -> bool | None:
        """Чем вставлять: True — буфером, False — по буквам.

        При «сам реши» берём буфер, а не общее правило «короткое
        печатаем». Диктуют всегда фразой, а не парой букв, и на фразе
        печать по буквам проигрывает дважды: она занимает секунду вместо
        мгновения и оказалась ненадёжной — в замере на настоящем
        Блокноте буфер доехал 6 раз из 6, а печать 4 из 6. Пропавший
        текст человек заметит гораздо болезненнее, чем то, что буфер
        обмена на десятую долю секунды побыл чужим и вернулся назад.

        Кому дорог буфер (менеджеры буфера, работа с паролями), в
        настройках есть «печатать по буквам».
        """
        режим = getattr(self._service.settings, "dictation", None)
        способ = getattr(режим, "paste_method", "auto") if режим else "auto"
        if способ == "type":
            return False
        return True

    def _распознать(self, pcm: np.ndarray) -> str:
        распознавание = self._получить_распознавание()
        if распознавание is None:
            return ""
        try:
            сегменты = распознавание.transcribe(
                pcm, SAMPLE_RATE, meeting_id="", offset=0.0, speaker="me"
            )
        except Exception:
            log.exception("Диктовка: распознавание не удалось")
            return ""
        куски = [(с.text or "").strip() for с in сегменты]
        return " ".join(к for к in куски if к).strip()

    def прогреть(self) -> None:
        """Поднять модель заранее, в фоне.

        Первая загрузка занимает пару секунд. Без прогрева человек
        получит их в подарок к первой же диктовке и решит, что она
        медленная.
        """
        def работа() -> None:
            распознавание = self._получить_распознавание()
            if распознавание is None or not hasattr(распознавание, "load"):
                return
            try:
                распознавание.load()
            except Exception:
                log.debug("Диктовка: прогреть модель не вышло", exc_info=True)

        threading.Thread(target=работа, name="диктовка-прогрев", daemon=True).start()
