# -*- coding: utf-8 -*-
"""Сторож: замечает разговор на компьютере, когда запись не идёт.

Зачем. Konspekt висит в трее, человек открывает Zoom или включает
подкаст — и программа об этом молчит, потому что слушает звук только
во время записи. А самая обидная потеря встречи именно такая: забыл
нажать «запись», поговорил сорок минут, вспомнил в конце. Пусть
программа сама заметит разговор и предложит записать.

Почему это не наглость. Сторож ничего не записывает: ни файла, ни
расшифровки, ни единого байта на диск. Он только слушает, и всё
решение сводится к одному вопросу человеку. Запись начнётся, лишь
если он сам нажмёт «Записать». Выключается в настройках целиком.

Чем отличается от слушателя внутри записи. Там вопрос дешёвый: встреча
уже пишется, и речь идёт лишь о второй дорожке. Здесь вопрос дороже —
это уведомление посреди чужой работы, — поэтому и порог выше:
разговор должен идти не двенадцать секунд, а полминуты. Короткий
«бздыньк» уведомления, звук нажатия и трейлер на YouTube до этого
порога не доживают.

Почему не следим за окнами Zoom. Список процессов пришлось бы обновлять
вечно, а звук — это то же самое, но честнее: если в системе кто-то
говорит, это слышно, чем бы оно ни было запущено.
"""

from __future__ import annotations

import logging
import threading
from typing import Any, Callable

import numpy as np

from ..core.events import SYSTEM_SPEECH_NOTICED, bus
from . import devices
from .buffers import SAMPLE_RATE, rms_level
from .чужая_речь import ОКНО, Слушатель

log = logging.getLogger(__name__)

BLOCK_FRAMES = 1600  # 0.1 с при 16 кГц, как у записи

# Сколько разговора должно набраться, прежде чем мы подадим голос.
# Тридцать секунд — это уже точно не «бздыньк» уведомления и не
# заставка ролика: столько длится только настоящий разговор.
# Пять окон по шесть секунд.
ПОДТВЕРЖДЕНИЙ = 5

# Сколько ждать после ответа человека, прежде чем спрашивать снова.
# Здесь дольше, чем внутри записи: там человек уже в программе и ждёт
# от неё внимания, а тут мы лезем в чужую работу. Отказался — значит
# следующий разговор должен быть заметно другим, а не тем же самым
# после короткой паузы.
ТИШИНЫ_ДЛЯ_ПОВТОРА = 120.0

# Между попытками открыть устройство. Звуковую карту могли выдернуть,
# занять монопольно или переключить: дёргать её без остановки значит
# греть процессор впустую.
ПАУЗА_ПОСЛЕ_ОШИБКИ = 30.0


class Сторож:
    """Слушает системный звук, пока запись не идёт, и зовёт человека.

    Живёт в своём потоке. Останавливается на время записи: там за
    системным звуком следит сама дорожка, и два открытых устройства
    только мешали бы друг другу.
    """

    def __init__(
        self,
        loopback_device_id: str | None = None,
        включён: bool = True,
        подтверждений: int = ПОДТВЕРЖДЕНИЙ,
    ) -> None:
        self.loopback_device_id = loopback_device_id
        self._включён = включён
        self._слушатель = Слушатель(
            подтверждений=подтверждений,
            тишины_для_повтора=ТИШИНЫ_ДЛЯ_ПОВТОРА,
        )
        self._поток: threading.Thread | None = None
        self._стоп = threading.Event()
        self._уровень = 0.0
        self._ошибка: str | None = None

    # --- управление -------------------------------------------------

    @property
    def работает(self) -> bool:
        return self._поток is not None and self._поток.is_alive()

    @property
    def ошибка(self) -> str | None:
        """Почему сторож молчит, если он включён, но не слышит."""
        return self._ошибка

    def запустить(self) -> None:
        """Начать слушать. Повторный вызов ничего не делает.

        Память об ответе человека при этом сохраняется. Сторож
        останавливается на каждую запись и поднимается после неё, и
        полный сброс здесь означал бы, что после любой встречи программа
        снова спросит про тот же самый подкаст, который всё это время
        играл.
        """
        if not self._включён or self.работает:
            return
        self._стоп.clear()
        # Хвост звука выбрасываем: между остановкой и запуском прошло
        # время, и склеивать куски из разных моментов в одно окно нельзя.
        self._слушатель.забыть_буфер()
        self._поток = threading.Thread(
            target=self._крутить, name="сторож-звука", daemon=True
        )
        self._поток.start()

    def остановить(self) -> None:
        """Отпустить устройство: запись начинается или программа закрывается."""
        self._стоп.set()
        поток = self._поток
        self._поток = None
        if поток is not None:
            поток.join(timeout=3.0)

    def настроить(self, включён: bool, loopback_device_id: str | None = None) -> None:
        """Человек поменял настройки: применяем сразу, не дожидаясь перезапуска."""
        self.loopback_device_id = loopback_device_id
        было = self._включён
        self._включён = включён
        if not включён:
            self.остановить()
        elif not было:
            self.запустить()

    def замолчать(self) -> None:
        """Человек ответил на вопрос: молчим, пока звук не сменится тишиной."""
        self._слушатель.замолчать()

    # --- работа -----------------------------------------------------

    def _крутить(self) -> None:
        """Открыть устройство и слушать до остановки.

        Устройство переоткрываем при обрыве: наушники выдёргивают,
        карту занимает другая программа, и молча замолчать навсегда
        здесь нельзя — человек включил слежку и вправе на неё
        рассчитывать.
        """
        devices.hold_com()
        while not self._стоп.is_set():
            try:
                self._слушать_заход()
            except Exception as exc:
                self._ошибка = str(exc)
                log.debug("Сторож: устройство недоступно (%s)", exc, exc_info=True)
                # Ждём с проверкой стопа, чтобы выход из программы не
                # висел полминуты.
                if self._стоп.wait(ПАУЗА_ПОСЛЕ_ОШИБКИ):
                    return

    def _слушать_заход(self) -> None:
        """Один заход с открытым устройством."""
        устройство = devices.open_loopback(self.loopback_device_id)
        with устройство.recorder(
            samplerate=SAMPLE_RATE, channels=1, blocksize=BLOCK_FRAMES
        ) as запись:
            self._ошибка = None
            log.debug("Сторож слушает «%s»", getattr(устройство, "name", "?"))
            while not self._стоп.is_set():
                данные = запись.record(numframes=BLOCK_FRAMES)
                if данные is None or len(данные) == 0:
                    continue
                моно = данные.reshape(-1) if данные.ndim == 1 else данные.mean(axis=1)
                self._уровень = rms_level(моно)
                self._разобрать(моно)

    def _разобрать(self, блок: np.ndarray) -> None:
        """Скормить кусок слушателю и позвать человека, если пора."""
        try:
            пора = self._слушатель.добавить(блок)
        except Exception:
            # Сторож — удобство, а не работа программы: его поломка не
            # имеет права мешать ничему остальному.
            log.exception("Сторож: сбой разбора звука")
            return

        оценка = self._слушатель.последняя
        if оценка is not None and оценка.доля_звука > 0:
            log.debug(
                "Сторож, окно: речь=%s доля=%.3f переключений=%.1f "
                "изрезанность=%.2f тембр=%.2f всплеск=%.2f",
                оценка.есть_речь, оценка.доля_звука, оценка.переключений,
                оценка.изрезанность, оценка.тембр, оценка.всплеск,
            )
        if not пора:
            return

        log.info(
            "На компьютере идёт разговор, а запись не включена "
            "(доля %.2f, переключений %.1f): предлагаем записать",
            оценка.доля_звука, оценка.переключений,
        )
        bus.emit(
            SYSTEM_SPEECH_NOTICED,
            {
                "признаки": оценка.to_dict(),
                "секунд": round(self._слушатель.подтверждений * ОКНО),
            },
        )
