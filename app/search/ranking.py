"""Как сложить поиск по словам и по смыслу в один список встреч.

Раньше поиск по словам требовал, чтобы в реплике были все слова запроса,
включая «за», «что» и «там». Человек пишет, как думает: «выручка за
август что там по продажам», а такой реплики нет, хотя разговор про
выручку и продажи был. Выдача пустая, и смысл, который эту встречу
нашёл, терялся вместе с ней.

Теперь так.

1. Из запроса выбрасываются служебные слова, остальные обрезаются до
   основы: «продажам» ищется как «продаж», и находятся «продажи»,
   «продажники», «продаж».
2. Встреча находится, если в ней есть хотя бы одна основа. Чем больше
   основ в одной реплике, тем выше встреча: реплика со всеми словами
   запроса по-прежнему идёт первой.
3. Смысл добавляет прибавку встречам, которые про то же самое, и
   приводит встречи, где слова другие вовсе. Такие помечены «по смыслу».
4. Список упорядочен по этому счёту, а не по дате.
"""

from __future__ import annotations

import re
from typing import Any

# Служебные слова: по ним искать бессмысленно, они есть в каждой
# встрече. Вопросительные слова тоже здесь: «когда релиз» ищет релиз, а
# не каждое «когда» в архиве.
СЛУЖЕБНЫЕ = frozenset("""
а без бы был была были было быть в вам вас весь во вот все всё всех вы где
да для до его её ей ему если есть ещё же за зачем и из или им их к как
какая какие какой когда кого ко кто ли либо мне мы на над нам нас не него
нет ни них но ну о об обо он она они оно от по под при про с со сколько
так там те тебе ты тут у уже чем что чтобы эта эти это этот я почему
которая которые который вообще просто можно нужно надо очень тоже
""".split())

# Основа: у длинных слов срезаем окончание. Русское окончание обычно в
# одну-две буквы, и «выручка», «выручки», «выручке» сходятся в «выруч».
# Короткие слова не трогаем: «сеть» без двух букв стала бы «се» и
# находила бы всё подряд.
ДЛИННОЕ = 6
СРЕЗ = 2
НАИБОЛЬШЕ_ОСНОВ = 8

# Прибавка за смысл. Выделение из архива ниже двух — это толпа, там
# прибавки нет. Выше — по четверти за каждую единицу: встреча, которая
# выделяется на 4, получает полбалла, как за половину слов запроса.
СМЫСЛ_ОТ = 2.0
ВЕС_СМЫСЛА = 0.25

# Сколько встреч показывать. По одному общему слову находится
# полархива, и хвост из тридцатой встречи уже никто не читает.
НАИБОЛЬШЕ_ВСТРЕЧ = 30
# Из них найденных только по смыслу: без единого общего слова ошибиться
# легче, и таких должно быть немного.
НАИБОЛЬШЕ_ПО_СМЫСЛУ = 8


def _ровно(текст: str) -> str:
    """Нижний регистр и ё как е, й как и.

    Так же сравнивает указатель SQLite (remove_diacritics 2): без этого
    «ещё» в запросе нашлось бы в базе, а здесь не засчиталось бы.
    """
    return текст.lower().replace("ё", "е").replace("й", "и")


def основы(запрос: str) -> list[str]:
    """Основы значимых слов запроса, без повторов и в порядке слов."""
    слова = re.findall(r"\w+", _ровно(запрос or ""))
    значимые = [с for с in слова if с not in СЛУЖЕБНЫЕ and len(с) >= 3]
    if not значимые:
        # Запрос из одних служебных слов («что там») всё равно чего-то
        # ищет: лучше найти их, чем показать пустоту.
        значимые = [с for с in слова if len(с) >= 2]
    итог: list[str] = []
    for с in значимые:
        о = с[:-СРЕЗ] if len(с) >= ДЛИННОЕ else с
        if о not in итог:
            итог.append(о)
    return итог[:НАИБОЛЬШЕ_ОСНОВ]


def покрытие(текст: str, осн: list[str]) -> float:
    """Какая доля основ запроса есть в тексте, от 0 до 1."""
    if not осн:
        return 0.0
    слова = re.findall(r"\w+", _ровно(текст))
    нашлось = sum(1 for о in осн if any(с.startswith(о) for с in слова))
    return нашлось / len(осн)


def rank(
    осн: list[str],
    by_words: list[dict[str, Any]],
    by_meaning: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """Один список встреч, лучшие первыми.

    by_words — реплики, где есть хоть одна основа (из базы, с полем
    `rank` от SQLite: чем меньше, тем лучше). by_meaning — куски, близкие
    по смыслу, с `standout` (насколько выделяются из архива) и `strong`
    (прошли строгий отбор и могут привести встречу сами).
    """
    встречи: dict[str, dict[str, Any]] = {}

    def встреча(строка: dict[str, Any]) -> dict[str, Any]:
        return встречи.setdefault(строка["meeting_id"], {
            "meeting_id": строка["meeting_id"],
            "title": строка["title"],
            "created_at": строка["created_at"],
            "hits": 0,
            "cover": 0.0,
            "standout": 0.0,
            "strong": False,
            "_слова": [],
            "_смысл": [],
        })

    for строка in by_words:
        доля = покрытие(строка["text"], осн)
        в = встреча(строка)
        в["hits"] += 1
        в["cover"] = max(в["cover"], доля)
        в["_слова"].append((доля, строка))

    for кусок in by_meaning:
        в = встреча(кусок)
        в["standout"] = max(в["standout"], float(кусок.get("standout", 0.0)))
        в["strong"] = в["strong"] or bool(кусок.get("strong"))
        в["_смысл"].append(кусок)

    итог = []
    по_смыслу = 0
    for в in встречи.values():
        if в["cover"] <= 0 and not в["strong"]:
            # Ни одного слова запроса и нет сильного сходства по смыслу.
            # Так бывает с репликой, которую база нашла, а мы слов не
            # насчитали, и со слабым сходством без общих слов. И то, и
            # другое шум: слабый смысл только поднимает найденное словами.
            continue
        в["score"] = в["cover"] + ВЕС_СМЫСЛА * max(0.0, в["standout"] - СМЫСЛ_ОТ)
        в["by_meaning"] = в["cover"] <= 0
        if в["by_meaning"]:
            кусков = sorted(в["_смысл"], key=lambda к: -к.get("score", 0.0))
            в["hits"] = len(кусков)
            в["quotes"] = [
                {"text": к["text"], "start": к["start_s"], "who": к["who"]}
                for к in кусков[:3]
            ]
        else:
            # Лучшая цитата — та, где больше слов запроса; при равенстве
            # та, что SQLite считает точнее.
            реплики = sorted(в["_слова"], key=lambda д: (-д[0], д[1].get("rank", 0.0)))
            в["quotes"] = [
                {"text": с["text"], "start": с["start_s"], "who": с["who"]}
                for _, с in реплики[:3]
            ]
        в["terms"] = осн
        for служебное in ("_слова", "_смысл", "strong"):
            в.pop(служебное)
        итог.append(в)

    итог.sort(key=lambda в: (-в["score"], -в["hits"], -(в["created_at"] or 0)))
    отобрано = []
    for в in итог:
        if в["by_meaning"]:
            if по_смыслу >= НАИБОЛЬШЕ_ПО_СМЫСЛУ:
                continue
            по_смыслу += 1
        отобрано.append(в)
        if len(отобрано) >= НАИБОЛЬШЕ_ВСТРЕЧ:
            break
    return отобрано
