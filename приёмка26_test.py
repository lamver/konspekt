# -*- coding: utf-8 -*-
"""Приёмка задачи №26 на живом окне и живом мосте.

Прежние проверки гоняли настоящий app.js, но в выдуманном окне: узлы
самодельные, мост подменён. Так не видно главного — работает ли это
там, где работает человек. Здесь всё настоящее:

* настоящий webview с настоящим index.html, стилями и app.js;
* настоящий мост pywebview (js_api), с той же передачей данных
  Python → JS, что и в программе;
* настоящие щелчки по настоящим кнопкам, а не вызовы функций напрямую.

Отдельно проверяем то, чего выдуманное окно увидеть не могло:
кириллические ключи в ответах моста («текст», «причина», «секунд») и
доступность буфера обмена в WebView2.

Каждое требование задачи проверяется своим щелчком, и печатается, что
именно произошло.
"""
import testenv  # noqa: F401  песочница вместо боевого профиля

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

try:
    import webview
except Exception as e:  # noqa: BLE001
    print(f"[skip] webview недоступен: {e}")
    raise SystemExit(0)

КОРЕНЬ = Path(__file__).parent
СТРАНИЦА = КОРЕНЬ / "web" / "index.html"

ЗАМЕТКИ = "# Итоги встречи\n\nРешили про **сроки**.\n\n- Петя чинит вход\n- Маша пишет письмо"
ПРОДИКТОВАНО = "когда мы выкатываем оплату"


class НастоящийМост:
    """То, что окно видит как pywebview.api.

    Возвращаем ровно те же словари, что и настоящий сервис, включая
    кириллические ключи: если они не переживут передачу в JS, окно
    получит пустоту, а человек — молчащую кнопку.
    """

    def __init__(self):
        self.вызовы = []
        self.отказать = False

    def start_field_dictation(self):
        self.вызовы.append("start")
        if self.отказать:
            return {"ok": False, "причина": "идёт запись встречи, модель занята"}
        return {"ok": True}

    def finish_field_dictation(self):
        self.вызовы.append("finish")
        return {"ok": True, "текст": ПРОДИКТОВАНО}

    def cancel_field_dictation(self):
        self.вызовы.append("cancel")
        return {"ok": True}

    # Остальное окну тоже нужно при запуске.
    def meetings(self):
        return []

    def settings(self):
        return {}

    def dictation_settings(self):
        return {"enabled": True, "hotkey": "<alt>+q", "mode": "hold"}

    def get_i18n_dict(self, lang="ru"):
        """Словарь окну отдаёт мост, как и в настоящей программе.

        Без него окно показывает ключи вместо слов: «copy.done» вместо
        «Заметки скопированы». Именно так и вышло при первом прогоне
        этой приёмки, и выдуманное окно такого не показывало, потому
        что словарь ему клали прямо в память.
        """
        путь = КОРЕНЬ / "web" / "i18n" / f"{lang}.json"
        if not путь.exists():
            return {}
        return json.loads(путь.read_text(encoding="utf-8"))

    def get_language(self):
        return "ru"


мост = НастоящийМост()
итог = {"ошибка": None, "шаги": []}


def шаг(окно, имя, скрипт):
    """Сделать шаг в живом окне и записать, что получилось."""
    ответ = окно.evaluate_js(скрипт)
    итог["шаги"].append((имя, ответ))
    return ответ


def приёмка(окно):
    try:
        # Ждём, пока окно соберётся: app.js грузит словарь и связывает узлы.
        # Ждём именно ui, а не конкретную кнопку: если ждать кнопку,
        # то её пропажа выглядит как «окно не поднялось», и приёмка
        # молча пропускает настоящую поломку.
        for _ in range(60):
            if окно.evaluate_js("typeof ui !== 'undefined' && !!ui.chatText"):
                break
            time.sleep(0.2)
        else:
            итог["ошибка"] = "окно не собралось за 12 секунд"
            return

        # Кнопки, без которых задача не выполнена. Проверяем до всего
        # остального и отдельно от «окно не поднялось»: пропавшая кнопка
        # это поломка, а не повод молча пропустить приёмку. На этом
        # приёмка однажды и попалась — мутация «убрать кнопку из
        # разметки» уходила в пропуск вместо падения.
        нехватка = окно.evaluate_js("""
          JSON.stringify(['summary-copy','summary-copy-plain','chat-mic','chat-text']
            .filter((и) => !document.getElementById(и)));
        """)
        итог["нет_кнопок"] = json.loads(нехватка)
        if итог["нет_кнопок"]:
            return

        # Буфер обмена подменяем на видимый: читать системный буфер
        # человека мы не вправе, а проверить надо, что окно в него
        # что-то кладёт и не падает по дороге.
        окно.evaluate_js("""
          window.__вбуфере = [];
          window.__ошибкаБуфера = '';
          if (!navigator.clipboard) { window.__ошибкаБуфера = 'clipboard нет вовсе'; }
          Object.defineProperty(navigator, 'clipboard', {
            configurable: true,
            value: { writeText: async (t) => { window.__вбуфере.push(t); } },
          });
          window.__тосты = [];
          window.__showToast = showToast;
          showToast = (т, мс) => { window.__тосты.push(т); };
          true;
        """)

        # --- Требование: кнопка «копировать» у заметок ---------------------
        шаг(окно, "заметки нарисованы", f"""
          state.current = {{ id: 'x', summary: {json.dumps(ЗАМЕТКИ)} }};
          state.currentId = 'x';
          renderSummary(state.current.summary);
          !document.getElementById('summary-copy').hidden;
        """)
        шаг(окно, "щелчок по «копировать»", """
          window.__вбуфере = []; window.__тосты = [];
          document.getElementById('summary-copy').click();
          'нажато';
        """)
        time.sleep(0.5)
        шаг(окно, "что в буфере после «копировать»",
            "JSON.stringify({буфер: window.__вбуфере, тост: window.__тосты[0] || ''})")

        # --- Требование: копирование без разметки --------------------------
        шаг(окно, "щелчок по «без разметки»", """
          window.__вбуфере = []; window.__тосты = [];
          document.getElementById('summary-copy-plain').click();
          'нажато';
        """)
        time.sleep(0.5)
        шаг(окно, "что в буфере после «без разметки»",
            "JSON.stringify({буфер: window.__вбуфере, тост: window.__тосты[0] || ''})")

        # --- Требование: копирование реплики цитатой -----------------------
        шаг(окно, "реплика нарисована", """
          state.hasAudio = true;
          appendSegment({
            id: 's1', speaker: 'them', text: 'это надо переделать',
            start: 750, end: 754, voice_label: 'Маша', lang: 'ru',
          }, false);
          !!document.querySelector('.turn__copy');
        """)
        шаг(окно, "щелчок по копированию реплики", """
          window.__вбуфере = []; window.__тосты = [];
          document.querySelector('.turn__copy').click();
          'нажато';
        """)
        time.sleep(0.5)
        шаг(окно, "что в буфере после реплики",
            "JSON.stringify({буфер: window.__вбуфере, тост: window.__тосты[0] || ''})")

        # --- Требование: диктовка в поле вопроса ---------------------------
        #
        # Здесь главное: ответ моста едет из Python с кириллическими
        # ключами. Выдуманный мост этого не проверял.
        шаг(окно, "щелчок по микрофону (начать)", """
          window.__тосты = [];
          document.getElementById('chat-mic').click();
          'нажато';
        """)
        time.sleep(1.0)
        шаг(окно, "окно слушает",
            "JSON.stringify({слушает: state.dictating,"
            " видно: document.getElementById('chat-mic')"
            ".classList.contains('is-listening')})")

        шаг(окно, "щелчок по микрофону (закончить)", """
          document.getElementById('chat-mic').click();
          'нажато';
        """)
        time.sleep(1.5)
        шаг(окно, "что попало в поле",
            "JSON.stringify({поле: ui.chatText.value, тост: window.__тосты[0] || ''})")

        # --- Требование: честный отказ во время записи ---------------------
        мост.отказать = True
        шаг(окно, "щелчок по микрофону при записи встречи", """
          window.__тосты = []; ui.chatText.value = '';
          document.getElementById('chat-mic').click();
          'нажато';
        """)
        time.sleep(1.0)
        шаг(окно, "что сказали об отказе",
            "JSON.stringify({тост: window.__тосты[0] || '',"
            " слушает: state.dictating})")

        шаг(окно, "буфер вообще доступен",
            "window.__ошибкаБуфера || 'доступен'")
    except Exception as e:  # noqa: BLE001
        итог["ошибка"] = repr(e)
    finally:
        окно.destroy()


окно = webview.create_window(
    "приёмка 26", str(СТРАНИЦА), js_api=мост, hidden=True,
)
webview.start(приёмка, окно, private_mode=True)

if итог.get("нет_кнопок"):
    # Не «skip»: кнопка, которой нет в разметке, — это невыполненное
    # обещание, а не отсутствие условий для проверки.
    raise AssertionError(
        f"в живом окне нет кнопок: {итог['нет_кнопок']}. Задача №26 "
        f"обещает их человеку"
    )

if итог["ошибка"]:
    print(f"[skip] живое окно не поднялось: {итог['ошибка']}")
    raise SystemExit(0)

шаги = dict(итог["шаги"])
for имя, ответ in итог["шаги"]:
    print(f"   [..] {имя}: {ответ}")
print()


def проверить_человеческий(текст: str, где: str) -> None:
    """Сообщение должно быть словами, а не ключом перевода.

    Живая приёмка сразу показала «copy.done» вместо «Заметки
    скопированы»: в выдуманном окне словарь клали прямо в
    память, а в настоящем он едет через мост, и его можно
    не дождаться. Человеку ключ не говорит ничего.
    """
    assert текст, f"{где}: человеку ничего не сказали"
    похож_на_ключ = (
        "." in текст.split(":")[0]
        and " " not in текст.split(":")[0]
    )
    assert not похож_на_ключ, (
        f"{где} показали ключ перевода вместо слов: {текст!r}. "
        f"Человеку это не говорит ничего"
    )


# --- Сверка требований с тем, что увидели ---------------------------------
буфер1 = json.loads(шаги["что в буфере после «копировать»"])
assert буфер1["буфер"], (
    "щелчок по «копировать» ничего не положил в буфер в ЖИВОМ окне: "
    "человек решит, что скопировал, и вставит в чат пустоту"
)
assert буфер1["буфер"][0] == ЗАМЕТКИ, буфер1
проверить_человеческий(буфер1["тост"], "после копирования заметок")
print(f"[ok] №26.1 кнопка «копировать» кладёт разметку: {буфер1['тост']}")

буфер2 = json.loads(шаги["что в буфере после «без разметки»"])
assert буфер2["буфер"], "щелчок по «без разметки» ничего не скопировал"
простой = буфер2["буфер"][0]
assert "#" not in простой and "**" not in простой, простой
assert "Петя чинит вход" in простой, простой
print(f"[ok] №26.2 «без разметки» отдаёт чистый текст: {простой!r}")

буфер3 = json.loads(шаги["что в буфере после реплики"])
assert буфер3["буфер"], "щелчок по копированию реплики ничего не скопировал"
цитата = буфер3["буфер"][0]
assert "Маша" in цитата and "это надо переделать" in цитата, цитата
print(f"[ok] №26.3 реплика копируется цитатой: {цитата!r}")

слушает = json.loads(шаги["окно слушает"])
assert слушает["слушает"], (
    "щелчок по микрофону не начал диктовку через НАСТОЯЩИЙ мост"
)
assert слушает["видно"], "человеку не видно, что программа слушает"
print("[ok] №26.4 микрофон начинает слушать, и это видно на кнопке")

поле = json.loads(шаги["что попало в поле"])
assert поле["поле"] == ПРОДИКТОВАНО, (
    f"продиктованное не попало в поле через настоящий мост: {поле!r}. "
    f"Если виноваты кириллические ключи в ответе Python, человек получит "
    f"молчащую кнопку"
)
print(f"[ok] №26.5 продиктованное попадает в поле: {поле['поле']!r}")

отказ = json.loads(шаги["что сказали об отказе"])
assert not отказ["слушает"], "диктовка началась вопреки отказу"
assert "запись" in отказ["тост"], (
    f"причину отказа человеку не сказали: {отказ!r}. Мёртвая кнопка без "
    f"объяснения читается как поломка программы"
)
проверить_человеческий(отказ["тост"], "при отказе в диктовке")
print(f"[ok] №26.6 при записи встречи причина названа: {отказ['тост']}")

assert "start" in мост.вызовы and "finish" in мост.вызовы, мост.вызовы
print(f"[ok] мост получил настоящие вызовы: {мост.вызовы}")

print("\nЗадача №26 проверена на живом окне и живом мосте.")
