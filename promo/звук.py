"""Звуковая дорожка промо-ролика: мягкие ASMR-звуки, синтезированные с нуля.

Ни одного чужого сэмпла: каждый звук собран из шума и синусов, поэтому
никаких вопросов с лицензиями. Моменты берутся из ролик.html (список
ЗВУКИ), чтобы картинка и звук не разъехались.

Запуск: python promo/звук.py  →  promo/out/звук.wav (48 кГц, стерео)
"""
from __future__ import annotations

import json
import re
import wave
from pathlib import Path

import numpy as np

ПАПКА = Path(__file__).resolve().parent
ЧАСТОТА = 48_000
ДЛИНА = 15.0
rng = np.random.default_rng(14)  # одно зерно: дорожка одинаковая при каждой сборке


def время(сек: float) -> np.ndarray:
    return np.arange(int(сек * ЧАСТОТА)) / ЧАСТОТА


def полоса(сигнал: np.ndarray, низ: float, верх: float) -> np.ndarray:
    """Полосовой фильтр через спектр: для коротких звуков проще и точнее рекурсии."""
    спектр = np.fft.rfft(сигнал)
    f = np.fft.rfftfreq(len(сигнал), 1 / ЧАСТОТА)
    окно = np.clip((f - низ * 0.7) / (низ * 0.3 + 1e-9), 0, 1) * np.clip((верх * 1.3 - f) / (верх * 0.3), 0, 1)
    return np.fft.irfft(спектр * окно, len(сигнал))


def шум(сек: float) -> np.ndarray:
    return rng.standard_normal(int(сек * ЧАСТОТА))


def затухание(n: int, тау: float) -> np.ndarray:
    return np.exp(-np.arange(n) / ЧАСТОТА / тау)


def норм(x: np.ndarray) -> np.ndarray:
    п = np.max(np.abs(x))
    return x / п if п > 0 else x


# --- Звуки. Каждый возвращает (левый, правый). ----------------------------

def моно(x: np.ndarray, пан: float = 0.0):
    """Панорама с сохранением громкости: -1 слева, +1 справа."""
    угол = (пан + 1) * np.pi / 4
    return x * np.cos(угол), x * np.sin(угол)


def клик(тон: float = 1.0, пан: float = 0.0):
    """Мягкое нажатие клавиши: щелчок пластика и тело удара."""
    n = int(0.06 * ЧАСТОТА)
    щелчок = полоса(шум(0.06), 1800 * тон, 5200 * тон) * затухание(n, 0.006)
    t = время(0.06)
    тело = np.sin(2 * np.pi * 190 * тон * t) * затухание(n, 0.012) * 0.6
    return моно(норм(щелчок * 0.8 + тело), пан)


def поп(тон: float = 1.0):
    """Мягкий хлопок, как пузырёк: короткий спад высоты."""
    t = время(0.12)
    f = 260 * тон + 700 * тон * np.exp(-t / 0.012)
    фаза = 2 * np.pi * np.cumsum(f) / ЧАСТОТА
    x = np.sin(фаза) * затухание(len(t), 0.035)
    x += полоса(шум(0.12), 2000, 6000) * затухание(len(t), 0.004) * 0.25
    return моно(норм(x))


def вжух(д: float = 0.55):
    """Проход воздуха слева направо: шум, полоса которого плывёт вверх."""
    n = int(д * ЧАСТОТА)
    t = np.linspace(0, 1, n)
    куски = []
    шаг = 1024
    сырой = шум(д + 0.1)
    for i in range(0, n, шаг):
        кусок = сырой[i:i + шаг * 2]
        центр = 400 + 3200 * t[min(i, n - 1)] ** 1.5
        куски.append(полоса(кусок, центр * 0.6, центр * 1.6)[:шаг])
    x = np.concatenate(куски)[:n]
    огибающая = np.sin(np.pi * t) ** 2.2
    x = норм(x * огибающая)
    пан = np.linspace(-0.7, 0.7, n)
    угол = (пан + 1) * np.pi / 4
    return x * np.cos(угол), x * np.sin(угол)


def нажатие():
    """Кнопка: щелчок вниз и тише щелчок отпускания."""
    л1, п1 = клик(0.8)
    л2, п2 = клик(1.1)
    сдвиг = int(0.09 * ЧАСТОТА)
    л = np.zeros(len(л1) + сдвиг)
    п = np.zeros_like(л)
    л[:len(л1)] += л1; п[:len(п1)] += п1
    л[сдвиг:сдвиг + len(л2)] += л2 * 0.45; п[сдвиг:сдвиг + len(п2)] += п2 * 0.45
    return л, п


def удар():
    """Глубокий мягкий удар: низкий тон с падением высоты."""
    t = время(0.9)
    f = 48 + 70 * np.exp(-t / 0.05)
    фаза = 2 * np.pi * np.cumsum(f) / ЧАСТОТА
    x = np.sin(фаза) * затухание(len(t), 0.28)
    x += полоса(шум(0.9), 60, 400) * затухание(len(t), 0.03) * 0.3
    return моно(норм(x))


def печать(д: float = 3.0):
    """Тихая печать: россыпь клавиш с живым ритмом и разной высотой."""
    n = int(д * ЧАСТОТА)
    л = np.zeros(n + ЧАСТОТА // 10)
    п = np.zeros_like(л)
    t = 0.0
    while t < д:
        тон = rng.uniform(0.85, 1.25)
        кл, кп = клик(тон, rng.uniform(-0.35, 0.35))
        i = int(t * ЧАСТОТА)
        г = rng.uniform(0.55, 1.0)
        л[i:i + len(кл)] += кл * г
        п[i:i + len(кп)] += кп * г
        t += rng.uniform(0.055, 0.12) + (0.18 if rng.random() < 0.08 else 0)  # иногда пауза между словами
    return л, п


def галка(тон: float = 1.0):
    """Галочка: хлопок и короткий стеклянный «тинь»."""
    t = время(0.5)
    звон = (np.sin(2 * np.pi * 1568 * тон * t) + 0.35 * np.sin(2 * np.pi * 3136 * тон * t)) * затухание(len(t), 0.11)
    pл, pп = поп(1.3 * тон)
    x = np.zeros(len(t))
    x[:len(pл)] += pл * 0.8
    x += звон * 0.45
    return моно(норм(x))


def щелчок_замка():
    """Защёлка: два металлических щелчка и короткий отзвук."""
    t = время(0.35)
    x = np.zeros(len(t))
    for сдвиг, г in ((0.0, 1.0), (0.028, 0.7)):
        i = int(сдвиг * ЧАСТОТА)
        m = len(t) - i
        x[i:] += полоса(шум(m / ЧАСТОТА + 1e-4)[:m], 2500, 9000) * затухание(m, 0.004) * г
    x += np.sin(2 * np.pi * 2650 * t) * затухание(len(t), 0.05) * 0.18
    return моно(норм(x))


def подъём(д: float = 0.6):
    """Нарастание перед финалом: шум, светлеющий и громче к концу."""
    n = int(д * ЧАСТОТА)
    t = np.linspace(0, 1, n)
    куски = []
    шаг = 1024
    сырой = шум(д + 0.1)
    for i in range(0, n, шаг):
        центр = 300 + 5000 * t[min(i, n - 1)] ** 2
        куски.append(полоса(сырой[i:i + шаг * 2], центр * 0.5, центр * 1.5)[:шаг])
    x = np.concatenate(куски)[:n] * t ** 2.5
    return моно(норм(x))


def звон():
    """Тихий колокольчик финала: мажорный аккорд с долгим хвостом."""
    t = время(2.4)
    x = np.zeros(len(t))
    for f, г in ((523.25, 1.0), (659.25, 0.6), (783.99, 0.7), (1046.5, 0.35), (2093.0, 0.12)):
        x += np.sin(2 * np.pi * f * t) * г * затухание(len(t), 0.9 if f < 1000 else 0.4)
    x *= np.clip(t / 0.008, 0, 1)
    return моно(норм(x))


ВИДЫ = {
    "клик": lambda з: клик(з.get("тон", 1.0)),
    "поп": lambda з: поп(з.get("тон", 1.0)),
    "вжух": lambda з: вжух(з.get("д", 0.55)),
    "нажатие": lambda з: нажатие(),
    "удар": lambda з: удар(),
    "печать": lambda з: печать(з.get("д", 3.0)),
    "галка": lambda з: галка(з.get("тон", 1.0)),
    "щелчок_замка": lambda з: щелчок_замка(),
    "подъём": lambda з: подъём(з.get("д", 0.6)),
    "звон": lambda з: звон(),
}


def отзвук(x: np.ndarray, сек: float = 0.5, доля: float = 0.16) -> np.ndarray:
    """Короткая комната: свёртка с затухающим шумом. Склеивает звуки в одно пространство."""
    n = int(сек * ЧАСТОТА)
    ик = rng.standard_normal(n) * затухание(n, сек / 5)
    ик = полоса(ик, 200, 7000)
    ик /= np.sqrt(np.sum(ик ** 2))
    m = len(x) + n
    размер = 1 << (m - 1).bit_length()
    мокрый = np.fft.irfft(np.fft.rfft(x, размер) * np.fft.rfft(ик, размер), размер)[:len(x)]
    return x + мокрый * доля


def main() -> int:
    html = (ПАПКА / "ролик.html").read_text(encoding="utf-8")
    м = re.search(r"/\*ЗВУКИ\*/(.*?)/\*/ЗВУКИ\*/", html, re.S)
    if not м:
        raise SystemExit("в ролик.html нет списка ЗВУКИ")
    события = json.loads(м.group(1))

    n = int(ДЛИНА * ЧАСТОТА)
    л = np.zeros(n + ЧАСТОТА * 3)
    п = np.zeros_like(л)
    for с in события:
        sl, sp = ВИДЫ[с["вид"]](с)
        i = int(с["t"] * ЧАСТОТА)
        г = с.get("г", 0.6)
        л[i:i + len(sl)] += sl * г
        п[i:i + len(sp)] += sp * г

    # Едва слышный воздух комнаты: тишина между звуками не «цифровая».
    воздух = полоса(шум(len(л) / ЧАСТОТА), 150, 3000)[:len(л)]
    воздух2 = полоса(шум(len(л) / ЧАСТОТА), 150, 3000)[:len(л)]
    л += норм(воздух) * 0.006
    п += норм(воздух2) * 0.006

    л, п = отзвук(л), отзвук(п)
    л, п = л[:n], п[:n]

    # Вход и выход без щелчка.
    края = np.ones(n)
    края[:int(0.02 * ЧАСТОТА)] = np.linspace(0, 1, int(0.02 * ЧАСТОТА))
    края[-int(0.6 * ЧАСТОТА):] = np.linspace(1, 0, int(0.6 * ЧАСТОТА)) ** 2
    л *= края; п *= края

    пик = max(np.max(np.abs(л)), np.max(np.abs(п)))
    масштаб = 10 ** (-2 / 20) / пик  # пик −2 дБ: межотсчётный пик и AAC добавляют своё
    стерео = np.stack([л, п], axis=1) * масштаб
    данные = (np.clip(стерео, -1, 1) * 32767).astype("<i2")

    выход = ПАПКА / "out" / "звук.wav"
    выход.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(выход), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(ЧАСТОТА)
        w.writeframes(данные.tobytes())
    print(f"звук: {выход}, событий {len(события)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
