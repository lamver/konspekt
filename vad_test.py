"""Речь не должна рваться посреди слова.

Жалоба пользователя (issue #2): в расшифровке попадаются огрызки вроде
«Пото.» и «Усу.». На его записи нашлись две разные причины, обе здесь и
проверяются.

Причина 1: когда человек говорит без пауз дольше max_segment, копить
звук вечно нельзя, и резать приходится. Раньше резали ровно по таймеру,
то есть вслепую — на боевой записи так вышло 172 реплики, где следующая
начиналась обрывком слова («П прогон», «Кз Электрогриль»). Теперь ищем
самое тихое место в конце куска: полной паузы там нет, но стык слов
тише середины слова.

Причина 2: минимальная длина речи сравнивалась с длиной куска ВМЕСТЕ с
запасом PAD по краям. При min_speech 0.35с и PAD 0.15с хватало 0.05с
звука, чтобы щелчок доехал до модели и вернулся огрызком.

Проверяем на синтезированном звуке, а не на записи пользователя: она
есть только на его машине, а тест должен идти у всех.
"""
import testenv  # noqa: F401  русский вывод в консоли Windows

import numpy as np

from app.asr.vad import PAD, SpeechSegmenter

ЧАСТОТА = 16000
БЕДЫ: list[str] = []


def проверить(условие: bool, что: str) -> None:
    print(("[ok] " if условие else "[FAIL] ") + что)
    if not условие:
        БЕДЫ.append(что)


def тон(секунд: float, громкость: float = 0.3) -> np.ndarray:
    """Звук, похожий на голос: не чистая синусоида, а шум с огибающей."""
    n = int(секунд * ЧАСТОТА)
    основа = np.sin(2 * np.pi * 150 * np.arange(n) / ЧАСТОТА)
    шум = np.random.RandomState(0).randn(n) * 0.3
    return ((основа + шум) * громкость).astype(np.float32)


def речь_со_стыками(секунд: float, слово: float = 0.4) -> np.ndarray:
    """Непрерывная речь, где между словами есть тихие стыки.

    Так говорит человек: пауз, которые заметит VAD, нет, но на стыке
    слов звук проседает. Ровный тон такого не воспроизводит, а без
    стыков нечему доказать, что резка стала умнее.
    """
    куски = []
    сделано = 0.0
    while сделано < секунд:
        куски.append(тон(слово))
        # Стык: тихо, но не тишина — VAD такое паузой не считает.
        куски.append(тон(0.06, громкость=0.02))
        сделано += слово + 0.06
    return np.concatenate(куски)


def тишина(секунд: float) -> np.ndarray:
    return np.zeros(int(секунд * ЧАСТОТА), dtype=np.float32)


def скормить(звук: np.ndarray) -> list:
    """Прогнать звук через VAD так же, как это делает живой захват."""
    сегментатор = SpeechSegmenter(sample_rate=ЧАСТОТА)
    куски = []
    шаг = int(0.5 * ЧАСТОТА)
    for н in range(0, len(звук), шаг):
        куски += сегментатор.feed(звук[н:н + шаг], н / ЧАСТОТА)
    return куски + сегментатор.flush()


def main() -> int:
    потолок = SpeechSegmenter.max_segment

    # --- длинная речь без пауз -------------------------------------------
    длинная = np.concatenate([
        тишина(0.5), речь_со_стыками(потолок * 2.5), тишина(1.0),
    ])
    куски = скормить(длинная)
    проверить(len(куски) >= 2,
              f"речь длиннее потолка режется на части (получено {len(куски)})")

    звука = sum(len(к.pcm) for к in куски) / ЧАСТОТА
    ожидаем = потолок * 2.5
    проверить(звука >= ожидаем * 0.9,
              f"при резке речь не теряется: {звука:.1f}с из {ожидаем:.1f}с")

    # Главное: режем не вслепую по таймеру, а по тихому месту. Точный
    # кадр разреза снаружи не виден: к куску с обеих сторон прихвачен
    # PAD, и в самом конце лежит уже следующее слово. Поэтому смотрим
    # зону разреза целиком — PAD плюс запас — и берём в ней минимум.
    # Если резали по стыку слов, минимум близок к тишине; если посередине
    # слова, там громкость обычной речи.
    отношения = []
    for к in куски[:-1]:
        зона = к.pcm[-int((PAD + 0.1) * ЧАСТОТА):]
        окно = int(0.02 * ЧАСТОТА)
        кадров = len(зона) // окно
        средняя = float(np.sqrt(np.mean(к.pcm ** 2)) + 1e-9)
        тишайший = min(
            float(np.sqrt(np.mean(зона[j * окно:(j + 1) * окно] ** 2)))
            for j in range(кадров)
        )
        отношения.append(тишайший / средняя)
    худшее = max(отношения) if отношения else 1.0
    проверить(худшее < 0.5,
              f"резка попадает на тихий стык, а не на середину слова "
              f"(громкость в точке разреза {худшее:.2f} от средней)")

    # Раньше принудительная резка сбрасывала «мы внутри речи», и остаток
    # до следующего громкого кадра пропадал целиком. Проверяем, что
    # куски идут подряд, без дыр между ними.
    дыры = [
        round(следующий.offset - (предыдущий.offset + len(предыдущий.pcm) / ЧАСТОТА), 2)
        for предыдущий, следующий in zip(куски, куски[1:])
    ]
    проверить(all(д <= 2 * PAD + 0.05 for д in дыры),
              f"между кусками одной речи нет провалов (дыры: {дыры})")

    # --- щелчок вместо речи ----------------------------------------------
    щелчок = np.concatenate([тишина(1.0), тон(0.05, громкость=0.5), тишина(1.0)])
    проверить(скормить(щелчок) == [],
              "мгновенный щелчок не уезжает в распознавание огрызком")

    # Настоящая короткая фраза при этом должна доехать: «Да.» — не щелчок.
    короткая = np.concatenate([тишина(1.0), тон(0.5), тишина(1.0)])
    проверить(len(скормить(короткая)) == 1,
              "короткая, но настоящая фраза распознаётся")

    if БЕДЫ:
        print(f"\nПровалено проверок: {len(БЕДЫ)}")
        return 1
    print("\nРечь не рвётся посреди слова")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
