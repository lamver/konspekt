# -*- coding: utf-8 -*-
"""Вопрос задаётся снова, когда звук сменился другим звуком.

Жалоба человека прямым текстом: «как определить следующий случай, если я
сказал это не пишем? Надо понять, что была тишина, и включить монитор.
Если аудио опять появилось, то предлагаем писать».

До этой правки программа замолкала навсегда: ответил один раз — и до
конца записи она глухая. Значит, ролик кончился, через полчаса в Zoom
заговорил живой собеседник, а его никто не пишет и никто об этом не
сказал. Ровно та потеря, ради которой всё и делалось.

Здесь проверяется граница между «тем же самым звуком» и «другим»:
тишина. Пока звук идёт, ответ действует; после долгой тишины вопрос
снова уместен.
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np

import testenv  # noqa: F401  русский вывод в консоли Windows

from app.audio import devices, wasapi
from app.audio.чужая_речь import ТИШИНЫ_ДЛЯ_ПОВТОРА, Слушатель
from app.core.events import RECORDING_FOREIGN_SPEECH, bus

ЧАСТОТА = 16000
БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def речь(секунд: float, зерно: int = 7) -> np.ndarray:
    """Похожий на разговор кусок: слоги, паузы, меняющийся тембр."""
    rng = np.random.default_rng(зерно)
    куски: list[np.ndarray] = []
    время = 0.0
    while время < секунд:
        длина = rng.uniform(0.12, 0.22)
        n = int(длина * ЧАСТОТА)
        ог = np.hanning(n).astype(np.float32)
        if rng.random() > 0.35:
            t = np.arange(n, dtype=np.float32) / ЧАСТОТА
            ядро = np.sin(2 * np.pi * rng.uniform(90, 220) * t).astype(np.float32)
        else:
            ядро = rng.normal(0, 1.0, n).astype(np.float32)
        куски.append((0.25 * ядро * ог).astype(np.float32))
        время += длина
        пауза = rng.uniform(0.04, 0.10) if rng.random() > 0.15 else rng.uniform(0.35, 0.6)
        куски.append(np.zeros(int(пауза * ЧАСТОТА), dtype=np.float32))
        время += пауза
    return np.concatenate(куски)[: int(секунд * ЧАСТОТА)]


def тишина(секунд: float) -> np.ndarray:
    """Не идеальный ноль: в настоящей дорожке всегда есть шорох оцифровки."""
    rng = np.random.default_rng(3)
    return rng.normal(0, 0.0005, int(секунд * ЧАСТОТА)).astype(np.float32)


def скормить(с: Слушатель, звук: np.ndarray, кусок: float = 0.1) -> int:
    """Скормить звук по кускам, как это делает живая дорожка."""
    сколько = 0
    шаг = int(кусок * ЧАСТОТА)
    for i in range(0, len(звук) - шаг + 1, шаг):
        if с.добавить(звук[i:i + шаг]):
            сколько += 1
    return сколько


def проверить_повтор_после_тишины() -> None:
    """Ролик кончился, тишина, заговорил собеседник: спрашиваем снова."""
    с = Слушатель()
    первый = скормить(с, речь(40.0))
    проверить(первый == 1, f"про первый разговор спросили один раз (было {первый})")
    проверить(с.ждём_тишины, "после ответа ждём, когда звук кончится")

    молчали = скормить(с, тишина(ТИШИНЫ_ДЛЯ_ПОВТОРА + 6.0))
    проверить(молчали == 0, f"в тишине человека не дёргают (было {молчали})")
    проверить(not с.ждём_тишины,
              "после долгой тишины вопрос снова разрешён: это уже другой звук")

    второй = скормить(с, речь(40.0, зерно=11))
    проверить(второй == 1,
              "про новый разговор спросили снова, а не промолчали навсегда "
              f"(было {второй})")


def проверить_молчание_пока_звук_идёт() -> None:
    """Тот же самый подкаст переспрашивать нельзя: это навязчивость."""
    с = Слушатель()
    скормить(с, речь(40.0))
    ещё = скормить(с, речь(180.0, зерно=5))
    проверить(ещё == 0,
              f"пока звук не прерывался, вопрос не повторяется (было {ещё})")


def проверить_короткую_паузу() -> None:
    """Пауза между репликами — не конец разговора.

    Человек в Zoom замолчал на десять секунд, пока говорил другой. Считать
    это «новым звуком» и спрашивать заново значило бы дёргать человека
    каждую минуту встречи.
    """
    с = Слушатель()
    скормить(с, речь(40.0))
    скормить(с, тишина(12.0))
    проверить(с.ждём_тишины,
              "короткая пауза не считается концом разговора")
    ещё = скормить(с, речь(40.0, зерно=13))
    проверить(ещё == 0,
              f"после короткой паузы вопрос не повторяется (было {ещё})")


def проверить_паузы_не_копятся() -> None:
    """Лекция с перерывами — это всё ещё та же лекция.

    Мутация вскрыла настоящую дыру: если счёт тишины не обнулять при
    возвращении звука, то за час подкаста наберётся полминуты пауз по
    частям, и программа переспросит про тот же самый звук. Тишина
    считается только подряд, иначе «граница между звуками» ничего не
    значит.
    """
    с = Слушатель()
    скормить(с, речь(40.0))
    # Шесть перерывов: в сумме заметно больше порога в 30 секунд, но ни
    # разу подряд. Считаем вопросы и внутри цикла: если тишина
    # сложится, вопрос прозвучит прямо там, а проверка только по итогу
    # его не заметит.
    ещё = 0
    for зерно in (21, 22, 23, 24, 25, 26):
        ещё += скормить(с, тишина(12.0))
        ещё += скормить(с, речь(30.0, зерно=зерно))
    ещё += скормить(с, речь(40.0, зерно=27))
    проверить(ещё == 0,
              f"разговор с перерывами не вызывает повторный вопрос (было {ещё})")
    проверить(с.ждём_тишины,
              "паузы внутри разговора не складываются в «звук кончился»")


def проверить_насовсем() -> None:
    """Выключил слежку — значит выключил: никакая тишина её не вернёт."""
    с = Слушатель()
    с.больше_не_спрашивать()
    скормить(с, тишина(ТИШИНЫ_ДЛЯ_ПОВТОРА + 12.0))
    сколько = скормить(с, речь(40.0))
    проверить(сколько == 0,
              f"после отказа насовсем не спрашивают вовсе (было {сколько})")


class Говорящий:
    """Устройство, из которого без конца льётся разговор."""

    name = "Чужой разговор"

    def __init__(self) -> None:
        self._поток = речь(60.0)
        self._поз = 0

    def recorder(self, **_):
        return self

    def __enter__(self):
        return self

    def __exit__(self, *_):
        return False

    def record(self, numframes):
        time.sleep(0.001)
        конец = self._поз + numframes
        if конец > len(self._поток):
            self._поз = 0
            конец = numframes
        кусок = self._поток[self._поз:конец]
        self._поз = конец
        return кусок.copy()


def проверить_дорожка_слушает_после_отказа() -> None:
    """Главное в этой правке: после «не писать» дорожка не глохнет.

    Без открытого устройства второй вопрос физически невозможен, сколько
    бы тишины ни прошло. Поэтому дорожка обязана перейти в режим
    «слушаю, но не пишу», а не исчезнуть совсем.
    """
    захват = wasapi.WasapiCapture(capture_mic=True, capture_system=True)
    захват._meeting_id = "проверка"
    захват.loopback_device_id = None
    захват._paths = {}
    # Подменяем открытие устройства: настоящая карта не нужна.
    прежний = devices.open_loopback
    devices.open_loopback = lambda _id=None: Говорящий()
    try:
        захват._tracks = {
            devices.TRACK_ME: wasapi._Track(
                name=devices.TRACK_ME, opener=lambda: Говорящий(),
                wav_path=Path(__file__).parent / "_повтор_me.wav",
                chunk_seconds=1.0, on_chunk=None,
            ),
            devices.TRACK_THEM: wasapi._Track(
                name=devices.TRACK_THEM, opener=lambda: Говорящий(),
                wav_path=Path(__file__).parent / "_повтор_them.wav",
                chunk_seconds=1.0, on_chunk=None,
            ),
        }
        for д in захват._tracks.values():
            д.start()
        time.sleep(0.5)

        ответ = захват.выключить_системный_звук()
        проверить(ответ.get("ok") is True, f"системный звук выключился ({ответ})")
        трек = захват._tracks.get(devices.TRACK_THEM)
        проверить(трек is not None,
                  "дорожка системного звука осталась, иначе второй вопрос "
                  "невозможен ни при какой тишине")
        проверить(bool(трек and трек._только_слушать),
                  "оставшаяся дорожка слушает, но ничего не пишет")
        проверить(ответ.get("слушаем") is True,
                  "ответ честно говорит, что слежка продолжается")
        проверить(захват.capture_system is False,
                  "настройка выключена: следующая встреча начнётся без сюрприза")

        # И при этом она не переспрашивает про тот же самый звук.
        пойманное: list[dict] = []
        отписаться = bus.on(RECORDING_FOREIGN_SPEECH, пойманное.append)
        предел = time.monotonic() + 16.0
        while time.monotonic() < предел and not пойманное:
            time.sleep(0.05)
        отписаться()
        проверить(not пойманное,
                  f"про тот же звук слушающая дорожка молчит (было {len(пойманное)})")

        for д in list(захват._tracks.values()):
            д.stop()
    finally:
        devices.open_loopback = прежний
        for имя in ("_повтор_me.wav", "_повтор_them.wav"):
            (Path(__file__).parent / имя).unlink(missing_ok=True)


def main() -> int:
    проверить_повтор_после_тишины()
    проверить_молчание_пока_звук_идёт()
    проверить_короткую_паузу()
    проверить_паузы_не_копятся()
    проверить_насовсем()
    проверить_дорожка_слушает_после_отказа()

    if БЕДЫ:
        print(f"\nНе прошло проверок: {len(БЕДЫ)}")
        return 1
    print("\nПосле тишины Konspekt спрашивает снова, а не глохнет навсегда.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
