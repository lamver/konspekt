"""Общая обвязка для тестов: русский вывод и чужой каталог данных.

Две вещи, одинаково нужные каждой проверке.

**Кодировка.** Консоль Windows по умолчанию живёт в cp1251, и `print` с
кириллицей роняет тест с `UnicodeEncodeError` уже после того, как все
проверки прошли. Выглядит как поломка кода, хотя сломана только
кодировка вывода.

**Чужой каталог данных.** Проверки поднимают настоящий `AppService`, а
он умеет сохранять настройки и писать записи на диск. Без своего
каталога он делает это в живой профиль человека: выключает ему
системный звук, заводит встречи, оставляет гигабайты WAV. Ровно это и
случилось — прогон набора выключил человеку `capture_system` и насыпал
в `%APPDATA%\\Konspekt\\audio` 139 папок с записями на 400 МБ.

Чинить это в каждой проверке по отдельности бесполезно: следующая
написанная снова всё сломает, и заметят это не сразу, а по чужой
жалобе. Поэтому подменяем каталог здесь, в одном месте, которое
импортируют все.

    import testenv  # noqa: F401

Каталог живёт под временной папкой системы и переживает один запуск
проверки. Кто хочет свой (например, приёмка, которой важно проверить
сохранение настроек), задаёт `KONSPEKT_DATA_DIR` до импорта — своё
значение мы не трогаем.
"""

from __future__ import annotations

import os
import sys
import tempfile

for stream in (sys.stdout, sys.stderr):
    if hasattr(stream, "reconfigure"):
        stream.reconfigure(encoding="utf-8", errors="replace")


# Подменяем каталог данных, если проверка не выбрала свой. Именно до
# того, как программа успеет его прочитать: `paths` запоминает значение
# при первом обращении.
if not os.environ.get("KONSPEKT_DATA_DIR"):
    _песочница = tempfile.mkdtemp(prefix="konspekt-проверка-")
    os.environ["KONSPEKT_DATA_DIR"] = _песочница
