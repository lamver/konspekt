# -*- coding: utf-8 -*-
"""Konspekt замечает разговор, когда запись не идёт.

Главная жалоба человека: «конспект просто включён в трее, но запись не
идёт. У меня включается на компе подкаст, зум или ещё что-то, что издаёт
звук, — конспект палит это и говорит: эй, будем это писать или нет?»

Это самая обидная потеря встречи: программа стоит в трее, человек
открыл Zoom и забыл нажать кнопку, вспомнил через сорок минут. Ничего
уже не вернуть.

Отдельное требование: «чтоб не реагировал на любой бздыньк, как минимум
по длительности, может, секунд десять». Поэтому здесь проверяется не
только то, что сторож слышит разговор, но и то, что он молчит на
коротких звуках: уведомление, щелчок, кусок заставки.

Звуковая карта не нужна: сторож работает с любым объектом, у которого
есть `record`.
"""
from __future__ import annotations

import time

import numpy as np

import testenv  # noqa: F401  русский вывод в консоли Windows

from app.audio import devices
from app.audio.сторож import ПОДТВЕРЖДЕНИЙ, Сторож
from app.audio.чужая_речь import ОКНО
from app.core.events import SYSTEM_SPEECH_NOTICED, bus

ЧАСТОТА = 16000
БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def речь(секунд: float, зерно: int = 7) -> np.ndarray:
    """Похожий на разговор кусок: слоги, паузы, меняющийся тембр."""
    rng = np.random.default_rng(зерно)
    куски: list[np.ndarray] = []
    время = 0.0
    while время < секунд:
        длина = rng.uniform(0.12, 0.22)
        n = int(длина * ЧАСТОТА)
        ог = np.hanning(n).astype(np.float32)
        if rng.random() > 0.35:
            t = np.arange(n, dtype=np.float32) / ЧАСТОТА
            ядро = np.sin(2 * np.pi * rng.uniform(90, 220) * t).astype(np.float32)
        else:
            ядро = rng.normal(0, 1.0, n).astype(np.float32)
        куски.append((0.25 * ядро * ог).astype(np.float32))
        время += длина
        пауза = rng.uniform(0.04, 0.10) if rng.random() > 0.15 else rng.uniform(0.35, 0.6)
        куски.append(np.zeros(int(пауза * ЧАСТОТА), dtype=np.float32))
        время += пауза
    return np.concatenate(куски)[: int(секунд * ЧАСТОТА)]


def тишина(секунд: float) -> np.ndarray:
    rng = np.random.default_rng(3)
    return rng.normal(0, 0.0005, int(секунд * ЧАСТОТА)).astype(np.float32)


def бздыньк() -> np.ndarray:
    """Звук уведомления: короткий, звонкий, и записи не заслуживает.

    Ради него человек и просил порог по длительности. Секунда звона в
    тишине не должна поднимать программу на ноги.
    """
    t = np.arange(int(0.35 * ЧАСТОТА), dtype=np.float32) / ЧАСТОТА
    затухание = np.exp(-6.0 * t).astype(np.float32)
    тон = (np.sin(2 * np.pi * 880 * t) + 0.5 * np.sin(2 * np.pi * 1320 * t))
    return (0.4 * тон * затухание).astype(np.float32)


def тиканье(секунд: float) -> np.ndarray:
    """Частые короткие щелчки: часы, индикатор, цепочка уведомлений.

    Самый коварный случай. По ритму это вылитая речь: звук-пауза по
    несколько раз в секунду, громкость скачет, тембр широкий. Отличает
    его только длина всплеска: слог человека длится 100–250 мс, а
    щелчок — тридцать. Без этой приметы программа срывалась бы на
    тикающих часах в соседней комнате.
    """
    rng = np.random.default_rng(19)
    куски: list[np.ndarray] = []
    время = 0.0
    while время < секунд:
        n = int(0.03 * ЧАСТОТА)
        щелчок = rng.normal(0, 1.0, n).astype(np.float32)
        щелчок *= np.hanning(n).astype(np.float32)
        куски.append((0.35 * щелчок).astype(np.float32))
        пауза = rng.uniform(0.08, 0.14)
        куски.append(np.zeros(int(пауза * ЧАСТОТА), dtype=np.float32))
        время += 0.03 + пауза
    return np.concatenate(куски)[: int(секунд * ЧАСТОТА)]


class Устройство:
    """Подделка звуковой карты: отдаёт заранее собранный поток."""

    name = "Подделка"

    def __init__(self, поток: np.ndarray, зациклить: bool = True) -> None:
        self._поток = поток
        self._поз = 0
        self._зациклить = зациклить

    def recorder(self, **_):
        return self

    def __enter__(self):
        return self

    def __exit__(self, *_):
        return False

    def record(self, numframes):
        time.sleep(0.001)
        конец = self._поз + numframes
        if конец > len(self._поток):
            if not self._зациклить:
                # Кончился заготовленный звук: дальше тишина.
                return np.zeros(numframes, dtype=np.float32)
            self._поз = 0
            конец = numframes
        кусок = self._поток[self._поз:конец]
        self._поз = конец
        return кусок.copy()


def прогнать(поток: np.ndarray, секунд: float = 25.0,
             зациклить: bool = True, **параметры):
    """Покрутить сторожа на потоке и вернуть пойманные предложения."""
    пойманное: list[dict] = []
    отписаться = bus.on(SYSTEM_SPEECH_NOTICED, пойманное.append)
    прежний = devices.open_loopback
    devices.open_loopback = lambda _id=None: Устройство(поток, зациклить)
    сторож = Сторож(**параметры)
    try:
        сторож.запустить()
        предел = time.monotonic() + секунд
        while time.monotonic() < предел and not пойманное:
            time.sleep(0.02)
    finally:
        сторож.остановить()
        devices.open_loopback = прежний
        отписаться()
    return пойманное, сторож


def проверить_замечает_разговор() -> None:
    """Ради этого всё и делалось: подкаст играет, запись не идёт."""
    пойманное, _ = прогнать(речь(60.0))
    проверить(bool(пойманное),
              "про разговор при выключенной записи человека спрашивают")
    if пойманное:
        проверить("признаки" in пойманное[0],
                  "в событии есть признаки, по которым принято решение")
        проверить(пойманное[0].get("секунд", 0) >= 10,
                  "в вопросе сказано, сколько уже идёт разговор")


def проверить_молчит_на_бздыньке() -> None:
    """Требование человека: не реагировать на короткие звуки.

    Шесть уведомлений подряд с паузами. Каждое громкое, звонкое и
    короткое: если бы порог был по громкости, программа сорвалась бы на
    первом же.
    """
    куски = []
    for _ in range(6):
        куски.append(бздыньк())
        куски.append(тишина(4.0))
    пойманное, _ = прогнать(np.concatenate(куски), секунд=20.0)
    проверить(not пойманное,
              f"на коротких уведомлениях не дёргают (было {len(пойманное)})")


def проверить_молчит_на_тиканье() -> None:
    """Часы и цепочка щелчков не должны сходить за разговор.

    По ритму это вылитая речь, и без приметы «длина всплеска» программа
    сорвалась бы на тикающих часах. Проверяем именно долгий поток: он
    идёт заметно дольше порога в полминуты, так что пройти незамеченным
    может только по существу, а не по нехватке времени.
    """
    пойманное, _ = прогнать(тиканье(60.0), секунд=25.0)
    проверить(not пойманное,
              f"частые щелчки не сходят за разговор (было {len(пойманное)})")


def проверить_молчит_на_коротком_разговоре() -> None:
    """Десять секунд речи — это ещё не встреча.

    Заставка ролика, реплика в чужой вкладке, «алло, я перезвоню». Порог
    в полминуты выбран именно чтобы такое не поднимало программу.
    """
    поток = np.concatenate([речь(10.0), тишина(30.0)])
    пойманное, _ = прогнать(поток, секунд=18.0, зациклить=False)
    проверить(not пойманное,
              f"десяти секунд разговора мало для вопроса (было {len(пойманное)})")


def проверить_порог_полминуты() -> None:
    """Порог именно такой, как обещано человеку и в подсказке настроек."""
    нужно = ПОДТВЕРЖДЕНИЙ * ОКНО
    проверить(нужно >= 30.0,
              f"разговор должен идти не меньше 30 секунд (сейчас {нужно:.0f})")


def проверить_выключенный_молчит() -> None:
    """Снял галочку — значит программа молчит и карту не трогает."""
    пойманное, сторож = прогнать(речь(60.0), секунд=12.0, включён=False)
    проверить(not пойманное,
              f"выключенный сторож молчит (было {len(пойманное)})")
    проверить(not сторож.работает,
              "выключенный сторож не занимает звуковую карту")


def проверить_ответ_человека() -> None:
    """Ответ «не надо» затыкает вопрос, пока звук не сменится тишиной."""
    пойманное: list[dict] = []
    отписаться = bus.on(SYSTEM_SPEECH_NOTICED, пойманное.append)
    прежний = devices.open_loopback
    devices.open_loopback = lambda _id=None: Устройство(речь(60.0), True)
    сторож = Сторож()
    try:
        # Затыкаем сразу, ещё до старта: вопроса быть не должно вовсе.
        сторож.замолчать()
        сторож.запустить()
        предел = time.monotonic() + 25.0
        while time.monotonic() < предел:
            time.sleep(0.05)
    finally:
        сторож.остановить()
        devices.open_loopback = прежний
        отписаться()
    проверить(not пойманное,
              f"после ответа человека вопрос не повторяется (было {len(пойманное)})")


def проверить_неудачу_устройства() -> None:
    """Карта занята другой программой: молчим, но не падаем.

    И честно говорим об этом: галочка, которая врёт, хуже отсутствия
    слежки — человек на неё понадеется.
    """
    прежний = devices.open_loopback

    def сломанное(_id=None):
        raise RuntimeError("устройство занято")

    devices.open_loopback = сломанное
    сторож = Сторож()
    try:
        сторож.запустить()
        time.sleep(1.0)
        проверить(сторож.ошибка is not None,
                  f"о занятом устройстве сказано честно ({сторож.ошибка})")
    finally:
        сторож.остановить()
        devices.open_loopback = прежний


def main() -> int:
    проверить_порог_полминуты()
    проверить_замечает_разговор()
    проверить_молчит_на_бздыньке()
    проверить_молчит_на_тиканье()
    проверить_молчит_на_коротком_разговоре()
    проверить_выключенный_молчит()
    проверить_ответ_человека()
    проверить_неудачу_устройства()

    if БЕДЫ:
        print(f"\nНе прошло проверок: {len(БЕДЫ)}")
        return 1
    print("\nKonspekt замечает разговор, даже когда запись не идёт.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
