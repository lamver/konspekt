"""Проверка антивирусами в сборке: логика шагов, а не текст YAML.

История. Первый шаг VirusTotal не запускался ни разу: в его условии
стояло `env.VT_API_KEY != ''`, а env, объявленный в том же шаге, в его
собственном `if` не виден. Условие всегда ложно, шаг всегда пропущен, и
заметить это нельзя: пропуск по ложному условию выглядит ровно как
осознанный пропуск без ключа.

Потом скан заработал, но шёл после публикации и только дописывал итог в
описание, так что 0.10.1 ушла к людям с тревогой Defender. Теперь
проверяет страж выпуска, до публикации (страж_test.py смотрит его
место и провал). Отдельный шаг VirusTotal убран: он заливал тот же
файл повторно, VirusTotal отвечал 409, и сборка 0.11.0 упала при чистом
установщике.

Здесь следим, чтобы ни одна из этих бед не вернулась.

Разбираем файл сами, без pyyaml: он приезжает транзитивно, через
huggingface_hub, и однажды уедет вместе с ним.
"""

import io
import re
import sys
from pathlib import Path

import testenv  # noqa: F401  русский вывод в консоли Windows

ФАЙЛ = ".github/workflows/build.yml"
ошибки = []


def проверить(ок, что):
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        ошибки.append(что)


текст = io.open(ФАЙЛ, encoding="utf-8").read()


def шаги() -> list[str]:
    """Шаги сборки кусками текста, по одному на шаг."""
    куски = re.split(r"\n(?=      - (?:name|uses):)", текст)
    return [к for к in куски if к.lstrip().startswith("- ")]


все = шаги()
стражи = [ш for ш in все if "tools/страж_выпуска.py" in ш]
проверить(len(стражи) == 2, f"страж зовётся дважды: для выпуска и для сборки по кнопке ({len(стражи)})")

# Ловушка первого шага: env своего шага в его же `if` не виден.
for ш in все:
    условие = re.search(r"\n        if: (.+)", ш)
    if условие and "VT_API_KEY" in (условие.group(1)):
        проверить(False, "условие шага смотрит на ключ VirusTotal: env в своём if не виден")

выпускной = [ш for ш in стражи if "refs/tags/v" in (re.search(r"\n        if: (.+)", ш) or [None, ""])[1]
             and "!startsWith" not in ш]
кнопочный = [ш for ш in стражи if "!startsWith" in ш]
проверить(len(выпускной) == 1, "есть страж для выпуска по тегу")
проверить(len(кнопочный) == 1, "есть проверка для сборки по кнопке")
if кнопочный:
    проверить("continue-on-error: true" in кнопочный[0],
              "без выпуска тревога не роняет сборку: она лишь сообщает")
if выпускной:
    проверить("continue-on-error" not in выпускной[0],
              "в выпуске тревога роняет сборку")

# Повторная заливка того же файла — ровно то, на чём упала 0.11.0.
проверить("ghaction-virustotal" not in текст,
          "файл не отправляется в VirusTotal второй раз: тот ответит 409 и уронит выпуск")

# Безымянный exe без издателя и версии машинное обучение антивирусов
# принимает за сброшенный загрузчик. Сведения о файле у обоих exe.
_спек = (Path(__file__).resolve().parent.parent / "packaging" / "konspekt.spec").read_text(encoding="utf-8")
_исс = (Path(__file__).resolve().parent.parent / "packaging" / "konspekt.iss").read_text(encoding="utf-8-sig")
проверить("version=версия_файла" in _спек and "CompanyName" in _спек,
          "у Konspekt.exe есть сведения о файле: издатель, описание, версия")
проверить("VersionInfoVersion={#AppVersion}" in _исс and "VersionInfoCompany=" in _исс,
          "у установщика есть сведения о файле, а не 0.0.0.0")
# 01.10: с lzma2/max Microsoft клеймил каждую сборку, с zip ни одну.
проверить('#define SetupCompression "zip"' in _исс,
          "установщик сжат zip: сильное сжатие антивирусы принимают за упаковщик")

print()
if ошибки:
    print(f"Не прошло: {len(ошибки)}")
    sys.exit(1)
print("Проверка антивирусами в сборке собрана правильно.")
