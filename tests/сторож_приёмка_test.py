# -*- coding: utf-8 -*-
"""Приёмка сторожа на настоящей программе, а не на её частях.

Зачем отдельно. Всё остальное проверяет части поодиночке: сторож
отдельно, окно отдельно, настройки отдельно. Ровно так в 0.7.0 и вышла
беда: каждая часть работала, а собранная программа не делала ничего,
потому что дорога между частями была разорвана. Здесь настоящие
`AppService` и `Api` — тот самый мост, который зовёт окно.

Подменяем единственное, что обязаны: драйвер звуковой карты. Настоящую
карту в проверке не завести, и это ограничение честно записано.

Сценарий человеческий, от начала до конца:
  1. Konspekt висит в трее, запись не идёт.
  2. Человек открыл Zoom, там говорят.
  3. Программа заметила и предложила записать.
  4. Человек нажал «Записать» — запись пошла.
  5. Сторож на время записи отпустил карту, а после остановки вернулся.
  6. Человек снял галочку в настройках — слежка прекратилась и это
     пережило перезапуск.
"""
from __future__ import annotations

import os
import tempfile
import time
from pathlib import Path

import numpy as np

# Свой каталог данных, и обязательно до импорта программы: иначе
# проверка перепишет настоящие настройки человека.
_ПЕСОЧНИЦА = Path(tempfile.mkdtemp(prefix="konspekt-сторож-"))
os.environ["KONSPEKT_DATA_DIR"] = str(_ПЕСОЧНИЦА)

import testenv  # noqa: F401  русский вывод в консоли Windows

from app.audio import devices, wasapi
from app.core import settings as settings_mod
from app.core.events import SYSTEM_SPEECH_NOTICED, bus
from app.core.service import AppService
from app.storage import Store
from app.ui.api import Api

ЧАСТОТА = 16000
БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def _речь(секунд: float = 120.0) -> np.ndarray:
    """Разговор: слоги двух видов вперемежку с паузами."""
    rng = np.random.default_rng(7)
    куски: list[np.ndarray] = []
    время = 0.0
    while время < секунд:
        длина = rng.uniform(0.12, 0.22)
        n = int(длина * ЧАСТОТА)
        ог = np.hanning(n).astype(np.float32)
        if rng.random() > 0.35:
            t = np.arange(n, dtype=np.float32) / ЧАСТОТА
            ядро = np.sin(2 * np.pi * rng.uniform(90, 220) * t).astype(np.float32)
        else:
            ядро = rng.normal(0, 1.0, n).astype(np.float32)
        куски.append((0.25 * ядро * ог).astype(np.float32))
        время += длина
        пауза = rng.uniform(0.04, 0.10) if rng.random() > 0.15 else rng.uniform(0.35, 0.6)
        куски.append(np.zeros(int(пауза * ЧАСТОТА), dtype=np.float32))
        время += пауза
    return np.concatenate(куски)


class ПоддельнаяКарта:
    """Единственная подмена: сама звуковая карта."""

    name = "Поддельная карта"

    def __init__(self, поток: np.ndarray) -> None:
        self._поток = поток
        self._поз = 0

    def recorder(self, **_):
        return self

    def __enter__(self):
        return self

    def __exit__(self, *_):
        return False

    def record(self, numframes):
        time.sleep(0.001)
        конец = self._поз + numframes
        if конец > len(self._поток):
            self._поз = 0
            конец = numframes
        кусок = self._поток[self._поз:конец]
        self._поз = конец
        return кусок.copy()


def main() -> int:
    речь = _речь()
    было_мик, было_луп = devices.open_microphone, devices.open_loopback
    devices.open_microphone = lambda _id=None: ПоддельнаяКарта(речь)
    devices.open_loopback = lambda _id=None: ПоддельнаяКарта(речь)

    tmp = Path(tempfile.mkdtemp())
    служба = AppService(store=Store(str(tmp / "test.db")))
    служба.settings.asr.enabled = False   # проверяем звук, а не модель
    служба.capture = wasapi.WasapiCapture(
        capture_mic=True, capture_system=True, chunk_seconds=1.0,
    )
    мост = Api(служба)

    предложения: list[dict] = []
    отписаться = bus.on(SYSTEM_SPEECH_NOTICED, предложения.append)

    try:
        # --- 1. Программа висит в трее, запись не идёт -------------------
        проверить(not служба.is_recording, "запись не идёт: программа просто в трее")
        настройки = мост.attention_settings()
        проверить(настройки.get("сторож") is True,
                  "слежка включена по умолчанию: забытая запись — самая "
                  "частая потеря")
        проверить(настройки.get("уведомления") is True,
                  "уведомления включены по умолчанию")

        служба.поднять_сторожа()
        time.sleep(0.5)
        проверить(мост.attention_settings().get("работает") is True,
                  "сторож слушает системный звук, пока записи нет")

        # --- 2. В Zoom говорят, программа замечает ------------------------
        предел = time.monotonic() + 60.0
        while not предложения and time.monotonic() < предел:
            time.sleep(0.05)
        проверить(bool(предложения),
                  "настоящая программа заметила разговор при выключенной записи")
        if not предложения:
            return 1
        проверить(предложения[0].get("секунд", 0) >= 30,
                  "в предложении сказано, сколько уже идёт разговор")

        # --- 3. Человек нажал «Записать» ----------------------------------
        ответ = мост.record_noticed_talk()
        проверить(ответ.get("ok") is True,
                  f"кнопка «Записать» отработала через мост окна ({ответ})")
        проверить(служба.is_recording,
                  "запись действительно пошла, а не только отрапортовала")
        проверить(служба.active_meeting_id is not None,
                  "встреча заведена: записывать есть во что")

        # --- 4. Сторож отпустил карту на время записи ---------------------
        проверить(not служба.сторож.работает,
                  "на время записи сторож отпускает звуковую карту: "
                  "два потока на одном устройстве мешают друг другу")

        # Микрофон при этом пишет.
        время_до = служба.capture._tracks[devices.TRACK_ME].duration
        time.sleep(1.5)
        время_после = служба.capture._tracks[devices.TRACK_ME].duration
        проверить(время_после > время_до,
                  f"встреча пишется ({время_до:.1f}с → {время_после:.1f}с)")

        # --- 5. После остановки сторож вернулся ---------------------------
        служба.stop_recording()
        проверить(not служба.is_recording, "запись кончилась штатно")
        time.sleep(0.5)
        проверить(служба.сторож.работает,
                  "после встречи сторож снова слушает: иначе слежка работала "
                  "бы ровно до первой записи за запуск программы")

        # И не спрашивает заново про тот же самый звук, который всё это
        # время играл: человек уже ответил на него нажатием «Записать».
        предложения.clear()
        time.sleep(14.0)
        проверить(not предложения,
                  f"про тот же звук после записи не переспрашивают "
                  f"(было {len(предложения)})")

        # --- 6. Человек снял галочку --------------------------------------
        итог = мост.save_attention_settings({"сторож": False})
        проверить(итог.get("сторож") is False, "галочка слежки снята")
        time.sleep(0.5)
        проверить(not служба.сторож.работает,
                  "снятая галочка действует сразу, а не после перезапуска")
        заново = settings_mod.load()
        проверить(заново.внимание.сторож is False,
                  "выбор человека пережил перезапуск программы")

        предложения.clear()
        служба.поднять_сторожа()
        time.sleep(3.0)
        проверить(not служба.сторож.работает,
                  "выключенную слежку не поднимает даже прямой вызов")
        проверить(not предложения,
                  f"выключенная слежка молчит (было {len(предложения)})")

        # Уведомления выключаются отдельно от слежки: это разные вещи.
        мост.save_attention_settings({"сторож": True, "уведомления": False})
        заново = settings_mod.load()
        проверить(заново.внимание.уведомления is False
                  and заново.внимание.сторож is True,
                  "уведомления и слежка переключаются независимо")

    finally:
        try:
            if служба.is_recording:
                служба.stop_recording()
        except Exception:
            pass
        try:
            служба.сторож.остановить()
        except Exception:
            pass
        отписаться()
        devices.open_microphone, devices.open_loopback = было_мик, было_луп

    if БЕДЫ:
        print(f"\nНе прошло проверок: {len(БЕДЫ)}")
        return 1
    print("\nПриёмка пройдена: программа сама замечает разговор и слушается ответа.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
