# -*- coding: utf-8 -*-
"""Уже записанное до выключения: помечаем, а не выбрасываем.

Из задачи №28: «Если человек выключил системный звук на третьей минуте,
первые три минуты в транскрипте уже лежат. Надо решить: убрать их,
пометить или оставить. Тихо оставить, наверное, нельзя — они и есть
источник испорченного саммари».

Решение: помечаем. Удалять нельзя — человек мог ошибиться, а записанное
уже не вернуть. Тихо оставить нельзя — ровно эти реплики и превращают
пересказ ролика в «решения встречи». Поэтому реплика остаётся в
расшифровке, видна приглушённой, но в заметки не идёт.
"""
from __future__ import annotations

import tempfile
from pathlib import Path

import testenv  # noqa: F401  русский вывод в консоли Windows

from app.core.models import Meeting, Speaker, TranscriptSegment
from app.storage import Store

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def _встреча_с_репликами(store: Store) -> str:
    встреча = store.create_meeting(Meeting(title="Встреча с роликом"))
    # Первые три минуты: чужой ролик в системном звуке и своя речь.
    store.add_segment(TranscriptSegment(
        meeting_id=встреча.id, speaker=Speaker.THEM, text="озвучка ролика",
        start=10.0, end=12.0,
    ))
    store.add_segment(TranscriptSegment(
        meeting_id=встреча.id, speaker=Speaker.ME, text="моя реплика",
        start=15.0, end=17.0,
    ))
    store.add_segment(TranscriptSegment(
        meeting_id=встреча.id, speaker=Speaker.THEM, text="ещё кусок ролика",
        start=100.0, end=102.0,
    ))
    return встреча.id


def проверить_пометку() -> None:
    store = Store(str(Path(tempfile.mkdtemp()) / "t.db"))
    mid = _встреча_с_репликами(store)

    сколько = store.mark_doubtful(mid, Speaker.THEM.value, 200.0)
    проверить(сколько == 2, f"помечены обе реплики системного звука (было {сколько})")

    реплики = {с.text: с for с in store.list_segments(mid)}
    проверить(реплики["озвучка ролика"].doubtful,
              "реплика ролика помечена")
    проверить(реплики["ещё кусок ролика"].doubtful,
              "вторая реплика ролика помечена")
    проверить(not реплики["моя реплика"].doubtful,
              "своя речь не помечена: человек говорил сам, и это не под сомнением")

    # Ничего не пропало: удалять нельзя, человек мог ошибиться.
    проверить(len(store.list_segments(mid)) == 3,
              "все реплики на месте, ничего не удалено")


def проверить_границу() -> None:
    """Помечается только то, что записано ДО ответа человека."""
    store = Store(str(Path(tempfile.mkdtemp()) / "t.db"))
    mid = _встреча_с_репликами(store)

    # Человек ответил на 50-й секунде: вторая реплика ролика (100с) ещё
    # не звучала и под сомнение попадать не должна.
    сколько = store.mark_doubtful(mid, Speaker.THEM.value, 50.0)
    проверить(сколько == 1, f"помечена только ранняя реплика (было {сколько})")

    реплики = {с.text: с for с in store.list_segments(mid)}
    проверить(реплики["озвучка ролика"].doubtful, "ранняя реплика помечена")
    проверить(not реплики["ещё кусок ролика"].doubtful,
              "поздняя реплика не помечена: её тогда ещё не было")


def проверить_саммари() -> None:
    """Помеченное не идёт в заметки, но остаётся в расшифровке."""
    from app.core.service import AppService

    tmp = Path(tempfile.mkdtemp())
    store = Store(str(tmp / "t.db"))
    служба = AppService(store=store)
    mid = _встреча_с_репликами(store)

    текст = служба.transcript_text(mid)
    проверить("озвучка ролика" in текст,
              "до пометки ролик попадает в заметки (в этом и беда)")

    store.mark_doubtful(mid, Speaker.THEM.value, 200.0)
    текст = служба.transcript_text(mid)

    проверить("озвучка ролика" not in текст,
              f"после пометки ролик в заметки не идёт (текст: {текст!r})")
    проверить("ещё кусок ролика" not in текст,
              "вторая реплика ролика тоже не идёт")
    проверить("моя реплика" in текст,
              "своя речь по-прежнему попадает в заметки")

    # В расшифровке всё на месте: человек должен видеть, что было.
    видно = [с.text for с in store.list_segments(mid)]
    проверить("озвучка ролика" in видно,
              "в расшифровке реплика осталась: вдруг человек ошибся")


def проверить_старую_базу() -> None:
    """Старый архив открывается, и там ничего не помечено."""
    store = Store(str(Path(tempfile.mkdtemp()) / "t.db"))
    mid = _встреча_с_репликами(store)
    реплики = store.list_segments(mid)
    проверить(all(not с.doubtful for с in реплики),
              "по умолчанию ничего не под сомнением: человека не спрашивали")


def main() -> int:
    проверить_пометку()
    проверить_границу()
    проверить_саммари()
    проверить_старую_базу()

    if БЕДЫ:
        print(f"\nНе прошло проверок: {len(БЕДЫ)}")
        return 1
    print("\nЗаписанное до выключения помечено и в заметки не идёт.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
