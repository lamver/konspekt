# -*- coding: utf-8 -*-
"""Папки встреч: сервис и база.

Что сторожит:
1. Встреча, начатая в папке, сразу в ней.
2. Перенести встречу в другую папку и вынуть обратно.
3. Удалили папку — встречи целы и вернулись в общий список.
4. Удалили встречу — привязка к папке ушла, счётчик папки уменьшился.
5. Перенос в несуществующую папку не ломает встречу и не создаёт мусор.
6. Пустое имя папки не принимается, длинное и с переносами приводится
   в порядок.
7. Свёрнутые папки переживают перезапуск.
8. База, в которой уже есть папки, открывается снова без ошибок.
"""
from __future__ import annotations

import testenv  # noqa: F401  песочница вместо боевого профиля

import tempfile
from pathlib import Path

from app.audio import NullCapture
from app.core import settings as settings_mod
from app.core.service import AppService
from app.storage.db import Store

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


база = Path(tempfile.mkdtemp()) / "t.db"
с = AppService(store=Store(str(база)), capture=NullCapture())
try:
    звонки = с.create_folder("Звонки клиентам")
    планёрки = с.create_folder("  Планёрки\n команды  ")
    проверить(планёрки["name"] == "Планёрки команды", f"имя без лишних пробелов и переносов: {планёрки['name']!r}")
    проверить(с.create_folder("")["name"] == "Новая папка", "папка без имени получает имя по умолчанию")
    проверить(len(с.create_folder("я" * 300)["name"]) == 80, "длинное имя обрезается до 80 знаков")

    # --- 1. Встреча в папке ---------------------------------------------------
    в_папке = с.create_meeting(folder_id=звонки["id"])
    проверить(в_папке["folder_id"] == звонки["id"], "встреча, начатая в папке, сразу в ней")
    обычная = с.create_meeting()
    проверить(обычная["folder_id"] is None, "обычная встреча вне папок")
    встречи = {m["id"]: m for m in с.list_meetings()}
    проверить(встречи[в_папке["id"]]["folder_id"] == звонки["id"] and встречи[обычная["id"]]["folder_id"] is None,
              "список встреч знает, какая где")
    проверить(с.get_meeting(в_папке["id"])["folder_id"] == звонки["id"], "открытая встреча знает свою папку")

    # --- 2. Перенос -----------------------------------------------------------
    проверить(с.move_meeting(обычная["id"], планёрки["id"])["ok"], "встречу можно перенести в папку")
    проверить(с.move_meeting(обычная["id"], звонки["id"])["ok"], "и в другую папку")
    папки = {f["id"]: f for f in с.list_folders()}
    проверить(папки[звонки["id"]]["count"] == 2 and папки[планёрки["id"]]["count"] == 0,
              f"встреча лежит в одной папке, а не в двух: {папки[звонки['id']]['count']}, {папки[планёрки['id']]['count']}")
    проверить(с.move_meeting(обычная["id"], None)["ok"], "встречу можно вынуть из папки")
    проверить({m["id"]: m for m in с.list_meetings()}[обычная["id"]]["folder_id"] is None, "и она снова вне папок")

    # --- 5. Несуществующая папка ----------------------------------------------
    проверить(not с.move_meeting(обычная["id"], "нет-такой")["ok"], "в несуществующую папку не переносится")
    проверить({m["id"]: m for m in с.list_meetings()}[обычная["id"]]["folder_id"] is None,
              "и встреча от этого не пострадала")
    проверить(не := с.create_meeting(folder_id="нет-такой"), "встреча в несуществующей папке всё равно создаётся")
    проверить(не["folder_id"] is None, "но вне папок, а не в пустоте")

    # --- 6. Имя ---------------------------------------------------------------
    проверить(not с.rename_folder(звонки["id"], "   ")["ok"], "пустое имя при переименовании не принимается")
    проверить(с.rename_folder(звонки["id"], "Продажи")["ok"], "папку можно переименовать")
    проверить({f["id"]: f for f in с.list_folders()}[звонки["id"]]["name"] == "Продажи", "новое имя сохранилось")

    # --- 4. Удалили встречу ---------------------------------------------------
    с.delete_meeting(в_папке["id"])
    проверить({f["id"]: f for f in с.list_folders()}[звонки["id"]]["count"] == 0,
              "удалили встречу — счётчик папки уменьшился")

    # --- 3. Удалили папку -----------------------------------------------------
    третья = с.create_meeting(folder_id=звонки["id"])
    проверить(с.delete_folder(звонки["id"])["ok"], "папку можно удалить")
    ids = {m["id"]: m for m in с.list_meetings()}
    проверить(третья["id"] in ids and ids[третья["id"]]["folder_id"] is None,
              "встреча из удалённой папки цела и вернулась в общий список")
    проверить(звонки["id"] not in {f["id"] for f in с.list_folders()}, "удалённой папки нет в списке")

    # --- 7. Свёрнутые папки ---------------------------------------------------
    с.set_collapsed_folders([планёрки["id"]])
    проверить(settings_mod.load().collapsed_folders == [планёрки["id"]], "свёрнутые папки сохранены в настройках")
finally:
    с.store.close()

# --- 8. Повторное открытие ----------------------------------------------------
снова = Store(str(база))
try:
    проверить(any(f["name"] == "Планёрки команды" for f in снова.list_folders()),
              "база с папками открывается снова, папки на месте")
finally:
    снова.close()

print()
print("Всё в порядке" if not БЕДЫ else f"Бед: {len(БЕДЫ)}")
raise SystemExit(1 if БЕДЫ else 0)
