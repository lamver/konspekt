# -*- coding: utf-8 -*-
"""Разборы без модели: разговор по времени реплик и тон по словам.

Цифры здесь человек примет на веру: «Анна говорила 70%» не
перепроверяют. Поэтому каждое число сверяем с посчитанным вручную, а
крайние случаи (пустая встреча, реплика без конца, одна дорожка,
шумовые голоса) — с тем, что честно можно сказать.
"""
from __future__ import annotations

import testenv  # noqa: F401  русский вывод в консоли Windows

from app.core import analysis as а

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def р(who, start, end, text="слово", track="them"):
    return {"who": who, "start": start, "end": end, "text": text, "track": track}


# --- Пустое ----------------------------------------------------------------
проверить(а.разговор([])["markdown"] == "" and а.тон([])["markdown"] == "", "пустая встреча — пустой разбор")
проверить(а.разговор([р("А", 0, 1, "   ")])["markdown"] == "", "реплики из пробелов не считаются")

# --- Доли и монологи --------------------------------------------------------
встреча = [
    р("Анна", 0, 30, "Расскажу про проект.", "them"),
    р("Анна", 30.5, 60, "И ещё про сроки.", "them"),     # склеивается в монолог
    р("Я", 61, 71, "А бюджет какой?", "me"),
    р("Анна", 80, 90, "Сто тысяч.", "them"),            # пауза 9 с
]
к = а.разговор(встреча)
люди = {ч["who"]: ч for ч in к["people"]}
проверить(люди["Анна"]["share"] == 87 and люди["Я"]["share"] == 13,
          f"доли по времени речи: Анна {люди['Анна']['share']}%, Я {люди['Я']['share']}%")
проверить(abs(к["totals"]["longest"]["seconds"] - 60) < 0.01 and к["totals"]["longest"]["who"] == "Анна",
          "реплики одного голоса без паузы — один монолог")
проверить(к["totals"]["turn_changes"] == 2, f"смен говорящего 2, а не {к['totals']['turn_changes']}")
проверить(к["totals"]["questions"] == 1, "вопросы считаются по знаку вопроса")
проверить(к["totals"]["long_pauses"] == 1, "пауза в 9 секунд замечена")
проверить("это скорее монолог" in к["markdown"], "перекос в 87% назван")
проверить("Перебиваний" in к["markdown"], "при двух дорожках перебивания показаны")
проверить(abs(к["totals"]["duration"] - 90) < 0.01, "длительность от первой реплики до конца последней")

# --- Одна дорожка: перебиваний не видно, и мы не врём «ноль» ----------------
одна = [р("А", 0, 10, track="them"), р("Б", 5, 15, track="them")]
к = а.разговор(одна)
проверить("Перебиваний" not in к["markdown"] and к["totals"]["interruptions"] is None,
          "у записи с одной дорожкой перебивания не показываются")

# --- Перебивание: наложение больше захлёста ---------------------------------
две = [р("А", 0, 10, track="me"), р("Б", 9.8, 12, track="them"), р("А", 11, 14, track="me")]
к = а.разговор(две)
проверить(к["totals"]["interruptions"] == 1,
          f"ответ через 0.2 с — очередь, наложение на секунду — перебивание: {к['totals']['interruptions']}")

# --- Шумовые голоса сворачиваются ------------------------------------------
шум = [р("Анна", 0, 300), р("Я", 300, 600)] + [р(f"Голос {i}", 600 + i, 600.5 + i) for i in range(30)]
к = а.разговор(шум)
строки = [с for с in к["markdown"].splitlines() if с.startswith("- ")]
проверить(sum("Голос" in с for с in строки) == 0 and any("Короткие реплики других голосов (30)" in с for с in строки),
          "тридцать голосов по полсекунды — одна строка, а не тридцать")
проверить(к["totals"]["speakers"] == 2, "заметных говорящих двое")
проверить("почти поровну" in к["markdown"], "диалог пополам назван диалогом")

# --- Кривые данные ----------------------------------------------------------
кривые = [{"who": None, "start": None, "end": None, "text": "да"}, {"who": "А", "start": 5, "end": 2, "text": "нет"}]
к = а.разговор(кривые)
проверить(bool(к["markdown"]), "реплика без времени и с концом раньше начала не роняет разбор")

# --- Длинный монолог и встреча без вопросов ---------------------------------
к = а.разговор([р("А", 0, 200), р("Б", 201, 400)])
проверить("дольше трёх минут" in к["markdown"], "монолог больше трёх минут замечен")
к = а.разговор([р("А", 0, 200, "Рассказываю."), р("Б", 201, 400, "Понятно.")])
проверить("ни одного вопроса" in к["markdown"], "пять минут без вопросов замечены")

# --- Живая запись: один голос, без пунктуации --------------------------------
# Так выглядит самая длинная встреча в архиве: 1663 реплики одного голоса
# без единой точки. Разбор обязан не врать про неё.
диктовка = [р("Я", i * 10, i * 10 + 9.5, "ну вот так и делаем", "me") for i in range(60)]
к = а.разговор(диктовка)
проверить(к["totals"]["turn_changes"] == 0, f"один голос — ни одной смены говорящего, а не {к['totals']['turn_changes']}")
проверить("потеряли" not in к["markdown"], "у диктовки в одиночку нет «собеседника потеряли»")
проверить("Вопросов" not in к["markdown"] and "ни одного вопроса" not in к["markdown"],
          "без пунктуации о вопросах молчим, а не пишем ноль")

# --- Тон ---------------------------------------------------------------------
мало = а.тон([р("А", 0, 5, "я думаю наверно да")])
проверить("Слишком мало речи" in мало["markdown"], "на трёх словах о тоне не судим")

сомневается = " ".join(["наверно это может сработать, кажется, я не уверен"] * 15)
уверен = " ".join(["мы точно сделаем, конечно, мы договорились, отлично"] * 15)
т = а.тон([р("Петя", 0, 60, сомневается), р("Маша", 60, 120, уверен)])
по = {ч["who"]: ч["per100"] for ч in т["people"]}
проверить(по["Петя"]["сомнение"] > по["Петя"]["уверенность"], "сомнения Пети посчитаны")
проверить(по["Маша"]["мы"] > по["Маша"]["я"] and по["Маша"]["уверенность"] > 0, "Маша говорит «мы» и уверенно")
проверить("Петя часто сомневается" in т["markdown"], "сомнение названо")
проверить("Маша говорит от лица команды" in т["markdown"], "«мы» названо")
проверить("не оценка человека" in т["markdown"], "есть оговорка, что это подсказка")

ради = " ".join(["ради радио классификация суперобложка"] * 30)
т = а.тон([р("А", 0, 60, ради)])
проверить(т["people"][0]["per100"]["позитив"] == 0, "«ради», «радио», «классификация» — не одобрение")
т = а.тон([р("А", 0, 60, " ".join(["я рад, это классно, супер"] * 30))])
проверить(т["people"][0]["per100"]["позитив"] > 0, "«рад», «классно», «супер» — одобрение")
т = а.тон([р("А", 0, 60, " ".join(["яблоко нести нельзяшка мыло"] * 30))])
проверить(т["people"][0]["per100"]["я"] == 0 and т["people"][0]["per100"]["мы"] == 0
          and т["people"][0]["per100"]["отрицание"] == 0,
          "«яблоко», «мыло», «нести» — не «я», «мы» и «не»")
т = а.тон([р("А", 0, 60, " ".join(["правительство решило"] * 60))])
проверить(т["people"][0]["per100"]["уверенность"] == 0 and т["people"][0]["per100"]["я"] == 0,
          "«решило» и «правительство» мимо словарей")

print()
print("Всё в порядке" if not БЕДЫ else f"Бед: {len(БЕДЫ)}")
raise SystemExit(1 if БЕДЫ else 0)
