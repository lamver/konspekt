"""Досчёт не должен мешать следующей встрече.

Досчёт кладёт куски в ту же очередь распознавания, что и живая речь, и
делает это с `block=True`: ждёт места сколько нужно. Пока встреча одна,
это правильно — торопиться некуда, терять нечего.

Но человек может нажать «новая встреча», не дожидаясь конца досчёта:
досчёт идёт фоном, встреча уже помечена готовой, и повода ждать у
человека нет. Тогда досчёт старой встречи и живая речь новой борются за
одни и те же места в очереди. Живая речь мест не ждёт (иначе
заблокируется захват звука) — она их просто теряет.

Здесь проверяется, что в этой борьбе живая речь не проигрывает.
"""
from __future__ import annotations

import tempfile
import threading
import time
from pathlib import Path

import numpy as np

import testenv  # noqa: F401  русский вывод в консоли Windows

from app.asr.queue import BACKFILL_RESERVE, MAX_PENDING, TranscriptionQueue
from app.core.models import Speaker, TranscriptSegment

RATE = 16000
БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


class МедленнаяМодель:
    """Модель, которая не успевает: ровно тот случай, ради которого досчёт.

    Скорость здесь не выдумана «для теста»: очередь переполняется именно
    тогда, когда распознавание медленнее речи, и проверять поведение
    очереди на быстрой модели бессмысленно — она никогда не переполнится.
    """

    name = "медленная"
    languages = ("ru",)

    def __init__(self, задержка: float = 0.05) -> None:
        self.задержка = задержка
        self.распознано: list[str] = []
        self._lock = threading.Lock()

    def transcribe(self, pcm, sample_rate, meeting_id, offset, speaker, **_):
        time.sleep(self.задержка)
        with self._lock:
            self.распознано.append(meeting_id)
        return [TranscriptSegment(
            meeting_id=meeting_id, speaker=Speaker(speaker),
            text=f"кусок {offset:.1f}", start=offset,
            end=offset + len(pcm) / sample_rate,
        )]


def main() -> int:
    tempfile.mkdtemp(prefix="konspekt-rivalry-")
    модель = МедленнаяМодель()
    готовые: list[TranscriptSegment] = []
    q = TranscriptionQueue(модель, on_segment=готовые.append, use_vad=False)
    q.start()

    кусок = np.zeros(RATE // 2, dtype=np.int16)

    # Досчёт старой встречи: много кусков, каждый с block=True. Ровно так
    # его запускает _run_backfill после кнопки «стоп».
    досчёт_кусков = MAX_PENDING * 3

    def досчёт() -> None:
        for i in range(досчёт_кусков):
            q.submit_raw("старая", "me", кусок, float(i), block=True)

    поток = threading.Thread(target=досчёт, name="досчёт", daemon=True)
    поток.start()

    # Даём досчёту набрать свой потолок: это его обычное состояние, он
    # ведь не ждёт ничего, кроме места.
    time.sleep(0.5)
    занято = q.pending
    потолок = MAX_PENDING - BACKFILL_RESERVE
    print(f"       мест в очереди занято досчётом: {занято} "
          f"(потолок досчёта {потолок} из {MAX_PENDING})")
    # Без этой проверки тест был бы обманом самого себя: если досчёт не
    # успел набрать свой потолок, живой речи никто не мешает, и зелёный
    # результат ничего не значит.
    проверить(занято >= потолок - 2,
              f"досчёт действительно упёрся в свой потолок ({занято} из {потолок}), "
              f"иначе соперничества нет и проверять нечего")
    # И при этом он обязан оставить место живой речи. Раньше этой границы
    # не было вовсе: досчёт забивал очередь целиком.
    проверить(занято <= потолок,
              f"досчёт не занимает всю очередь, запас живой речи цел "
              f"({занято} из {MAX_PENDING})")

    # Человек начал новую встречу и говорит. Живая речь места не ждёт:
    # именно submit(block=False), как её шлёт захват звука через
    # AppService._on_chunk. Со значением по умолчанию у submit_raw
    # (block=True) тест был бы обманом: «живая» речь тихо ждала бы
    # места вместо того, чтобы теряться, и потерь не было бы никогда.
    #
    # Темп подачи взят из жизни, а не «как можно быстрее». Захват отдаёт
    # кусок раз в chunk_seconds (5 с), а распознавание такого куска
    # занимает заметно меньше — иначе программа не работала бы вовсе.
    # Здесь те же пропорции в уменьшенном виде: модель считает кусок
    # 0.05 с, значит куски идут раз в 0.15 с. Слать их вплотную значило
    # бы проверять не досчёт, а поведение очереди при взрыве, которого в
    # записи звука не бывает.
    было_потеряно = q.dropped
    живых = 40
    for i in range(живых):
        q.submit("новая", "me", кусок, float(i), block=False)
        time.sleep(0.15)

    потеряно_живых = q.dropped - было_потеряно
    print(f"       живых кусков: {живых}, из них потеряно: {потеряно_живых}")

    поток.join(60)
    q.wait_idle(timeout=60)
    q.stop(timeout=30)

    новых_дошло = sum(1 for s in готовые if s.meeting_id == "новая")
    print(f"       до расшифровки новой встречи дошло: {новых_дошло} из {живых}")

    # Главное: живая речь новой встречи не должна тонуть в досчёте старой.
    # Немного потерь допустимо (очередь конечна, машина занята), но не
    # большинство: иначе человек говорит, а на экране пусто.
    проверить(новых_дошло >= живых * 0.8,
              f"живая речь новой встречи доходит до расшифровки, "
              f"несмотря на идущий досчёт старой ({новых_дошло} из {живых})")

    # И сам досчёт при этом не должен потеряться: он для того и затеян.
    старых_дошло = sum(1 for s in готовые if s.meeting_id == "старая")
    проверить(старых_дошло == досчёт_кусков,
              f"досчёт старой встречи доведён до конца "
              f"({старых_дошло} из {досчёт_кусков})")

    if БЕДЫ:
        print(f"\nПровалено проверок: {len(БЕДЫ)}")
        return 1
    print("\nДосчёт прошлой встречи не съедает живую речь следующей")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
