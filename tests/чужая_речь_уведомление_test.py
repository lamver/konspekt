"""Вопрос про чужой звук доходит до человека даже при свёрнутом окне.

В задаче №28 это записано прямым текстом: «спрашивать заметно, вплоть
до системного уведомления: окно записи часто свёрнуто, и подсказка
внутри него никого не спасёт». Плашка внутри окна этого не решает: во
время встречи Konspekt обычно сидит в трее, и человек увидит вопрос
через час, когда ролик уже уехал в расшифровку.

Трей поднимать не будем: он требует свой цикл событий и живого рабочего
стола. Проверяем то, что важно — что трей подписан на событие и зовёт
показ уведомления.
"""
from __future__ import annotations

import types

import testenv  # noqa: F401  русский вывод в консоли Windows

from app.core.events import RECORDING_FOREIGN_SPEECH, RECORDING_STARTED, bus
from app.tray.icon import TrayIcon
from app.ui import уведомления

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def main() -> int:
    трей = TrayIcon()

    # Подменяем показ: настоящий тост требует живого рабочего стола, а
    # pystray — своего цикла событий.
    тосты: list[dict] = []
    облачка: list[tuple] = []
    прежний = уведомления.показать_вопрос
    уведомления.показать_вопрос = lambda **к: (тосты.append(к) or True)
    трей._icon = types.SimpleNamespace(
        notify=lambda сообщение, заголовок=None: облачка.append((сообщение, заголовок)),
        icon=None,
        title="",
    )

    try:
        bus.emit(RECORDING_FOREIGN_SPEECH, {"track": "them", "признаки": {}})

        проверить(bool(тосты),
                  "трей показал уведомление с кнопками: человек узнает о "
                  "беде и ответит, не открывая окно")
        if тосты:
            т = тосты[0]
            проверить("систем" in т["текст"].lower(),
                      f"в уведомлении сказано, о чём речь ({т['текст'][:60]})")
            проверить("konspekt" in т["заголовок"].lower(),
                      f"уведомление подписано программой ({т['заголовок']})")
            проверить(len(т["текст"]) < 200,
                      f"уведомление короткое, его дочитают ({len(т['текст'])} знаков)")
            # Главное: ответить можно прямо из угла экрана.
            проверить({т["ответ1"], т["ответ2"]} == {"off", "keep"},
                      f"в уведомлении обе кнопки ответа ({т['ответ1']}, {т['ответ2']})")
            проверить(bool(т["кнопка1"].strip()) and bool(т["кнопка2"].strip()),
                      "кнопки подписаны словами, а не пустые")

        # Пока тост показан, дублировать «облачком» незачем: два
        # уведомления об одном и том же раздражают сильнее одного.
        проверить(not облачка,
                  f"тост не дублируется старым облачком (было {len(облачка)})")
    finally:
        уведомления.показать_вопрос = прежний

    # Чужие события трей уведомлением не сопровождает: иначе на каждую
    # запись сыпались бы всплывашки.
    тосты.clear()
    облачка.clear()
    прежний = уведомления.показать_вопрос
    уведомления.показать_вопрос = lambda **к: (тосты.append(к) or True)
    try:
        bus.emit(RECORDING_STARTED, {"meeting_id": "m1", "started_at": 0})
    finally:
        уведомления.показать_вопрос = прежний
    проверить(not тосты and not облачка,
              f"обычный старт записи уведомлением не сопровождается "
              f"(было {len(тосты) + len(облачка)})")

    # Поломка уведомлений не имеет права ронять запись.
    тосты.clear()

    def падать(*_а, **_к):
        raise RuntimeError("уведомления недоступны")

    прежний = уведомления.показать_вопрос
    уведомления.показать_вопрос = падать
    трей._icon = types.SimpleNamespace(notify=падать, icon=None, title="")
    try:
        bus.emit(RECORDING_FOREIGN_SPEECH, {"track": "them", "признаки": {}})
        упало = False
    except Exception:
        упало = True
    finally:
        уведомления.показать_вопрос = прежний
    проверить(not упало,
              "система без уведомлений не роняет программу: встреча важнее")

    if БЕДЫ:
        print(f"\nНе прошло проверок: {len(БЕДЫ)}")
        return 1
    print("\nВопрос про чужой звук доходит до человека мимо окна.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
