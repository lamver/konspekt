# -*- coding: utf-8 -*-
"""Граница сборки: доехали ли строки плашки до готовой программы.

Словари едут внутрь дистрибутива целой папкой web. Это удобно и потому
опасно: забытый ключ обнаружится не здесь, а у человека на экране, в
виде «recording.silent_where» вместо предупреждения. Смотрим не исходники,
а то, что лежит в собранной программе.

Смотрим только на dist: там лежит свежая сборка этого кода.
Установленная программа нарочно не трогается: у человека там стоит
выпущенная версия, и она законно старее того, что мы только что
починили. Путать эти две вещи — значит ловить ложную тревогу при
каждом прогоне до выпуска.

Если сборки нет, честно пропускаем: на чужой машине её и не должно быть.
"""
import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

НУЖНЫЕ = ["silent_mic", "silent_system", "silent_where", "silent_hint"]
ЯЗЫКИ = ["ru", "en", "es", "sr"]

места = [Path("dist/Konspekt/_internal/web/i18n")]

нашли = False
плохо = 0
for место in места:
    if not место.exists():
        print(f"[нет] {место}")
        continue
    нашли = True
    print(f"[есть] {место}")
    for язык in ЯЗЫКИ:
        файл = место / f"{язык}.json"
        if not файл.exists():
            print(f"   [ПЛОХО] нет словаря {язык}")
            плохо += 1
            continue
        раздел = json.loads(файл.read_text(encoding="utf-8")).get("recording", {})
        пропало = [к for к in НУЖНЫЕ if к not in раздел]
        if пропало:
            print(f"   [ПЛОХО] {язык}: не доехали {пропало}")
            плохо += 1
        else:
            образец = раздел["silent_where"].replace("{track}", раздел["silent_system"])
            print(f"   [ok] {язык}: {образец.replace('{seconds}', '10')}")

    # Код окна тоже едет целиком: если там старый app.js, плашка снова
    # будет русской у всех. Ищем именно место вызова, а не имя где-то в
    # файле: переименованная функция содержала бы старое имя как часть
    # нового, и проверка проспала бы подмену.
    appjs = место.parent / "app.js"
    if appjs.exists():
        текст = appjs.read_text(encoding="utf-8")
        if "showToast(silentMessage(payload)" in текст:
            print("   [ok] app.js в сборке умеет собирать текст плашки сам")
        else:
            print("   [ПЛОХО] app.js в сборке старый: плашка останется русской")
            плохо += 1

if not нашли:
    print("[пропуск] собранной программы на этой машине нет")
    sys.exit(0)
sys.exit(1 if плохо else 0)
