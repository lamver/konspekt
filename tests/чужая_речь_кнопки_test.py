"""Кнопки в системном уведомлении управляют работающей программой.

Задача №28 требует спрашивать заметно, «вплоть до системного
уведомления», и давать ответить в один щелчок. Плашка в окне этого не
решает: во время встречи Konspekt сидит в трее.

Windows умеет только одно: по нажатию кнопки запустить программу с
аргументом. Поэтому цепочка такая:

    кнопка → konspekt:off → второй запуск → файл ответа → работающая копия

Рвётся она молча в любом звене, и человек этого не заметит: кнопка
нажалась, а звук как писался, так и пишется. Здесь проверяем каждое
звено отдельно.
"""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import testenv  # noqa: F401  русский вывод в консоли Windows

from app.ui import уведомления

БЕДЫ: list[str] = []


def проверить(ок: bool, что: str) -> None:
    print(("[ок] " if ок else "[БЕДА] ") + что)
    if not ок:
        БЕДЫ.append(что)


def проверить_разбор_аргумента() -> None:
    """Ответ приезжает ссылкой в командной строке."""
    import app.__main__ as точка_входа

    было = sys.argv
    try:
        for аргумент, ждём in (
            (["konspekt:off"], "off"),
            (["konspekt:keep"], "keep"),
            (["konspekt:OFF"], "off"),          # регистр приходит разный
            (["konspekt:off/"], "off"),         # Windows дописывает слеш
            (["--что-то", "konspekt:keep"], "keep"),
        ):
            sys.argv = ["app"] + аргумент
            получили = точка_входа._ответ_из_уведомления()
            проверить(получили == ждём,
                      f"{аргумент[-1]} разобран как {ждём} (получили {получили})")

        # Чужое и мусор игнорируем: в командную строку прилетает что
        # угодно, и слепо ему верить нельзя.
        for мусор in (["konspekt:rm-rf"], ["другое:off"], ["просто-текст"], []):
            sys.argv = ["app"] + мусор
            проверить(точка_входа._ответ_из_уведомления() is None,
                      f"мусор {мусор} не принят за ответ")
    finally:
        sys.argv = было


def проверить_передачу() -> None:
    """Ответ доезжает от второго запуска к работающей копии."""
    каталог = Path(tempfile.mkdtemp())

    проверить(уведомления.прочитать_ответ(каталог) is None,
              "на пустом месте ответа нет")

    уведомления.записать_ответ(каталог, "off")
    проверить(уведомления.прочитать_ответ(каталог) == "off",
              "ответ доехал до работающей копии")

    # Второй раз того же ответа быть не должно: иначе одно нажатие
    # выключало бы звук на каждой следующей встрече.
    проверить(уведомления.прочитать_ответ(каталог) is None,
              "прочитанный ответ не исполняется повторно")


def проверить_текст_тоста() -> None:
    """XML тоста не должен ломаться на кавычках и скобках."""
    опасно = 'Ролик «Как <b>всё</b> устроено» & "прочее"'
    чисто = уведомления._экранировать(опасно)
    for знак in ("<b>", "&&", '"'):
        проверить(знак not in чисто,
                  f"опасный знак {знак} экранирован (получилось: {чисто[:50]})")
    проверить("&lt;" in чисто and "&amp;" in чисто,
              "экранирование сделано по правилам XML")


def проверить_защиту() -> None:
    """Уведомления — вежливость, а не работа: их поломка не роняет запись."""
    проверить(уведомления.доступны() == (sys.platform == "win32"),
              "на не-Windows тосты честно объявляются недоступными")

    # Каталог, которого нет: запись ответа не имеет права падать.
    нет_такого = Path(tempfile.mkdtemp()) / "нет" / "и" / "не" / "будет"
    try:
        уведомления.записать_ответ(нет_такого, "off")
        упало = False
    except Exception:
        упало = True
    проверить(not упало, "недоступный каталог не роняет программу")

    try:
        значение = уведомления.прочитать_ответ(нет_такого)
        упало = False
    except Exception:
        значение = None
        упало = True
    проверить(not упало and значение is None,
              "чтение из несуществующего каталога безопасно")


def main() -> int:
    проверить_разбор_аргумента()
    проверить_передачу()
    проверить_текст_тоста()
    проверить_защиту()

    if БЕДЫ:
        print(f"\nНе прошло проверок: {len(БЕДЫ)}")
        return 1
    print("\nКнопки уведомления доносят ответ до работающей программы.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
