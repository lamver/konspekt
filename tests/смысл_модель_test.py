"""Настоящая модель смысла: понимает ли она русский так, как мы ждём.

Поддельная модель в смысл_test.py проверяет всё вокруг, но не саму
модель. А ломается модель тихо: забыли приставку «query: » — поиск
работает, только хуже; перепутали среднее с первым кусочком — тоже
работает, только хуже. Ни одна такая ошибка не роняет программу, их
видно лишь по тому, что нашлось не то.

Поэтому проверяем по смыслу, на фразах из настоящих встреч: запрос
обязан оказаться ближе к своей фразе, чем к чужой, хотя общих слов у
них нет.

Нужны скачанные веса (135 МБ). Без них проверка говорит об этом и
пропускается: качать их на каждый прогон незачем.
"""

from __future__ import annotations

import testenv  # noqa: F401

import sys
import time

import numpy as np

from app.core import paths
from app.search import model as model_mod
from app.search.model import MODEL_DIR_NAME, MeaningModel, mean_pool

провалов = 0


def проверить(условие: bool, что: str) -> None:
    global провалов
    print(f"[{'ok' if условие else 'FAIL'}] {что}")
    if not условие:
        провалов += 1


# Пары «запрос → фраза из встречи» без общих слов и чужие фразы рядом.
# Взяты из настоящего архива, на котором модель выбирали.
ПАРЫ = [
    ("тестовые платежи картой",
     "Нельзя будет проводить эти тестовые платежи без прохождения верификации"),
    ("нагрузка на сеть",
     "Таких клиентов может быть параллельно много, и они могут нагрузить сетевой канал хоста"),
    ("доставка курьером",
     "Отдельно курьер с вами свяжется для согласования даты и времени доставки"),
]
ЧУЖИЕ = [
    "Пойдём на обед, возьмём пиццу и кофе",
    "Погода сегодня отличная, можно гулять в парке",
    "Мама позвонила и спросила, когда мы приедем",
]


def check_pool() -> None:
    """Среднее без заполнителя: иначе смысл зависит от соседей по пачке."""
    скрытое = np.array([[[1.0, 0.0], [3.0, 0.0], [100.0, 100.0]]], dtype=np.float32)
    маска = np.array([[1, 1, 0]])
    v = mean_pool(скрытое, маска)[0]
    проверить(np.allclose(v, [1.0, 0.0]), "заполнитель не входит в среднее")


def main() -> int:
    check_pool()

    модель = MeaningModel(paths.models_dir() / MODEL_DIR_NAME)
    if not модель.is_downloaded():
        print(f"[пропуск] весов нет в {модель.model_dir}: проверка настоящей модели не проводилась")
        return 0 if not провалов else 1

    t = time.monotonic()
    модель.load()
    print(f"модель поднялась за {time.monotonic() - t:.1f} с")

    фразы = [п[1] for п in ПАРЫ] + ЧУЖИЕ
    t = time.monotonic()
    тексты = модель.passages(фразы)
    проверить(тексты.shape == (len(фразы), model_mod.DIM), f"вектор из {model_mod.DIM} чисел на фразу")
    проверить(np.allclose(np.linalg.norm(тексты, axis=1), 1.0, atol=1e-4), "векторы нормированы")

    for i, (запрос, _) in enumerate(ПАРЫ):
        б = тексты @ модель.query(запрос)
        лучший = int(np.argmax(б))
        проверить(лучший == i,
                  f"«{запрос}» ближе всего к своей фразе ({б[i]:.3f}), а не к чужой ({np.delete(б, i).max():.3f})")

    # Одна и та же фраза в пачке и по одной даёт почти тот же смысл.
    # Ровно одинаковым он не будет: модель сжата до 8 бит, и масштаб
    # чисел подбирается по всей пачке сразу. Проверено, что дело не в
    # заполнителе: длинная фраза, которой он не нужен, расходится так же.
    # Расхождение 0.997 по близости; порог отбора живёт на уровне 0.85,
    # и такая разница его не двигает. А вот протёкший заполнитель дал бы
    # 0.9 и ниже, и это поймается.
    по_одной = np.vstack([модель.passages([ф]) for ф in фразы])
    сходство = (по_одной * тексты).sum(axis=1)
    проверить(bool(сходство.min() > 0.99),
              f"смысл фразы почти не зависит от соседей по пачке (хуже всего {сходство.min():.4f})")

    # Приставки запроса и текста разные, и это важно: без них модель
    # сравнивает вопрос с текстом как текст с текстом.
    с_приставкой = модель.query("тестовые платежи картой")
    без = модель._embed(["тестовые платежи картой"], "")[0]
    проверить(not np.allclose(с_приставкой, без, atol=1e-3), "запрос считается с пометкой «query: »")

    t = time.monotonic()
    for _ in range(20):
        модель.query("оплата картой")
    мс = (time.monotonic() - t) / 20 * 1000
    проверить(мс < 200, f"запрос считается быстро: {мс:.0f} мс, окно не подвиснет")

    if провалов:
        print(f"\nПровалов: {провалов}")
        return 1
    print("\nМодель понимает смысл, а не только совпадение слов.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
